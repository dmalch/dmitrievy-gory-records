from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, birth, birth_month, birth_records, page,
                          person)

# Метрическая тетрадь Покровской церкви с. Димитріевы Горы за 1797 г., часть первая
# «О родившихся». **ГАВО ф. 556 оп. 106 д. 132, лл. 221–222** (альбом «Дмитриевы Горы
# 1796-1797 (ГАВО 556-106-132)», кадры 0259–0261; табель — л. 225).
#
# ⚠⚠ **КРАТКИЙ РЕЕСТР**, как 1798–1802 гг.: «[отецъ] сынъ/дочь [имя], воспріемникъ
# былъ [имя]»; матери не названы, воспріемникъ один. Тетрадь № 13, «подана Генваря 13
# дня 1798 года»; священникъ **Василій Андреевъ** (табель за болѣзнью священника
# **Стефана Иванова** подписал діаконъ Егоръ Алексѣевъ).
#
# **Состав:** ч. 1 — лл. 221–222 (**32**: 16 м / 16 ж); ч. 2 — л. 222 (**12 браковъ**);
# ч. 3 — л. 222об (**20**: 6 м / 14 ж); табель — л. 225. ✅ **Сходится по всем трём
# частям** (прочитано целиком 05.10.2026).
# ⛔ Семіонъ Васильевъ не женится ни в 1796 (4 брака), ни в 1797 г. (12 браков); Ксеніи
# Кондратьевой в книгах нет.
#
# ✅ Вычитано по сканам в Verso 05.10.2026.
# Первое чтение: реестр прочитан по страницам при ~1.5×, входящая сюда запись — кропом при 3×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_births_1797 = birth_records(
    "ГАВО", "556", "106", "132", "Дмитриевы Горы", "Покровская",
    1797,
    *page("222",
          *birth_month(Month.DECEMBER,
                       # 🔴 **ДОЧЬ СЕМЁНА ВАСИЛЬЕВА — ВОПРОС 69.** «Тогожъ села **Семена Васильева** дочь
                       # **Варвара**, была воспріемница жена **Татьяна Васильева**», родилась 4, крещена 10
                       # декабря. Это единственный ребёнок Семёна Васильева во всём ряду 1796–1808 гг. до
                       # Силвестра (30.12.1809, 1809 ч. 1 № 90, мать Ксенія Кондратьева).
                       # ✅ **Решено ИР 1810 г.** (двор 51): «Семіонъ 35 … у Семіона жена Оксинья Кондратьева,
                       # дѣти ихъ Варвара 11, Марья 9» — дочь второго из Семёновъ ниже, род. ок. 1779.
                       # Прежде было не решено: Семёновъ Васильевыхъ в селѣ два: один 55 лѣтъ замёрз 7
                       # генваря 1803 г. (1803 ч. 3 м. № 1), у него дочь-невѣста Овдотья в 1807 г. (1807 ч. 2
                       # № 15); другой — двор 38 ревизии 1816 г., род. ок. 1779, ему в 1797 г. 18. Ревизия
                       # 1816 г. Варвары в дворе 38 не числит (ей было бы 18 — могла выйти замуж).
                       # ⓘ Кума «жена Татьяна Васильева» — по отчеству, возможно, сестра отца
                       birth(32, Gender.FEMALE, 4, 10,
                             child=person("Варвара"),
                             father=person("Семенъ", "Васильевъ"),
                             god_parent1=person("Татьяна", "Васильева", status="крестьянская женка вотчины г-на Баташева")),
                       ),
          ),
    defaults=DEFAULTS,
)
