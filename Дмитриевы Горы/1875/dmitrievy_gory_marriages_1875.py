# поручителей нет и не было. Это не пропуск разбора, а разрыв разворота на границе
# частей — та же оговорка, что по 1876 г. (там пострадали № 22–26).
#
# 🔴🔴🔴 **ГЛАВНОЕ: ВЕНЧАНИЕ ДИМИТРІЯ МАКСИМОВИЧА КИКѢЕВА, 9 НОЯБРЯ 1875 г. (№ 25).**
# Фамилия писана в самой записи — **«Кикѣевъ»**, через ять, и **такого написания в
# корпусе больше нет ни одного**: из семнадцати засвидетельствованных форм ять несёт
# только эта. ⇒ она **недостающее звено** между ревизской «Кикеевъ» (1858) и переписной
# «Кикевъ» (1897): ять — то самое «е», которое перепись роняет, а современная фамилия
# сохраняет.
# ⚠ **Самым ранним написанием фамилии во всём корпусе оно НЕ является** — «земской
# **Игнатъ Ѳедоровъ Кекевъ**» стоит в МК **1836** г. (ф. 556, ч. 2), а ревизия **1858** г.
# даёт «Кикеевъ». Первенство 1875 г. уже́ — **в ряду приходских подлинников оп. 12**
# (д. 195–200, с 1871 г.): там самым ранним было «Егоръ Максимовъ Кекевъ» МК 1879 г.
# 🔴🔴 **И запись даёт ему жену: «Агрипина Иванова», прихода села Санчуръ, 19 л. 4 мѣс.,
# ПЕРВЫМЪ бракомъ у обоих.** Перепись 1897 г. кладёт в двор 5 «Дмитрия Максимовича
# Кикева», 40 л., с женой **Агриппиной Ивановной**, 40 л.; МК 1891 г. называет её
# «Агрофеной Ивановой». Здесь она названа **первой** женой, с 1875 г.
# ⚠⚠ **И ЭТО ЛОМАЕТ ПРЕЖНЮЮ РАСКЛАДКУ ЕГО ЖЁН.** Корпус держал последовательность
# «Ѳеодора Иларіонова (1881) → Авдотья Максимова (1884) → Агриппина Иванова
# (1891, 1897)» как ряд вдовств. Если Агриппина — жена с 1875 г. и она же жена в
# 1891 и 1897 гг., то **1884 г. («Димитрій Максимовъ Кекевъ и жена его Авдотья
# Максимова») в этот ряд не ложится**, а 1881 г. («Димитрій Максимовъ», без фамилии)
# тем более. ⇒ либо в селе **два Димитрія Максимова с фамилией**, либо чтение имени
# жены 1884 г. надо перепроверить по скану. Разбор не закрыт; ни один профиль не сведён.
# 🔴 **Возраст даёт ему рождение ок. ноября 1854 — ноября 1855 г.**, тогда как перепись
# 1897 г. («40 л.») давала ~1857. Расхождение в два года — обычная переписная округлость.
#
# 🔴🔴🔴 **ВТОРОЕ: ФИЛИППЪ ѲОКИНЪ СЕЛА ВЕНЧАЕТСЯ 3 ОКТЯБРЯ 1875 г. (№ 17)** — и этим
# подтверждается вывод 1880 года, что **Филипповъ Ѳокиныхъ в приходе ДВОЕ**.
