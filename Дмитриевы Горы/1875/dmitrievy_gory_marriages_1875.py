# декабре — **ни одного**. **ДВЕ записи.**
#
# ⓘ Распределение то же, что в 1876–1877 гг.: зимний мясоед и куст после Успенского
# поста, но октябрьский куст здесь **самый большой из прочитанных** — шестнадцать
# браков, из них **тринадцать 3 октября** (№ 8–20). Против 12 в 1876 г. и 21 брака на
# весь 1877 г.
#
# ⚠⚠ **ПОРУЧИТЕЛЕЙ ПОСЛЕДНИХ ПЯТИ БРАКОВ (№ 21–25) В КНИГЕ НЕ СУЩЕСТВУЕТ.** Ч. 2
# кончается на л. 121об, а столбец «Кто были поручители» стоит на ЛИЦЕВОЙ стороне
# разворота — на л. 122, **а он чист** (проверено по скану кадра 0147: на листе только
