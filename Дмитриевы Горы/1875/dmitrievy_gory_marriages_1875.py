# Метрическая книга Покровской церкви с. Димитріевы Горы за 1875 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**195**, записи лл. 117об–121об
# (титул — л. 117). **25 браковъ**: январь 3 (№ 1–3), апрель 2 (№ 4–5), май 2 (№ 6–7),
