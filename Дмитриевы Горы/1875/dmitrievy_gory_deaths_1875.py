from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import PLEURISY
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, TEMP_OBLIGED_PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1875 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**195**, лл. 122об–133об
# (**титульного листа у части НЕТ**, л. 122 чист). **60 мужских и 59 женских —
# 119 погребений.** **ДВЕ записи.**
#
# ⚠⚠ **ПОГРЕБЕНИЙ БОЛЬШЕ, ЧЕМ В ЛЮБОМ ИЗ ПРОЧИТАННЫХ ЛЕТ**: 119 против 112 (1876),
# 101 (1877), 87 (1878), 84 (1879) — и это при **самом малом числе рождений** (135).
# Год эпидемический, и причина смерти названа почти в каждой записи: **оспа** (январь —
# март), **скарлатина** (март — сентябрь), **коклюшъ** (июнь — декабрь), **поносъ**
# (июнь — август). Ни одного месяца без детских погребений.
#
# ⚠ **ВОЗРАСТ В Ч. 3 ЭТОГО ГОДА ПИШЕТСЯ С ЕДИНИЦЕЙ** — «3 недѣли», «5½ мѣсяцевъ»,
# «9 дней», «1 мѣсяцъ»; голое число означает годы. Проверено изнутри года не менее
# **пятнадцати раз**: младенец, рождённый и погребённый в одной книге, каждый раз даёт
# сходящийся интервал (Григорій Степана Авдѣева — 2 янв. → 24 апр., «4 мѣсяца»;
# близнецы Михаила Трофимова — 21 июня → 22 июня «1 день» и 1 июля «9 дней»;
# Мавра Ивана Павлова — 25 апр. → 13 окт., «5½ мѣсяцевъ»). ⇒ **правило 3
# regional-rules («голое число не всегда годы») для 1875 г. разрешается в пользу лет**,
# и `death-age-check` по этому году должен сходиться.
#
# ⛔ **«ВТОРОЙ РОМАНЪ АНДРЕЕВЪ В СЕЛЕ» СНЯТ ВЫЧИТКОЙ 15.10.2026** (№ ж38, л. 130об). Здесь
# стояло, что погребённая 26 сентября 1875 г. «дочь младенецъ **Варвара**, 1 мѣсяцъ»
# родилась в конце августа, через пять с половиной месяцев после Дарьи (ч. 1 № ж15), и
# потому отцы разные. Вычитка прочла возраст «**1 годъ 10 мѣс.**» ⇒ это **Варвара
# корпусной пары**, род. 26.11.1873 (МК 1873 ч. 1 № ж60), — день в день. Романъ
# Андрѣевъ в селе один. Разбор — в комментарии к записи.
#
# 🔴🔴 **ВТОРОЕ: АЛЕКСѢЙ ѲОКИНЪ НАЗВАН ОТЦОМ** (№ ж49, л. 132об) — хоронит дочь Марѳу.
# Корпус знает Алексея Фокича (~1844, двор 3) по переписи 1897 г. и по метрикам
# 1880-х; здесь он на пять лет раньше и **с ребёнком, которого у корпуса нет**.
#
# Вычитан в Verso 15.10.2026: две записи года, заведённые в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1875 = death_records(
    "ГАВО", "590", "12", "195", "Дмитриевы Горы", "Покровская",
    1875,
    *page("130об",
          *death_month(Month.SEPTEMBER,
                       # ⛔ **«В СЕЛЕ ДВА РОМАНА АНДРЕЕВА» — СНЯТО ВЫЧИТКОЙ 15.10.2026.** «Того же села
                       # временнообязаннаго крестьянина **Романа Андрѣева** дочь младенецъ **Варвара**», **1 годъ
                       # 10 мѣс.** До вычитки возраст читался «1 мѣсяцъ» (дважды «сверен при 12×»), и на этом
                       # чтении стоял довод: Варвара род. ок. конца августа 1875 г., через пять с половиной месяцев
                       # после Дарьи Романовны (ч. 1 № ж15) ⇒ отцы разные ⇒ в селе два Романа Андреева, корпусный
                       # (~1852) опознаётся только по имени жены, а запись в род не заводится. Метрики Варвары не
                       # нашлось в ч. 1 1875 г.; находка 1873 г. (ч. 1 № ж60) была объявлена «не ею», а пара
                       # 1873 ж60 / 1875 ж38, которую ловил `death-age-check`, — ложной и заглушена `namesake=`.
                       # 🔴 С «1 г. 10 мѣс.» всё сходится: Варвара корпусной пары, род. **26 ноября 1873 г.**
                       # («Романъ Андрѣевъ и жена его Агафья Прокопьева»), а 26.11.1873 + 1 г. 10 мѣс. — ровно
                       # 26.09.1875, день погребения. ⇒ **одна девочка, отец — корпусный Романъ**; `namesake=`
                       # снят. Правило 5 regional-rules (имя с отчеством никого не опознаёт) остаётся в силе, но
                       # Андреевичи 1875 г. — больше не его пример: Романа здесь опознаёт дочь
                       death(38, Gender.FEMALE, 26, 28,
                             deceased=person("Варвара"), age="1 год 10 мес",
                             relatives=[relative(person("Романъ", "Андрѣевъ", status=TEMP_OBLIGED_PEASANT_MALE), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("132об",
          *death_month(Month.NOVEMBER,
                       # 🔴🔴 **У ДВОРА 3 НОВАЯ ДОЧЬ — МАРѲА АЛЕКСѢЕВНА; ЕЁ МЕТРИКА НАЙДЕНА В 1874 ГОДУ.** «Того
                       # же села временнообязаннаго крестьянина **Алексѣя Ѳокина** дочь **Марѳа**», отъ
                       # коклюша. Фамилия сверена при 13×: Ѳ (овал с перечерком) — о — **к** — и — н — а
                       # (родительный падеж), не «Ѳомина». 🔴 Это **Алексей Фокичъ двора 3** (~1844) — перепись
                       # 1897 г. даёт его главой двора («Кикев Алексей Фокин», 53 г.), regional-rules знают
                       # его третьим сыном сельского Фоки рядом с Павломъ и Аникитой. ⚠ **Отодвинуть его эта
                       # запись НЕ может**: корпус знает его отцом с МК **1872** г. (№ м1, с женой **Ксеніей
                       # Емельяновой**), и та же пара стоит в 1877, 1878, 1883 и 1885 гг. Новое здесь — **сама
                       # Марѳа**, дочери с таким именем у пары не было. 🔴🔴🔴 **ВОЗРАСТ ИСПРАВЛЕН 15.09.2026: «1
                       # г. 2 мѣс.», А НЕ «1 г. 5 мѣс.» — И ЭТО БЫЛА ОШИБКА РАСШИФРОВКИ, НЕ ПИСЦА.** Первое
                       # чтение дало «5» и вывело рождение «ок. июня 1874 г.». Прочитанный 1874 год такой
                       # метрики не показал, и **скан перечитан при 12×**: цифра после «1 г.» — **двойка**
                       # (округлая верхушка и нижний росчерк вправо), не пятёрка. 🔴 **Арифметика закрывается
                       # точно.** МК 1874 ч. 1 № ж50 даёт Марѳу **28 августа 1874 г.** у той же пары (Алексѣй
                       # Ѳокинъ × Ксенія Емельянова); 28 августа 1874 + 1 год 2 месяца = 28 октября 1875,
                       # смерть 2 ноября — усечение, как писецъ и делает везде в этих делах. С «5 мѣс.»
                       # рождение пришлось бы на начало июня 1874 г., а **июнь 1874 г. прочитан целиком** (№
                       # м44–м55, ж33–ж39) и Ѳокиныхъ среди родителей не держит. ⓘ В ч. 1 1875 г. её нет —
                       # сентябрь и октябрь прочитаны целиком, Ѳокиныхъ среди родителей нет. ⚠ Имя матери не
                       # названо — ч. 3 называет одного отца, — так что **Ксенія Емельянова матерью Марѳы НЕ
                       # приписана**, хотя по годам вокруг (1872–1885) другой жены у него нет. ⓘ Год кладёт
                       # рядом **трёх** Ѳокиныхъ села: Алексѣя (здесь), дѣвицу **Надежду** (ч. 1 № м40) и
                       # **Филиппа**, который 3 октября венчается (ч. 2 № 17). Родство между ними источником
                       # НЕ сказано и не приписано
                       death(49, Gender.FEMALE, 2, 4,
                             deceased=person("Марфа"), age="1 г 2 мес",
                             relatives=[relative(person("Алексѣй", "Ѳокинъ", status=TEMP_OBLIGED_PEASANT_MALE), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    defaults=DEFAULTS,
)
