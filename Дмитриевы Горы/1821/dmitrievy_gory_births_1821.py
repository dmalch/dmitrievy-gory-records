# Формула 1821 года: «вотчины **Г-на Коллежскаго Ассессора Ивана Родіоновича Баташева**»
# (ч. 1 №№ 2, 48; ч. 2 № 1; ч. 3 ж. № 3; сверено при 9×), обычно сокращаемая до «вотчины
# Господина Баташева». ⇒ это **Иванъ Родіоновичъ Баташевъ**, выксунский заводчик, и
# **вотчина переходит к Шепелевымъ между книгой 1821 и книгой 1822 года**: 1822-й уже
# пишет «вотчины малолѣтныхъ дѣтей Его Превосходительства Господина Генералъ Лейтенанта
# **Дмитрія Дмитріевича Шепелева**». ⇒ «малолѣтные дѣти», восемь лет смущавшие проход, —
# это **наследники Баташева по женской линии**, и тем же объясняются постоянные связи
# прихода с **Вильскимъ** и **Сноведскимъ заводами** Ардатовской округи (баташевскими):
# ч. 3 ж. № 16 хоронит солдатку из «деревни **Новой Дмитревки** прихода **Вилинскаго
# Завода**», а 1825 год зовёт тамошних «**одновотчинными**» — одна вотчина и есть.
#
# 🔴🔴🔴 **И ГОД ЦЕЛИКОМ ОБЪЯСНЯЕТ СМЕНУ ПРИЧТА.** До февраля священник — **Стефанъ
# Ивановъ**. Ч. 2 № 5 (6 февраля): «Владимірской Семинаріи окончившій курсъ ученія
# Богословскаго ученикъ втораго разряда **Тихонъ Екземплярскій**… села Дмитріевыхъ горъ
# **Священника Стефана Иванова съ дочерью, дѣвицею Анною**» — венчал муромскій
# протоіерей Ѳеодоръ Тубровскій, поручителями стояли четверо духовных. Дальше по книге:
# 17 апрѣля (№ 29) он «**новопроизведённый** Священникъ», 6 мая (№ 34) Стефанъ Ивановъ
# уже «**заштатный**», а ведомость года подписывает «Священникъ Тихонъ Екземплярскій».
# ⇒ **семинарист женился на дочери настоятеля и наследовал место тестя за три месяца**,
# и «**Анна Стефанова**», жена священника в книгах 1822–1823 гг., — это она.
#
# 🔴 **20 ФЕВРАЛЯ 1821 г.** (№ 20 ниже) — девятый перенос подряд первой записи о роде:
# 1830 → 1829 → 1828 → 1827 → 1826 → 1825 → 1824 → 1823 → 1822 → **1821**. ⛔ Отозвано
# утверждение 1822 года (25 марта 1822 г.).
# ⛔ **И САМО ОНО ОТОЗВАНО 12.09.2026 ПО ПРОЧТЕНИИ 1820 ГОДА** («самая ранняя запись о
