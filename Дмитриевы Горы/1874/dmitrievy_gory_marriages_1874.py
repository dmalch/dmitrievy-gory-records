from verso.ru.dsl import (Month, RecordDefaults, Side, marriage, marriage_month, marriage_records,
                          page, person)
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1874 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**195**, записи лл. 92об–94об
# (титул — л. 92). **28 браковъ**: январь 4 (№ 1–4), апрель 3 (№ 5–7), май 6 (№ 8–13),
# июль 1 (№ 14), сентябрь 1 (№ 15), **октябрь 8** (№ 16–23), ноябрь 5 (№ 24–28).
# В феврале, марте, июне, августе и декабре — **ни одного**. **ОДНА запись.**
#
# ⓘ Каждый месячный «итого» сверен с числом строк: январь четыре, апрель три, май шесть,
# октябрь восемь, ноябрь пять. Июль и сентябрь держат по одному браку без итоговой
# строки. **Год покрыт без дыр** — это и делает отрицательный результат ниже весомым.
#
# 🔴🔴🔴 **ГЛАВНОЕ — ЧЕГО В ЧАСТИ НЕТ.** Три венчания, которые ARCHIVES.md ищет, в
# 1874 г. **отсутствуют**, и при сплошь прочитанном годе это не пробел, а вывод:
#   • **Романъ Андрѣевъ × Агафья Прокопьева** — а сам Романъ в 1874 г. дважды стоит
#     воспріемникомъ и зван «крестьянинъ» (ч. 1 № м71, м82);
#   • **Павелъ Ѳокинъ × вдова Евдокія Меркурьева** — а у пары в марте 1874 г. уже дочь
#     (ч. 1 № ж20);
#   • **Андрей Ивановичъ × Стефанида Егорова** — а Стефанида в декабре 1874 г. уже
#     «женка» (ч. 1 № ж65).
# Ч. 2 **1872** г. прочитана по консисторской копии (д. 45) — ни одного венчания рода;
# ч. 2 **1875** г. прочитана целиком — тоже нет. ⇒ **все три венчания лежат в 1873 г.**,
# д. 195 ч. 2 — **лл. 68об–70об, три листа**. Это самая узкая цель, какая у прохода была.
#
# ⚠ **Возрасты женихов — 17–20 лет, невест 15–17**, то есть венчают едва по достижении
# канонического возраста; «17½» и «16 и 9 мѣс.» писаны с дробями. Это та же манера, что
# в 1875 г. («19 л. 3 мѣс.»), и она даёт год рождения с точностью до месяца.
#
# ⓘ Приход берёт невест широко: г. Меленки (№ 1), Ардатовскій уѣздъ (№ 4, 13, 19),
# приходы сёл Воютина (№ 6, 23), Казнева (№ 14, 15), Синчура (№ 10, 25), д. Урносово
# (№ 12, 14). Обратного движения — своих невест на сторону — ч. 2 не показывает.
#
# Вычитан в Verso 14.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1874 = marriage_records(
    "ГАВО", "590", "12", "195", "Дмитриевы Горы", "Покровская",
    1874,
    *page("92об",
          *marriage_month(Month.JANUARY,
                          # 🔴🔴🔴 **ВЕНЧАНИЕ КОНОНОВСКАГО ВАСИЛІЯ ѲОКИНА.** «Деревни Кононовой крестьянскій сынъ **Василій Ѳокинъ**, православнаго
                          # вѣроисповѣданія, первымъ бракомъ», 18 л. × «города **Меленокъ** мѣщанская дѣвица
                          # **Анастасья Андрѣева**, православнаго вѣроисповѣданія, первымъ бракомъ», 20 л.
                          # (обе стороны сверены при 5×). ⇒ род. ок. **1856 г.** ⛔ **Вывод «кононовскихъ
                          # Василіевъ Ѳокиныхъ ДВОЕ» СНЯТ 13.10.2026.** Он стоял на МК **1872** г. (ч. 1 № м5),
                          # читанной как «Василій Ѳокинъ и жена его Наталья Ѳедорова»: восемнадцатилетний
                          # жених, венчающийся первым браком в январе 1874 г., отцом в 1872-м быть не мог.
                          # Вычитка 1872 г. прочла там **«Василій Іоновъ» и «Пелагія Іосифова»** ⇒ противоречия
                          # нет, Василій кононовскій — один, и спор 1879 г. («перемена жены или ошибка чтения
                          # отчества») решён вторым ответом: ошибкой чтения. ✅ **Имя жены решено вариантом
                          # (а)**: МК 1877 и 1879 гг. давали Василію Ѳокину кононовскому жену «Наталья
                          # Андреева», и вычитка 13.10.2026 прочла там «Настасья» — та же Анастасія, что здесь
                          # (сведено, секция Z2). «Наталья» остаётся за МК 1882 г., в DSL не заведённой. ⓘ Ч. 1
                          # 1874 г. даёт **свою** «Наталью Андрѣеву» — женку
                          # **села**, замужем за Семеномъ Михайловымъ (№ ж65). Она этой невесте не
                          # тождественна. 🔴 **Невеста — мѣщанка города Меленокъ**, не крестьянка прихода. Этим
                          # объясняется, почему её метрики в книгах Дмитріевыхъ Горъ нет и искать её здесь
                          # незачем: род. ок. 1854 г. в Меленкахъ. 🔗 Отец жениха назван в ч. 1 того же года:
                          # «**Ѳока Ивановъ** и жена его Марья Иванова» (№ м15), у которых Василій Ѳокинъ
                          # стоит воспріемникомъ. Родство не сказано источником и не приписано
                          marriage(1, 7,
                                   groom=person("Василій", "Ѳокинъ", residence="Кононово", status=PEASANT_SON),
                                   bride=person("Анастасья", "Андрѣева", residence="Меленки", status="мещанская девица"),
                                   groom_marriage_num=1, bride_marriage_num=1,
                                   groom_age=18, bride_age=20, witness1=person("Алексѣй", "Семеновъ", side=Side.GROOM), witness2=person("Егоръ", "Данилинъ", side=Side.GROOM), witness3=person("Михаилъ", "Дмитріевъ", side=Side.BRIDE), witness4=person("Иванъ", "Якимиховъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
