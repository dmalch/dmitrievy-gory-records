                       # Кононовой Крестьянинъ **Никифоръ Митрофановъ**, 78» (сверено при 8×) ⇒ род. ок.
                       # **1796 г.** 🔴 Корпус знает **Ѳоку Митрофанова**, † 15 марта 1872 г., 70 л. (д. 45 ч.
                       # 3 № м14, род. ок. 1802 г.) — того самого, которым ARCHIVES.md закрыл поиск
