# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**195**, записи лл. 68об–70об
# (титул — л. 68). **16 браковъ**: январь 3 (№ 1–3), апрель 1 (№ 4), **октябрь 11**
