# **ДВЕ записи.**
#
# ⓘ **Год самый бедный на браки из семи прочитанных** — 16 против 28 (1874), 25 (1875),
# 26 (1876), 21 (1877). Октябрьский куст обычный (11 из 16, и 8 из них 3 октября),
