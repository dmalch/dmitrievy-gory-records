# рассматривал, а оно дешевле: венчают обыкновенно у невесты.
#
# ⓘ **Помѣщики названы прямо**: «временнообязанный **Г. Шепелевыхъ** крестьянскій сынъ»
# (№ 5, 7, 9) — та же фамилия, что в МК 1833 г. («Иванъ Димитріевичъ Шепелевъ»).
# Отдельно поминается **починокъ** села (№ 8, 10, 11) как своё поселение.
# ⓘ Невест берут из Старой Вереи (№ 3), Домнина (№ 14), Казнева и Воютина — рисунок
# тот же, что в 1874 г.
#
# Вычитан в Verso 14.10.2026: две записи года, заведённые в DSL; поручители обоих браков
# выписаны с recto.

