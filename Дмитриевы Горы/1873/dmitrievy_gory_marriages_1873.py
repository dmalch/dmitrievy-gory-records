# ⚠⚠ **А ДВУХ ДРУГИХ ИСКОМЫХ ВЕНЧАНІЙ В ГОДУ НЕТ** — и это, при сплошь прочитанной
# части, вывод. Ни **Романа Андрѣева с Агафьей Прокопьевой**, ни **Андрея Ивановича
# со Стефанидой Егоровой**. Между тем ч. 1 этого же года даёт Роману **дочь Варвару**
# (26 ноября, № ж60) ⇒ он женат **до 1873 г.**, а не в нём. С прочитанными ч. 2 1872
