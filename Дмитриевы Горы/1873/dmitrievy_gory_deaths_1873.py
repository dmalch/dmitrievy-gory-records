from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DEBILITY, FEVER, PLEURISY
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, SOLDIER, SOLDIER_SPOUSE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1873 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**195**, лл. 71об–77об
# (титул — л. 71). **51 мужское и 42 женских — 93 погребения.** **ЧЕТЫРЕ записи.**
#
# ⓘ **Погребений меньше всех семи прочитанных лет** — 93 против 102 (1874), 119 (1875),
# 112 (1876), 101 (1877), 87 (1878), 84 (1879). ⚠ Но и рождений записано меньше всех
# (132 без декабря), так что прирост года считать нельзя.
#
# ⚠ **Возраст: голое число = годы, младенцы всегда с единицей** — та же мера, что в
# 1874 г. Проверено арифметикой по парам «родился и умер в одной книге» (их в году не
# меньше девяти): Иларіонъ Флоровъ род. 21 марта, † 1 мая, писано «5 недѣль» (41 день);
# Марѳа Данилина род. ок. 24 июня, † 8 июля, «2 недѣли»; Петръ Сильвестровъ род. июнь,
# † 1 октября, «4 мѣсяца».
#
# ⚠⚠ **ЛѢТО 1873 г. — КОРЕВОЕ.** «Отъ кори» умирают с мая по сентябрь, всего не меньше
# пятнадцати детей, пик в июне–августе. Отдельно бросается в глаза **июль: три мужских
# против одиннадцати женских** — перекос, какого нет ни в одном другом месяце года.
# ⓘ Для сравнения: осень **1874** г. будет оспенной, а январь 1874 г. — скарлатинным.
# Три года подряд у прихода своя эпидемия.
#
# ⓘ **Двѣ смерти под следствием**: № м19 «по видѣнію Г. Станового Пристава» и № м43
# «по вскрытіи Г. Судебнаго слѣдователя» — оба взрослые мужчины села. В прочитанных
# годах такие пометы встречаются впервые.
#
# Вычитан в Verso 14.10.2026: четыре записи года, заведённые в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1873 = death_records(
    "ГАВО", "590", "12", "195", "Дмитриевы Горы", "Покровская",
    1873,
    *page("71об",
          *death_month(Month.JANUARY,
                       # 🎯🎯🎯 **ПЕРВАЯ ЖЕНА ПАВЛА ѲОКИНА — НАЙДЕНА, С ДАТОЙ И ПРИЧИНОЙ.** «Села Дмитріевскихъ
                       # Горъ **Солдата Павла Ѳокина Жена Акилина Порфирьева**» (вычиткой 14.10.2026: имя —
                       # «Акилина», не «Акулина»), 36, **отъ воспаленія послѣ
                       # родовъ** (сверено при 8×; фамилия перенесена через строку «Ѳо-кина»). ⇒ род. ок.
                       # **1837 г.** 🔴 **Это ровно то, что предсказал 1874 год.** Комментарий к метрике
                       # Ѳеодосіи (1874 ч. 1 № ж20) гласил: «в 1872 г. женой Павла Ѳокина названа Акулина
                       # Порфирьева ⇒ между 1872 и 1873 гг. он овдовел… смерти её в ч. 3 1874 г. нет — искать
                       # в 1872–1873 гг.». Искали — и вот она, **в первую же неделю 1873 года**. 🔴🔴 **И
                       # причина смерти вытягивает за собой ребёнка.** «Послѣ родовъ» ⇒ роды были в конце
                       # декабря 1872 г., и восемь дней спустя ч. 3 хоронит **двухнедѣльнаго Василія, сына
                       # того же Павла Ѳокина** (№ м3 ниже). Мать и новорождённый умерли с разницей в неделю.
                       # 🔗 **Дальше развязка в одной книге**: 15 апреля вдовецъ Павелъ, 38 л., венчается с
                       # вдовой **Евдокіей Меркурьевой**, 32 л. (ч. 2 № 4), а 18 марта 1874 г. у них родится
                       # дочь **Ѳеодосія**. ⓘ Порфирьевыхъ в приходе несколько (Алексѣй, Ефимъ, Макаръ, Иванъ,
                       # Николай, Марья, Анна, Настасья) — из них **Алексѣй Порфирьевъ**, билетный солдатъ,
                       # теряет жену **Стефаниду Данилину** 1 апреля того же года, тоже после родов. Родства с
                       # Акилиной источник не говорит
                       death(3, Gender.FEMALE, 1, 3,
                             deceased=person("Акилина", "Порфирьева", status=SOLDIER_SPOUSE), age=36,
                             relatives=[relative(person("Павелъ", "Ѳокинъ", status=SOLDIER), Relationship.HUSBAND)],
                             cause_of_death="от воспаления после родов"),
                       # 🎯🎯 **СЫНЪ, РОДИВШИЙСЯ ЦЕНОЙ ЖИЗНИ МАТЕРИ И ПЕРЕЖИВШИЙ ЕЁ НА НЕДѢЛЮ.** «Того же села
                       # **Солдата Павла Ѳокина сынъ младенецъ Василій**», 2 недѣли, отъ слабосилія (вычиткой 14.10.2026:
                       # не «слабости»; сверено при 8×). ⇒ род. ок. **25 декабря 1872 г.** 🔗 Мать — **Акилина
                       # Порфирьева** (№ ж3 выше),
                       # умершая 1 января «отъ воспаленія послѣ родовъ». Запись о рождении Василія лежит в
                       # **книге 1872 года** (ф. 590 оп. 5 д. 45, консисторская копия, прочитана) — сверить
                       # там декабрь: корпус держит пару «Павелъ Ѳокинъ × Акулина Порфирьева» по 1872 г. (там имя ещё читается «Акулина» — запись не
                       # перечитана), но
                       # этого ребёнка у него нет. ⚠ **Мать в ч. 3 не названа** — часть третья зовёт одного
                       # отца; связь с Акилиной держится на дате и на причине её смерти, а не на самой записи.
                       # ⓘ Этот **Василій Павловичъ Ѳокинъ** — не тот Василій Ѳокинъ, что венчается в 1874 г.:
                       # тот кононовскій, сынъ Ѳоки Иванова, и ему 18 лет
                       death(3, Gender.MALE, 8, 10,
                             deceased=person("Василій"), age="2 нед",
                             relatives=[relative(person("Павелъ", "Ѳокинъ", status=SOLDIER), Relationship.FATHER)],
                             cause_of_death=DEBILITY),
                       ),
          ),
    *page("73об",
          *death_month(Month.MAY,
                       # 🔴🔴🔴 **ЭТА ЗАПИСЬ СВЯЗЫВАЕТ ДВЕ ЧАСТИ КНИГИ ЧЕРЕЗ ОДНОГО РЕБЁНКА — И ФАМИЛИЯ В НИХ ОДНА.**
                       # «Села Дмитріевскихъ Горъ Крестьянина **Василья Флорова** сынъ млад. **Иларіонъ**», 5
                       # недѣль (сверено при 9×: Ф-**л**-о-р-о-в-а, без «ед»; вычиткой 14.10.2026 — прописная
                       # Ф, не фита). 🔴 А ч. 1 того же года крестит того же Иларіона у «**Василія Флорова** и
                       # жены его **Евдокіи Кодратовой**» (№ м21, 21 марта; до вычитки там читалось «Ѳедоровъ»
                       # и «Кондратова», и на этом чтении стоял довод «два написания — один человѣкъ»: двух
                       # написаний нет). **Одна книга, один год, один младенецъ, одна фамилия** ⇒ двор один.
                       # 🔗 Арифметика сходится: род. 21 марта, † 1 мая = 41 день, писано «5 недѣль» — писецъ
                       # округляет вниз на полнедели. 🔴 **Пара отодвинута с 1875 на 1873 г.** Корпус знал
                       # **Василія Флорова и Евдокію Кондратову** по МК 1880 г., 1875-й отодвинул на пять лет
                       # (дочь Екатерина); теперь ещё на два, и **Иларіонъ** — ребёнокъ, которого не было.
                       # ⚠ Мать в ч. 3 не названа; связь с Евдокіей Кодратовой держится на записи о рождении
                       death(20, Gender.MALE, 1, 3,
                             deceased=person("Иларіонъ"), age="5 нед",
                             relatives=[relative(person("Василій", "Флоровъ"), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("75об",
          *death_month(Month.AUGUST,
                       # 🔗 **МУЖ, ПО СМЕРТИ КОТОРОГО ВДОВА ОСТАЛАСЬ БЕРЕМЕННОЙ.** «Села Дмитр. Горъ
                       # крестьянинъ **Иванъ Исидоровъ**», 38, отъ горячки ⇒ род. ок. **1835 г.** 🔴 В феврале
                       # **1874** г. ч. 1 записывает: «того же села **оставшаяся беременной по смерти мужа
                       # своего вдова Ивана Исидорова Ксенія Михайлова**» — дочь **Евдокія**, воспріемникъ
                       # **Егоръ Максимовъ**. Эта запись даёт мужу дату смерти, а вдове — срок: он умер 8
                       # августа 1873 г., она была тогда на третьем месяце. 🔗 А 7 апреля 1874 г. ч. 3 хоронит
                       # и саму **Евдокію, дочь вдовы Ксеніи Михайловой**, «1 недѣля» (1874 ч. 3 № ж15). ⚠
                       # **Тёзка**: «Ксенія Михайлова» зовут и жену **Егора Максимова** (ч. 1 № ж45 этого
                       # года). Это разные женщины — одна вдова, другая при живом муже, — и пример того,
                       # почему имя с отчеством в этом селе ничего не решает
                       death(38, Gender.MALE, 8, 10,
                             deceased=person("Иванъ", "Исидоровъ"), age=38,
                             cause_of_death=FEVER),
                       ),
          ),
    defaults=DEFAULTS,
)
