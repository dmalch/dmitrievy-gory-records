from corpus.statuses import SHEPELEV_PEASANT, SHEPELEV_PEASANT_FEMALE, SHEPELEV_PEASANT_WIFE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DROPSY, FEVER, NATURAL
from verso.ru.dsl.statuses import RETIRED_SOLDIER

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1827 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 487, лл. 267–271** (кадры альбома 12–16).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 24 м / 20 ж = 44 погребения**, и ведомость (л. 271об)
# пишет ровно столько же; её возрастная разбивка мужчин («ниже году 15, 1½ — 2, 2 — 1,
# 25 — 1, 45 — 1, 57 — 1, 69 — 1, 74 — 1, 81 — 1») даёт «итого 24».
#
# ✅ **ГРАФА «КАКОЮ БОЛѢЗНІЮ» В 1827 ГОДУ ЕСТЬ.** Узкая, между «Лѣтами» и «Кѣмъ исповѣданы
# и приобщены», с заголовком «Какою болѣзнію померъ» (кадр 275, л. 268), и заполнена: № ж6
# «водяною», № м14 «горячкою», № ж20 «натуральною смертію». ⛔ **ОТОЗВАНО 06.10.2026 (вычитка
# по скану):** первое прочтение графы не увидело и выводило, что форма 1827 г. причину не
# пишет вовсе, а графа «скачет через год» (1826 — есть, 1827 — нет, 1828 — снова есть). Графа
# есть во всех прочитанных годах 1825–1828; в 1827 г. её ещё никто не выписал целиком —
# причины стоят только у трёх записей ниже. Итог ведомости: «въ семъ 1827-мъ году
# **ненатуральною смертію умершихъ быть никого не случилось**».
#
# ⓘ Год лёгкий: 44 погребения против 87 рождений (в 1828 — 74 против 83, в 1829 — 55
# против 97, в 1830 — 93 против 77). Младенцев мужского пола «ниже году» — пятнадцать
# из двадцати четырёх.
#
# 🆕 **НА ВЕДОМОСТИ — ПЕРВАЯ ЗА ВЕСЬ ПРОХОД ПОМЕТА ДУХОВНОГО ПРАВЛЕНИЯ.** После подписей
# причта дьячекъ **Василій Лаврентьевъ** приписывает: «При разсматриваніи сей Метрической
# тетради **въ Правленіи оказалось**, что 1-й части подъ № 7 въ 5-й графѣ **по чищеному
# написано**… и 1-й части число, начиная съ 62-го по 75, по чищеному написано». ⇒ Муромское
# духовное правление вычитывало тетрадь построчно, находило подчистки и требовало их
# заверить. Ни один другой прочитанный год такой пометы не несёт.
#
# 🔴 **Погребений рода в году нет** — ни Ѳоки, ни Игната, ни Антона, ни их детей.
# Дочь Ѳоки **Анна**, родившаяся 10 іюня (ч. 1 № 30), этот год переживёт и будет
# похоронена 24 іюня 1828 г.
#
# ✅ Вычитано по сканам в Verso 05.10.2026.
# Первое чтение: имена сверены кропом при 2.3× в сером.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1827 = death_records(
    "ГАВО", "556", "106", "487", "Дмитриевы Горы", "Покровская",
    1827,
    *page("268",
          *death_month(Month.APRIL,
                       # 🆕 **ЧЕЛОВЕК, КОТОРЫЙ К 1828 ГОДУ ОВДОВЕЛ ДВАЖДЫ.** «Крестьянина **Михаила
                       # Варсонофьева** жена **Прасковья Венедиктова**, 23». ⚠⚠ **ИМЯ ЖЕНЫ СПОРИТ С 1824
                       # ГОДОМ.** 20 генваря 1824 г. «вдовствующій крестьянинъ Михайло Варсонофьевъ» венчается
                       # **вторымъ** бракомъ на дѣвкѣ **Евдокіи Венедиктовой** (1824 ч. 2 № 5, сверено при
                       # 9×). Отчество то же, счёт браков сходится (третий — 1828-й), второй свадьбы между
                       # 1824 и 1827 гг. в прочитанных книгах нет ⇒ **это одна женщина**, и одно из двух имён
                       # прочитано неверно. **Перечитать эту строку по скану.** 🔗 18 мая 1828 г. он венчается
                       # снова — и запись прямо говорит «**женихъ ТРЕТЬИМЪ**, а невѣста первымъ бракомъ» (1828
                       # ч. 2 № 8). ⇒ Прасковья была второй женой, а первая умерла до 1827 г., в непрочитанном
                       # году. ⓘ Третий брак — единственный за все прочитанные годы; вторые встречаются
                       # постоянно
                       death(6, Gender.FEMALE, 12,
                             14,
                             deceased=person("Прасковья", "Венедиктова", status=SHEPELEV_PEASANT_WIFE),
                             age=23,
                             relatives=[relative(person("Михайло", "Варсонофьевъ"), Relationship.HUSBAND)],
                             cause_of_death=DROPSY),
                       ),
          ),
    *page("269",
          *death_month(Month.JUNE,
                       # 🆕 **ОТСТАВНОЙ СОЛДАТ, ПОХОРОНЕННЫЙ В СЕЛЕ.** «Означеннаго села **отставной солдатъ
                       # Миронъ Александровъ**, 45». ⓘ Солдатки в этих книгах на каждой странице — жёны и
                       # вдовы взятых в рекруты, — а вот сам вернувшийся солдат встречается за проход
                       # считанные разы. Рекрутчина видна в приходе почти исключительно с женской стороны:
                       # **Стефанида Харитонова** станет солдаткой между 1829 и 1836 гг., **Осипа Антонова**
                       # отдадут в рекруты в 1840-м
                       death(14, Gender.MALE, 12,
                             14,
                             deceased=person("Миронъ", "Александровъ", status=RETIRED_SOLDIER),
                             age=45,
                             cause_of_death=FEVER),
                       ),
          ),
    *page("271",
          *death_month(Month.DECEMBER,
                       # ⓘ **Старейшая из умерших за год** — восьмидесяти трёх лет, род. ок. 1744 г. 🔗
                       # Ведомость подтверждает её отдельной строкой возрастной разбивки («81 — 1» относится к
                       # кононовскому Михайлу Иванову, † 23 іюля; её собственные 83 стоят в женской половине,
                       # которую ведомость по возрастам не расписывает). Причина — «натуральною смертію»,
                       # погребена «декабря 10 дня» (вычитка 06.10.2026; графа болѣзни есть — см. шапку)
                       death(20, Gender.FEMALE, 8,
                             10,
                             deceased=person("Евдокія", "Кононова", status="вдова вотчины гг. Шепелевых"),
                             age=83,
                             cause_of_death=NATURAL),
                       ),
          ),
    defaults=DEFAULTS,
)
