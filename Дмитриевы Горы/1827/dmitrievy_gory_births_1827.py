#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ВЕДОМОСТЬ (л. 271об) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** —
# третий такой год подряд после 1829 и 1828. «Родившихся мужеска 48, женска 39, обоего
# пола **87**» = 87 сквозных номеров; «бракосочетавшихся лицъ 38, супружествъ **19**»;
# «умершихъ мужеска **24**, женска **20**, обоего **44**», и её возрастная разбивка
# мужчин даёт «итого 24». Незаконнорожденные «1 м / 1 ж» — № 25 (Петръ у солдатки
# Екатерины Лаврентьевой) и № 59 (Устинья у солдатки Агафьи Ефимовой).
#
# 🆕 **ВОТЧИНА НАЗВАНА ПОЛНЕЕ, ЧЕМ ВО ВСЕ ПОСЛЕДУЮЩИЕ ГОДЫ**: здесь сплошь «вотчины
# **МАЛОЛѢТНЫХЪ** дѣтей Господъ Шепелевыхъ» (№№ 1, 73, 77, 82 и далее), тогда как
# 1828–1830 гг. пишут коротко «вотчины дѣтей Г. Г. Шепелевыхъ». ⇒ наследники Шепелевых
# в 1827 г. **малолетние**, имение под опекой — это и объясняет, почему слово «дѣтей»
# держится в формуле ещё полтора десятка лет.
#
# ⓘ Причт тот же: священникъ **Тихонъ Экземплярскій**, діаконъ **Егоръ Драчевскій**,
# дьячекъ **Василій Лаврентьевъ**, пономарь **Михайло Егоровъ**. В конце ноября один раз
# крестит **священникъ села Воютина Алексѣй Яковлевъ** (№ 76) — как и в генварѣ 1828 г.
#
# ✅ Вычитано по сканам в Verso 05.10.2026.
# Первое чтение: имена сверены кропом при 2.3× в сером (почерк 1827 г. крупнее и чище
# соседних лет, `--enhance` не нужен), ключевые — при 7×.

