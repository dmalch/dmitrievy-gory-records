from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DEBILITY, MEASLES
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1899 г.,
# часть третья «О умерших». ГАВО ф.590 оп.12 д.**197**, лл. 322–332об
# (титул — л. 322, записи на лл. 322об–332об). Листы лежат подряд.
#
# ⚠⚠ **ЯНВАРЬ 1899 г. — САМЫЙ СМЕРТНЫЙ МЕСЯЦ ВСЕГО ПРОХОДА**: он один занимает
# пять листов (322об–326об) и кончается итогом «умершихъ муж. пола двадцать, а
# женскаго двадцать [девять]». Почти все умершие — младенцы и дети до трёх лет.
# Графа «отъ чего умеръ» стоит на правой странице разворота; первым проходом
# она не выверялась, вычитка 03.11.2026 завела причины обоих кекевских
# погребений (корь у Лидіи, слабость у Ѳеодора).
#
# **ДВА кекевских погребения**, оба детские — и оба дают корпусу новых людей.
#
# Вычитано в Verso 03.11.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1899 = death_records(
    "ГАВО", "590", "12", "197", "Дмитриевы Горы", "Покровская",
    1899,
    *page("326об",
          *death_month(Month.JANUARY,
                       # ✅ **17.09.2026 ИМЯ ИСПРАВЛЕНО ПО СКАНУ: ЛИДІЯ, НЕ МАРІЯ.** В книге стоит «…Іоанна
                       # Михайлова Кекева дочь **Лидія**», возраст «**1¾**» (сверено при 6×). Это **Лидія,
                       # рожд. 19 марта 1897 г.** — ч. 1 № ж12, л. 225об, та же пара: от рождения до 26 января
                       # 1899 г. год и десять месяцев, а «1¾» и есть год и девять — округление на месяц.
                       # 🔁 **Прежний разбор дошёл до верного ответа и остановился в шаге от него.** Он писал:
                       # «вероятнее всего хоронят Лидію, а Марія — замена редкого имени самым частым; но имена
                       # в записях разные, и тождество не доказано». Имена расходились **только из-за ошибки
                       # расшифровки**: доказывать было нечего, надо было перечитать. Урок ровно тот, что в
                       # `check_the_scan_before_blaming_the_scribe`, но с другого конца — подозревать своё
                       # чтение стоит не только когда писец «ошибся», но и когда запись просто не сходится.
                       # 🔴 **Марія, рожд. 11 февраля 1895 г. (ч. 1 № ж16, л. 152об), к этому погребению не
                       # относится** и в 1899 г. жива — четырёхлетняя сестра Лидіи. ⚠ У той же пары в июне
                       # 1899 г. родится дочь **Евфросиния** (ч. 1 № ж23): год начинается похоронами одной
                       # дочери и кончается крестинами другой — тот же рисунок, что у них в 1901 г. ⚠ Запись
                       # стоит последней в январском прогоне, а январь этого года унёс в приходе около
                       # полусотни человек
                       death(29, Gender.FEMALE, 26, 27,
                             deceased=person("Лидія"), age="1 г 9 мес",
                             relatives=[relative(person("Іоаннъ", "Михайловъ", last_name_orig="Кекевъ"), Relationship.FATHER)],
                             cause_of_death=MEASLES),
                       ),
          ),
    *page("330об",
          *death_month(Month.JULY,
                       # ✅✅ **21.09.2026: ОТЧЕСТВО ОТЦА ПЕРЕЧИТАНО ПО СКАНУ — «МАКСИМОВЪ», НЕ
                       # «ІАКОВЛЕВЪ».** Прежнее чтение делало эту запись главной уликой за «третьего
                       # Иаковлевича» и кончалось «НЕ РЕШЕНО»; улики нет, вопроса нет. Отчество стоит В
                       # ПЕРЕНОСЕ: строка кончается «Георгіе Макси|», следующая начинается «мова Кекева
                       # сынъ Ѳеодоръ». Решает не буква, а сравнение с ч. 1 № 30 (л. 305об) — рождение
                       # ЭТОГО ЖЕ Феодора 2 июня 1899 г.: та же рука ломает отчество на том же слоге
                       # («Георгіи Макси|мовъ Кекевъ»), и следующее слово в обеих записях одно и то же.
                       # 🔑 И арифметика сходится сама: 2 июня → 30 июля ровно два месяца, а графа
                       # «Лѣта умершаго» в мужском столбце пишет «2 мцовъ» (сверено при 5×, соседняя
                       # строка № ж52 — «6½ мц», единица у этого писца названа всегда).
                       # ⇒ отец — **Георгій Максимовъ Кекевъ**, муж Надежды Димитріевой (ч. 1 № 30), и в
                       # 1899 г. Іаковлевичъ в приходе ОДИН: Георгій Іаковлевъ РОДИНЪ (ч. 1 № 68, л. 315об).
                       death(37, Gender.MALE, 30, 31,
                             deceased=person("Ѳеодоръ"), age="2 мес",
                             relatives=[relative(person("Георгій", "Максимовъ", last_name_orig="Кекевъ"), Relationship.FATHER)],
                             cause_of_death=DEBILITY),
                       ),
          ),
    # Вторая волна (08.11.2026): дети замужних дочерей Кекевых, найденные по имени мужа.
    # Вычитано владельцем 12.11.2026: № м4.
    *page("323об",
          *death_month(Month.JANUARY,
                       # Феодор — сын Николая Васильевича Горбачева и Марфы Максимовны Кекевой, род. 27.05.1898 (1898 ч. 1, № м27);
                       # причина смерти — корь (вычитка владельца 12.11.2026)
                       death(4, Gender.MALE, 4, 5,
                             deceased=person("Ѳеодоръ"), age="7 мес",
                             relatives=[relative(person("Николай", "Василіевъ", last_name_orig="Горбачевъ"), Relationship.FATHER)],
                             cause_of_death=MEASLES),
                       ),
          ),
    defaults=DEFAULTS,
)
