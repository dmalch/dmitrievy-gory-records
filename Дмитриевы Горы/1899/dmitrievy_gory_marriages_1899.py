from verso.ru.dsl import (Month, RecordDefaults, Side, marriage, marriage_month, marriage_records,
                          page, person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1899 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**197**, лл. 317–321об
# (титул — л. 317, записи на лл. 317об–321об). **19 браков**, лежат подряд и
# без разрывов — после д. 198 это отдых.
#
# **ДВА кекевских брака, и оба выдают невесту**: женихов нашего рода в году нет.
# Невесты — **Евдокія Іоаннова** и **Матрона Романова** (⛔ «Иосифова» первого
# чтения вычитка 03.11.2026 прочла «Іоаннова»).
#
# ⚠ **Поручители браков № 17–19 (в том числе кекевского № 18) УТРАЧЕНЫ.**
# Правая половина разворота л. 321об — это л. 322, а на нём печатный титул
# части третьей: разворот разорван границей частей. У браков № 13–16 поручители
# на месте (л. 321).
#
# ⚠ Год венчает и **Максима Ѳеодорова Абашина тожъ Костина**, 18 лет (№ 15,
# 27 окт., с Анной Андреевой Будановой) — того самого, который в 1909 г.
# женится ВТОРЫМ браком двадцати восьми лет на **Матроне Георгиевой Кекевой**
# двора 5. Возраст сходится в год, и это связывает две записи через десять лет.
#
# Вычитано в Verso 03.11.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1899 = marriage_records(
    "ГАВО", "590", "12", "197", "Дмитриевы Горы", "Покровская",
    1899,
    *page("320об",
          *marriage_month(Month.OCTOBER,
                          # ⛔⛔ **Вычитка 03.11.2026: невеста — «Евдокія ІОАННОВА Кекева», не «Иосифова».**
                          # Вывод о «шестом деде рода Иосифе Кекеве» стоял только на этом отчестве и снят.
                          # «Крестьянская дѣвица Евдокія Іоаннова Кекева» крестит в марте того же года дочь
                          # Георгия Иоаннова (ч. 1 № ж13) — по отчеству она сестра Иоанновичей. ⚠ Поручители по
                          # невесте — **Романъ Андреевъ Кекевъ** (прежде «Косма Андреевъ» — такого лица нет) и
                          # Василій Тимоѳеевъ Скрулетовъ. ⚠ Жених — **Орѣховъ** (прежде «Орловъ»), и поручители
                          # по жениху тоже Орѣховы
                          marriage(14, 3,
                                   groom=person("Алексій", "Симеоновъ", last_name_orig="Орѣховъ", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age="18 лет 6 мес",
                                   bride=person("Евдокія", "Іоаннова", last_name_orig="Кекева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=18,
                                   witness1=person("Лазарь", "Симеонов", last_name_orig="Орѣховъ", side=Side.GROOM),
                                   witness2=person("Іоаннъ", "Поликарповъ", last_name_orig="Орѣховъ", side=Side.GROOM),
                                   witness3=person("Романъ", "Андреевъ", last_name_orig="Кекевъ", side=Side.BRIDE),
                                   witness4=person("Василій", "Тимофѣевъ", last_name_orig="Скрулетовъ", side=Side.BRIDE)),
                          ),
          ),
    *page("321об",
          *marriage_month(Month.NOVEMBER,
                          # ⚠⚠ **ВТОРОЙ РОМАНОВИЧ В КОРПУСЕ.** Отчество Романов до сих пор носил один человек
                          # — **Косма Романовъ Кекевъ**, венчавшийся 3 окт. 1901 г. двадцати лет, о чьём отце
                          # в 1901 г. записано: «отец Роман корпусу неизвестен». Матроне здесь 22½ ⇒ род.
                          # около апреля 1877 г., то есть она старшая сестра Космы. **Дед Роман получает
                          # второго ребёнка и сдвиг вглубь: он женат не позже середины 1870-х.** ⚠ Жених —
                          # **Иоаннъ Евфиміевъ ЮКАЧЕВЪ**, и это ровно то имя, которое в 1913 г. однажды
                          # прочитали как «Кекева» и исправили по скану на «Юкаева». Здесь фамилия читается
                          # уверенно, и она у жениха, а не у невесты. ⚠ Поручители не записаны: правая
                          # половина разворота — титул части третьей
                          marriage(18, 10,
                                   groom=person("Іоаннъ", "Евфиміевъ", last_name_orig="Юкачевъ", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=23,
                                   bride=person("Матрона", "Романова", last_name_orig="Кекева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age="22 года 6 мес"),
                          ),
          ),
    defaults=DEFAULTS,
)
