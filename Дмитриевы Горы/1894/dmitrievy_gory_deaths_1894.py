#
# ⚠ **Марѳа Михайлова Кузина, 73 (№ ж3, 18/20 января)** — единственная
# взрослая Кузина года и **единственный кандидат в матери двора 6**,
# какого дал проход. «Крестьянская **жена**» (не вдова) ⇒ муж в январе
# 1894 г. был жив; год рождения ок. 1821. Павел Фокеев род. ок. 1836/1840,
# то есть при её материнстве ей было бы 15–19 лет — туго, но возможно.
# **Родство не доказано**: Кузины в селе есть и помимо двора 6 (Даниловы,
# Васильевы), а Фока по имени в записи не назван. Запись заведена потому,
# что отвергнуть её нечем — в отличие от Кузиных-Васильевичей ниже.
#
# ⚠ Кузины НЕ двора 6 (в записи не заводятся): «находящійся въ военной
# службѣ **Иванъ Васильевъ КУЗИНЪ**» хоронит сына **Илію** 8½ мес.
# (№ м27, л. 141об) и дочь **Евфимію** 2¾ (№ ж38, л. 142об) — двоих детей
# за несколько дней. Он же крестит с Матіаной Емельяновой в 1895 г.
#
# ⚠⚠ **ДВОЕ ѲОКИНЫХ БЕЗ ФАМИЛИИ, и проход по фамилиям их не ловит.**
# 17/18 сентября (ч. 1, № ж39) крестит дочь «уволенный въ запасъ арміи
# солдатъ **Григорій Ѳокинъ БЕЗЪ ФАМИЛІИ** и жена его Софія Николаева» —
# писец сам отмечает отсутствие фамилии. 4/5 августа хоронят «крестьянина
# **Василія Ѳокина** дочь Матрону», 1¾ (№ ж50, л. 144об), тоже без фамилии.
# У Фоки корпус знает троих сыновей — Аникиту (~1843), Алексея (~1844) и
# Павла (~1836/40), — и все трое пишутся то «Кекевъ», то (Павел) «Кузинъ»
# (⛔ «Кекъ» из ряда снят 16.09.2026: это чтение, а не форма). Григорий и Василий Фокины ложатся в тот же ряд, но **отчество —
# это не доказательство**, а Фок в селе может быть несколько. В записи не
# заводятся; см. вопрос в `families/Кикеевы.md`.
#
# ⚠ **Правые половины разворотов части третьей (лл. 137, 138 … 148) несут
# только графы «Отъ чего умеръ», «Кто исповѣдывалъ» и «Кто совершалъ
# погребеніе»** — имён там нет. Причины смерти заведены вычиткой 26.10.2026:
# дифтерит у обоих мальчиков (№№ м4, м53), естественная смерть у Марѳы
# Кузиной (№ ж3); у Анисіи не заведена.
#
# Вычитан в Verso 26.10.2026: 4 записи года, заведённых в DSL.

