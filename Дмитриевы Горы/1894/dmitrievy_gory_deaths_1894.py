# проверяет». Андрей жив: он «Андрей Игнатьевъ, 2» переписи 1897 г.
#
# ⚠⚠ **И ПРАВИЛО «ГОЛЫЙ ВОЗРАСТ = ГОДЫ» В 1894 г. ДЕРЖИТСЯ.** На этой записи
# стояло его единственное исключение в д.197 («4» = мѣсяцы); исключения
