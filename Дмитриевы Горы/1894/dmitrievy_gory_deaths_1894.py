#
# ✅ **№ м53 — АЛЕКСѢЙ ЧЕТЫРЁХ ЛЕТ, А НЕ АНДРЕЙ ЧЕТЫРЁХ МѢСЯЦЕВЪ** (вычитка
# 26.10.2026). Сын Игнатия Феодоровича, погребённый 7 декабря, — «Алексій»,
