# Метрическая книга Покровской церкви с. Димитриевы Горы за 1894 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**197**,
# лл. 129–135об (титул — л. 129, записи на лл. 129об–135об). **34 брака**,
# из них **24 — в один день, 2 октября**.
#
# **ТРИ НЕВЕСТЫ ИЗ РОДА В ОДИН ГОД** — двух корпус не знал вовсе, третью
# знал под фамилией мужа и держал под вопросом.
#
# 🔴🔴 **№ 26 (2 октября) — венчание Ксении Иоанновны, и его поручители
# важнее самой невесты.** По невесте поручались «того же села крестьяне
# **Романъ Андреевъ и Георгій Максимовъ КЕКЕВЫ**» (фамилия стоит один раз на
# двоих). Отсюда:
#   • **Роман Андреевич Кекев** (~1852 — †29.08.1913, 61 г., от чахотки)
#     упомянут **на девятнадцать лет раньше**, чем в прежней самой ранней
#     своей записи. Отчество корпус знал по его же метрике о смерти; ново
#     здесь то, что он живой участник записи, и что у него есть **третий
#     ребёнок, старший** — Дарья (брак № 34 этого же года).
#   • **Георгий Максимович** (двор 5) отодвигается с 1896 на 1894 год.
# ⇒ И поручительство **по невесте** — тот самый структурный довод, каким
# 1897 год закрыл вопрос 37 (у Елены Игнатьевны по невесте поручались её
# дядья Николай и Михаил Феодоровичи). Роман Андреевич по отчеству брат
# **Иоанна Андреевича** (~1857 — †23.07.1903); если он дядя невесты, её
# «Іоаннъ» — это Иоанн Андреевич, а не кто-то из «Иоанновых» ветви Феодора,
# и «Андрей» перестаёт быть дедом с одним сыном. Доказательством это не
# является — поручителем бывает и свойственник; см. вопрос в `families/`.
#
# 🔴 **№ 33 (11 ноября) — венчание Феодосии Павловны, и вопрос о ней закрыт.**
# «Солдатская дочь **Феодосія Павлова КУЗИНА**», 20½. Корпус знал её как
# «крестьянскую женку Феодосію Павлову **Игнаткину**» (вычитка 1897 г. 27.10.2026:
# «Ипишкину»), восприемницу 1897 г. (д.197 л. 237), и держал под «❓ возможно сестра» — отчество то же, что у
# трёх братьев двора 6, но перепись женщин во дворе Павла Фокеева не
# записала. Здесь она выходит за **Максима Архиппова ИПАТКИНА** (вычитка
# 26.10.2026; прежде «Іаковъ Архиповъ Игнаткинъ»), откуда и фамилия 1897 года
# (там читано «Игнаткина»; книга 1897 г. не вычитана), а звание «**солдатская** дочь» при отце-отставном
# солдате Павле Фокееве Кекеве-Кузине сходится точно. ⇒ **Двор 6 получает
# дочь**, четвёртого ребёнка Павла Фокеева.
#
# 🔴 **№ 34 (11 ноября) — венчание Дарьи Романовны**, 19½ (⇒ род. ок. мая
# 1875 г.). Четвёртый известный ребёнок Романа Андреевича и **самый старший**:
# Матрона ~1877 (по её возрасту 1899 г.), Косма ~1881 (по венчанию 1901 г.),
# Кристина — в замужестве Федюнина (1918 г.).
#
# ⚠ **Поручителей у браков № 33 и 34 НЕТ**, и это не пропуск: они стояли бы
# на л. 136, а там печатный титул части третьей. То же самое случилось в
# 1895 г. с браками № 19–20 (л. 173) — граница частей рвёт разворот.
#
# ⚠ **Кузины НЕ двора 6 (в записи не заводятся)**: брак № 3 (16 февраля) —
# «крестьянская дочь **Екатерина Абрамова КУЗИНА**», 28, за Михаила
# Григорьева Бельчихина. Отчества **Абрамъ** в роду нет ни у кого.
#
# ⚠ **Брак № 21 (2 октября) подтверждает исправление 1898 года**:
# «крестьянскій сынъ **Михаилъ Павловъ КОЗЛОВЪ**», 19 л. 11 мес, венчается с
# «Наталіей Павловой Малышевой», 20. Это та самая пара, чьи записи 1898 г.
# были изъяты из корпуса 04.09.2026 после перечтения сканов («Кузинъ» там
# оказался «Козловъ»). Теперь их венчание прочитано в третьей книге, и «з»
# в фамилии видно при пятикратном увеличении: чтение подтверждено ещё раз.
#
# Вычитан в Verso 26.10.2026: 3 записи года, заведённых в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE, status_mother=PEASANT_FEMALE)

