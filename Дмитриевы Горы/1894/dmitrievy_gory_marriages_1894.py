                          # крестьянская дочь **Ксенія Іоаннова КЕКЕВА**», 17½ (⇒ род. ок. апреля 1877 г.),
                          # первым браком; корпусу она неизвестна. Жених — «крестьянскій сынъ Петръ Іоанновъ
                          # Шиковъ», 17 л. 10½ мес. 🔴🔴 **Поручители по невесте — «Романъ Андреевъ и Георгій
                          # Максимовъ КЕКЕВЫ»** (фамилия написана один раз на двоих). **Роман Андреевич**
                          # (~1852 — †29.08.1913, 61 г.) — патриарх ветви «Романовы»; отчество его корпус знал
                          # по метрике о смерти, но самая ранняя его собственная запись была 1913 г. ⇒ **он
                          # отодвигается на девятнадцать лет**. **Георгий Максимович** (двор 5) отодвигается с
                          # 1896 на 1894 год. ⚠ **Отсюда же — самый сильный довод об отце невесты.** В этом
                          # приходе по невесте поручается её РОДНЯ (так 1897 год закрыл вопрос 37: у Елены
                          # Игнатьевны поручителями по невесте были дядья Николай и Михаил Феодоровичи). Роман
                          # Андреевич по отчеству брат **Иоанна Андреевича** (~1857 — †23.07.1903); если он
                          # дядя Ксении, её «Іоаннъ» — это Иоанн Андреевич, и группа «Иоанновых» ветви Феодора
                          # тут ни при чём. Довод структурный, но не доказательство: поручителем мог быть и
