# Метрическая книга Покровской церкви с. Димитриевы Горы за 1895 г.,
# часть третья «О умерших». ГАВО ф.590 оп.12 д.**197**, лл. 173–184об
# (титул — л. 173, записи на лл. 173об–184об).
#
# **ШЕСТЬ кекевских погребений** — столько же, сколько в 1898 г. до правки, и
# больше, чем в любом другом прочитанном году кроме 1901-го. Пятеро — дети,
# и **одна взрослая женщина**, которая и есть главная находка года.
#
# 🔴🔴 **«Крестьянская жена СТЕФАНИДА ГЕОРГІЕВА КЕКЕВА», 31 года, погребена
# 27 июня 1895 г.** (№ ж8, л. 175об). Мужа метрика не называет — правило
# прихода, — но год складывается в последовательность:
#   26 июня — умирает Стефанида Георгиева Кекева, 31 г.;
#   29 июля — умирает «дочь **Андрея Іоаннова Кекева** Пелагія»,
#             одиннадцати месяцев (№ ж19, л. 178об);
#   12 ноября — **Андрей Іоанновъ Кекевъ венчается ВДОВЫМ**, вторым браком
#             (ч. 2, № 20).
# ⇒ **Стефанида Георгиевна — первая жена Андрея Иоанновича старшего.**
#
# ✅✅ **ЭТО БОЛЬШЕ НЕ ГИПОТЕЗА (05.09.2026).** Проход по 1894 году нашёл
# запись, где они названы мужем и женой прямо: 21 сентября 1894 г.
# «крестьянинъ Андрей Іоанновъ Кекевъ и жена его Стефанида Георгіева»
# крестят дочь **Пелагію** (ч. 1 1894 г., № ж40, л. 124об). Та же Пелагия и
# погребена здесь 29 июля — возраст в скане **«11 мѣс»**, а не «1 мес», как
# было прочитано при первом проходе (сведены 26.10.2026,
# `pelageja_andreevna_kekeva_1894`). Оба вывода, стоявшие на «месяце от
# роду», сняты: рождения в части первой 1895 г. и не должно было быть, а
# «смерть в родах» ничем не подтверждается.
#
# 🆕 **Год дал четверых детей, корпусу неизвестных**, и все четверо
# отодвигали свои семьи в тогда непрочитанные 1890–1893 гг.:
#   Стефанъ Алексѣевичъ (2 г. ⇒ ок. 1893), Анна Феодоровна (2 г. ⇒ ок. 1893),
#   **Дарія Николаевна (5 л. ⇒ ок. 1890)** и Стефанъ Иоанновичъ (3 г. ⇒ ок.
#   1892). Метрики трёх нашлись и сведены: Стефанъ Алексѣевичъ — 1893 № м46,
#   Анна — 1893 г. (6 сентября), Стефанъ Иоанновичъ — 1892 № м59. Даріи нет.
#   У Николая Флоровича (прежде «Феодоровича») корпус знал одну дочь этого
#   поколения — Параскеву, погребённую в 1898 г. десяти с четвертью лет
#   (⇒ ок. 1888); теперь их две.
#
# ⚠ **Правые половины разворотов (лл. 174, 175 … 184) несут только графы
# «Отъ чего умеръ», «Кто исповѣдывалъ» и «Кто совершалъ погребеніе»** — имён
# там нет. Причины смерти заведены вычиткой 26.10.2026: чахотка у Стефаниды,
# понос у Пелагѣи, дифтерит у четверых детей октября–ноября.
#
# ⚠ Вставной посторонний лист: **л. 182 / 182об** — печатный бланк и
# **свидетельство о рождении НКВД СССР**. Из-за него разворот л. 181об
# смотрит на л. 183.
#
# ⚠ Кузины не двора 6 (в записи не заводятся): 17/18 декабря погребена
# «солдатская женка **Елизавета Васильева КУЗИНА**», 29 лет (№ ж38, л. 184об)
# — жена Николая Данилова Кузина, с которой он крестил дочь в феврале этого
# же года; **19 января 1896 г. он венчается вторым браком**. Год сам себя
# проверяет. Плюс двойня Феодора Васильева Кузина, родившаяся 3 декабря и
# погребённая 19 и 28 декабря.
#
# Вычитан в Verso 26.10.2026: 6 записей года, заведённых в DSL.

