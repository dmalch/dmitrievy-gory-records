# ⇒ **Двор 6 писан «Кузиными» уже в 1895 г., и сразу на двух братьях** — на
# два года раньше прежней самой ранней связки «Кузинъ тожи Кекевъ» (1897).
#
# ⚠ Кузины НЕ двора 6 (в записи не заводятся, как и в прочие годы): «Іоаннъ
# Даниловъ … Кузины» + Елена Діонисіева (л. 150об); зап. солдат «Іоаннъ
# Васильевъ Кузинъ» + Матіана Емельянова (л. 151об, восприемник — Пётръ
