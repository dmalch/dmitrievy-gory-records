#             отцом — отставным солдатом Павлом Фокеевым;
#   л. 151  — «солдатскій сынъ **Стефанъ Павловъ КУЗИНЪ**» (с крест. дѣвицей
#             Стефанидой Аѳанасіевой Бурмистровой), и он же снова на **л. 152**
#             (с солдатской женкой Ириной Арсеніевой Люлиной). Корпус знал его
#             с венчания 3 октября 1897 г.;
#   л. 160  — «крестьянскій сынъ **Михаилъ Симеоновъ КИКЕЕВЪ**», ДВАЖДЫ (с
#             крест. дѣвицами Анной Мелитоновой Мирошкиной и Пелагіей
#             Никитиной Юкачевой) — за год до собственного венчания, и опять
#             в современной форме «Кикеевъ»;
#   л. 161  — «крестьянскій сынъ **Симеонъ Іоанновъ КЕКЕВЪ**» (с крест.
#             дѣвицей Маріей Максимовой Ганиной). Корпус знал его с 1897 г.;
#   л. 164  — «крестьянскій сынъ **Косма Романовъ КЕКЕВЪ**» (с крест. дѣвицей
#             Варварой Петровой Рыбкиной). Он венчается 3 октября 1901 г.
