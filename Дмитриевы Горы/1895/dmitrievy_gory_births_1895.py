#
# ⛔ **ОТОЗВАНО 16.09.2026.** Здесь стояло: «писец 1895 г., как и писец 1896 г.,
# пишет фамилию то полностью („Кекевъ“), то коротко („Кекъ“/„Кексъ“)».
