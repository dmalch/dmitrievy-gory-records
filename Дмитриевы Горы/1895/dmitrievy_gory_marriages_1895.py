# Метрическая книга Покровской церкви с. Димитриевы Горы за 1895 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**197**,
# лл. 168–172об (титул — л. 168, записи на лл. 168об–172об). **20 браков**;
# по месяцам: январь 2, февраль 2, апрель 2, сентябрь 1, октябрь 11, ноябрь 2.
#
# **ДВА КЕКЕВСКИХ ВЕНЧАНИЯ, и оба — крупные.**
#
# 🔴 **№ 3 (3 февраля) — венчание Григория Павловича, двор 6.** Оно даёт его
# возраст (18 л. 2 мес ⇒ род. около декабря 1876 г.), его звание («солдатскій
# сынъ» при отце-отставном солдате Павле Фокееве) и **девичью фамилию Иулитты
# Максимовой**, которую корпус знал по 1897 и 1899 гг. только по имени с
# отчеством, — **Терентьева** (вычитка 26.10.2026; прежде «Мерситьева»). Невеста —
# из **деревни Муратова прихода села Санчуръ**.
#
# 🔴🔴 **№ 20 (12 ноября) — венчание Андрея Иоанновича старшего, и он ВДОВЕЦ.**
# Корпус знал эту пару с 1903 г. (крещение дочери Александры) и вывел из
# 1903–1904 гг., что Наталия Евфимиева — его жена, а он умер 7 марта 1904 г.
# сорока одного года. Здесь — само венчание: ему **33 года, вторым браком**,
# ей **26, первым**, и она «**солдатская дочь**», фамилия **Пѣтухова** (вычитка
# 26.10.2026; прежде «Потухова»).
# ⇒ **У Андрея Иоанновича была первая жена**, и она умерла до ноября 1895 г.
# Часть третья этого же года хоронит 26/27 июня «крестьянскую жену **Стефаниду
# Георгіеву КЕКЕВУ**, 31 года», а 29/30 июля — «дочь Андрея Іоаннова Кекева
# **Пелагію**» одиннадцати месяцев.
#
# ✅✅ **ПЕРВАЯ ЖЕНА НАЗВАНА — В 1894 ГОДУ (найдено 05.09.2026).** «Крестьянинъ
# Андрей Іоанновъ Кекевъ и жена его **Стефанида Георгіева**» крестят дочь
# Пелагію 21 сентября 1894 г. (ч. 1 1894 г., № ж40, л. 124об). Отождествление
# перестало быть гипотезой; та же Пелагия и погребена в июле 1895 г. Ушёл
# вместе с гипотезой и довод «смерть в родах»: он стоял на чтении «месяца от
# роду», а в скане «11 мѣс». См. ч. 3.
#
# ⚠ **Поручителей у брака № 20 в деле НЕТ**: они стояли бы на л. 173, а там
# печатный титул части третьей. Та же беда, что с браками № 17–19 в 1899 г.
#
# 🔴 **Поручитель по невесте в браке № 3 — «крестьянинъ Алексѣй Ѳокинъ Кекевъ»**
# («Кекъ» снято 16.09.2026), и до 05.09.2026 это была самая ранняя метрическая
# запись главы двора 3; теперь её обгоняют 1894 год, где 6 марта он хоронит дочь
# Анисію 13 л. 3 мѣс. (ч. 3 1894 г., № ж26, л. 139об), и метрики 1880 и 1887 гг. До августа 2026 г. Алексей Фокин был
# известен только по переписи 1897 г. (53 года, четыре сына). Он — родной
# брат Павла Фокеева, то есть дядя жениха.
#
# Вычитан в Verso 26.10.2026: 2 записи года, заведённых в DSL.

