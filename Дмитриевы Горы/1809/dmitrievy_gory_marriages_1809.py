                          # поручители были: **Алексѣй Антоновъ, Ѳедоръ Харитоновъ** и Родіонъ Кондратьевъ»
                          # (сверено при 8×). Венчаны «крестьянской жены Анны Ивановой сынъ **Семіонъ**» и
