from corpus.statuses import SHEPELEV_PEASANT
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import CONSUMPTION, NATURAL
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1834 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 572, лл. 405–407об** (кадры альбома 13–16).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 30 погребений (14 м / 16 ж).** Проверка — итоговая
# ведомость причта на л. 408: «умершихъ мужеска 14, женска 16, обоего пола 30». **ТРИ
# записи из 30** ниже.
#
# 🩺 **САМЫЙ ЗДОРОВЫЙ ГОД ПРОХОДА, И ЭТО ВИДНО ЦИФРОЙ.** 30 погребений против 76 рождений;
# ведомость расписывает умерших мужеска пола по возрастам и даёт «**ниже году — 5**» из 14.
# Для сравнения: 1836 г. — 71 погребение и 23 младенца, 1837 г. — 74 и 24, 1839 г. — 86.
# Ни одного месяца сплошного мора: за апрѣль–май умерло трое, за весь іюль — двое.
#
# ⚠ **И причт это подчёркивает сам**: «Въ семъ 1834-мъ году **ненатуральною смертію
# умершихъ никого не случилось**. Села Димитріевыхъ горъ Священникъ Михаилъ Экземплярскій
# руку приложилъ» (л. 408). ⚠⚠ Но в самой части третьей стоит **№ 14 м, «отъ паденія»**
# (ниже) — то есть ведомость и записи расходятся. Расхождение источника с самим собою;
# обе строки сверены, править нечего.
#
# ⚠ Дат погребения эта форма не пишет: одна дата на запись, и это **дата смерти**.
#
# 🔴 **Погребений рода в году нет** — ни братьев Ѳедоровыхъ, ни их жён и детей, ни вдовы
# Ѳедоры Антоновой (68 лет по ревизии этого же года; она доживёт до мая 1839 г.).
#
# Имена сверены кропом при 2.1×.
# Вычитано в Verso 09.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1834 = death_records(
    "ГАВО", "556", "106", "572", "Дмитриевы Горы", "Покровская",
    1834,
    *page("405об",
          *death_month(Month.JUNE,
                       # ⚠ **ЕЩЁ ОДИН АНТОНОВЪ — И ОН ПОКАЗЫВАЕТ, КАКОВА ЭТА ВЕТВЬ.** «Тогожъ села и вотчины
                       # крестьянинъ **Ѳеофанъ Антоновъ**, 36, отъ чахотки» ⇒ род. ок. 1798 г. Корпус знает в
                       # приходе Михайла, Ѳеодора, Наталью, Іосифа, Іону, Евѳима и солдатку Ѳеодору Антоновыхъ
                       # — детей **Антона Петрова** (венчание 1837 г. называет его прямо). Ѳеофанъ по возрасту
                       # им ровесник. 🔴 Заведён затем, что отчество «Антоновъ» в этом селе **не указывает на
                       # наш двор**: наш Антонъ Ѳедоровъ (ок. 1796) в 1834 г. жив и записан в ревизии, а его
                       # дети — Осипъ, Петръ, Андрей, Максимъ и Прасковья
                       death(3, Gender.MALE, 6,
                             deceased=person("Ѳеофанъ", "Антоновъ", status=SHEPELEV_PEASANT),
                             age=36,
                             cause_of_death=CONSUMPTION),
                       ),
          ),
    *page("407об",
          *death_month(Month.DECEMBER,
                       # ⓘ **САМЫЙ СТАРЫЙ ЧЕЛОВЕК, КОТОРОГО ХОРОНИТ ПРОХОД.** «Тогожъ села и вотчины
                       # крестьянинъ **Алексѣй Григорьевъ**, 82, натуральная» ⇒ род. ок. 1752 г., то есть
                       # застал ещё **третью ревизию**. Заведён как мера того, что этот приход считает
                       # долголетием: в возрастной ведомости года он стоит один в строке «82», следующий — 69.
                       # ⚠ Возраст восьмидесятилетнего — round number по определению; той же осторожности
                       # требует «80» у **Ѳедоры Антоновой** в 1839 г.
                       death(12, Gender.MALE, 11,
                             deceased=person("Алексѣй", "Григорьевъ", status=SHEPELEV_PEASANT),
                             age=82,
                             cause_of_death=NATURAL),
                       # ⚠⚠ **ЗАПИСЬ, КОТОРОЙ ПРОТИВОРЕЧИТ ИТОГОВАЯ ВЕДОМОСТЬ ТОЙ ЖЕ КНИГИ.** «Тогожъ села и
                       # вотчины крестьянина **Егора Филатова** сынъ, отрокъ **Никита**, 17, **отъ паденія**».
                       # А на л. 408, восемью строками ниже последней записи, причт свидетельствует: «Въ семъ
                       # 1834-мъ году **ненатуральною смертію умершихъ никого не случилось**». ⇒ либо падение
                       # сочли смертью естественной, либо сводку писали не глядя в часть третью. **Расхождение
                       # источника с самим собою, а не ошибка чтения** — обе строки сверены. 🔴 Практический
                       # вывод: **итоговая ведомость надёжна для СЧЁТА и не надёжна для КАЧЕСТВА**. Числа её
                       # сошлись с чтением по всем трём частям всех четырёх прочитанных лет; её оценочные
                       # фразы — нет. ⓘ Единственная насильственная смерть года; в 1837 г. их тоже одна —
                       # утонувший Егоръ Макаровъ
                       death(14, Gender.MALE, 19,
                             deceased=person("Никита", status="крестьянский сын отрок вотчины гг. Шепелевых"),
                             age=17,
                             relatives=[relative(person("Егоръ", "Филатовъ", status=SHEPELEV_PEASANT), Relationship.FATHER)],
                             cause_of_death="от падения"),
                       ),
          ),
    defaults=DEFAULTS,
)
