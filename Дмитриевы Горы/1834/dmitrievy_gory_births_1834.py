# ⚠⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 393–408**, приходъ
# **№ 19**. Титул на л. 393: «Подана Генваря 11-го дня 1835-го года. Книга, данная изъ
# Муромскаго Духовнаго Правленія… на 1834 годъ. **Часть первая о раждающихся**» — и первые
# записи стоят на том же листе, как в 1836 и 1837 гг. Форма та же: три-четыре графы, даты
# прописью, месяц строкой-заголовком, **записи по ОБЕИМ сторонам листа**.
#
# ✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ: 76 записей о рождении (38 м / 38 ж).** Проверка — итоговая
# ведомость причта на л. 408: «родившихся мужеска 38, женска 38, обоего пола 76;
# **незаконнорожденныхъ 4**; изъ Дворянской фамиліи не имѣется; раскольниковъ нѣтъ».
# Сошлась и по двум другим частям (29 венчаний, 30 погребений). Ниже — **восемь из 76**.
#
# 🔴🔴🔴 **ЭТОТ ГОД — ЛУЧШИЙ УРОК ПРОХОДА: РЕВИЗИЯ И МЕТРИКА ЛОВЯТ РАЗНЫХ ДЕТЕЙ.**
# 8-я ревизия по этому селу подана **1 апреля 1834 г.** и даёт у Ѳоки Ѳедорова одну дочь
# Ѳедосью. А 7 мая, **через пять недель после сказки**, у него родился сын **Николай**
# (№ 12 м ниже) — и в ревизию он попасть не мог, а до РС-9 1850 г. не дожил. ⇒ ребёнок,
# которого корпус не знал бы никогда, если бы читал только ревизии.
#
# ⓘ Причт тот же: священники **Тихонъ** и **Михаилъ Ивановы Экземплярскіе**, діаконъ
# **Яковъ Звѣревъ**, дьячекъ **Василій Лаврентьевъ Горскій**, пономарь **Михаилъ Егоровъ**.
# Дважды крестил приезжий — «села Санчуръ Священникъ **Іоаннъ Доброградовъ**».
#
# 🩺 **Год необычайно здоровый.** 30 погребений против 76 рождений, и младенцев до года
# умерло **пятеро** (ведомость л. 408) — против 23–24 в 1836 и 1837 гг. Самый благополучный
# год из четырёх прочитанных в ф. 556.
#
# Имена сверены кропом при 2.1×, ключевые — при 4.2×.
