# Ревизская сказка 8-й ревизии, 1834 г., с. Дмитриевы Горы.
# **ГАВО ф. 301 оп. 5 д. 485, л. 128об** (скан ЭЧЗ 0130), сказка от 1 апреля 1834 г.
#
# Дело — «Ревизские сказки 8-ой ревизии помещичьих крестьян Меленковского уезда»
# (без литер в заголовке). Раздел села — сканы **0105–0178**; порядок селений в деле:
# Шиморское (л.16об) → Казнево (л.56об) → Санчуры (л.96об) → **Дмитриевы Горы** →
# Урваново → … → Мотмос, Песочная, Черная → Железницкий завод.
#
# 🔴 **ЭТО ВОСЬМОЕ КОЛЕНО ЛИНИИ АННЫ.** Двор 49 — тот же, что № 45 ревизии 1850 г. и
# № 42 ревизии 1858 г.: соседний двор 50 «Данила Максимовъ» стоит в 1850 г. под № 46,
# то есть порядок дворов между ревизиями сохранён со сдвигом на 4.
#
# ✅ **ВСЕ ВОЗРАСТЫ СХОДЯТСЯ С РЕВИЗИЕЙ 1850 г. БЕЗ ЕДИНОГО ИСКЛЮЧЕНИЯ**: Антонъ 38→54,
# Игнатъ 36→52, Ѳока 32 (умеръ 1847), Осипъ 15 (рекрутъ 1840), Петръ 12→28, Андрей 8→24,
# Максимъ 4→20, Фролъ 4→20, Ѳедоръ полгода→16½, Елена 38→54.
#
# Прочитано один раз при 3×; скан этого дела заметно чище, чем 1858 г.
# Вычитано в Verso 09.10.2026.

census = census_records(
    "ГАВО",
    "301",
    "5",
    "485",
    "Дмитриевы Горы",
    1834,
    *page("128об",
          household("49",
                    member(1, person("Антонъ", "Федоровъ"), CensusRole.HEAD, age=38, previous_age=20),
                    # 🔴🔴🔴 «Антона Ѳедорова МАТЬ» — вдова Ѳедора, родоначальника двора; род. ок. 1766. Её
                    # отчество АНТОНОВА объясняет, почему старший внук назван Антономъ. Восьмое колено линии
                    # Анны
                    member(2, person("Федора", "Антонова"), CensusRole.MOTHER, ref_member=1, age=68),
                    # «Егоже сестра» — ДВОЮРОДНАЯ (09.10.2026): это «Татьяна, Василья Харитонова дочь, 25»
                    # ревизии 1816 г. того же двора — род. ок. 1791 по обеим сказкам, и родной сестры того
                    # же года там нет. Писец дал ей отчество братьев. Незамужняя «Татьяна Васильева,
                    # дѣвка» — кума с Ѳокой 1817 № 28 и 1821 № 55 и у Антона 1826 № 50; замужняя
                    # «Татьяна Ѳедорова, женка» 1818–1824 гг. — другая. Отец — скрытый член 19
                    member(3, person("Татьяна", "Федорова"), CensusRole.SISTER, ref_member=1, age=43,
                           parent_member=19),
                    # в 1850 г. «Елена Васильева, 54» — сходится
                    member(4, person("Елена"), CensusRole.WIFE, ref_member=1, age=38),
                    member(5, person("Праскева"), CensusRole.DAUGHTER, ref_member=1, age=10),
                    # в 1850 г. «15, отданъ въ рекруты въ 1840»; его сынъ Макаръ растёт в дворе деда (ИР
                    # 1855, двор 21)
                    member(6, person("Осипъ"), CensusRole.SON, ref_member=1, age=15),
                    # в 1850 г. 12 → 28
                    member(7, person("Петръ"), CensusRole.SON, ref_member=1, age=12,
                           comment="по прошлой (7-й) ревизии новорожденный"),
                    # в 1850 г. 8 → 24; отданъ въ рекруты въ 1853 г. (РС 1858)
                    member(8, person("Андрей"), CensusRole.SON, ref_member=1, age=8,
                           comment="по прошлой (7-й) ревизии новорожденный"),
                    # в 1850 г. 4 → 20. Мужъ Ѳедоры Петровой, пара МК 1859 и 1869 гг.
                    member(9, person("Максимъ"), CensusRole.SON, ref_member=1, age=4,
                           comment="по прошлой (7-й) ревизии новорожденный"),
                    # 🔴 «Антона Ѳедорова братъ». ПРЯМАЯ ЛИНИЯ АННЫ идёт НЕ через него, а через третьего брата
                    # Ѳоку — см. families/Кикеевы.md
                    member(10, person("Игнатъ", "Федоровъ"), CensusRole.BROTHER, ref_member=1,
                           age=36, previous_age=18),
                    # в 1850 г. «Авдотья Иванова»; к 1855 г. Игнатій уже вдовъ
                    member(11, person("Авдотья"), CensusRole.WIFE, ref_member=10, age=33),
                    member(12, person("Афимья"), CensusRole.DAUGHTER, ref_member=10, age=14),
                    member(13, person("Екатерина"), CensusRole.DAUGHTER, ref_member=10, age=7),
                    # в 1850 г. 4 → 20; «Игнатовъ сынъ» — как в РС 1850 и 1858 гг.
                    member(14, person("Фролъ"), CensusRole.SON, ref_member=10, age=4),
                    # «новорожденный» ⇒ род. ок. середины 1833 г.; в 1850 г. ½ → 16½, погребён 1909 в 76
                    # л. Хозяин двора 4 переписи 1897 г.
                    member(15, person("Федоръ"), CensusRole.SON, ref_member=10, age="полгода"),
                    # 🔴🔴🔴 «Антона Ѳедорова вторый братъ». СЕДЬМОЕ КОЛЕНО ЛИНИИ АННЫ: его сын Алексій (род. ок.
                    # 1845, здесь ещё не родился) — хозяин двора 3 переписи 1897 г. Умеръ въ 1847 г. (РС-9
                    # 1850)
                    member(16, person("Фока", "Федоровъ"), CensusRole.BROTHER, ref_member=1,
                           age=32, previous_age=14),
                    # в 1850 г. «Марья Семенова»; в ИР 1855 г. вдова, 51 год, глава двора 22
                    member(17, person("Марья"), CensusRole.WIFE, ref_member=16, age=31),
                    # 🔴 «Ѳедосья Ѳокина» МК 1859 г., жена Сильвестра Алексѣева; в ИР 1855 г. ей 26 при 2 годах
                    # здесь — расхождение в три года
                    member(18, person("Федосья"), CensusRole.DAUGHTER, ref_member=16, age=2),
                    # В сказке его нет: дядя братьев, умеръ 22.06.1812 (МК 1812 ч. 3 № 8). Восстановлен
                    # отцом Татьяны (чл. 3) по ревизии 1816 г., где она «Василья Харитонова дочь».
                    # ref_member не ставится: у скрытого родителя он назвал бы мать его детей
                    member(19, person("Василій", "Харитоновъ"), CensusRole.UNCLE, hidden=True),
                    ),
          ),
    record_day=1,
    record_month=Month.APRIL,
    prev_revision_year=1816,
    defaults=RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                            status_female=SHEPELEV_PEASANT_FEMALE),
)
