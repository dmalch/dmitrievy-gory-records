# «О бракосочетавшихся». **ГАВО ф. 556 оп. 106 д. 378, лл. 789–791об** (кадры альбома
# 724–727).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 16 венчаній**, ведомость (л. 797) пишет
# «бракосочетавшихся лицъ 32, супружествъ **16**» — сходится до единицы.
#
# 🔴🔴🔴 **№ 12 ЛОМАЕТ ПРАВИЛО, ВЫВЕДЕННОЕ ИЗ 1820 ГОДА.** Поручителем здесь стоит
# **Ѳока Ѳедоровъ** — за **два года** до своего венчанія (27 августа 1820 г.,
# 1820 ч. 2 № 1). ⛔ Утверждение 1820 года «в этом приходе холостой крестьянскій сынъ у
# купели не стоит, и отсутствие человека в части первой само по себе датирует его
# холостым» **уточнено**: холостой не стоит **кумомъ**, но **поручителем стоит**.
# ⇒ Свод по Ѳокѣ теперь такой: поручитель 1818 (холост) → нет нигде в 1819 и 1820 до
# свадьбы → венчанъ 27 августа 1820 → поручитель 5 октября и **кумъ** 16 ноября 1821.
# ⇒ **Кумовство маркирует женатого; поручительство — нет.**
# ⛔⛔ **И ЭТО ОТОЗВАНО ЦЕЛИКОМ 13.09.2026 ПО ПРОЧТЕНИИ 1817 ГОДА.** 1817 год дважды
# называет кумомъ «**крестьянскаго сына Ѳоку Ѳедорова**» (ч. 1 №№ 28 и 56) — холостой
# стоит и у купели. ⇒ **роль не маркирует ничего; маркирует ТИТУЛ**: «крестьянинъ» (свой
# двор, женат) против «крестьянскій сынъ» (в отцовском дворе). Ѳока — «крестьянскій сынъ»
# в 1817-м и «крестьянинъ» с 1821-го; Игнатій — «сынъ вдовы» женихом в генварѣ 1817 г. и
# «крестьянинъ» кумомъ в ноябрѣ того же года.
# ✅ **А венчаніе Игнатья найдено: 17 генваря 1817 г.** (1817 ч. 2 № 2) ⇒ вывод «1816 г.
# или раньше» **перелетел цель на год** и отозван.
#
# 🚫 **ЖЕНИХАМИ НИ ѲОКИ, НИ АНТОНА, НИ ИГНАТЬЯ НЕТ** — 16 женихов разобраны поимённо.
#
# ⓘ Гнёзда: 13 генваря (№№ 1–3), 24 апрѣля (№№ 4–5), 6 и 10 мая (№№ 6–7), 4–21 октября
# (№№ 8–15), 3 ноября (№ 16). Поручителей чаще трое.
# ⓘ **Три невесты из Тамбовской губерніи Елатомской округи** (№№ 1, 2 — деревня Ешиновъ),
# и поручителями там стоят **елатомскіе однодворцы**; № 3 выдаёт крестьянскую вдову за
# человека из **Нижегородской губерніи Ардатовской округи** — то есть в баташевскую
# заводскую вотчину. ⇒ брачный круг прихода шире, чем в 1820-х.
# ⚠ **Вдовы Харитоновы.** № 6 женит Ивана Евсевьева на **вдовѣ Дарьѣ Харитоновой** (оба
# вторымъ бракомъ), а 1820 ч. 2 № 4 венчает сына **вдовы Ѳеклы Харитоновой**. Отчество
# то же, что у отца братьев (**Ѳедоръ Харитоновъ** по ревизиям) — зацепка на его сестёр,
# но не доказательство.
#
# ✅ Вычитано по сканам в Verso 02.10.2026.
