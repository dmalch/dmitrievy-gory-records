                          # друга — как и в 1884 г., где он поручитель у **своего** брата Николая. Второй
                          # поручитель по жениху — «Максимъ Тимофѣевъ», к роду не ведёт. ⚠ Отчество жениха
                          # сверено тестом 1884 года при 16×: после первой буквы высокая петля «л», выносного вниз
                          # нет ⇒ **Флоровъ**, не Ѳедоровъ
