from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import FEVER, PLEURISY
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1882 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**196**, л. 121 (титул),
# записи лл. 121об–132об. **ДВЕ записи.**
#
# ⚠ **Форма ч. 3 1882 г. — «КОПІЯ СЪ МЕТРИЧЕСКОЙ КНИГИ НА 1882»** (как в 1883, 1884,
# 1886 и 1887 гг.), возраст в ДВУХ колонках (мужеска / женска), **«Отъ чего умеръ» — на
# ОБОРОТЕ** ⇒ ч. 3 читается по одним оборотам, recto имён не несёт.
#
# ⚠⚠ **ВОЗРАСТНАЯ КОНВЕНЦИЯ ч. 3 1882 г. — УСТАНОВЛЕНА ИЗНУТРИ ГОДА, ДВАЖДЫ.**
# Единица измерения пишется почти всегда («2 недѣли», «3 мѣс.», «4 дня»), голое число —
# **годы**, голое «½» — **полгода**. Оба правила доказаны записями, у которых рождение
# и погребение лежат в одной книге:
# * **голое число = ГОДЫ.** «Матвѣя Иванова дочь **Устинья**», 3½ (л. 121об, 2/4
#   февраля, дер. Кононово). Будь это мѣсяцы, она родилась бы в октябре 1881 г. — но
#   ч. 1 крестит сына того же Матвѣя Иванова 23 марта 1882 г., пятью месяцами позже.
#   Невозможно ⇒ **годы**.
# * **голое «½» = ПОЛГОДА.** «Дьячка Петра Покровскаго дочь **Марья**», ½ (л. 125об,
#   7/8 июля). Её крещение — ч. 1, **16 января 1882 г.** (л. 92об) ⇒ 5 мѣс. 21 дн.
#   Полгода, а не полмесяца.
# Ср. 1886 г., где голое «3½» у младенца значило МѢСЯЦЫ: конвенция не переносится через
# год (правило 3 regional-rules), и здесь она взята из самой книги.
#
# ⛔ **МАКСИМЪ КАРПОВЪ — НЕ КИКЕВЪ, А КОЛТЕВЪ** (№ м37, вычитка 19.10.2026). Пятьдесят
# восьми лет, «отъ горячки», с фамилией при имени — но фамилия **Колтевъ**, и в род
# Кекевыхъ он не входит. Вопрос, не он ли отец корпусного maksim_karpovich (дети
# 1871–1880, фамилии нет), открыт.
#
# 🔴 **АЛЕКСѢЙ СЕМЕНОВЪ ЗАЛЕТИНЪ** (№ ж49; прежде читано «Аникей Семеновъ Земсковъ») —
# отец Марьи, крещённой четырьмя месяцами раньше (ч. 1, № ж44): девочка одна, сведено
# 19.10.2026. Вычитка прочла фамилию и в метрике, так что «погребение назвало то, что
# метрика скрыла» больше не верно — обе записи пишут его Залетинымъ.
#
# ⚠ **НЕ ЗАВЕДЕНЫ (голое отчество без второго сигнала) — см. `../ARCHIVES.md` § 1882:**
# «крестьянина **Григорія Ѳедорова** сынъ млад. **Андрей**», 4½ мѣс. (3/5 декабря,
# л. 131об) — второе появление после 1883 г., фамилии по-прежнему нет; и трое **Ѳокиныхъ
# ДЕРЕВНИ КОНОНОВОЙ**, среди них «отданнаго въ рекруты крестьянина **Филиппа Ѳокина**
# сынъ **Ѳлоръ**», 4½ мѣс. (25/27 декабря, л. 132об).
#
# Вычитан в Verso 19.10.2026: две записи года, заведённых в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1882 = death_records(
    "ГАВО", "590", "12", "196", "Дмитриевы Горы", "Покровская",
    1882,
    *page("129об",
          *death_month(Month.OCTOBER,
                       # ⛔ **«КИКЕВЪ» СНЯТ ВЫЧИТКОЙ 19.10.2026: «Того же села крестьянинъ Максимъ Карповъ
                       # КОЛТЕВЪ»**, 58 л., «отъ горячки». Род. ок. 1824 г. Отчество «Карповъ» сверено при 20×
                       # и ни на «Антоновъ», ни на «Ѳедоровъ» не похоже ⇒ **это не Максимъ Антоновичъ двора 5**
                       # (его дети и после 1882 г. зовутся «Максимовыми»). С «Кикевымъ» уходят и оба вывода
                       # прежнего чтения: Максимъ Карповъ — не «новое лицо рода», и **самым ранним «Кикевымъ»
                       # метрических книг прохода 1882 год больше не является**; «Катерина Кикева» 1883 г. (ч. 1
                       # № ж55) вычиткой тоже снята («Катерина Алексѣева»), и без ять это написание теперь
                       # впервые стоит в 1886 г. (Иванъ Михайловъ Кикевъ, восприемникъ). ❓ Не он ли отец
                       # корпусного maksim_karpovich — детей 1871–1880 гг., у которых фамилии нет: МК 1872 г.
                       # (ф. 590 оп. 5 д. 45, ч. 1 № м29) даёт Максима Карпова отцом 18 июня 1872 г. Не сведено
                       death(37, Gender.MALE, 19, 21,
                             deceased=person("Максимъ", "Карповъ", last_name_orig="Колтевъ"),
                             age=58,
                             cause_of_death=FEVER),
                       ),
          ),
    *page("130об",
          *death_month(Month.NOVEMBER,
                       # 🔴🔴 **ДОЧЬ АЛЕКСѢЯ СЕМЕНОВА ЗАЛЕТИНА.** «Села Димитріевыхъ Горъ крестьянина **Алексѣя
                       # Семенова Залетина** дочь **Марья**», 4½ мѣс., «отъ колотья» (вычитка 19.10.2026;
                       # прежде «Аникея Семенова Земскова»). **Родилась и умерла внутри одной книги**: ч. 1,
                       # № ж44, л. 104об — 17/19 июля 1882 г., отец «Алексѣй Семеновъ Залетинъ», мать **Настасья
                       # Спиридонова**. 17 июля → 25 ноября = **4 мѣс. 8 дн.** ⇒ имя, отец и возраст сходятся:
                       # ребёнок один. Сведено 19.10.2026 (marija_alekseevna_zaletina_1882, отец —
                       # aleksej_semenovich_zaletin). Залетины — те же Залепины книг 1903–1914 гг.; к Земсковымъ
                       # (уличная фамилия Феодоровичей двора 4) и к Акиллинамъ запись отношения не имеет
                       death(49, Gender.FEMALE, 25, 26,
                             deceased=person("Марья"), age="4 мес 2 нед",
                             relatives=[relative(person("Алексѣй", "Семеновъ", last_name_orig="Залетинъ"), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    defaults=DEFAULTS,
)
