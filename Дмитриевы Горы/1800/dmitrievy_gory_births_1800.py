from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, birth, birth_month, birth_records, page,
                          person)

# Метрическая тетрадь Покровской церкви с. Димитріевы Горы за 1800 г., часть первая
# «О родившихся». **ГАВО ф. 556 оп. 111 д. 194, лл. 102–103** — дело в ЭЧЗ не
# выложено, получено копиями по заказу № 4594 (05.10.2026), альбом «Дмитриевы Горы
# 1800 (ГАВО 556-111-194)».
#
# ⚠⚠ **КРАТКИЙ РЕЕСТР, как 1798, 1799 и 1802 гг.**: одна строка на запись — «[отецъ]
# сынъ/дочь [имя], воспріемникъ былъ [имя]»; **матери не названы, воспріемникъ один**.
# Нумерация сквозная, без разделения по полу. Тетрадь № 24 Муромскаго Духовнаго
# Правленія; священникъ **Стефанъ Ивановъ**.
#
# **Состав:** ч. 1 — лл. 102–103 (**55** записей); ч. 2 — л. 103 (**14 венчаній**); ч. 3 —
# л. 103об (**12** погребеній); **табель — л. 103об**: «родившихся мужеска 32, женска 23,
# обоего 55; бракосочетавшихся 28 лицъ, 14 супружествъ; умершихъ мужеска 6, женска 6,
# обоего 12» — ✅ **сходится по всем трём частям** (прочитано целиком 05.10.2026).
#
# 🏆 Род в году назван трижды, все — ниже: **Василій Харитоновъ** кумъ 17 августа (№ 37) и
# отец 30 сентября (№ 45 — его сынъ Григорій), **Ѳедоръ Харитоновъ** кумъ 25 сентября (№ 43).
# ⓘ Не взято, но к сведению: № 44 — «Семена Ефимова дочь **Ѳекла**, воспріемница была
# **Агафья Ефимова**» (24/27 сентября). Та же кума стоит у детей Семена и Евдокіи
# Харитоновой в 1803, 1806 и 1809 гг., но Харитоновых в записи нет, а мать реестр не пишет.
# ⓘ Часть третья хоронит «девку **Февронію Харитонову**, 14 лѣтъ» (22 сентября) — она из
# **экономической деревни Конновки**, не из села: другой род.
# ⛔ **Вопрос 69**: Марій в году нет вовсе; Семіонъ Васильевъ ни отцом, ни женихомъ не назван.
#
# ✅ Вычитано по сканам в Verso 05.10.2026.
# Первое чтение: реестр прочитан по полустраницам при ~2×, входящие сюда — кропом при 3×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_births_1800 = birth_records(
    "ГАВО", "556", "111", "194", "Дмитриевы Горы", "Покровская",
    1800,
    *page("102об",
          *birth_month(Month.AUGUST,
                       # «Василія Кирилова сынъ **Алексѣй**, воспріемникъ былъ **Василій Харитоновъ**».
                       # 🔗 Тот же Василій Кириловъ получит от Василія Харитонова кумовство и в 1803 г.
                       # (ч. 1 м. № 10, сынъ Кононъ) и в 1806 г. (м. № 37)
                       birth(37, Gender.MALE, 14, 17,
                             child=person("Михей"),
                             father=person("Василій", "Кириловъ"),
                             god_parent1=person("Василій", "Харитоновъ")),
                       ),
          *birth_month(Month.SEPTEMBER,
                       # «Наума Дорофѣева сынъ **Иванъ**, воспріемникъ былъ **Ѳедоръ Харитоновъ**» — кумовство
                       # самого Ѳедора, второе после 1799 г. (ч. 1 № 15)
                       birth(43, Gender.MALE, 23, 25,
                             child=person("Иванъ"),
                             father=person("Наумъ", "Дарофѣевъ"),
                             god_parent1=person("Ѳедоръ", "Харитоновъ")),
                       # 🏆🏆 **МЕТРИКА ГРИГОРІЯ, СЫНА ВАСИЛІЯ ХАРИТОНОВА.** «Василія Харитонова сынъ
                       # **Григорій**, воспріемникъ былъ **Николай Тимоѳеевъ**», родился и крещенъ 30
                       # сентября. Прежде его рождение выводилось только из погребенія: «Григорій, сынъ
                       # Василія Харитонова, 6 лѣтъ», † 9 октября 1806 г. (1806 ч. 3 м. № 23) ⇒ «род. ок.
                       # 1800». Теперь дата — 30.09.1800, и погребеніе 1806 г. держит возраст точно (6 лѣтъ
                       # 9 дней). ⇒ Григорій — ребёнокъ **первой** жены (до венчанія с Авдотьей Арефьевой
                       # 17.04.1803), как и Емеліанъ (8 августа 1799 г., 1799 ч. 1 № 30)
                       birth(45, Gender.MALE, 30, 30,
                             child=person("Григорій"),
                             father=person("Василій", "Харитоновъ"),
                             god_parent1=person("Николай", "Тимофѣевъ")),
                       ),
          ),
    defaults=DEFAULTS,
)
