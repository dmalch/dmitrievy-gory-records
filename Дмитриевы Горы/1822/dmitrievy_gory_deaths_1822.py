from corpus.statuses import SHEPELEV_PEASANT, SHEPELEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DIARRHEA

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1822 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 428, лл. 259–264** (кадры альбома 268–273).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 24 м / 28 ж = 52 погребения**, и ведомость (л. 264об)
# пишет ровно «умершихъ мужеска **24**, женска **28**, обоего пола **52**». Её возрастная
# разбивка мужчин — «ниже году 6, 2 — 2, 3 — 3, 4 — 1, 5 — 4, 8 — 1, 24 — 1, 50 — 2,
# 70 — 1, 72 — 1, 73 — 1, 83 — 1, итого **24**» — сходится с прочитанным **построчно**.
# ⓘ Строка «ниже году — 6» включает **нашего Ивана Ѳокина** (м. № 21 ниже).
#
# 🔴🔴🔴 **ГОД, В КОТОРОМ ГРОЗА УБИЛА ВОСЕМЬ ЧЕЛОВЕК.** Ведомость: «Въ семъ 1822-мъ году
# не натуральною смертію умершихъ, **кромѣ неизвѣстныхъ крестьянина и шести женъ,
# убитыхъ громовымъ ударомъ**, и села Дмитріевыхъ горъ… крестьянина **Саввы Кононова**,
# также убитаго громомъ, не имѣлось».
# - **23 іюня** (м. № 19 и ж. №№ 13–18, л. 262): «Неизвѣстныхъ, крестьянина и шесть
#   женщинъ, шедшихъ вмѣстѣ въ городъ Муромъ, убило на дорогѣ громовымъ ударомъ»;
#   мужчинѣ 50 лѣтъ, женщины без возрастов, имён нет ни у кого. Погребены **25 іюня** на
#   отведенном кладбище Дмитріевыхъ горъ «по данному изъ **Меленковскаго Земскаго Суда**
#   вѣдѣнію». ⇒ семь неизвестных прохожих, погибших разом, — **самая крупная разовая
#   потеря за весь проход**, и одна из двух записей за восемь лет, где погребение
#   разрешает светский суд.
# - **4 іюля** (м. № 20, л. 262): «у крестьянина **Савву Кононова**, ѣхавшаго съ работы
#   домой, убило на полѣ громовымъ ударомъ», 24 года, погребенъ 6 іюля тем же порядком.
#   ⇒ он же 8 апрѣля того года крестил сына **Антипа** (ч. 1 № 19): сын родился в
#   апрелѣ, отца не стало в іюлѣ.
# Профилей по этим записям не заводится: шестеро женщин и крестьянинъ безымянны, а Савва
# Кононовъ роду не родня.
#
# 🔴 **ГОД ХОРОНИТ ОДНОГО РЕБЁНКА РОДА** — м. № 21, **Иванъ, сынъ Ѳоки Ѳедорова**,
# родившийся в этой же книге 24 іюня.
#
# ⓘ **Возрастная конвенция 1822 года: голое число = ГОДЫ, месяцы и недели названы
# словом** («10 мѣсяцевъ», «шести недѣль», «2-хъ недѣль», «дву мѣсяцевъ», «полу году»).
# Книга проверяет себя сама — трижды возраст сходится с метрикой того же года день в
# день: **Хрисанѳъ Ивановъ** род. 12 марта, погребенъ «2-хъ недѣль» 26 марта (14 дней);
# **Марина Андреева** род. 26 февраля, погребена «5-ти мѣсяцевъ» 28 іюля; **Агрипина
# Иванова** род. 15 іюня, погребена «2-хъ мѣсяцевъ» 20 августа. ⇒ **писец 1822 года
# точен**, в отличие от 1823-го, округляющего вверх.
#
# ⓘ Графа «Какою болѣзнію» заполнена сплошь и написана **вертикально** одной строкой на
# несколько записей; «Кѣмъ исповѣданы и приобщены» — сплошь «означеннаго села
# Священникомъ Тихономъ Экземплярскимъ».
# ⓘ Часть третья 1822 года начинается **с генваря** (в отличие от 1823-го, где генварских
# погребений нет вовсе).
# 🔗 **Солдатка Анна Ѳедорова** — одна из «зацепок на сестёр» 1824 года — здесь хоронит
# сына **Игнатія** «дву мѣсяцевъ» 11 апрѣля (м. № 14), то есть родила его ок. февраля
# 1822 г. при муже в солдатах. ⚠ Родства с братьями это по-прежнему не доказывает.
# 🔗 **Михайло Ворсонофьевъ** хоронит жену **Евдокію Ильину, 21 года**, 19 августа
# (ж. № 23) — вероятное объяснение расхождения в имени его жены между 1824 и 1826 гг.:
# он овдовел в 1822-м и женился снова.
#
# ✅ Вычитано по сканам в Verso 02.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящая сюда — при 8×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1822 = death_records(
    "ГАВО", "556", "106", "428", "Дмитриевы Горы", "Покровская",
    1822,
    *page("262",
          *death_month(Month.JULY,
                       # 🔴🔴 **ПЯТНАДЦАТЬ ДНЕЙ ЖИЗНИ — И ВСЯ ОНА В ЭТОЙ ЖЕ КНИГЕ.** «Прихода тогожъ села и
                       # означенной вотчины у крестьянина **Ѳоки Ѳедорова** сынъ **Иванъ** по причастіи
                       # Святыхъ таинъ скончался», поносомъ; погребенъ 11 іюля (сверено при 8×). 🔗 Он родился
                       # **24 іюня** того же года (ч. 1 № 34) ⇒ прожил **15 дней**. ⚠ **Графа «Лѣта мужеска»
                       # заполнена, но не читается**: запись сделана мелким письмом в две строки и лежит ниже
                       # разрешения скана (ГАВО ЭЧЗ даёт ~750 px на лист; при 22× слова рассыпаются). Поэтому
                       # возраст здесь **не проставлен**: сам интервал книга задаёт точно, и **ведомость года
                       # относит его к строке «ниже году»**. Читать его нужно по скану большего разрешения,
                       # если он появится. 🔗 **Ѳока хоронит второго первенца подряд**: Иванъ (1822) и Матѳей
                       # (19 іюня – 3 августа 1823) родились почти день в день с разницей в год и оба не
                       # прожили двух месяцев. ⇒ из шести известных детей Ѳоки **четверо умерли младенцами**
                       death(21, Gender.MALE, 9, 11,
                             deceased=person("Иванъ"),
                             relatives=[relative(person("Фока", "Федоровъ"), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    defaults=DEFAULTS,
)
