from corpus.statuses import (SHEPELEV_PEASANT, SHEPELEV_PEASANT_DAUGHTER_GIRL,
                             SHEPELEV_PEASANT_FEMALE, SHEPELEV_PEASANT_SON)
from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1822 г., часть вторая
# «О бракосочетавшихся». **ГАВО ф. 556 оп. 106 д. 428, лл. 256–258об** (кадры альбома
# 265–268).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 17 венчаній**, ведомость (л. 264об) пишет
# «бракосочетавшихся лицъ 34, супружествъ **17**» — сходится до единицы.
#
# 🚫🚫 **ЖЕНИХАМИ НИ ѲОКИ, НИ АНТОНА, НИ ИГНАТЬЯ НЕТ И ЗДЕСЬ** — семнадцать женихов
# разобраны поимённо. ⇒ вместе с частью первой (Игнатій **отец** 25 марта, Ѳока **отец**
# 24 іюня) это ставит венчания **Ѳоки и Игнатья в 1821 г. или раньше**. ⛔ Отозвано
# утверждение 1823 года («обе свадьбы в 1822 г. или раньше»).
# ⛔ **И это, в свой черёд, уточнено 12.09.2026 по прочтении 1821 года:** женихами их нет
# и там (23 венчанія разобраны поимённо) ⇒ **1820 г. или раньше**.
# ✅✅ **А 1820 год дал саму запись:** **27 августа 1820 г.** венчаны «крестьянской вдовы
# Ѳедоры Антоновой сынъ **Ѳока**» и «крестьянская дѣвка **Марья Семенова**», оба первымъ
# бракомъ (1820 ч. 2 № 1). ⇒ **у Игнатья остаётся 1819 г. или раньше.**
# ⛔ И отозвано его основание: **1822-й НЕ последний оцифрованный год** — альбомы прихода
# есть за 1821, 1820, 1819, 1818, 1817, 1816, 1815, 1814, 1813, 1812, 1810–1802 и за
# сдвоенные книги 1798-1799 … 1778-1779. **Следующий год прохода — 1820 (556-106-405)**;
# 1821-й (556-106-416) прочитан.
#
# ⓘ **Поручителей в 1822 году трое, а не двое**, как в 1823–1827 гг.: №№ 1–5, 7, 15–17
# называют три имени, №№ 6, 8–14 — два. ⇒ число поручителей в этом приходе не константа
# и на «незаполненное третье место» опираться нельзя.
# ⓘ Гнёзда венчаній: 15–25 генваря (№№ 1–3), 30 генваря (№ 4), 14 мая (№ 5), 2 іюля
# (№ 6), 2–4 октября (№№ 7–12), 6 и 22 октября (№№ 13–15), 8 ноября (№№ 16–17).
# ⓘ Все семнадцать пар венчаны **«оба первымъ бракомъ»** — ни одного вдовца и ни одной
# вдовы за год.
# ⓘ Формула согласия полнее, чем в поздних годах: «по добровольному **ихъ, родителей и
# Господъ ихъ** согласію» — помещичье разрешение названо прямо (у кононовских казённых
# крестьян, №№ 2 и 5, формула короче: «ихъ и родителей»).
#
# ✅ Вычитано по сканам в Verso 02.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 9–10×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_marriages_1822 = marriage_records(
    "ГАВО", "556", "106", "428", "Дмитриевы Горы", "Покровская",
    1822,
    *page("258",
          *marriage_month(Month.OCTOBER,
                          # 🔴🔴 **АНТОНЪ И ѲОТІЙ ѲЕДОРОВЫ ПОРУЧИТЕЛЯМИ В ОДНОЙ ЗАПИСИ, И ИХ ДВОЕ НА ВСЮ
                          # ЗАПИСЬ.** «При томъ поручители были тогожъ села и вотчины крестьяне: **Антонъ
                          # Ѳедоровъ** и **Ѳотій Ѳедоровъ**» (сверено при 9×). ⛔ **ОТОЗВАНО утверждение 1823
                          # года**, что поручительство Антона 7 февраля 1823 г. — самая ранняя запись о роде:
                          # 1822-й называет его с іюня, а 1821-й — с **20 февраля 1821 г.** (1821 ч. 1 № 20).
                          # ⚡ **ѲОТІЙ ѲЕДОРОВЪ — ЗАЦЕПКА, НО НЕ ДОКАЗАТЕЛЬСТВО.** 1823 год закрыл вопрос
                          # 1825-го о нерасшифрованном «[Ѳо…ій] Ѳедоровѣ» в его пользу; здесь он появляется
                          # **на год раньше** (и ещё раз поручителем 2 іюля, ч. 2 № 6) и **впервые стоит рядом
                          # с Антономъ**. ⓘ Уточнено 1821 годом: Ѳотій назван и там — кумомъ 1 мая 1821 г.
                          # (1821 ч. 1 № 33), но **не рядом с родом**; пара «Антонъ + Ѳотій» встречается
                          # только здесь. Двое мужчин с одним отчеством, одной вотчины, вместе поручителями —
                          # это именно то, чего ждёшь от братьев. ⚠ Но «Ѳедоровъ» — самое частое отчество
                          # прихода (в одном 1822 году названы Петръ Ѳедоровъ дважды в разных дворах, Иванъ
                          # Ѳедоровъ, Кузьма Ѳедоровъ, Емельянъ Ѳедоровъ, Василій Ѳедотовъ), и решить может
                          # только ревизия, называющая сыновей Ѳедора Харитонова поимённо. 🔗 Ѳотій — по
                          # отчеству отец **Филиппа Ѳотіева**, женившегося 28 генваря 1825 г.
                          marriage(14, 6,
                                   groom=person("Михайло", "Васильевъ", status=SHEPELEV_PEASANT_SON),
                                   bride=person("Ирина", "Тимоѳеева", status=SHEPELEV_PEASANT_DAUGHTER_GIRL),
                                   groom_marriage_num=1, bride_marriage_num=1,
                                   witness1=person("Антонъ", "Ѳедоровъ"),
                                   witness2=person("Фотій", "Ѳедоровъ")),
                          ),
          ),
    defaults=DEFAULTS,
)
