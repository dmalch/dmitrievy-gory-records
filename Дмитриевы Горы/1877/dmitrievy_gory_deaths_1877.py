from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DIARRHEA
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, TEMP_OBLIGED_PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1877 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**195**, л. 201 (титул),
# записи лл. 201об–212об. **48 мужских и 53 женских — 101 погребение**
# (в 1878 г. было 84, в 1879 г. — 87). **ОДНА запись.**
#
# ⚠ Форма как в 1878–1879 гг.: **всё на обороте, включая «ОТЪ ЧЕГО УМЕРЪ»**; recto несёт
# только «кто исповѣдывалъ» и «кто совершалъ погребеніе». Ч. 3 читается по оборотам.
# Возраст снова **с единицей**, голое число = годы — проверено доброй дюжиной пар
# «метрика ↔ погребение» внутри года.
#
# ⓘ **Самый смертный из трёх прочитанных лет, и болезни идут тремя волнами**: январь–март
# **коклюшъ**, июнь–сентябрь **поносъ** (в июле умерло 15 человек, из них десять девочек),
# октябрь–декабрь **корь**. Из 101 погребения заметно больше половины — младенцы до года.
#
# 🔴 **ПОЖАР В КОНОНОВЕ 18 ДЕКАБРЯ 1877 г.** — № ж49 и № ж50: «вдовая солдатка **Устинья
# Лукьянова**», 70, и «крестьянская дѣвица **Февронія Васильева**», 10½, обе «**сгорѣвшая
# во время пожара**». Единственное упоминание пожара за три прочитанных года.
#
# ⚠ **НЕ ЗАВЕДЕНЫ:**
#   • № м2 (л. 201об): «временно-обязанный крестьянинъ **Павелъ Андреевъ**», **57**
#     († 13 января) ⇒ род. ок. 1820 г. — Андреевичъ поколением СТАРШЕ Романа (~1852) и
#     Иоанна (~1857); другой Андрей, не их отец по возрасту.
#   • № м22 (л. 206об): «**Наумъ Максимовъ**», **80** († 3 августа) ⇒ род. ок. 1797 г. —
#     самый старший Максимовичъ, какого дал проход.
#   • № м32 (л. 209об): «**Василія Антонова** сынъ млад. **Максимъ**», 2 г. 7½ мѣс. Это
#     Василій Антоновъ **Мирошкинъ** (ч. 1 № ж20 этого года даёт его с женой Ириной
#     Неофитовой) ⇒ Мирошкины подтверждены как род Антоновичей и на 1877 г.
#   • № м37 (л. 209об): «**Сильвестра Емельянова** сынъ млад. **Михаилъ**», 4½ мѣс. —
#     ребёнок, родившийся 7 июля этого года (ч. 1 № м29); старший Сильвестръ на месте.
#   • № ж52 (л. 211об): дочь самого причта — «дьячка **Петра Евграфова Покровскаго** дочь
#     млад. **Надежда**», от кори.
#
# Вычитан в Verso 16.10.2026: одна запись года, заведённая в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1877 = death_records(
    "ГАВО", "590", "12", "195", "Дмитриевы Горы", "Покровская",
    1877,
    *page("207об",
          *death_month(Month.AUGUST,
                       # 🔴🔴🔴 **ДВОР 3 ПОТЕРЯЛ МЛАДЕНЦА, И ИМЕННО ПОЭТОМУ КОРПУС О НЁМ НЕ ЗНАЛ.** «Села
                       # Димитріевыхъ горъ временно-обязаннаго крестьянина **Алексѣя Ѳокина** сынъ младенецъ
                       # **Антонъ**», **1 мѣс.** (сверено при 10×). 🔴 **Это ребёнок, крещённый 5 июля того же
                       # года** (ч. 1 № м27): от 4 июля до 6 августа — 1 мѣс. 2 дн., сходится день в день. ⇒
                       # **метрика и погребение Антонія Алексѣевича сомкнулись внутри одного года**, и старшим
                       # выжившим ребёнком пары остаётся **Сергѣй** (1 июля 1878 г., МК 1878 № м39), которого
                       # корпус и держал за первенца. ⓘ Пара — корпусные **Алексей Фокич Кикевъ** (двор 3
                       # переписи 1897 г.) и **Ксения Емельяновна**; детей у них теперь известно четверо:
                       # **Антоній (1877, † 1 мѣс.)**, Сергѣй (1878), Анисья (1880) и Пётръ (1885). ⚠ Фамилии
                       # при отце здесь нет, как и в ч. 1; тождество опирается на имя жены и на повторяющуюся
                       # пару восприемников (Василій Флоровъ и вдова Анна Емельянова) в 1877 и 1878 гг.
                       death(25, Gender.MALE, 6, 8,
                             deceased=person("Антонъ"), age="1 мес",
                             relatives=[relative(person("Алексѣй", "Ѳокинъ", status=TEMP_OBLIGED_PEASANT_MALE), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    defaults=DEFAULTS,
)
