                          # записям (1883, 1886, 1889, 1891) и по переписи 1897 г.; чтение МК **1879** (№ м46)
                          # дало «Надежда **Ефимова**» и было записано как несведённое разногласие.
                          # **Собственная запись о венчании подтверждает корпус: Димитріева.** ⇒ «Ефимова»
