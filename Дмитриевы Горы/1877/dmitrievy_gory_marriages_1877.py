# Метрическая книга Покровской церкви с. Димитріевы Горы за 1877 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**195**, записи лл. 196об–200об.
# **21 бракъ**: январь 8 (№ 1–8), **октябрь 11** (№ 9–19, из них **девять 2 октября**),
# ноябрь 2 (№ 20–21). С февраля по сентябрь и в декабре — **ни одного**. **ДВЕ записи.**
#
# ⚠⚠ **У ч. 2 1877 г. НЕТ ТИТУЛЬНОГО ЛИСТА**: ч. 1 кончается на л. 195об, л. 196 чист, и
# часть начинается прямо с оборота 196об (см. `../ARCHIVES.md` § «Оговорки по д. 195» —
# одна из пяти безтитульных частей дела).
#
# ⚠ Форма как везде в ч. 2: оборот несёт счётъ, мѣсяцъ и день, жениха, невесту и лѣта
# обоих; **поручители — на RECTO**, сняты выровненной по строке склейкой оборот+лицевая.
# Лѣта — с точностью до месяца.
#
# 🔴🔴🔴 **ЭТОТ ГОД ДАЁТ ВЕНЧАНИЕ ДВОРА 5 — ЗАПИСЬ, КОТОРОЙ У КОРПУСА НЕ БЫЛО НИКОГДА**
# (№ 12, см. ниже), и **закрывает открытый вопрос об Игнатіи Ѳедоровѣ** (№ 16). Обе
# записи — 2 октября, в один день с семью другими венчаниями.
#
# ⚠ **НЕ ЗАВЕДЕНЫ:** № 1 (Николай Петровъ × **Прасковья Максимова**), № 11 (Владиміръ
# Тарасовъ × **Евгенія Максимова**), № 14 (Яковъ Емельяновъ × **Татьяна Максимова**) —
# три Максимовны венчаются в один год, и ни одна не опознаётся (правило 5). № 10 венчает
# **Тихона Семенова × Евфросинію Филиппову** — пару, которая в МК 1879 г. крестит дочь
# Кристину (ч. 1 № ж9). № 5 (16 января): невеста «**секты Австрійскаго священства**» —
# старообрядцы названы в приходе уже в 1877 г., на год раньше, чем отмечено по 1878-му.
#
# Вычитан в Verso 16.10.2026: две записи года, заведённые в DSL; поручители браков № 12 и
# № 16 записаны со сторонами.

