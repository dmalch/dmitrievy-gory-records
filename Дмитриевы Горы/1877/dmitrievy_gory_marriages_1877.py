                          # исправлена. 🔴 **ПОРУЧИТЕЛИ ПО ЖЕНИХѢ — «МИХАИЛЪ МАКСИМОВЪ» И «РОМАНЪ АНДРЕЕВЪ»**
                          # (сняты выровненной склейкой оборот+лицевая). Михаилъ — брат жениха (он же крёстный
