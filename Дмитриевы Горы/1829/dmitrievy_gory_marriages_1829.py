# Метрическая книга Покровской церкви с. Димитріевы Горы за 1829 г., часть вторая
# «О брачившихся». **ГАВО ф. 556 оп. 106 д. 511, лл. 683–685об** (кадры альбома 11–14).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 18 венчаний**, и ведомость (л. 692) пишет
# «бракосочетавшихся лицъ 36, супружествъ **18**» — **сходится до единицы**, как и обе
# другие части этого года.
#
# ⓘ **Форма 1829 года ПОЛНЕЕ, чем в 1830-м**: каждая запись добавляет «и по учиненіи объ
# нихъ въ церкви **указнаго обыска**, которой и вписанъ въ данной для того изъ
# Муромскаго Духовнаго Правленія книгѣ» — то есть прямо ссылается на **обыскную книгу**,
# которой в 1830 г. писец уже не поминает. Если обыскные книги этого прихода где-то
# сохранились, эта формула — указание, что за 1829 г. они велись.
#
# 🔴 **Своих в части нет**: ни один из трёх братьев Ѳедоровыхъ здесь не венчается и не
# поручает — весь их вклад в этот год лежит в частях первой и третьей. Ниже две записи,
# которые год всё же даёт корпусу.
#
# Имена сверены кропом при 3× в сером.
# Вычитано в Verso 06.10.2026.

