from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import PLEURISY
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1880 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**196**, л. 31 (чистый recto),
# записи лл. 31об–45об. **ОДНА запись.**
#
# ⚠ **Форма ч. 3 1880 г.** — возраст в ДВУХ колонках (мужеска / женска), **«Отъ чего
# умеръ» — на ОБОРОТЕ** ⇒ ч. 3 читается по одним оборотам, recto несёт только «кто
# исповѣдывалъ» и «кто совершалъ погребеніе» и имён не даёт.
#
# ⚠⚠ **ЧАСТЬ ТРЕТЬЯ ОБРЫВАЕТСЯ НА НОЯБРЕ — ДЕКАБРЯ В НЕЙ НЕТ.** После ноябрьского итога
# («умершихъ мужескаго пола девятнадцать») сразу стоит «Свидѣтельствовалъ Благочинный»,
# и год кончается на л. 45об; л. 46 — уже титул 1881 года. Декабрьские погребения 1880 г.
# в книге отсутствуют, при том что январь 1881 г. открывается эпидемией оспы в деревне
# Кононовой. **Это дефект дела, а не альбома** — листы идут сплошь, кадры не пропущены.
# Дочитывать по консисторской копии.
#
# ⚠ **ВОЗРАСТНАЯ КОНВЕНЦИЯ ч. 3 1880 г. — ТА ЖЕ, ЧТО В 1881 И 1882 гг.** Единица пишется
# почти всегда («2 недѣли», «3 мѣс.», «10 дней»), **голое число — годы**, голое «½» —
# полгода. Проверено записями, у которых рождение и погребение лежат в одной книге:
# «Евграфа Максимова сынъ Михаилъ», 2 нед. († 19 июля) при крещении 6 июля; «Козьмы
# Максимова дочь Ирина», 2½ мѣс. († 22 июля) при крещении 4 мая; «Григорія Ѳокина сынъ
# Михаилъ», **1 день** († 2 ноября) при крещении 2 ноября; «Козьмы Ѳедорова дочь Марѳа»,
# 3½ мѣс. († 13 октября) при крещении 5 июля.
#
# ⚠ **Эпидемии года**: январь–апрель — коклюшъ и скарлатина; июнь–август — поносъ
# (летняя детская смертность); **сентябрь–ноябрь — оспа**, и ноябрь уносит девятнадцать
# мужских душ, больше всего в деревне Кононовой. Январь 1881 г. продолжает ту же оспу.
#
# ⚠ **НЕ ЗАВЕДЕНО (голое отчество без второго сигнала) — см. `../ARCHIVES.md` § 1880:**
# «Того же села крестьянина **Филиппа Ѳокина** дочь млад. **Настасья**», 3 недѣли
# (№ ж7, 29/31 марта, л. 32об). Селение прочитано по цепочке вверх и это **село**, а не
# Кононово; между тем кононовскій Филиппъ Ѳокинъ венчался **11 февраля 1880 г.**
# (ч. 2 брак № 3) и трёхнедельного ребёнка в марте иметь не мог. ⇒ **Филипповъ Ѳокиныхъ
# двое**, как и Василіевъ; разбор в ARCHIVES.
#
# Вычитан в Verso 16.10.2026: одна запись года, заведённая в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1880 = death_records(
    "ГАВО", "590", "12", "196", "Дмитриевы Горы", "Покровская",
    1880,
    *page("32об",
          *death_month(Month.APRIL,
                       # 🔴 **ДОЧЬ МАКСИМА КАРПОВА, О КОТОРОЙ КОРПУС НЕ ЗНАЛ.** «Села Димитріевыхъ горъ
                       # крестьянина **Максима Карпова** дочь младенецъ **Агафья**», 2 г., «отъ колотья»
                       # (сверено при 11×). ⇒ род. ок. 1878 г. ✅ **Второй сигнал — тот же год**: ровно через
                       # месяц, 3 мая 1880 г., у него рождается дочь **Пелагея**, и та запись впервые называет
                       # жену — **Анну Васильеву** (ч. 1 № ж28). Мать была беременна, когда умерла Агафья. 🔴
                       # Сам Максимъ Карповъ умрёт **в 1882 г., 58 лет** (ч. 3 № м37), и та запись —
                       # единственная, где он назван с фамилией: «Максимъ Карповъ **Кикевъ**». Отчество
                       # «Карповъ» в приходе больше не встречается, и оно же, по разбору 1882 г.,
                       # **разъединяет** его с Максимомъ Антоновичемъ двора 5. ⚠ Фамилия здесь не проставлена;
                       # родство девочки приписано только к названному отцу, в род она не заведена
                       death(8, Gender.FEMALE, 3, 5,
                             deceased=person("Агафья"), age=2,
                             relatives=[relative(person("Максимъ", "Карповъ"), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    defaults=DEFAULTS,
)
