# 🔴 **ЗАЦЕПКА, КОТОРУЮ ЭТОТ БРАК ОТКРЫВАЕТ, А 1886 ГОД НЕ ЗАКРЫВАЕТ.** Через семь
# недель после свадьбы, 8 января 1886 г., в приходе хоронят «**Флора Антонова**», 72 л.
