# давно. **Один женится впервые, другой
# в те же недели крестит ребёнка — это не может быть один человек.** Вместе с
# восприемничеством Филатова 8 ноября (л. 250об) и с «Николаемъ Данилинымъ Филатовымъ»
# 1886 г. это и выбивает отчество «Данилинъ» как признак Кузиныхъ.
#
