# при чтении «Марьи Саввиной», жены Михаила Ѳеодоровича, — но переписывать её по этой
# догадке нельзя, написание источника сохраняется.
#
# ⓘ № 6 венчает вдову «села **Сноведскаго Завода** Ардатовскаго уѣзда Нижегородской
# губерніи» — тот самый приход **с. Сноведь**, куда корпус ходит за детьми Андрея
# Фёдоровича (Николай, род. 04.04.1910). Связь села со Сноведью старше на четверть века.
