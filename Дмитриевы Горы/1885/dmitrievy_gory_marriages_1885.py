# самое, каким корпус зовёт дедов **двора 5**. Гипотеза: он отец Алексѣя (и Ивана,
# Николая Флоровичей) и брат Максима и Алексія Антоновичей. **Не заведено** — фамилии нет,
# второго сигнала нет. Проверять по восприемникамъ у детей Алексѣя: первенец — Алексѣй,
# 30 сентября 1887 г. (МК 1887, № м59).
#
# ⚠⚠ **БРАК № 15 — ЭТО НЕ НАШ НИКОЛАЙ ДАНИЛОВИЧЪ.** 2 октября венчается **первым
# бракомъ** «крестьянскій сынъ **Николай Даниловъ ФИЛАТОВЪ**», 20½ л. (⇒ род. ок. апреля
# 1865 г.), с «прихода села Санчуръ крестьянской дочерью **Агафьей Маркиной**», 16 л.
# 8 мѣс. А **Николай Данилинъ КУЗИНЪ** 31 октября (вычитка 19.10.2026; прежде — 24-го)
