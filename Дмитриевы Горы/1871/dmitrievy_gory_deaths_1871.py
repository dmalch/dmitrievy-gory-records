from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DIARRHEA, PLEURISY
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, SOLDIER

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1871 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**195**, лл. 21об–28об
# (**титульного листа у части НЕТ**, л. 21 чист). **51 мужское и 57 женских —
# 108 погребений.** **ДВЕ записи.**
#
# ⓘ Погребений 108 против 102 (1874), 119 (1875), 112 (1876), 101 (1877), 87 (1878),
# 84 (1879), 93 (1873). При 167 рождениях прирост года **+59** — самый большой из
# восьми прочитанных лет.
#
# ⚠ **Возраст: голое число = годы, младенцы всегда с единицей** — как в 1873 и 1874 гг.
# Проверено парами «родился и умер в одной книге», которых в году не меньше десяти;
# две из них заведены ниже, и обе сходятся день в день.
#
# ⚠ **Столбцы возраста в этой части ДВА** («лѣта умершаго мужеска / женска»), как и
# столбцы счёта; для младенца пишется «3 недѣли», «1½ мѣсяца», «12 дней».
#
# ⓘ **Июль — женский месяц**: три мужских погребения против одиннадцати женских. То же
# было в 1873 г. (тоже июль, три против одиннадцати). Совпадение или манера причта —
# не разобрано.
# ⓘ **Отъ беременности** — редкая формула, встречена дважды (ж10 марта, «Іосифа Иванова
# жена Марья Ефимова, 41»). В 1873 г. те же смерти пишутся «отъ воспаленія послѣ
# родовъ» и «отъ простуды послѣ родовъ».
#
# Имена, номера, даты и возрасты сверены кропом при 2.4–9×; обе записи вычитаны в Verso
# 13.10.2026. Год не перечитан вторым сплошным проходом.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1871 = death_records(
    "ГАВО", "590", "12", "195", "Дмитриевы Горы", "Покровская",
    1871,
    *page("22об",
          *death_month(Month.FEBRUARY,
                       # 🔗 **ПАРА К САМОЙ ПЕРВОЙ ЗАПИСИ ДЕЛА.** «Той же деревни находящійся въ домовомъ
                       # отпуску рядоваго солдата **Харитона Ѳокина** сынъ младенецъ **Василій**», **1½
                       # мѣсяца**, отъ колотья. ⓘ В DSL возраст стоит как «1 мес 2 нед»: дробную форму «1.5
                       # мес» линтер не принимает, хотя в корпусе она встречается — те записи лежат в
                       # `dsllint_baseline.tsv`. 🔗 Метрика — ч. 1 **№ м1, 1 января 1871 г.**, мать **Марина
                       # Саввина**. 1 января → 16 февраля = **46 дней**, писано «1½ мѣсяца» — сходится без
                       # натяжки и подтверждает меру возрастов года. ⓘ Харитонъ Ѳокинъ корпусу до 1874 г.
                       # известен не был; здесь он на три года раньше, и **Ѳеодоръ 1874 года у него не первый
                       # ребёнокъ**. ⚠ Мать в ч. 3 не названа — часть третья зовёт одного отца
                       death(8, Gender.MALE, 16, 18,
                             deceased=person("Василій"), age="1 мес 2 нед",
                             relatives=[relative(person("Харитонъ", "Ѳокинъ", residence="Кононово", status=SOLDIER, comment="находящийся в домовом отпуску рядовой солдат"), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("24об",
          *death_month(Month.JUNE,
                       # 🔗 **ВТОРАЯ ПАРА «РОДИЛСЯ И УМЕР В ОДНОЙ КНИГЕ», И ОНА КАСАЕТСЯ КОРПУСНОЙ ПАРЫ.**
                       # «Того же села крестьянина **Максима Карпова** дочь младенецъ **Татіана**», полгода,
                       # отъ поноса. 🔗 Метрика — ч. 1 **№ ж3, 9 января 1871 г.**, мать **Анна Васильева**. 9
                       # января → 20 іюня = пять месяцев одиннадцать дней; писецъ пишет полгода, округляя
                       # вверх, как и в других записях этого года. 🔴 **Максимъ Карповъ и Анна Васильева**
                       # стоят в списке ARCHIVES.md; их брак датировался «до 1872 г.» по сыну Петру. Татіана
                       # отодвигает пару на 1871 г. и делает брак **старше всего дела**. ⓘ Известных детей
                       # пары теперь четверо: **Татіана (9.01.1871 – 20.06.1871)**, Петръ (18.06.1872), Агафья
                       # (ок. 1878) и Спиридонъ (7.12.1874 – 12.12.1874). Двое из четырёх умерли младенцами. ⚠
                       # Мать в ч. 3 не названа
                       death(32, Gender.FEMALE, 20, 22,
                             deceased=person("Татіана"), age="6 мес",
                             relatives=[relative(person("Максимъ", "Карповъ"), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    defaults=DEFAULTS,
)
