# Метрическая тетрадь Покровской церкви с. Димитріевы Горы за 1787 г., часть первая
# «О раждающихся». **ГАВО ф. 556 оп. 106 д. 79, лл. 173–174об** (кадры 0192–0194).
#
# ⛔⛔ **ЭТОТ ГОД КОРПУС СЧИТАЛ ПОТЕРЯННЫМ, И ЗРЯ.** Прежняя помета — «альбом «1786-1787»
# содержит 1787 год **чужого** прихода (с. Ивотчино), 1787 Дмитріевыхъ Горъ в альбомѣ
# НЕТ» — **отозвана 14.09.2026**: она выведена по **л. 172об**, то есть по ЛѢВОЙ половинѣ
# разворота, гдѣ лежит хвостъ предыдущаго прихода. Указатель МК даёт «1787 — д. 79
# **лл. 173–174**», Санчуръ начинается съ л. 176, а въ альбомѣ лежат кадры 0192 (172об-173),
# 0193 (173об-174) и 0194 (174об-175) ⇒ **весь разделъ былъ на дискѣ всё это время**.
#
# ⓘ **Состав года:** л. 173 — титулъ («Подана Генваря 13 дня 1788 года») и ч. 1 №№ 1–7;
# л. 173об — ч. 1 №№ 8–14; л. 174 — ч. 2 (**5 венчаній**) и ч. 3 (**4 погребенія**);
# **табель — л. 174об**. Разделъ НЕ разорванъ, въ отличіе отъ 1782, 1786 и 1788 гг.
#
# ✅✅ **ТАБЕЛЬ (л. 174об) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ.** «Крестьянъ: родившихся мужеска
# **8**, женска **6**, обоего **14**; брачившихся лицъ **10**, супружествъ **5**; умершихъ
# мужеска **1**, женска **3**, обоего **4**» — и единственный возрастъ въ графѣ «29 — 1».
# Подписи: іерей **Василій Андреевъ**, діаконъ **Стефанъ Ивановъ**, дьячекъ **Лаврентій
# Ивановъ**, пономарь **Симеонъ Ѳедоровъ** — тотъ же причтъ, что въ 1786 и 1788–1797 гг.
#
# 🔴🔴 **ГОДЪ ДАТИРУЕТЪ ПЕРЕХОДЪ СЕЛА КЪ БАТАШЕВЫМЪ И НАЗЫВАЕТЪ НЕ ТОГО БРАТА.** Шапка
# ч. 1: «вотчины дворянина **Андрея Родіонова Баташева** села Дмитріевыхъ Горъ да
# Николошинскаго вѣдомства деревни Кононовки крестьянъ» (сверено при 11× — «андрѣа», не
# «ивана»); та же формула въ шапкѣ ч. 2. Въ **1786** г. село ещё «генерала **Павла
# Ивановича Глѣбова**», въ **1788** — уже «**Ивана** Родіоновича Баташева».
# ⇒ переходъ **Глѣбовъ → Баташевъ случился между 1786 и 1787 гг.**, и первымъ Баташевымъ
# былъ **Андрей Родіоновичъ**, а не Иванъ. Всё «баташевское» въ корпусѣ начинается здѣсь.
#
# 🚫 **РОДА ВЪ ГОДУ НѢТЪ** — ни Ѳедора, ни Василія Харитоновыхъ, ни Харитона Петрова.
# Единственная запись съ отчествомъ рода — № 9 ниже, и это **Иванъ Харитоновъ**, то есть
# **чужой кустъ** (род. ок. 1731 по сказкѣ 1782 г.).
# 🔴 **И это закрываетъ поискъ погребенія ХАРИТОНА ПЕТРОВА въ ф. 556.** Онъ живъ въ
# 1782 г. (40 лѣтъ); 1784, 1786, 1787 и 1788–1830 гг. прочитаны и его не держат; а части
# третьи **1783 и 1785 гг. не существуют вовсе** (см. `ARCHIVES.md`, § «1778–1785»).
# ⇒ если онъ погребёнъ въ своёмъ приходѣ, то **въ 1783 или 1785 году, и записи объ этомъ
# нѣтъ**. Единственный умершій мужчина 1787 г. — **Семенъ Ефимовъ, 29 лѣтъ, отъ чахотки**
# (ч. 3 № 2, 2 марта; сверено при 6.5×).
#
# ⚠ Тетрадь **матерей не называетъ** ни въ одной записи; воспріемниковъ двое.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: страницы прочитаны при 2.0×, входящая сюда запись — при 7.5×.

BATASHEV_M = "крестьянин вотчины дворянина А. Р. Баташева"
BATASHEV_F = "крестьянка вотчины дворянина А. Р. Баташева"
BATASHEV_MAIDEN = "девица вотчины дворянина А. Р. Баташева"

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_M,
                          status_female=BATASHEV_F)

dmitrievy_gory_births_1787 = birth_records(
    "ГАВО", "556", "106", "79", "Дмитриевы Горы", "Покровская",
    1787,
    *page("173об",
          *birth_month(Month.SEPTEMBER,
                       # 🔴 **ЕДИНСТВЕННАЯ ЗАПИСЬ 1787 ГОДА СЪ ОТЧЕСТВОМЪ РОДА — И ЭТО ЧУЖОЙ КУСТЪ.** «Того
                       # села **Данила Мартынова** сынъ **Захарій**. Были воспріемники **Иванъ Харитоновъ**,
                       # да дѣвица Евдокія Дми[тріева]» (л. 173об, ч. 1 № 9, рожденъ и крещенъ 5 сентября;
                       # сверено при 7.5×). ⓘ **Иванъ Харитоновъ** — не родня Харитону Петрову: сказка 1782 г.
                       # (лл. 858–858об) даёт ему род. ок. **1731**, то есть онъ ровесникъ самого Харитона. Въ
                       # селѣ **два не связанныхъ рода Харитоновыхъ**, и это второй. Здѣсь ему ок. 56 лѣтъ;
                       # корпусъ зналъ его по метрикамъ 1788 и 1806 гг. ⚠ Тетрадь матери не называетъ — ни въ
                       # одной изъ четырнадцати записей года
                       birth(9, Gender.MALE, 5, 5,
                             child=person("Захарій"),
                             father=person("Данилъ", "Маѯимовъ"),
                             god_parent1=person("Иванъ", "Харитоновъ"),
                             god_parent2=person("Евдокія", "Дмитріева", status="женка вотчины дворянина А. Р. Баташева")),
                       ),
          ),
    defaults=DEFAULTS,
)
