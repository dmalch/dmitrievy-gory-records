# Метрическая книга Покровской церкви с. Димитріевы Горы за 1828 г., часть первая
# «О родившихся». **ГАВО ф. 556 оп. 106 д. 500, лл. 459–467об** (кадры альбома 1–10).
#
# ⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 459–478**, приходъ
# **№ 38** (1829 — № 34, 1830 — № 9, 1833 — № 49 ⇒ номер прихода в деле СВОЙ для каждого
