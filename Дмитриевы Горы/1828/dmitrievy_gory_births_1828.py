# листе, как во всех прочитанных годах ряда.
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, И ВЕДОМОСТЬ (л. 478) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ ДО
# ЕДИНИЦЫ** — второй такой год подряд после 1829-го. «Родившихся мужеска 40, женска 43,
# обоего пола **83**» = 83 сквозных номера части первой; «браковъ 22 лица, супружествъ
# **11**» = 11 венчаний; «умершихъ мужеска **36**, женска **38**, обоего **74**» =
# последние номера части третьей. Даже «незаконнорожденныхъ **1 м / 1 ж**» проверяется
# поимённо: № 56 (Устинья у дѣвки Ирины Лаврентьевой) и № 65 (Аверкій у вдовы Прасковьи
# Сергеевой).
#
# 🔴 **Роду этот год даёт метрику Дарьи Антоновой (№ 20) — и больше в части первой
# ничего.** Ни Ѳоки, ни Игната здесь нет: оба стоят только в части третьей, и оба хоронят
# детей, рождённых до 1828 года (см. `..._deaths_1828.py`). ⇒ **следующий год вниз, 1827
# (556-106-487, лл. 256–275), нужен ради двух конкретных метрик**: дочери Ѳоки **Анны**
# (ок. декабря 1827) и — глубже — сына Игната **Семена** (ок. 1824).
#
# ⓘ Причт тот же: священникъ **Тихонъ Экземплярскій**, діаконъ **Егоръ Драчевскій**,
# дьячекъ **Василій Лаврентьевъ**, пономарь **Михайло Егоровъ**. 🆕 В конце января
# крестит **священникъ села Воютина Алексѣй Яковлевъ** (№№ 6, 7, 8) — свой на неделю
# отлучился; больше за проход такого нет.
