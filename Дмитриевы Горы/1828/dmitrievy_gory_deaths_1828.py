                       # «род. ок. декабря 1827 г.». **1827 год прочитан: она родилась 10 іюня 1827 г.** (1827
                       # ч. 1 № 30, сверено при 7×) ⇒ прожила **год и две недели**, а не полгода. Обе записи
                       # сверены по скану, так что это **ошибка писца, а не расшифровки**; `make death-age-
                       # check` держала её как [HIGH] «расхождение 5.5 мес» — находка верная, перечитывать
                       # сканы не нужно; 🔄 **17.09.2026 подавлена через `source_age_error`**. ⚠ Урок общий: в этом году восемь других пар сошлись день в день, и
                       # всё же **выводить дату рождения из одного возраста нельзя**. 🔴 **И имя повторено.**
                       # Дочь, которую корпус считал первым ребёнком Ѳоки, родилась в 1837 г. и тоже **Анна**.
                       # ⇒ имя дано вторично, по умершей — обычай, на который у проекта есть отдельная
                       # проверка (`two_birth_records_are_two_children`), и здесь он виден внутри одной семьи.
                       # 🔗 Детей Ѳоки теперь известно четверо, и **трое умерли младенцами**: Анна (ок. дек.
                       # 1827 – 24.06.1828), **Акилина** (1.06.1829 – 6.08.1829), **Николай** (7.05.1834, умер
                       # до РС-9) и Анна (1837). Ни один из первых трёх не попал ни в одну ревизию. ⚡ И вся
                       # хронология сдвигается: ребёнок, зачатый в начале 1827 г., означает, что **Ѳока женат
                       # на Марьѣ Семеновой уже в 1826 г.** — а венчания его нет ни в 1828, ни в 1829, ни в
