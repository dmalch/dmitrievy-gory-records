# Метрическая книга Покровской церкви с. Димитріевы Горы за 1828 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 500, лл. 470–477об** (кадры альбома 12–20).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 36 м / 38 ж = 74 погребения**, и ведомость (л. 478) пишет
# ровно «умершихъ мужеска **36**, женска **38**, обоего пола **74**».
#
# ⚠ **1828-й — ГОД ОСПЫ, И ЭТО ТРЕТЬЯ ЭПИДЕМИЯ ЗА ТРИ ПРОЧИТАННЫХ ГОДА.** Генварь и
# февраль размечены «оспою», дальше идут «коклюшемъ» и «горячкою»; ведомость считает
# **16 умерших мужчин «ниже году»** из 36. Для сравнения: 1829-й — корь и коклюшъ, шесть
# младенцев; 1830-й — сплошной коклюшъ, семнадцать. ⇒ **каждый год прихода болеет своим,
# и переносить причину смерти из года в год нельзя.**
#
# ⓘ Форма и возрастная конвенция те же, что в 1829 г.: две даты (числовая колонка — день
# смерти, «погребенъ N-го» в тексте), возраст словами, округление **вверх** к ближайшему
# месяцу. Проверено внутри года не менее восьми раз (Маріамна Петрова 16 февр. → 6 марта
# = 2 нед. 4 дн. → «3 недѣль»; Прокопій Евстаѳьевъ 22 февр. → 18 дек. = 9 мѣс. 26 дн. →
# «10 мѣсяцевъ»; и т. д.).
#
# 🔴🔴🔴 **ЭТА ЧАСТЬ — ГЛАВНОЕ, ЧТО ГОД ДАЁТ РОДУ, И ОНА ДАЁТ ДВУХ ДЕТЕЙ, КОТОРЫХ НЕ
# ВИДЕЛА НИ ОДНА РЕВИЗИЯ И НИ ОДНА ПРОЧИТАННАЯ МЕТРИКА.** Ни Ѳока, ни Игнатъ не
# появляются в частях первой и второй этого года — они стоят только здесь, и оба хоронят
# детей, **рождённых до 1828 года**. ⇒ дальше вниз идти обязательно.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

