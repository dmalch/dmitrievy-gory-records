                          # 1834 г. → метрики с 1834 → 1830 (три поручительства) → 1829 (дочь Дарья в генваре,
                          # кумъ в іюнѣ, сынъ Максимъ в августѣ). Теперь **16 мая 1828 г.**, и он снова
