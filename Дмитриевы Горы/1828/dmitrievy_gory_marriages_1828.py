# Метрическая книга Покровской церкви с. Димитріевы Горы за 1828 г., часть вторая
# «О брачившихся». **ГАВО ф. 556 оп. 106 д. 500, лл. 468–469об** (кадры альбома 10–12).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 11 венчаний**, ведомость (л. 478) пишет «бракосочетавшихся
# лицъ 22, супружествъ **11**» — сходится до единицы, как и обе другие части.
#
# ⓘ **Форма 1828 года — самая полная из прочитанных.** Каждая запись не только ссылается
# на «указный обыскъ, вписанный въ данной изъ Муромскаго Духовнаго Правленія книгѣ» (как
# в 1829-м), но и добавляет, что вѣнчаніе «совершаемо было по церковному чинопослѣдованію
# **въ церкви предъ людми въ узаконенное время**». К 1830 г. обе формулы исчезнут.
#
# 🔴🔴 **ГЛАВНОЕ ЗДЕСЬ — ОТСУТСТВИЕ: ВЕНЧАНИЯ ѲОКИ ѲЕДОРОВА В ЭТОЙ ЧАСТИ НЕТ.** Его нет
# и в 1829, и в 1830 гг., а в генваре 1830-го он уже назван «крестьяниномъ» (хозяином
# двора), в 1829-м у него рождается дочь, а в этом году он хоронит дочь **полугоду**
# (ч. 3 № 20 ж) ⇒ ребёнок зачат в начале 1827 г. **Свадьба Ѳоки лежит в 1826 г. или
# раньше**; при рождении ок. 1802 г. (РС-7 1816) это даёт окно **1822–1826**, и все эти
# годы ф. 556 держит оцифрованными.
#
# Имена сверены кропом при 3× в сером.
# Вычитано в Verso 06.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

