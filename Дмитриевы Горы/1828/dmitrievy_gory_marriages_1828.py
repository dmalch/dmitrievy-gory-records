                          # же округи и вѣдомства **прихода села Степанькова деревни НИЖНЕЙ ВЕРЕИ** съ
                          # крестьянскою дочерью, дѣвкою **Ѳевроньею Степановою**». 🔗 20 генваря 1829 г.
