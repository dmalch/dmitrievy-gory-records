from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1908 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**, лл. 403–406об
# (титул — л. 403, записи — на лл. 403об–406об).
#
# Год целиком: 21 брак, из них ШЕСТНАДЦАТЬ обвенчаны в один день, 3 октября
# («Итого въ Октябрѣ совершено браковъ шестнадцать» — л. 406об). Осенний
# мясоед после Успенского поста; за поручителей у всех шестнадцати стоят одни
# и те же четверо — учитель ц.-приходской школы Александр Иоаннов Казанский,
# Пётр Варлаамов Усов, Николай Феодоров Космин и Иван Михайлов Мирошкин.
#
# ⚠ **Внутренняя опись дела отводит 1908 году «403–415об. ч.2»** — то есть
# считает брачной всю пачку до конца. На деле часть вторая кончается на
# л. 406об, а с л. 407 идёт часть третья «О умерших», описи неизвестная;
# см. `dmitrievy_gory_births_1908.py` и `dmitrievy_gory_deaths_1908.py`.
#
# Кекевы в двух браках из двадцати одного — в обоих со стороны нашей фамилии;
# Земсковых нет. Оба брака 3 октября.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1908 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1908,
    *page("405об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ЭТО РАЗГАДКА записи 1909 г.: восприемницей у Михаила Симеонова Кикеева (л. 193об
                          # д.198) стоит «крестьянская женка **Наталія Симеонова Мирошкина**» — вместе с
                          # Иосифом Симеоновым Кикеевым, — и было предположено, что она сестра отца, вышедшая
                          # за Мирошкина. Венчание 3 октября 1908 г. это подтверждает прямо: невеста
                          # «крестьянская дочь **Наталія Симеонова Кикева**», 19 лет (род. ок. 1889 г.), жених
                          # Максим Михайлов Мирошкин, 18 и 8 мес. Значит у Симеона Кикева трое известных детей
                          # — Михаил, Иосиф и Наталия, — а сам он ветвь, которой перепись 1897 г. не знает
                          marriage(15, 3,
                                   groom=person("Максим", "Михайлов", last_name_orig="Мирошкин", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age="18 лет 8 мес",
                                   bride=person("Наталия", "Симеонова", last_name_orig="Кикева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=19,
                                   witness1=person("Александр", "Иоаннов", last_name_orig="Казанский", status="учитель церковно-приходской школы"),
                                   witness2=person("Петр", "Варлаамов", last_name_orig="Усов"),
                                   witness3=person("Николай", "Феодоров", last_name_orig="Космин"),
                                   witness4=person("Иван", "Михайлов", last_name_orig="Мирошкин")),
                          # венчание пары, которая до сих пор была известна с 1909 г. (л. 200об д.198) и
                          # прослеживается через 1911 г. (л. 8об д.199) и 1914 г. (л. 135об) до 1917 г. (л.
                          # 237об). Жених — **вдовый**, вторым браком, 23 лет (род. ок. 1885 г.): в январе
                          # того же года умерла «крестьянская жёнка **Матрона Іоаннова Кекева**», 21 года, от
                          # водянки (ч. 3, № ж1, л. 407об), и она — самый вероятный кандидат в первые жёны:
                          # единственная замужняя Кекева, умершая в селе в этом году, и вдовец в том же году
                          # венчается заново. Прямо этого, однако, ни одна запись не говорит — метрика о
                          # смерти мужа не называет. Отец жениха назван в записи о рождении № м53 (л. 396об) —
                          # Николай Феодоров Кекев. Фамилия невесты — тот же род, что Анастасия Артемиева
                          # Шерстнева, восприемница 1911 г. (л. 8 д.199)
                          marriage(17, 3,
                                   groom=person("Алексий", "Николаев", last_name_orig="Кекев", status="вдовый крестьянин"),
                                   groom_marriage_num=2, groom_age=23,
                                   bride=person("Любовь", "Емелианова", last_name_orig="Шерстнева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=21,
                                   witness1=person("Александр", "Иоаннов", last_name_orig="Казанский", status="учитель церковно-приходской школы"),
                                   witness2=person("Павел", "Иоаннов", last_name_orig="Щукин"),
                                   witness3=person("Петр", "Варлаамов", last_name_orig="Усов"),
                                   witness4=person("Иван", "Михайлов", last_name_orig="Мирошкин")),
                          ),
          ),
    defaults=DEFAULTS,
)
