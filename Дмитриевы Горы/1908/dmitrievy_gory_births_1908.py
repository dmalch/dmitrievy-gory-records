# л. 380об смотрит на л. 382, л. 383об — на л. 385, л. 386об — на л. 388.
# Нумерация записей через вставки НЕ прерывается (м8 → м9, ж6 → ж7), значит ни
# одного листа с записями не потеряно. Ещё одна вставка, л. **401** (свидетельство
# 1927 г., Давыдова Анастасия Григорьевна), стоит уже после конца части.
#
# ⚠ **Фамилия отца записи № м6 писана «Кикеевъ», а отчество — «Стефановъ»**, тогда
# как и метрика о смерти этого же младенца (ч. 3, № м24, л. 411об), и запись 1909 г.
# (л. 193об) зовут отца **Симеоновым**. Отчество исправлено НЕ было: DSL держит
