from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DIARRHEA, DROPSY, WHOOPING_COUGH
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, PEASANT_ZHONKA

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1908 г.,
# часть третья «О умерших». ГАВО ф.590 оп.12 д.**198**, лл. 407–415об
# (титул — л. 407, записи — на лл. 407об–415об). Итог года: м44 + ж41.
#
# ⚠ **ЭТОЙ ЧАСТИ НЕТ ВО ВНУТРЕННЕЙ ОПИСИ ДЕЛА.** Опись расписывает 1908 год
# двумя строками — «379–402 ч.1 1908г» и «403–415об. ч.2 1908» — и на этом
# основании до сих пор считалось (ARCHIVES.md, файлы 1909 г.), что смертей за
# 1908 и 1909 гг. в д.198 нет и искать их надо в консисторской копии ф.590
# оп.5. Для 1908 г. это НЕВЕРНО: часть вторая кончается на л. 406об браком
# № 21, а л. **407** — печатный титул «ЧАСТЬ ТРЕТІЯ, О УМЕРШИХЪ», и дальше до
# конца пачки идут погребения января–декабря 1908 г. Тринадцать листов, которые
# архивист приписал брачной части, — это ч. 2 (4 листа) плюс ч. 3 (9 листов).
# Для 1909 г. ч. 3 в альбоме по-прежнему не найдена, но опись после этого
# доказательством её отсутствия не является.
#
# Прочитано на ОБЕ фамилии. Кекевых трое, и все три записи смыкаются с частями
# первой и второй того же года; Земсковых нет. Год тяжёлый для младенцев:
# в июле «поносом» унесено 8 мальчиков и 6 девочек, осенью идёт коклюш.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1908 = death_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1908,
    *page("407об", reviewed=False,
          *death_month(Month.JANUARY,
                       # ПЕРВАЯ запись части третьей и единственная взрослая Кекева, умершая в селе в этом
                       # году. «Крестьянская жёнка», то есть замужняя, 21 года (род. ок. 1887 г.); мужа
                       # метрика не называет, и это обычное дело для здешнего писца. Через восемь с половиной
                       # месяцев, 3 октября, **Алексий Николаев Кекев венчается ВДОВЫМ, вторым браком**, 23
                       # лет (брак № 17, л. 405об) — она самый вероятный кандидат в его первые жёны, но
                       # прямого свидетельства нет ни в той записи, ни в этой. Погребена «на отдалённомъ
                       # кладбищѣ» — формула, которой писец открывает год и дальше отсылает к ней «тамъ же»
                       death(1, Gender.FEMALE, 16, 18,
                             deceased=person("Матрона", "Иоаннова", last_name_orig="Кекева", status=PEASANT_ZHONKA),
                             age=21,
                             cause_of_death=DROPSY),
                       ),
          ),
    *page("411об", reviewed=False,
          *death_month(Month.JULY,
                       # это младенец, рождённый 14 января того же года (запись о рождении № м6, л. 380об):
                       # оба конца жизни — на одном развороте дела. И запись о смерти решает спор об отчестве
                       # отца: здесь он **Симеонов**, как и в 1909 г. (л. 193об), а «Стефановъ» метрики о
                       # рождении — описка. Умер в разгар июльской волны поноса: из четырнадцати погребённых в
                       # этом месяце одиннадцать — «отъ поноса», и почти все младенцы
                       death(24, Gender.MALE, 25, 27,
                             deceased=person("Павел"), age="полгода",
                             relatives=[relative(person("Михаил", "Симеонов", last_name_orig="Кикев"), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    *page("414об", reviewed=False,
          *death_month(Month.SEPTEMBER,
                       # дочь, о которой корпус не знал: полутора лет, то есть рождена около марта 1907 г., —
                       # года, который ещё не прочитан. Родителям она не первая потеря и не последняя: в марте
                       # того же 1908 г. у них родилась Мария (запись о рождении № ж20, л. 388об), а в 1910 г.
                       # — ещё дочь (л. 165об). Умерла в осеннюю волну коклюша
                       death(34, Gender.FEMALE, 28, 30,
                             deceased=person("Анна"), age="полтора года",
                             relatives=[relative(person("Евфимий", "Иоаннов", last_name_orig="Кекев", status="запасный солдат"), Relationship.FATHER)],
                             cause_of_death=WHOOPING_COUGH),
                       ),
          ),
    # Вторая волна (09.11.2026): дети замужних дочерей Кекевых, найденные по имени мужа. reviewed=False.
    *page("412об", reviewed=False,
          *death_month(Month.AUGUST,
                       # Василий — сын Григория Петровича Рыбкина и Дарьи Романовны Кекевой, род. 12.03.1908 (ч. 1, № м21)
                       death(28, Gender.MALE, 5, 7,
                             deceased=person("Василій"), age="5 мес", comment="в подлиннике «около 5 мѣс.»",
                             relatives=[relative(person("Григорій", "Петровъ", last_name_orig="Рыбкинъ"), Relationship.FATHER)]),
                       ),
          ),
    defaults=DEFAULTS,
)
