# (**9 погребеній**); **табель — л. 27**, таблица болѣзней по возрастамъ — **л. 27об**.
# Альбом = **развороты**: кадр 0033 несёт и л. 21об чужого прихода.
#
# ✅✅ **ТАБЕЛЬ (л. 27) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ.** «Крестьянъ: родившихся мужеска
# **11**, женска **9**, обоего **20**; брачившихся лицъ **16**, супружествъ **8**;
