# умершихъ поимённо — 19, 30, 32, 46, 56, 61, 74, 76, 80 — и **исправляет одно моё
# чтение**: женка Елисавета Васильева (ч. 3 № 7) — **76**, а не 16.
#
# 🏆🏆🏆 **САМАЯ РАННЯЯ ЗАПИСЬ О РОДѢ ВО ВСЁМ КОРПУСѢ — 17 МАРТА 1780 г.** (№ 6 ниже),
# и она **на шесть лет глубже** прежней границы: до 14.09.2026 корпус не знал о родѣ
# ничего раньше 1786 г., а по метрикамъ — раньше 1799 г.
# ⇒ **Ѳедоръ Харитоновъ женатъ не позже 1779 г.**, девятнадцати лет отъ роду
# (род. ок. 1761 по ревизіи 1782 г.).
#
# ✅✅ **СПОРЪ СЪ РЕВИЗІЕЙ 1782 ГОДА РАЗРѢШЁНЪ ПЕРЕЧТЕНІЕМЪ 14.09.2026: ЭТО ДВА РАЗНЫХЪ
# МАЛЬЧИКА.** Сказка (301-5-137 А, л. 860об) знает у Ѳедора и Ѳедоры сына **Григорея** и
# **Алексѣя не знает вовсе**; провѣрялось, не читается ли то имя «Алексѣй». **Нѣтъ.**
# На той же страницѣ стоит **второй Григорей** — сынъ Симеона, member 8, — и при 10×
# оба написанія совпадаютъ буква въ букву (Г-р-и-г-о-р-ѣ-и, съ одинаковымъ длиннымъ
# хвостомъ начальной «Г»); «Алексѣй» исключёнъ, въ словѣ нѣтъ ни округлой «А», ни «к»,
# ни «с». ⇒ **Алексѣй — старшій ребёнокъ, умершій до іюня 1782 г.**, а Григорей — второй.
# ⇒ метрика **Григорея въ источникѣ отсутствуетъ**: 1781 и 1782 гг. прочитаны сплошь, оба
# табеля сходятся (17 / 7 / 7 и 17 / 8 / 10), Харитоновыхъ рожденій въ нихъ нѣтъ. Это
# ровно то, чего и ждать: тетради этихъ лѣтъ пишутъ по 15–20 рожденій въ годъ противъ
# **109** въ 1806-мъ, то есть охватываютъ шестую часть прихода.
# ✅ **Возрастъ Григорея — 1** (споръ «1 vs 4» закрытъ 14.09.2026) ⇒ род. ок. **1781**,
# и порядокъ дѣтей таковъ: **Алексѣй (17.03.1780) — первенецъ**, Григорей — второй.
# ⓘ Калибровка почерка сказки — въ `1782/dmitrievy_gory_census_1782.py`, member 19:
# одиночная «1» пишется тамъ иначе, чѣмъ «1» внутри «13»/«17».
#
# 🔴 **Отсутствіе погребенія Алексѣя ничего не доказываетъ.** Части третьи 1780, 1781 и
# 1782 гг. — **26 погребеній, младшему 19 лѣтъ**; ни одного ребёнка. Приходъ въ эти годы
# **дѣтскихъ смертей не записывалъ вовсе**, при 54 крещеніяхъ за тѣ же три года.
#
# ⓘ **Причтъ 1780–1781 гг. — другой, чѣмъ съ 1782 г.**: тетради 1780 и 1781 выданы
# «священнику **Ивану Стефанову** съ причетники» (сверено при 6×), а **Василій Андреевъ**,
# который съ 1782 по 1797 г. будетъ священникомъ, въ 1781 г. подписываетъ табель ещё
# причетникомъ (л. 167).
# ⓘ Вотчина — «**полковника** Павла Ивановича Глѣбова» (такъ же 1778, 1779, 1781, 1783,
# 1784; въ 1785 «помѣщика», въ 1786 уже «генерала»).
#
# ⚠ **Матерей эта тетрадь не называетъ** — ни въ одной изъ 20 записей; воспріемниковъ
# двое (мужчина и дѣвица/жена/баба).
#
# ✅ Вычитано по сканам в Verso 30.09.2026.
# Первое чтение: страница прочитана при 2.0×, входящая сюда запись — при 7×.

