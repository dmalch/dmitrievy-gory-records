from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, birth, birth_month, birth_records, page,
                          person)

# Метрическая тетрадь Покровской церкви с. Димитріевы Горы за 1802 г., часть первая
# «О родившихся». **ГАВО ф. 556 оп. 106 д. 163, лл. 198–199об** (5 одиночных кадров).
#
# ⚠⚠ **КРАТКИЙ РЕЕСТР, а не метрическая книга** — одна строка на запись, **матери не
# названы**, воспріемникъ **только один**. То же в 1798 и 1799 гг. ⓘ Тетрадь **№ 5**,
# дана изъ **Муромскаго Духовнаго Правленія** «во исполненіе 29-го пункта прибавленія
# Духовнаго Регламента».
#
# **Состав:** л. 198 — титул и тут же ч. 1; ч. 1 — лл. 198–199об (**61 запись**);
# ч. 2 — л. 199об (**13 венчаній**); ч. 3 — лл. 199об–200 (**5 м / 9 ж = 14**);
# **табель — л. 200**.
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ТАБЕЛЬ (л. 200) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** —
# **двадцать восьмой такой год подряд**. «Крестьяне: родившихся мужеска **32**, женска
# **29**, обоего **61**; браковавшихся лицъ **26**, супружествъ **13**; умершихъ мужеска
# **5**, женска **9**, обоего **14**». Возрастная разбивка (35 — 1, 55 — 2, 60 — 1,
# 85 — 1) даёт 5 и сошлась построчно.
# ⓘ Табель кончается формулой, которой в поздних книгах нет: «а чрезвычайно рожденныхъ,
# подкидышей, убитыхъ, съ ума сшедшихъ, новокрещенныхъ, самоубійцъ, отшельныхъ
# раскольниковъ и иныхъ партей никакихъ не имѣлось».
# ⓘ Причт: священникъ **Степанъ Ивановъ** (болен — подписано за него), діаконъ **Егоръ
# Алексѣевъ**, дьячекъ **Лаврентій Ивановъ** (тоже болен), пономарь **Варсонофій
# Степановъ**.
#
# 🔴 **ВАСИЛІЙ ХАРИТОНОВЪ КУМОМЪ ДВАЖДЫ**: № 17 (2/9 апрѣля, у **Игнатья Иванова** сынъ
# Абрамъ) и № 23 (21/25 апрѣля, у **Симеона Ефимова** сынъ Макаръ — ниже).
#
# 🚫🚫 **И ГЛАВНЫЙ ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ: ѲОКА ѲЕДОРОВЪ В 1802 ГОДУ НЕ РОЖДАЛСЯ.**
# Ревизия 1816 г. даёт ему 14 лѣтъ, и РС-8 1834 г. это подтверждает («по прошлой ревизии
# 14») ⇒ род. ок. 1802. Но среди шестидесяти одной записи года **нет ни одного ребёнка
# Ѳедора Харитонова**; то же в 1799 (35 записей) и 1798 (50). ⇒ **Ѳока род. в 1800 или
# 1801 году**, и **альбомов за эти два года нет**.
# 🚫 **И Харитона год не хоронит** — четырнадцать погребеній разобраны.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 6×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_births_1802 = birth_records(
    "ГАВО", "556", "106", "163", "Дмитриевы Горы", "Покровская",
    1802,
    *page("198об",
          *birth_month(Month.APRIL,
                       # 🔴 **ВТОРОЙ ИЗ ПЯТИ РАЗ У ОДНОГО ДВОРА.** «**Симеона Ефимова** сынъ **Макаръ**.
                       # Воспріемникъ былъ **Василій Харитоновъ**» (сверено при 6×). 🔗 Полный ряд: **1798**
                       # (Гавріилъ), **1802** (здесь), **1803** (Параскева), **1806** (Иванъ), **1809**
                       # (Гавріилъ) — пять крестин за одиннадцать лет у одной семьи. С 1803 года полные книги
                       # называют жену Семена **Евдокіей Харитоновой**, а его самого — **земскимъ** ⇒ Василій
                       # крестит у сестры. ⚠ Краткий реестр 1802 года имени жены не пишет; родство выводится
                       # из книг 1803–1809 гг.
                       birth(23, Gender.MALE, 21, 25,
                             child=person("Макаръ"),
                             father=person("Симеонъ", "Ефимовъ"),
                             god_parent1=person("Василій", "Харитоновъ")),
                       ),
          ),
    defaults=DEFAULTS,
)
