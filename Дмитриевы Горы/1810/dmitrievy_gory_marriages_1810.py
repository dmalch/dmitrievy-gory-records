                          # «Владимірской Губерніи и Епархіи Меленковской Округи приходу Села Дмитревыхъ Горъ
                          # вотчины Господина Баташева **крестьянина ѲЕДОРА ХАРИТОНОВА сынъ АНТОНЪ**, оной же
                          # вотчины и Села съ крестьянского дочерью **дѣвкою ЕЛЕНОЮ ВАСИЛЬЕВОЮ**, по
