# «О бракосочетавшихся». **ГАВО ф. 556 оп. 106 д. 267, лл. 467–472** (кадры 0513–0518).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 15 венчаній**, и ведомость (л. 478) пишет ровно
# «бракосочетавшихся лицъ **30**, супружествъ **15**». Месяцы: **генварь** (№№ 1–3,
# все 23-го), **октябрь** (№№ 4–13), **ноябрь** (№№ 14–15).
# ⚠ Заголовок месяца в этой книге **разорван между колонками**: слева «МѢСЯЦЪ», справа
# название. Октябрьский стоит на л. 467об, ноябрьский — на л. 471; оба сверены при 8×.
#
# 🏆🏆🏆🏆🏆 **№ 9 — ВЕНЧАНІЕ АНТОНА ѲЕДОРОВА И ЕЛЕНЫ ВАСИЛЬЕВОЙ, 9 ОКТЯБРЯ 1810 г.**
# Последнее из трёх венчаній братьев и самое важное: оно **называет их отца по имени и
# отчеству** — «крестьянина **Ѳедора Харитонова** сынъ **Антонъ**». До сегодня это
# отчество читалось **только** в одной строке ревизской сказки 1816 года, и то косвенно
# (три брата названы там племянниками Василія Харитонова).
#
# 🔴 И поручителем стоит **Ѳока Ѳедоровъ** — тот самый взрослый тёзка, из-за которого
# прочтение 1814 года усомнилось в атрибуции 1818 ч. 2 № 12. Первая запись того же года
# (ч. 1 № 1) даёт ему жену **Саломею Петрову** — ту же, что у **Ѳотія Ѳедорова** в 1812 г.
# ⇒ **Ѳока и Ѳотій Ѳедоровы — один человек**, см. `dmitrievy_gory_births_1810.py`.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 8×.

