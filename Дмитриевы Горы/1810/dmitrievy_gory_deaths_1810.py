from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, death, death_month, death_records, page,
                          person)
from verso.ru.dsl.causes_of_death import FEVER

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1810 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 267, лл. 473–477об** (кадры 0519–0524).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 20 погребеній**, и ведомость (л. 478) пишет ровно
# «умершихъ мужеска **12**, женска **8**, обоего **20**» — **самая лёгкая часть третья
# за весь проход**. ⓘ Нумерация здесь **сквозная**, а не по полам, как во всех
# последующих годах; пол читается из колонок «лѣта мужеска / женска».
# ⓘ Возрастная разбивка мужчин («ниже году 3, 2 — 1, 4 — 1, **50 — 1**, 60 — 1, 43 — 1,
# 56 — 1, 76 — 1, 68 — 1, 41 — 1») даёт 12 и сошлась построчно; строка «50 — 1» — это
# запись ниже. «Въ семъ 1810-мъ году ненатуральною болѣзнію умершихъ быть неимѣлось».
#
# 🏆🏆🏆🏆🏆 **№ 4 — ПОГРЕБЕНІЕ ѲЕДОРА ХАРИТОНОВА, ОТЦА ТРЁХ БРАТЬЕВ.** Это запись,
# которую проход искал с 1820 года и четыре раза передатировал. Она же делает 1810 год
# **последней метрикой, которая роду нужна**: ниже лежат уже не братья и не их отец, а
# поколение Харитона, и оно читается только ревизиями.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 5×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1810 = death_records(
    "ГАВО", "556", "106", "267", "Дмитриевы Горы", "Покровская",
    1810,
    *page("473об",
          *death_month(Month.MAY,
                       # 🏆🏆🏆🏆🏆 **ѲЕДОРЪ ХАРИТОНОВЪ — ОТЕЦ ѲОКИ, АНТОНА И ИГНАТІЯ. ЗАПИСЬ, КОТОРУЮ ПРОХОД ИСКАЛ
                       # С 1820 ГОДА.** «Въ маѣ. Приходу означеннаго Села вотчины Господина Баташева **тогожъ
                       # села крестьянинъ ѲЕДОРЪ ХАРИТОНОВЪ** по исповѣди и Святыхъ таинъ причастіи
                       # **скончался маія 10го дня** и погребенъ по церковному чиноположенію», **50** лѣтъ,
                       # **горячкою**; погребенъ **11 мая** (сверено при 5×; возраст подтверждён строкой «50 —
                       # 1» в ведомости л. 478). ⇒ **род. ок. 1760 г.** — на семь лет старше брата Василія (†
                       # 22 іюня 1812 г., 45 лѣтъ) и на шесть лет старше жены **Ѳедоры Антоновой** (род. ок.
                       # 1766 по РС-7 1816 г.). ✅✅ **И ЭТО СХОДИТСЯ С РЕВИЗИЕЙ ТОЧНО.** РС-7 1816 г. пишет
                       # состав двора по 6-й ревизии **1811 г.** и Ѳедора в нём уже нет — ни строкой «умеръ».
                       # Отсюда прочтение 1816 года вывело «умеръ до 1811 г.»; теперь **10 мая 1810 г.**, то
                       # есть меньше чем за год до переписи. ⛔ **ЧЕТЫРЕ ОТОЗВАННЫЕ ДАТИРОВКИ.** Проход вёл её
                       # так: «умер до 27 августа 1820 г.» (1820, по вдовству Ѳедоры) → «между РС-7 1816 и 17
                       # генваря 1817 г.» (1817) → «внутри 1816 года» (1817, отозвано 1816-м) → «до 1811 г.»
                       # (1816). Каждая была верна в своих границах; **эта — запись**. 🔴🔴 **И ОНА ОБЪЯСНЯЕТ
                       # ВЕСЬ 1810 ГОД.** Через пять месяцев, 9 октября, его старший сын **Антонъ венчается
                       # пятнадцати лет** (ч. 2 № 9) — и запись о венчаніи всё ещё зовёт жениха «крестьянина
                       # Ѳедора Харитонова сынъ», потому что формула называет двор, а не живого человека. Двор
                       # берёт на себя дядя **Василій Харитоновъ** (РС-7 1816 г. ставит его первым и числит
                       # братьев его племянниками) — и умрёт сам 22 іюня 1812 г. 📍 **Дальше метрики
                       # бессильны.** Ѳедоръ род. ок. 1760 г.; чтобы найти его отца **Харитона**, нужны **5-я
                       # ревизия 1795 г.** (ГАВО 301-5-220) и **6-я 1811 г.** (301-3-158/160/161). Метрические
                       # книги прихода оцифрованы до 1778 г. и могут дать его женитьбу (ок. 1785–1790) и
                       # рождение братьев, но **имени деда они не назовут** — отчество в них пишут, фамилий
                       # нет
                       death(4, Gender.MALE, 10, 11,
                             deceased=person("Федоръ", "Харитоновъ"),
                             age=50,
                             cause_of_death=FEVER),
                       ),
          ),
    defaults=DEFAULTS,
)
