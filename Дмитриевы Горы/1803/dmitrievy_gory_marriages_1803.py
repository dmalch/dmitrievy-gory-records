from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1803 г., часть вторая
# «О бракосочетавшихся». **ГАВО ф. 556 оп. 106 д. 181, лл. 435–437** (кадры 0438–0440).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 15 венчаній**, и ведомость (л. 438об) пишет ровно
# «браковавшихся лицъ **30**, супружествъ **15**».
# ⚠ **Поручителей этот год не записывает вовсе** — ни одно из пятнадцати венчаній их не
# называет. Так же устроены части вторые 1805 и 1806 гг.; поручители возвращаются в
# 1807-м. ⇒ отсутствие рода среди поручителей 1803–1806 гг. **ничего не значит**.
#
# 🏆🏆🏆🏆🏆 **№ 4 — ВЕНЧАНІЕ ВАСИЛІЯ ХАРИТОНОВА, И ОНО ВТОРОЕ ДЛЯ ОБОИХ.**
# 17 апрѣля 1803 г.: «крестьянинъ **ВАСИЛІЙ ХАРИТОНОВЪ** со вдовою тойже вотчины и села
# **ЕВДОКІЕЮ АРЕФЬЕВОЮ**… **оба вторымъ бракомъ**» (сверено при 7–8×).
# ⇒ Это **перестраивает весь его двор**: дочь **Татьяна** (род. ок. 1791) и сынъ
# **Григорій** (род. ок. 1800, † 9 октября 1806 г.) — дети **первой** жены, имени которой
# корпус не знает; **Настасья** (1806), **Родіонъ** (1807) и **Прасковья** (1810) — дети
# Авдотьи Арефьевой.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 7–8×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_marriages_1803 = marriage_records(
    "ГАВО", "556", "106", "181", "Дмитриевы Горы", "Покровская",
    1803,
    *page("435об",
          *marriage_month(Month.APRIL,
                          # 🏆🏆🏆🏆🏆 **ВЕНЧАНІЕ ВАСИЛІЯ ХАРИТОНОВА — И ОНО ПЕРЕСТРАИВАЕТ ВЕСЬ ЕГО ДВОРЪ.** «Тойже
                          # Округи Означенной вотчины Села Дмитревыхъ Горъ **крестьянинъ ВАСИЛІЙ ХАРИТОНОВЪ**
                          # со вдовою тойже вотчины и села **ЕВДОКІЕЮ АРЕФЬЕВОЮ** по добровольному ихъ, и
                          # Господина согласію, и по учиненіи объ нихъ въ церкви указнаго обыска… **оба
                          # ВТОРЫМЪ бракомъ**» (имена при 7×, «оба вторымъ бракомъ» при 8×). 🔴🔴 **ДВА ВТОРЫХ
                          # БРАКА — ЭТО ДВЕ ПРЕЖНИЕ СЕМЬИ.** До сегодня корпус знал у Василія одну жену —
                          # **Авдотью Арефьеву** (метрики 1806, 1807, 1810 гг.) — и считал её матерью всех его
                          # детей. Теперь дети делятся надвое: ⇒ **от первой, неизвестной жены**: **Татьяна**
                          # (25 лѣтъ в РС-7 1816 г. ⇒ род. ок. 1791), **Емеліанъ** (8 августа 1799 г., 1799 ч.
                          # 1 № 30 — найден 14.09.2026) и **Григорій** (6 лѣтъ при погребеніи 9 октября 1806
                          # г. ⇒ род. ок. 1800); ⇒ **от Авдотьи Арефьевой**: **Настасья** (8 марта 1806 г.),
                          # **Родіонъ** (8 ноября 1807 г.) и **Прасковья** (28 августа 1810 г.) — и **ни
                          # одного** из этих троих ревизия 1816 года не числит. ⇒ **Василій Харитоновъ
                          # похоронил четверых детей из пяти**, и двор достался племянникам не потому, что
                          # сыновей не было, а потому что они умерли. ⓘ **Авдотья Арефьева тоже вдова**, и её
                          # родня в приходѣ видна: 9 октября 1807 г. Василій ручается на свадьбѣ **Пелагіи
                          # Арефьевой**, дочери **Арефья Иванова** (1807 ч. 2 № 16), а сама Пелагея стоит
                          # кумой у его дочери Настасьи в 1806-м. В приходѣ есть также **Мокей**, **Еремей** и
                          # **Родіонъ Арефьевы**. ⚠ Год поручителей не записывает — ни в одном из пятнадцати
                          # венчаній
                          marriage(4, 17,
                                   groom=person("Василій", "Харитоновъ"),
                                   bride=person("Евдокія", "Арефьева", status="вдова вотчины г-на Баташева"),
                                   groom_marriage_num=2, bride_marriage_num=2),
                          ),
          ),
    defaults=DEFAULTS,
)
