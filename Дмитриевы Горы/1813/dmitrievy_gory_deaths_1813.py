from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import FEVER

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1813 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 309, лл. 430–436об** (кадры альбома 17–24 из
# 25; лл. 429 и 430 сняты поодиночке).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 24 м / 32 ж = 56 погребений**, и ведомость (л. 437) пишет
# ровно «умершихъ мужеска **24**, женска **32**, обоего **56**».
# ⓘ «Ненатуральною смертію въ семъ 1813-мъ году умершихъ никого быть не случилось».
# ⓘ Возрастная колонка года — **в годахъ по голому числу**; младенческий возраст писец
# выписывает словом или дробью («полгода», «½», «5 мѣсяцевъ»), так что «8» ни с чем не
# путается.
#
# 🚫 **РОДА ЧАСТЬ ТРЕТЬЯ НЕ ХОРОНИТ.** Ни Ѳедора Харитонова (он умеръ до 1811 г.), ни
# Ѳедоры Антоновой, ни детей Антона. ⇒ дочь **Анна** (3 лѣтъ по РС-7 1816 г.) 1813 год
# переживает, и её метрику надо искать в **1812 г.**, см. `dmitrievy_gory_births_1813.py`.
#
# ⚠ Тёзки на месте: м. № 19 — **Дмитрій Антоновъ, 42 лѣтъ** († 13 мая); ж. № 21 — вдова
# **Ѳедора Саввина, 45** (казённаго вѣдомства д. Коннова) — тёзка нашей Ѳедоры Антоновой
# по имени, но не по отчеству и не по вотчинѣ.
# ⓘ **Ополченіе 1812 года слышно и здесь**: м. № 21 хоронит младенца Ивана, «пяти
# мѣсяцевъ», **у ратниковой жены** — того самого, которого крестили 5 генваря (ч. 1 № 1).
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 5–7×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1813 = death_records(
    "ГАВО", "556", "106", "309", "Дмитриевы Горы", "Покровская",
    1813,
    *page("436",
          *death_month(Month.NOVEMBER,
                       # ⚡⚡ **ЕДИНСТВЕННАЯ ЗАПИСЬ 1813 ГОДА О ѲОТІѢ ѲЕДОРОВѢ — И ОНА СТАРИТ ЕГО НА
                       # ПОКОЛЕНИЕ.** «Приходу означеннаго Села вотчины Господина Баташева **Крестьянина Ѳотія
                       # Ѳедорова сынъ Прокопій** по исповѣди и Святыхъ таинъ причастіи скончался Ноября 16го
                       # дня», **8** лѣтъ, горячкою; погребенъ 18 ноября (сверено при 7×). ✅✅ **МЕТРИКА
                       # НАЙДЕНА 14.09.2026: род. 3 ІЮЛЯ 1806 г.**, крещ. 8 іюля (1806 ч. 1 м. № 26) — «у
                       # крестьянина **Ѳоки Ѳедорова** и отъ жены его **Саломеи Петровой** родился сынъ
                       # Прокофій». ⇒ на момент погребенія ему **7 лет 4 месяца**, и писец округлил вверх до
                       # восьми. ⛔ Оценка «род. ок. 1805» снята. 🔴🔴🔴 **И ЭТА ПАРА ЗАПИСЕЙ ДОКАЗЫВАЕТ, ЧТО ѲОКА
                       # И ѲОТІЙ ѲЕДОРОВЫ — ОДИН ЧЕЛОВЕК**: один и тот же сынъ Прокопій, одна и та же жена
                       # Саломея/Саломида Петрова, два написания имени отца. Прежде отождествление держалось
                       # на совпадении имени жены; теперь — на общем ребёнке. ⇒ Ѳотій женился не позже 1805
                       # г.; **вывод «род. ок. 1784 или раньше» ослаблен** — он строился на округлённом
                       # возрасте, и по метрикѣ отец Прокопія мог родиться и позже. 🔴🔴 **ЗАЧЕМ ЭТО НУЖНО.**
                       # Ѳотій Ѳедоровъ — самый плотный узел кумовства вокруг Антона: он стоит воспріемникомъ
                       # у **Ксеніи (1815)**, **Стефаниды (1816)** и **Осипа (1818)**, а Антонъ — у его сына
                       # **Максима (1817)**. Четыре года из четырёх, взаимно, и корпус с 1815 года держит
                       # открытым вопрос, не брат ли он. Возраст, выведенный здесь, **этому не мешает, а
                       # помогает**: Ѳедоръ Харитоновъ род. ок. 1765–1770, его жена Ѳедора Антонова — ок. 1766
                       # ⇒ сынъ 1784 года рождения у них возможен, и он был бы **старшим братом**, к 1811 г.
                       # уже отделившимся своим дворомъ — потому РС-7 1816 г. и не числит его среди
                       # племянниковъ Василія Харитонова в семьѣ 45. ⚠⚠ **Это догадка, а не вывод.** Отчество
                       # «Ѳедоровъ» в приходѣ носят ещё **Петръ** (двое), **Иванъ**, **Михайло** († 1815, 95
                       # лѣтъ), **Кодратъ** († 1814, 94), **Денисъ** († 1814, 80) и **второй, взрослый Ѳока**
                       # (1814 ч. 2 № 8) — на одном отчествѣ родства не строят. 📍 **Решить может только
                       # ревизия**: искать дворъ **Ѳотія Ѳедорова** в РС-7 1816 г. (ГАВО 301-5-366, раздел
                       # села — сканы 0272–0326) и смотреть, не назван ли он тоже племянникомъ Василія
                       # Харитонова или сыном Ѳедоры Антоновой
                       death(23, Gender.MALE, 16, 18,
                             deceased=person("Прокопій"),
                             age=8,
                             relatives=[relative(person("Фотій", "Ѳедоровъ"), Relationship.FATHER)],
                             cause_of_death=FEVER),
                       ),
          ),
    defaults=DEFAULTS,
)
