#
# ⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 414–437об**, и это
# сказано в самой книге: заверка на л. 437об пишет «въ сей тетради нумеровано двадцать
# четыре листа, а пришнуровано Муромскаго Духовнаго Правленія печатью» — **414–437 = ровно
# 24 листа**. ⇒ л. 438 принадлежит **другому приходу** (с. Никулина Меленковской округи,
# церкви Спаса Нерукотвореннаго образа, священнику Николаю Ѳедорову).
# ⚠ **Тетрадь выдана Владимірской Духовной Консисторіей 8 генваря 1813 г.**, а
# пришнурована Муромскимъ Духовнымъ Правленіемъ — две инстанции на одной тетради.
#
# **Состав:** л. 414 — титул **и тут же ч. 1**; ч. 1 — лл. 414–423об (**65 записей**);
# ч. 2 — лл. 424–427об (**10 венчаній**); лл. 428, 429 — **чистые бланки ч. 2**;
# ч. 3 — лл. 430–436об (**24 м / 32 ж = 56**); **ведомость — л. 437**, заверка — л. 437об.
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ВЕДОМОСТЬ (л. 437) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** —
# **семнадцатый такой год подряд**. «Родившихся мужеска **37**, женска **28**, обоего пола
# **65**»; «бракосочетавшихся лицъ **20**, супружествъ **10**»; «умершихъ мужеска **24**,
