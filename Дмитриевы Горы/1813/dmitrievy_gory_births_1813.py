# никого быть не случилось».
#
# 🔴🔴 **САМАЯ РАННЯЯ ЗАПИСЬ О РОДЕ ВО ВСЁМ КОРПУСЕ — 26 ДЕКАБРЯ 1813 г.** (№ 64 ниже),
