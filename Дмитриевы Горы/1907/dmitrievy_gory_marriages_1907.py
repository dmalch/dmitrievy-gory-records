from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import (PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON,
                                   SOLDIER)

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1907 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**, лл. 363–368об
# (титул — л. 363, записи — на лл. 363об–368об). 28 браков за год.
#
# Как и в 1908 г., осенний мясоед берёт своё: **шестнадцать венчаний 3 октября**
# («Итого въ Октябрѣ совершено браковъ семнадцать» — л. 368об, семнадцатое
# 7 октября). И у всех шестнадцати одни и те же четверо поручителей — Евфимий
# Васильев Горячев и Иоанн Лавров Лужин по женихе, запасный солдат Максим
# Кириллин Залетнин и Стефан Тимофеев Скрулетов по невесте.
#
# Кекевы в одном браке из двадцати восьми — жених; Земсковых нет. Кроме того,
# **Димитрий Максимов Кекев** (двор 5, «запасный солдатъ») стоит поручителем по
# женихе брака № 9 от 8 июня (л. 365) — это самое раннее его появление в
# метриках и первое свидетельство, что семья вернулась в село из Ардатовского
# уезда Нижегородской губ., где перепись 1897 г. застала её целиком. Запись не
# заводится: правило прохода — Кекев участник, а не свидетель.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1907 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1907,
    *page("366об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ВЕНЧАНИЕ Григория Алексиева — третьего из братьев Алексиевых двора 3 переписи 1897
                          # г. (там ему 9 лет, здесь 19 и 11 месяцев, то есть род. ок. ноября 1887 г. —
                          # сходится). Первым браком, и первый его ребёнок родится через два года (Татиана, 10
                          # дек. 1909, л. 208об). ⚠ **ИМЯ НЕВЕСТЫ ЗДЕСЬ «АНИСІЯ», а не «Анна»**: жена Григория
                          # во всех позднейших записях — «Анна Даміанова» (1909, л. 208об; 1911, л. 18об
                          # д.199) и «Анна Дометіанова» (1913, л. 101об). Отчество редкое и совпадает, брак у
                          # обоих первый, а смерти Анисии Кекевой нет ни в 1907, ни в 1908 г. (обе части
                          # третьи прочитаны целиком) — значит это одна женщина, и в одном из двух написаний
                          # имя перепутано. Чтение сверено по скану при шестикратном увеличении. Главное, что
                          # даёт запись: её ДЕВИЧЬЯ фамилия — **Горячева**, а поручителем по жениху стоит
                          # Евфимий Васильев Горячев, то есть, по-видимому, её родня
                          marriage(18, 3,
                                   groom=person("Григорий", "Алексиев", last_name_orig="Кекев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age="19 лет 11 мес",
                                   bride=person("Анисия", "Дамианова", last_name_orig="Горячева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=19,
                                   witness1=person("Евфимий", "Васильев", last_name_orig="Горячев"),
                                   witness2=person("Иоанн", "Лавров", last_name_orig="Лужин"),
                                   witness3=person("Максим", "Кириллин", last_name_orig="Залетнин", status=SOLDIER, comment="запасный солдат"),
                                   witness4=person("Стефан", "Тимофеев", last_name_orig="Скрулетов")),
                          ),
          ),
    defaults=DEFAULTS,
)
