from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import SCARLATINA
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1907 г.,
# часть третья «О умерших». ГАВО ф.590 оп.12 д.**198**, лл. 369–378об
# (титул — л. 369, записи — на лл. 369об–378об). Итог года: м41 + ж51.
#
# Прочитано на ОБЕ фамилии. Кекев один, и он смыкается с частью первой того же
# года (см. запись о рождении № ж82); Земсковых нет.
#
# ⚠ **Январь 1907 г. — хвост скарлатины**, начавшейся в октябре 1906 г.: из
# одиннадцати погребённых в этом месяце десять умерли «отъ Скарлатины», и почти
# все — дети до пяти лет. Кекевский младенец в их числе; та же волна унесла в
# октябре и декабре 1906 г. трёх кекевских девочек (см. `../1906/`). Ни один
# другой месяц 1907 года такой волны не даёт.
#
# ⚠ **Возраст единственной записи ИСПРАВЛЕН при разборе 1906 года**: «1½ мца» —
# полтора месяца, а не полтора года, и младенец родился 26 ноября 1906 г.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1907 = death_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1907,
    *page("369об", reviewed=False,
          *death_month(Month.JANUARY,
                       # ⚠ ВОЗРАСТ В ИСТОЧНИКЕ — «1½ **мца**», то есть полтора МЕСЯЦА, а не полтора года: при
                       # первом чтении 1907 г. единица меры была прочитана неверно, и из неё выведено рождение
                       # около середины 1905 г. Разбор 1906 года это опроверг — младенец родился **26 ноября
                       # 1906 г.** (запись о рождении № м74, л. 310об), значит прожил сорок дней; графа
                       # сверена по скану при шестикратном увеличении и стоит в мужском столбце. Мать здесь не
                       # названа, но и в записи о рождении, и в декабрьской записи того же 1907 г. (№ ж82, л.
                       # 360об) жена Феодора Иоаннова — **Пелагия Феодорова**, первая. Умер в январской волне
                       # скарлатины, которая шла с октября 1906 г.: из одиннадцати погребений месяца десять
                       # «отъ Скарлатины». У Феодора Иоаннова это не последняя потеря — в 1910 г. умрёт
                       # четырёхмесячный Алексий (л. 421об), в 1913 г. двухлетний Василий (л. 117об д.199)
                       death(3, Gender.MALE, 5, 7,
                             deceased=person("Николай"), age="1 мес 15 дн",
                             relatives=[relative(person("Феодор", "Иоаннов", last_name_orig="Кекев"), Relationship.FATHER)],
                             cause_of_death=SCARLATINA),
                       ),
          ),
    # Вторая волна (09.11.2026): дети замужних дочерей Кекевых, найденные по имени мужа. reviewed=False.
    *page("377об", reviewed=False,
          *death_month(Month.OCTOBER,
                       # Любовь — дочь Иоанна Евфимиевича Юкачева и Матроны Романовны Кекевой, род. 16.09.1906 (1906 ч. 1, № ж52)
                       death(44, Gender.FEMALE, 29, 31,
                             deceased=person("Любовь"), age=1,
                             relatives=[relative(person("Іоаннъ", "Евфиміевъ", last_name_orig="Юкачевъ"), Relationship.FATHER)]),
                       ),
          ),
    defaults=DEFAULTS,
)
