from corpus.statuses import SHEPELEV_PEASANT, SHEPELEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import FEVER, THROAT

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1824 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 453, лл. 455–459об** (кадры альбома 13–18).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 26 м / 34 ж = 60 погребений**, и ведомость (л. 460) пишет
# ровно «умершихъ мужеска **26**, женска **34**, обоего пола **60**»; её возрастная
# разбивка мужчин («ниже году 5, году 6, 2 — 1, 3 — 1, 4 — 1, 7 — 1, 9 — 1, 13 — 1,
# 18 — 1, 25 — 1, 32 — 1, 35 — 1, 45 — 1, 54 — 1, 55 — 1, 58 — 1, 59 — 1») даёт «итого 26».
#
# ⓘ **Графа «Какою болѣзнію» есть и заполнена сплошь** — как в 1825 и 1826 гг. ⇒ пропуск
# 1827 года остаётся единственным за пять подряд прочитанных лет.
#
# ⚠⚠ **1824-й — ГОД «ОТЪ ГОРЛА», И ОН УБИВАЕТ НЕ МЛАДЕНЦЕВ, А ДЕТЕЙ ПОСТАРШЕ.** С начала
# октября до середины ноября причина почти всех погребений — «горломъ». **Андрей Павловъ
# теряет трёх дочерей за десять дней** (8 октября Евдокію 4 лѣтъ и Наталью 2, 18 октября
# Неонилу 15), **вдова Анна Ѳедорова — двух сыновей** (26 октября Іону 4 лѣтъ, 13 ноября
# Егора 13). ⇒ ведомость не зря считает по мужчинам «году — 6» и «13 — 1»: возрастной
# профиль этого года не похож ни на оспяной 1828-й, ни на коклюшный 1830-й.
# **Причину смерти между годами по-прежнему не переносить.**
#
# 🔴 **Погребений рода в году нет** — ни Ѳоки, ни Игната, ни Антона, ни их детей. Сын
# Игната **Семенъ**, родившийся 26 апрѣля (ч. 1 № 21), этот год переживает: его похоронят
# 11 іюля 1828 г. «4 лѣтъ».
#
# ✅ Вычитано по сканам в Verso 02.10.2026.
# Первое чтение: имена сверены кропом при 2.6× в сером.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

RETIRED_PRIEST = "заштатный священник"

dmitrievy_gory_deaths_1824 = death_records(
    "ГАВО", "556", "106", "453", "Дмитриевы Горы", "Покровская",
    1824,
    *page("456",
          *death_month(Month.MARCH,
                       # 🆕 **ЕДИНСТВЕННОЕ ЗА ПРОХОД ПОГРЕБЕНИЕ ПРИ САМОЙ ЦЕРКВИ, И ХОРОНИТ ЕГО СОБОР.** «Села
                       # Дмитріевыхъ горъ **заштатный Священникъ Стефанъ Ивановъ**, по исповѣди и святыхъ
                       # таинъ причастіи скончался», 59, «по горячкѣ» — «и погребенъ по церковному
                       # чиноположенію **при церкви** села [Кириллова?] Священникомъ **Симеономъ Елецкимъ** съ
                       # прочими разныхъ селъ Священниками, діаконами и причетниками и означеннаго села
                       # Дмитріевыхъ горъ священноцерковнослужителями», 7 марта. ⓘ Все прочие шестьдесят
                       # погребений года — «на отведенномъ кладбищѣ» и своим причтом. ⇒ место и состав
                       # служащих здесь сами по себе говорят о положении покойного: **заштатный**, то есть
                       # отставленный от места, но клир нескольких сёл съезжается. 🔗 Приход и так тесно связан
                       # с соседними: в этом же году у своего священника крестит сына денятинскій **Варсонофій
                       # Владимірскій**, а в 1825–1827 гг. постоянно служит воютинскій **Алексѣй Яковлевъ**
                       death(5, Gender.MALE, 6, 7,
                             deceased=person("Стефанъ", "Ивановъ", status=RETIRED_PRIEST),
                             age=59,
                             cause_of_death=FEVER),
                       ),
          ),
    *page("458об",
          *death_month(Month.OCTOBER,
                       # ⚠⚠ **ЖЕНЩИНА, КОТОРАЯ ЗА ОДИН ГОД РОДИЛА ОДНОГО СЫНА И ПОХОРОНИЛА ДВУХ.** «Тогожъ
                       # села и вотчины **вдовы Анны Ѳедоровой** сынъ **Іона**, 4, горломъ», погребенъ 28
                       # октября; через две с половиной недели её же сынъ **Егоръ, 13 лѣтъ**, «горломъ» (м. №
                       # 21, 13 ноября). А 13 іюня она родила сына **Леонтія** (ч. 1 № 27) — и кумомъ у него
                       # стоял **Антонъ Ѳедоровъ**. ⚠ В части первой она названа «**солдаткой**», здесь и в
                       # ноябре — «**вдовой**»: мужа, взятого в рекруты, к осени 1824 г. уже нет в живых. ⚡
                       # **И отчество у неё то же, что у братьев.** Вместе с «дѣвкой **Татьяной Ѳедоровой**»,
                       # кумой у сына Игната (ч. 1 № 21), это две зацепки на **сестёр** Антона, Игната и Ѳоки
                       # — но «Ѳедоровъ» самое частое отчество прихода, и решать должны ревизии, а не метрики.
                       # ⓘ Леонтія она переживёт ненадолго в смысле спокойствия: 1 февраля 1826 г. хоронят и
                       # его, «1½» (1826 ч. 3 м. № 2)
                       death(19, Gender.MALE, 26, 28,
                             deceased=person("Іона"),
                             age=4,
                             relatives=[relative(person("Анна", "Ѳедорова", status="вдова вотчины гг. Шепелевых"), Relationship.MOTHER)],
                             cause_of_death=THROAT),
                       ),
          ),
    *page("459",
          *death_month(Month.NOVEMBER,
                       # 🆕 **ЕДИНСТВЕННАЯ НЕНАТУРАЛЬНАЯ СМЕРТЬ ГОДА, И ВЕДОМОСТЬ НАЗЫВАЕТ ЕЁ ОТДЕЛЬНО.** «Села
                       # **Григорова** вотчины **Господина Макарова** крестьянинъ **Андрей Козминъ**, 55,
                       # **безъ исповѣди и святыхъ таинъ причастія, въ рѣкѣ Окѣ утопилъ[ся]**», погребенъ 24
                       # ноября. 🔗 Итог на л. 460 подтверждает: «въ семъ 1824-мъ году **не натуральною смертію
                       # умершихъ, кромѣ** [сего] утопшаго крестьянина, **не имѣлось**». Для сравнения: 1825,
                       # 1826 и 1827 гг. пишут «ненатуральною смертію умершихъ никого не имѣлось». ⓘ Человек
                       # **чужой вотчины и чужого прихода** — Ока течёт в семи верстах, и утонувшего хоронят
                       # там, куда вынесло. Приход вообще видит проезжих часто: в этом же году крестит сына
                       # рязанскій проѣзжающій крестьянинъ (ч. 1 № 47 — 1825 г.), кумомъ стоит **рядовой 10-го
                       # Егерскаго полка**, родится сын у **муромскаго мѣщанина Заворыкина**. ⚠ «Безъ
                       # исповѣди» при утоплении — формула, а не приговор: самоубийство церковь хоронила бы
                       # иначе, и запись стоит в общем ряду «на отведенномъ кладбищѣ по церковному
                       # чиноположенію»
                       death(22, Gender.MALE, 21, 24,
                             deceased=person("Андрей", "Косминъ", residence="Григорово", status="крестьянин вотчины г-на Макарова"),
                             age=55,
                             cause_of_death="утонул в реке"),
                       ),
          ),
    defaults=DEFAULTS,
)
