                          # крестьянскій сынъ **Сильвестръ Алексѣевъ Кекевъ**», 19 л. 2 мѣс., первымъ бракомъ, и
                          # «того же села крестьянская дочь **Евдокія Игнатьева**», 17 л. 11 мѣс., первымъ бракомъ
