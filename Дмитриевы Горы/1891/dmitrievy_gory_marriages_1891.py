# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**197**, лл. 65–72об
# (титул — л. 65, записи на лл. 65об–72об). **28 браков**, из них 19 — 2 октября.
#
# **ДВА КЕКЕВСКИХ ВЕНЧАНИЯ, И ОБА В ОДИН ДЕНЬ, 2 ОКТЯБРЯ.** Год, в котором
# женятся сразу двое: Сильвестр Алексеевич двора 3 и Иоанн Михайлович двора 2.
# Оба первым браком, Сильвестру девятнадцать, Иоанну восемнадцать, и поручителями у
# каждого стоит Кекев.
#
# ✅✅ **ВОПРОС 27 ЗАКРЫТ ПОЛНОСТЬЮ.** Жена Иоанна Михайловича в самой ранней
# прежде известной его записи (1895 г.) названа только именем — «Наталия». Брак
# № 20 даёт и отчество, и фамилию, и родину: **Наталья Егорова Козлова** (фамилия
# прочитана вычиткой 25.10.2026), **прихода села Санчуръ,
# деревни Муратовы**. Муратово уже стоит в `geni/locations.py` — оно добавлено
# по 1895 году, той же Дмитриево-Горской волости.
#
# ✅ **ОБА ПЕРВЕНЦА СХОДЯТСЯ С ДАТАМИ ВЕНЧАНИЙ.** Сын Сильвестра Иаков крещён
# 22 октября 1892 г. — через двенадцать месяцев; сын Иоанна Стефан 16 декабря
# 1892 г. — через четырнадцать. Ни у той, ни у другой пары ребёнка раньше нет,
# и это независимо подтверждает, что найденные в 1892 году метрики — первые.
#
# 🔴 **Возрасты дают годы рождения, которых корпус не имел** (вычитка 25.10.2026;
# прежде 19½, 17 л. 10 мес. и 19): Сильвестр Алексеевич 19 л. 2 мес. ⇒ ок. августа
# 1872 г.; Евдокия Игнатьева 17 л. 11 мес. ⇒ ок. ноября 1873 г.; Иоанн Михайлович 18 ⇒
# ок. 1873 г.; Наталья Егорова 20 ⇒ ок. 1871 г.
#
# ⚠ **Кекевских невест в году нет** — оба раза Кекев жених.
#
# ⚠ Не заведены: «деревни Кононовой крестьянскій сынъ **Трофимъ Павловъ Кузинъ**»
# (№ 8, 28 апреля) — отчество то же, что у двора 6, но он **другой деревни**, и
# «деревни Кононовой … **Яковъ Ивановъ Кс?левъ**» (№ 6), где фамилия не читается.
# «Вдовый крестьянинъ **Пётръ Максимовъ Сухаревъ**», 20½ (№ 27) — тот самый
# Максимович, что крестит у Кекевых в 1892 г.; в род не заводится.
# ⚠ Поручителем по невесте при браке № 17 стоит «запасно-отпускной солдатъ
# **Григорій Ѳокинъ**» — без фамилии, третий год подряд (1891, 1892, 1894).
#
# Вычитан в Verso 25.10.2026: 2 записи года, заведённых в DSL.

