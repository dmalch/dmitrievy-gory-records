# Метрическая книга Покровской церкви с. Димитриевы Горы за 1883 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**196**, л. 159 (титул),
# записи лл. 159об–173об. **ДВЕ записи.**
#
# ⚠ Заголовок части — «**КОПІЯ СЪ МЕТРИЧЕСКОЙ КНИГИ НА 1883**», как в 1884, 1886 и
# 1887 гг. Счёт раздельный, м/ж; **возраст в ДВУХ колонках** («Мужеска» / «Женска») —
# пол берётся из того, в какой колонке стоит число.
# ⚠ **«Отъ чего умеръ» — на ОБОРОТЕ** (в 1887 г. было на recto), поэтому ч. 3 1883 г.
# читается по одним оборотам целиком.
# ⚠ **Единица измерения пишется почти всегда** («2 недѣли», «9½ мѣс.», «5½ мѣс.»);
# голое число — это годы, и у взрослых оно доходит до 81. **Голое «½» — полгода**, а не
# полмесяца: двухнедельного младенца этот писец пишет «2 недѣли» (л. 165об, № м26).
#
# 🔴 **У ИГНАТІЯ ѲЕОДОРОВИЧА БЫЛА ДОЧЬ** (№ ж38) — Матрона, крещённая 29 октября 1882 г.
# (МК 1882, ч. 1 № ж62); сведено 19.10.2026 (matrona_ignatievna_1882). Она же —
# **третье появление Игнатія в этом году**: восприемникъ в октябре у брата Михаила (ч. 1,
# № ж42) и поручитель у Абашина (ч. 2, № 22).
#
# 🔴 **У ДИМИТРІЯ МАКСИМОВИЧА БЫЛА ДОЧЬ МАРЬЯ** (№ ж53; до вычитки 19.10.2026 — № ж59;
# отец сведён в dmitrij_maksimovich_kikeev), и она **ведёт в 1882 год**:
# полгода на 7 октября ⇒ род. около апреля 1883 г., а части первой 1883 г. такого
# рождения НЕТ — обороты 137об–140об перечитаны прицельно при 4× по графе родителей.
# Значит либо она родилась в 1882 г. и «½» округлено вверх, либо её метрика в этом
# годе записана без фамилии и мимо глаза. **Проверить в книге 1882 г.** (следующий год
# прохода). Косвенный довод за 1882-й: её брат **Иванъ** родился 14 января 1884 г.
# (ч. 1 1884 г., № м4), а зачат, стало быть, около 20 апреля 1883 г. — впритык к
# апрельским родам.
#
# ⚠ **НЕ ЗАВЕДЕНЫ (нет второго сигнала, правило 1/5 regional-rules):**
# • **«Николая КОЗЛИНА сынъ Михаилъ»**, ½, 1/3 июня (л. 164об). При 2,4× читалось
#   «**Кузина**» — и это была бы четвёртая фамилия прохода. При 14× первая гласная
#   круглая «о» без выносного: **Козлинъ**. Подтверждает ч. 2 того же года — «Василій
#   Козлинъ», поручитель в браке № 23. ⇒ **не Кузинъ**, и противоречие с венчанием
#   Николая Данилина Кузина 3 октября 1884 г. (17 л. 9 мѣс.) снято.
# • **«Григорія Ѳедорова сынъ младенецъ Козьма»**, 2 недѣли, 10/12 июля (л. 165об,
#   № м26) — голое отчество; он же поручитель в браке № 21 (см. ч. 2).
# • **«Лавра Флорова дочь Наталья»**, 4, и **«Василія Флорова сынъ Петръ»**, 3
#   (л. 171об, 13/15 и 20/22 октября, оба от скарлатины). Отчество «Флоровъ» стало
#   девятым отчеством рода только что, и соблазн записать двух новых Флоровичей велик;
#   но фамилии при обоих нет, а сыновья родоначальника ветви пишутся с фамилией (Алексѣй,
#   Иванъ, Николай — все «Кекевы» в 1884–1885 гг.). Флоровъ в селе к тому же не один:
#   восприемникъ ч. 1 этого года (№ м53) — **Флоръ Власовъ** (вычитка 19.10.2026; прежде
#   читано «Флоръ Ивановъ»). Голые Флоровы могут быть и родом Флоровыхъ. **Открытый вопрос.**
# • **«Филиппа Ѳокина дочь Елена»**, 2, 10/11 августа (л. 169об), и **«Николая Ѳокина
#   сынъ Ѳеодоръ»**, 1 мѣс., 22/24 августа (л. 168об) — те же голые Ѳокеевичи, что
#   1884 год уже оставил наводками (там у Филиппа умирает дочь Марья).
#
# ✅ **Проверено и снято**: «Алексѣя Матвѣева Еськина дочь Екатерина», 4 дней, 21/23
# ноября (л. 172об) — при 2,4× читалось «Аникиты Ѳокеева», что дало бы Аникиту
# Ѳокеевича Кекева. Но ч. 1 того же года крестит её 19 ноября (№ ж54, отец «Алексѣй
# Матвѣевъ Еськинъ», мать Ульяна Максимова): **четыре дня сходятся, и это не наш род.**
#
# Вычитан в Verso 19.10.2026: две записи года, заведённых в DSL.

