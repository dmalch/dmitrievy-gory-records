from verso.ru.dsl import (Month, RecordDefaults, Side, marriage, marriage_month, marriage_records,
                          page, person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1883 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**196**, л. 153 (титул),
# записи лл. 153об–158об. **30 браков**: январь 6 (№ 1–6), февраль 2 (№ 7–8),
# апрель 2 (№ 9–10), май 1 (№ 11), июнь 1 (№ 12), октябрь 18 (№ 13–30, из них
# **шестнадцать 2 октября** — № 13–28). Последнее венчание — 31 октября.
#
# **ОДНА запись.** Прочитаны все шесть оборотов; recto (поручители) снято `spread`-ом
# по всем шести разворотам — построчно, потому что поручители в этом приходе и есть
# главный улов части второй.
# ⚠ Форма как везде в ч. 2: оборот несёт счётъ, мѣсяцъ и день, жениха, невесту и лѣта
# обоих; **поручители — на RECTO**. (В ч. 1 этого года наоборот — воспріемники на
# обороте.)
#
# 🔴🔴🔴 **БРАК № 22 — ЛОВУШКА, КОТОРУЮ СНЯЛ КОРПУС, А НЕ СКАН.** Жених — «крестьянскій
# сынъ **Ѳедоръ Ѳедоровъ**», 17½, первымъ бракомъ; поручитель по нему — **Игнатій
# Ѳедоровъ**. По обычаю прихода поручитель по жениху родня, и ровно этим доводом 1884
# год признал женихом брата Игнатія (брак № 17, Николай Ѳедоровъ). Здесь тот же довод
# ведёт в ложную сторону: **невеста — «Настасья Петрова», 21 год**, а корпус уже знает
# эту пару — «**Ѳедоръ Ѳедоровъ АБАШИНЪ** и жена его **Настасья Петрова**», родители
# Марьи, крещённой 14 марта 1888 г. (ч. 1 1888 г., № ж10). ⇒ **жених не Кекевъ, а
# Абашинъ, и это его венчание.**
#
# ✅✅ **ЗАТО СВЯЗЬ КЕКЕВЫХЪ И АБАШИНЫХЪ ОТОДВИНУТА С 1888 НА 1883 г.** 1888-й год
# отметил её дважды («Абашины и Ѳеодоровичи связаны дважды за год»): Андрей и Ирина
# Ѳедоровы Кекевы держат дочь Ѳедора Абашина, а Игнатій Ѳедоровъ Кекевъ стоит поручителем
# у его брата Михаила. **Здесь Игнатій стоит поручителем у самого Ѳедора, за пять лет
# до того** — связь семей не эпизод, а обычай.
#
# ⚠⚠ **И ЭТО ПРЕДОСТЕРЕЖЕНИЕ НА ВЕСЬ ПРОХОД.** В селе два рода Ѳеодоровичей — Кекевы и
# Абашины, — и «X Ѳедоровъ» без фамилии не опознаёт человека даже при родственном
# поручителе. Правило 5 regional-rules («фамилия решает, отчество не решает ничего»)
# работает и там, где второй сигнал вроде бы есть.
#
# ⚠ **НЕ ЗАВЕДЕНЫ (нет второго сигнала):**
# • **«Николай Ѳедоровъ»** — поручитель по невесте в браке № 5 (16 января, л. 153об/154).
#   Корпусный Николай Ѳеодоровичъ Кекевъ венчается в октябре 1884 г. в 19 л. 10 мѣс.
#   ⇒ в январе 1883 г. ему 18 лет, и поручительство возможно. Но после брака № 22
#   «Николай Ѳедоровъ» с равным правом Абашинъ.
# • **«Григорій Ѳедоровъ»** — поручитель по невесте в браке № 21 (2 октября). Он же
#   отец младенца Козьмы, погребённого 12 июля (ч. 3, № м26). Два появления за год,
#   и ни одного с фамилией.
# • **«Егоръ Ѳедоровъ»** (брак № 14), **«Яковъ Ѳедоровъ»** (брак № 7), **«Козьма
#   Ѳедоровъ»** (брак № 2), **«Василій Ѳедоровъ»** (брак № 12), **«Максимъ Ѳокинъ»**
#   (брак № 4) — тот же класс.
#
# ⓘ Побочно: **Кузиныхъ, Земсковыхъ и Акиллиныхъ в части второй 1883 г. нет вовсе** —
# ни женихами, ни невестами, ни поручителями. Проверено по всем шести разворотам.
#
# Вычитан в Verso 19.10.2026: одна запись года, заведённая в DSL. Фамилии «Абашинъ», которую
# DSL ставил жениху № 22 по корпусу, источник не пишет — вычитка её сняла; каноник
# fedor_fedorovich_abashin держит её по метрике 1888 г.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1883 = marriage_records(
    "ГАВО", "590", "12", "196", "Дмитриевы Горы", "Покровская",
    1883,
    *page("156об",
          *marriage_month(Month.OCTOBER,
                          # 🔴🔴 **ВЕНЧАНИЕ ѲЕДОРА ѲЕДОРОВА АБАШИНА, И ОНО ЖЕ — ПРЕДОСТЕРЕЖЕНИЕ ПРОХОДУ.** «Того
                          # же села крестьянскій сынъ **Ѳедоръ Ѳедоровъ**», 17½, первымъ бракомъ; невѣста —
                          # «того же села крестьянская дочь **Настасья Петрова**», 21 г., первымъ бракомъ
                          # (`spread` л. 156об/157 при 2,6×). Фамилии при женихе источник не даёт. **Пару
                          # опознаёт корпус, а не скан**: в 1888 г. (ч. 1, № ж10) «**Ѳедоръ Ѳедоровъ Абашинъ**
                          # и жена его **Настасья Петрова**» крестят дочь Марью. Имя, отчество, имя жены и её
                          # отчество сходятся ⇒ **это его венчание, и он не Кекевъ**. Род. ок. апреля 1866 г.
                          # ⚠⚠ **Поручитель по жениху — «Игнатій Ѳедоровъ», и по обычаю это родня.** Ровно так
                          # 1884 год признал Николая Ѳедорова братом Игнатія (брак № 17). Здесь тот же довод
                          # даёт ложный ответ: **Ѳеодоровичей в селе два рода**, и Кекевы стоят у Абашиныхъ
                          # постоянно. ✅✅ **Связь двух семей отодвинута с 1888 на 1883 г.**: в 1888 г. Игнатій
                          # Ѳедоровъ Кекевъ поручительствует у **брата** этого жениха, Михаила Ѳедорова
                          # Абашина (ч. 2, № 23), а Андрей и Ирина Ѳедоровы Кекевы держат **его дочь**. Здесь
                          # он стоит у него самого. 🔴 **Игнатій Ѳеодоровичъ отодвинут с 1884 на 1883 г.**
                          # (вторым разом того же года — ч. 1, № ж42, восприемникъ у брата Михаила). ⚠ Второй
                          # поручитель по
                          # жениху — «Михаилъ Григорьевъ», по невѣстѣ — «Іосифъ и Петръ Даниловы» (фамилия
                          # писана во множественном числе на двоих, как принято в этом приходе); к роду никто
                          # из них не ведёт
                          marriage(22, 2,
                                   groom=person("Ѳедоръ", "Ѳедоровъ", status=PEASANT_SON),
                                   bride=person("Настасья", "Петрова", status=PEASANT_DAUGHTER),
                                   groom_marriage_num=1, bride_marriage_num=1,
                                   groom_age="17 л 6 мес", bride_age=21,
                                   witness1=person("Михаилъ", "Григорьевъ", side=Side.GROOM),
                                   witness2=person("Игнатій", "Ѳедоровъ", side=Side.GROOM),
                                   witness3=person("Іосифъ", "Даниловъ", side=Side.BRIDE),
                                   witness4=person("Петръ", "Даниловъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
