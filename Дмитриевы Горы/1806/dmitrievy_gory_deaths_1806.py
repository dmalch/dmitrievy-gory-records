from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DROPSY, NATURAL

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1806 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 208, лл. 506об–511** (кадры 0513–0517).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 33 м / 19 ж = 52 погребенія**, и ведомость (л. 511об)
# пишет ровно «умершихъ мужеска **33**, женска **19**, обоего **52**». Возрастная разбивка
# мужчин сошлась и содержит строку **«65 — 4»**, одна из которых — запись ниже.
# ⓘ Ненатуральная смерть названа отдельно: **Гаврила Андреевъ**, 62 лѣтъ, «**задавленъ
# глиною**», по свидѣтельству Нижняго Земскаго Суда (м. № 19, 12 сентября).
#
# 🏆🏆🏆 **ГОД ХОРОНИТ ДВУХ ХАРИТОНОВЫХЪ, И ОДИН ИЗ НИХ — СТАРШИЙ ИЗ ВСЕХ, КОГО ПРОХОД
# НАШЁЛ ЗА ЭТИМ ОТЧЕСТВОМ.** м. № 11 — **Никифоръ Харитоновъ, 65 лѣтъ** (⇒ род. ок. 1741);
# м. № 23 — **Григорій, сынъ Василія Харитонова, 6 лѣтъ** (⇒ род. ок. 1800).
# ⓘ Год хоронит и **Трофима Родіонова, 36 лѣтъ, горячкою** (м. № 5, 13 марта) — мужа
# **Офимьи Харитоновой**, после чего она становится вдовой, какой её знает 1810 год.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 7×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1806 = death_records(
    "ГАВО", "556", "106", "208", "Дмитриевы Горы", "Покровская",
    1806,
    *page("507об",
          *death_month(Month.JUNE,
                       # 🏆🏆🏆 **НИКИФОРЪ ХАРИТОНОВЪ — СТАРШИЙ НОСИТЕЛЬ ОТЧЕСТВА ЗА ВЕСЬ ПРОХОД.** «Приходу
                       # Означеннаго Села вотчины Господина Баташева **крестьянинъ НИКИФОРЪ ХАРИТОНОВЪ** по
                       # исповѣди и Святыхъ таинъ причастія скончался и погребенъ на кладбищѣ по церковному
                       # чиноположенію мѣсяца іюня 13 дня», **65** лѣтъ, натуральною (сверено при 7×; возраст
                       # подтверждён строкой «65 — 4» в ведомости л. 511об). ⇒ **род. ок. 1741 г.** 🔴🔴 **И ЭТО
                       # ЕДИНСТВЕННОЕ, ЧТО МЕТРИКИ ГОВОРЯТ О ХАРИТОНѢ.** Если Никифоръ — сын того же Харитона,
                       # что Ѳедоръ (род. ок. 1760) и Василій (ок. 1767), то **Харитонъ род. ок. 1715–1720
                       # г.**, и разброс между старшим и младшим сыном — двадцать шесть лет, то есть у
                       # Харитона было **два брака**. ⚠⚠ **Но это догадка, и вот почему она слабее прочих.**
                       # Венчаніе 1808 года доказало, что «Харитоновъ» в этом приходѣ — **дедичество**,
                       # семейное прозвание, которым зовут и внуков Харитона. ⇒ Никифоръ может быть и сыном
                       # Харитона, и его племянником, и вовсе однофамильцем; двадцатишестилетний разрыв скорее
                       # говорит за **два поколения**, чем за одно. 📍 Разделить их метрики не могут:
                       # **Харитонъ не крестит, не ручается и не хоронится ни в одной из двадцати пяти
                       # прочитанных книг** (1803–1830) ⇒ он умеръ **до 1803 г.**, и его надо искать в
                       # сдвоенных книгах 1778–1799 гг. или в ревизиях
                       death(11, Gender.MALE, 12, 13,
                             deceased=person("Никифоръ", "Харитоновъ"),
                             age=65,
                             cause_of_death=NATURAL),
                       ),
          ),
    *page("509",
          *death_month(Month.OCTOBER,
                       # 🏆 **СЫНЪ ВАСИЛІЯ ХАРИТОНОВА — И ОН ОТ ПЕРВОЙ ЖЕНЫ.** «Приходу Означеннаго Села
                       # вотчины Господина Баташева, **крестьянина ВАСИЛЬЯ ХАРИТОНОВА сынъ ГРИГОРІЙ**, по
                       # исповѣди и Святыхъ таинъ причастія скончался и погребенъ на кладбищѣ по церковному
                       # чиноположенію мѣсяца октября 10 дня», **6** лѣтъ, водяною (сверено при 7×). ⇒ **род.
                       # ок. 1800 г.**, то есть **за три года до венчанія отца с Авдотьей Арефьевой** (17
                       # апрѣля 1803 г., оба вторымъ бракомъ, 1803 ч. 2 № 4) ⇒ Григорій — ребёнокъ **первой**
                       # жены Василія, имени которой корпус не знает, как и его сестра **Татьяна** (25 лѣтъ в
                       # РС-7 1816 г. ⇒ род. ок. 1791). 🔗 **Полный счёт детей Василія Харитонова**: от первого
                       # брака — **Татьяна** (ок. 1791), **Емеліанъ** (8 августа 1799 г., 1799 ч. 1 № 30) и
                       # **Григорій** (ок. 1800 – 9 октября 1806); от второго — **Настасья** (8 марта 1806),
                       # **Родіонъ** (8 ноября 1807) и **Прасковья** (28 августа 1810). ⇒ **из шести детей
                       # ревизия 1816 года застаёт в живых одну Татьяну**, и комментарий корпуса «своих
                       # сыновей у него нет» отозван окончательно: сыновей было **трое**, и всех троих он
                       # похоронил
                       death(23, Gender.MALE, 9, 10,
                             deceased=person("Григорій"),
                             age=6,
                             relatives=[relative(person("Василій", "Харитоновъ"), Relationship.FATHER)],
                             cause_of_death=DROPSY),
                       ),
          ),
    defaults=DEFAULTS,
)
