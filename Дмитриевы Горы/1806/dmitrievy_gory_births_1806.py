# Метрическая книга Покровской церкви с. Димитріевы Горы за 1806 г., часть первая
# «О родившихся». **ГАВО ф. 556 оп. 106 д. 208, лл. 497–504об** (кадры 0503–0511).
#
# ⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 497–511об**; альбом
# захватывает чистый л. 496об и лл. 512–513. Кадры .tif. ⓘ **Сплошная проза без бланка**,
# нумерация раздельная по полу — как в 1803 и 1805 гг.
#
# **Состав:** л. 497 — титул и тут же ч. 1; ч. 1 — лл. 497–504об (**41 м / 68 ж = 109**);
# ч. 2 — лл. 505–506 (**11 венчаній**); ч. 3 — лл. 506об–511 (**33 м / 19 ж = 52**);
# **ведомость — л. 511об**.
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ВЕДОМОСТЬ СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** — **двадцать
# третій такой год подряд**. «Родившихся мужеска **41**, женска **68**, обоего **109**»;
# «браковавшихся лицъ **22**, супружествъ **11**»; «умершихъ мужеска **33**, женска
# **19**, обоего **52**». ⓘ Перекос рождений (68 девочек против 41 мальчика) — самый
# резкий за проход. ⓘ Ненатуральная смерть названа отдельно: **Гаврила Андреевъ**,
# 62 лѣтъ, «**задавленъ глиною**» (ч. 3 м. № 19, 12 сентября).
# ⚠ **Поручителей год не записывает** — как 1803 и 1805 гг.
#
# 🏆🏆🏆🏆🏆 **ГЛАВНОЕ: м. № 26 — МЕТРИКА ПРОКОПІЯ, И ОНА ДОКАЗЫВАЕТ, ЧТО ѲОКА И ѲОТІЙ
# ѲЕДОРОВЫ — ОДИН ЧЕЛОВЕК.** 3 іюля у **Ѳоки Ѳедорова** и **Саломеи Петровой** родился
# сынъ **Прокопій**; 16 ноября 1813 г. хоронят «крестьянина **Ѳотія Ѳедорова** сына
# **Прокопія**, 8 лѣтъ» (1813 ч. 3 м. № 23). **Тот же сын, та же жена, два написания
# имени отца.** До сегодня отождествление держалось на совпадении имени жены; теперь оно
# держится на **общем ребёнке**.
#
# 🏆 **И ГОД ДАЁТ ЕЩЁ ТРИ ЗАПИСИ О ХАРИТОНОВЫХЪ:** ж. № 19 — дочь **Настасья** у Василія
# Харитонова и Авдотьи Арефьевой; м. № 33 — сынъ **Иванъ** у Семена Ефримова и **Овдотьи
# Харитоновой**; а часть третья хоронит **Никифора Харитонова, 65 лѣтъ**, и **Григорія,
# сына Василія Харитонова, 6 лѣтъ** (см. `dmitrievy_gory_deaths_1806.py`).
# ⓘ **Василій Харитоновъ назван в году четырежды**: кумъ 14 генваря (м. № 3, у Саввы
# Дорофеева), отец 17 марта (ж. № 19), кумъ 25 сентября (м. № 33) и кумъ 11 ноября
# (м. № 37, у Василія Кирилова).
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 6–7×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE, status_mother=BATASHEV_PEASANT_WIFE)

dmitrievy_gory_births_1806 = birth_records(
    "ГАВО", "556", "106", "208", "Дмитриевы Горы", "Покровская",
    1806,
    *page("499об",
          *birth_month(Month.MARCH,
                       # 🏆 **ПЕРВЫЙ РЕБЁНОКЪ ВАСИЛІЯ ХАРИТОНОВА ОТ ВТОРОЙ ЖЕНЫ.** «…у крестьянина **Василья
                       # Харитонова** и отъ жены его **Овдотьи Арефьевой** родилась дочь **Настасья** мѣсяца
                       # марта 8 дня, молитвована и крещена въ домѣ тогожъ мѣсяца 17 дня… воспріемники были:
                       # оной же вотчины и Села **крестьянской сынъ отрокъ Ѳедоръ Семеновъ** и крестьянская
                       # дочь дѣвка **Пелагея Арефьева**» (обе половины при 6×). 🔗 **Оба кума — свои.**
                       # Венчались Василій и Авдотья **17 апрѣля 1803 г.**, оба вторымъ бракомъ (1803 ч. 2 №
                       # 4) ⇒ Настасья — первая из троих детей этого брака (после неё **Родіонъ** 1807 и
                       # **Прасковья** 1810). Кума **Пелагея Арефьева** — по отчеству сестра матери; в 1807 г.
                       # Василій будет ручаться на её свадьбѣ, и там назовут её отца — **Арефій Ивановъ**
                       # (1807 ч. 2 № 16). Кумъ **Ѳедоръ Семеновъ**, «крестьянской сынъ отрокъ», встанет у
                       # купели и двух следующих детей Василія — в 1807 и 1810 гг. Три раза подряд. ⚠
                       # **Настасьи нет в ревизии 1816 г.**, как нет Родіона и Прасковьи. Её погребенія нет ни
                       # в одной прочитанной части третьей 1806–1810 гг. ⇒ она умерла в **1811 году**, альбома
                       # за который нет — как и двое младших
                       birth(19, Gender.FEMALE, 8, 17,
                             child=person("Настасья"),
                             father=person("Василій", "Харитоновъ"),
                             mother=person("Овдотья", "Арефьева"),
                             god_parent1=person("Ѳедоръ", "Семеновъ", status="крестьянский сын отрок вотчины г-на Баташева"),
                             god_parent2=person("Пелагея", "Арефьева", status="крестьянская дочь девка вотчины г-на Баташева")),
                       ),
          ),
    *page("501об",
          *birth_month(Month.JULY,
                       # 🏆🏆🏆🏆🏆 **ЭТА ЗАПИСЬ ДОКАЗЫВАЕТ, ЧТО ѲОКА И ѲОТІЙ ѲЕДОРОВЫ — ОДИН ЧЕЛОВЕК.** «…у
                       # крестьянина **Ѳоки Ѳедорова** и отъ жены его **Саломеи Петровой** родился сынъ
                       # **Прокофій** іюля 3 дня, молитвованъ и крещенъ въ церкви тогожъ іюля 8 дня…
                       # воспріемники были: крестьянинъ **Панфилъ Ивановъ** и **солдатка Екатерина Петрова**»
                       # (сверено при 6×). 🔴🔴 **ПОТОМУ ЧТО ЭТОГО САМОГО ПРОКОПІЯ ХОРОНЯТ КАК СЫНА ѲОТІЯ.** 16
                       # ноября 1813 г.: «крестьянина **Ѳотія Ѳедорова** сынъ **Прокопій**», **8** лѣтъ,
                       # горячкою (1813 ч. 3 м. № 23). От 3 іюля 1806 г. до 16 ноября 1813 г. — **7 лет 4
                       # месяца**, и писец округляет вверх, как он это делает всегда. ⇒ **один и тот же сын,
                       # одна и та же жена, два написания имени отца**. Прежде отождествление держалось на
                       # совпадении имени жены (Саломея Петрова в 1810-м, Саломида Петрова в 1812-м); теперь
                       # оно держится на **общем ребёнке**, и это доказательство. ⛔ **Окончательно закрыт
                       # «второй, взрослый Ѳока Ѳедоровъ»**, которого завело прочтение 1814 года. Его нет:
                       # есть **Ѳотій**, он же **Ѳокій**, он же **Ѳока**, — поручитель на свадьбѣ Антона 9
                       # октября 1810 г., поручитель в 1807, 1808 и 1814 гг. и кумъ у трёх детей Антона (1815,
                       # 1816, 1818). 🔗 **И его возраст теперь тоже осмыслен**: сынъ род. 1806 ⇒ женился он не
                       # позже 1805 г., а не «1804 или раньше», как выводилось из округлённого возраста при
                       # погребеніи. Версия «старший брат» (род. ок. 1785 или раньше) держится, но её
                       # арифметика ослабла: по этой метрикѣ он мог родиться и ок. 1785, и позже. ⚠ Решает
                       # ревизия
                       birth(26, Gender.MALE, 3, 8,
                             child=person("Прокофій"),
                             father=person("Фока", "Федоровъ"),
                             mother=person("Саломея", "Петрова"),
                             god_parent1=person("Панфилъ", "Ивановъ"),
                             god_parent2=person("Екатерина", "Петрова", status=SOLDIER_WIFE)),
                       ),
          ),
    *page("503",
          *birth_month(Month.SEPTEMBER,
                       # 🔴 **ТА ЖЕ ЧЕТВЁРКА У КУПЕЛИ ВТОРОЙ РАЗ ИЗ ТРЁХ.** «…у крестьянина **Семена Ефримова**
                       # и отъ жены его **Овдотьи Харитоновой** родился сынъ **Иванъ**, сентября 23 дня…
                       # воспріемники были: оной же вотчины **крестьянинъ Василій Харитоновъ** и крестьянская
                       # дочь дѣвка **Агафья Ефримова**» (обе половины при 6×). 🔗 Те же родители и те же
                       # кумовья стоят у купели **1 ноября 1803 г.** (дочь Параскева, 1803 ч. 1 ж. № 32, где
                       # отец назван **земскимъ**) и **27 марта 1809 г.** (сынъ Гавріилъ, 1809 ч. 1 № 28, где
                       # мать записана «**Евдосія** Харитонова»). ⇒ **Овдотья = Евдокія = Евдосія**, одна
                       # женщина, и это **не** та Авдотья Харитонова, что в 1808 г. вышла за Максима
                       # Васильева: та — дочь Ѳедора Харитонова. ⚠ Двух тёзок в одном приходѣ различает только
                       # муж. ⚠ **Орфография источника**: писец 1806 года пишет «Семенъ **Ефримовъ**»,
                       # «**Овдотья** Харитонова» и «Агафья **Ефримова**» — метатеза и просторечная форма. В
                       # DSL взяты написания 1803 и 1809 гг. («Ефимовъ», «Авдотья»), чтобы три записи об одной
                       # семье не рассыпались на трёх разных людей при сводѣ
                       birth(33, Gender.MALE, 23, 25,
                             child=person("Иванъ"),
                             father=person("Семенъ", "Ефимовъ"),
                             mother=person("Овдотья", "Харитонова"),
                             god_parent1=person("Василій", "Харитоновъ"),
                             god_parent2=person("Агафья", "Ефимова", status="крестьянская дочь девка вотчины г-на Баташева")),
                       ),
          ),
    defaults=DEFAULTS,
)
