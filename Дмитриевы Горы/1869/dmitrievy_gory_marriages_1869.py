from verso.ru.dsl import (Month, RecordDefaults, Side, marriage, marriage_month, marriage_records,
                          page, person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1869 г., часть вторая
# «О бракосочетавшихся». **ГАВО ф. 590 оп. 5 д. 34**, титул — л. 613 (чистый recto),
# записи лл. 613об–619об (закрывающий recto — л. 620). **ОДНА запись из 31.**
#
# ⚠⚠ **Консисторская копия** — см. шапку файла о рождениях.
#
# ⚠ **В ч. 2 этой копии поручители стоят на RECTO** (в отличие от ч. 1 и ч. 3, которые
# читаются по одним оборотам). Обороты дают счёт, день, жениха с невестой и их лета;
# recto — «Кто совершалъ таинство», «Кто были поручители» и подпись свидѣтелей.
# Поручители этой записи прочитаны вычиткой 12.10.2026 на recto л. 618.
#
# ⓘ **31 брак за год**, из них **шестнадцать 3 октября** — послепокровский день, тот же,
# что в 1872 г. (четырнадцать браков 2 октября) и в 1881 г. Декабрьских венчаний нет.
#
# 🔴🔴 **ѲЕДОРА КАРПОВА — ДОЧЬ КАРПА, И КАРПЪ СЕЛЬСКІЙ.** Корпус знал Карпа только как
# отчество **Максима Карпова** (ок. 1824, † 1882, 58 л., «Максимъ Карповъ Кикевъ» — та
# запись и дала роду небывалое отчество и неизвестного деда). Здесь названа его дочь,
# и **селение при ней — село**, тот же помещичий приход. В том же году Максимъ Карповъ
# стоит восприемникомъ 3 декабря (ч. 1 № ж83): брат и сестра в одной книге.
#
# ⚠⚠ **И это снимает довод 1880 года.** Разбор МК 1880 утверждал, что отчество «Карповъ»
# в приходе больше не встречается и потому однозначно опознаёт Максима. 1869 год даёт
# **двоих**: сельскую Ѳедору и **кононовского Тимофея Карпова** (ч. 1 л. 600об, дочь
# Марѳа; она же погребена 1 августа, ч. 3 л. 630об). Та же развилка село/Кононово, что
# у Ѳокиныхъ, и опираться на одно отчество больше нельзя.
#
# Сверено кропом при 9×, вычитано в Verso 12.10.2026; год не перечитан вторым сплошным
# проходом.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE,
                          status_bride=PEASANT_DAUGHTER,
                          status_groom=PEASANT_SON)

dmitrievy_gory_marriages_1869 = marriage_records(
    "ГАВО", "590", "5", "34", "Дмитриевы Горы", "Покровская",
    1869,
    *page("617об",
          *marriage_month(Month.OCTOBER,
                          # 🔴🔴 **ДОЧЬ КАРПА — ДЕДА, КОТОРОГО КОРПУС ЗНАЛ ТОЛЬКО ПО ОТЧЕСТВУ СЫНА.** «Того же
                          # села крестьянская дочь **Ѳедора Карпова**», 17½ (⇒ ок. 1852 г.), первымъ бракомъ
                          # (сверено при 9×: К-а-р-п-о-в-а). ✅ **Второй сигнал стоит в том же году**: 3
                          # декабря 1869 г. восприемникомъ у Кузьмы Ѳедорова стоит «того же села крестьянинъ
                          # **Максимъ Карповъ**» (ч. 1 № ж83) — та же рука, та же форма отчества. Брат и
                          # сестра в одной книге, оба сельскіе. ⚠ **Родство источником не сказано** и в записи
                          # не проставлено: сводит их редкое отчество при одном селении. Разница в возрасте
                          # велика — Максиму здесь около 45, Ѳедорѣ 17½ (28 лет) ⇒ либо у Карпа два брака,
                          # либо родство иное (напр. племянница). ⚠⚠ **Отчество «Карповъ» в приходе НЕ
                          # уникально** — 1869 год даёт и кононовского **Тимофея Карпова** (ч. 1 л. 600об).
                          # Довод разбора 1880 г. («в приходе больше не встречается») этим снят. 🔴 **Но
                          # поручитель по невесте — сам Максимъ Карповъ**: «по невѣстѣ, того же села крестьяне:
                          # **Максимъ Карповъ** и Емельянъ Николаевъ» (л. 618, вычитка 12.10.2026, сверено по
                          # скану); по жениху — «Иванъ и Ѳедоръ Петровы». Поручитель со стороны невесты — как
                          # правило её родня ⇒ связь Ѳедоры с Максимомъ теперь стоит на записи, а не только на
                          # отчестве; что он брат, а не другой родственник, источник всё ещё не говорит. ⚠
                          # Жених роду не принадлежит — запись заведена ради невесты
                          marriage(22, 3,
                                   groom=person("Алексѣй", "Степановъ"),
                                   bride=person("Ѳедора", "Карпова"),
                                   groom_age="17 лет 8 месяцев", bride_age="17 лет 6 мес",
                                   groom_marriage_num=1, bride_marriage_num=1, witness1=person("Иванъ", "Петровъ", side=Side.GROOM), witness2=person("Ѳедоръ", "Петровъ", side=Side.GROOM), witness3=person("Максимъ", "Карповъ", side=Side.BRIDE), witness4=person("Емельянъ", "Николаевъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
