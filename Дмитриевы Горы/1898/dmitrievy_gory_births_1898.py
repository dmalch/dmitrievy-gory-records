# Метрическая книга Покровской церкви с. Димитриевы Горы за 1898 г.,
# часть первая «О родившихся». ГАВО ф.590 оп.12 д.**197**, лл. 260–277об
# (титул — л. 260, записи на лл. 260об–277об).
#
# Читано на четыре фамилии — Кикев/Кекев, Земсков, Кузин и Акиллин.
# **ДВЕ записи**, где отец нашего рода, — после тринадцати рождений 1899 года
# год выглядит пустым, но пустота эта только в части первой: часть третья даёт
# **пять кекевских погребений**.
#
# ❌ **ИСПРАВЛЕНО 04.09.2026: третья запись (№ ж37, Любовь, 15 сент., л. 271об)
# ИЗЪЯТА — это не Кузины, а КОЗЛОВЫ.** Отец был прочитан «Михаилъ Павловъ
# КУЗИНЪ» и по отчеству отнесён ко двору 6; скан перечитан по наводке 1896 года
# (где та же пара — Михаил Павлов + Наталия Павлова — написана «Козловъ», л.
# 187об, и где «Михаилъ Павловъ Козловъ» стоит поручителем по невесте Анне
# Іосифовой **Козловой**, брак № 9). На л. 271об при увеличении читается
# **КОЗЛОВЪ**, с характерным «з»; восприемница той же записи — Варвара Петрова
# **Козлова**. Погребение той же девочки (ч. 3, № ж49, л. 293об) читается так же
# и изъято вместе с ней. ⇒ **Двор 6 в 1898 г. представлен ОДНИМ братом —
# Григорием Павловым Кекевым (ч. 3, № ж4)**, а формула «одна книга, один двор,
# две фамилии на двух братьях» из этого года снимается: она держалась на
# ошибке чтения.
#
# ⚠⚠ **Двойная фамилия в 1898 г. стоит на ДВУХ РАЗНЫХ Феодоровичах сразу** —
# «Ѳеодоръ Іоанновъ Кекевъ **тоже Земсковъ**» (л. 260об) и «Алексѣй Флоровъ
# Кекевъ», где «тожъ Земсковъ» писец зачернул (л. 266об; вычитка 28.10.2026), — а в
# части третьей она же написана в
# ОБРАТНОМ порядке: «Николая Ѳеодорова **Земскова, тожъ Кекева**» и «Алексѣя
# Ѳеодорова **Земскова, тожъ Кекева**». Ни в одном другом году корпуса обе
# фамилии не меняются местами. После 1899 г., где та же связка доказана женой
# Игнатия Феодоровича, это просто ещё четыре подтверждения.
#
# ⚠ Кекевы-восприемники: **Андрей Іоанновъ Кекевъ**, «крестьянскій сынъ»
# (дважды — лл. 261 и 273), то есть МЛАДШИЙ Андрей четырнадцати лет, за четыре
# года до своего венчания; **Анна Іоаннова Кекева**, «крестьянская женка»
# (л. 261) — жена Георгия Иоанновича; и **Анна Николаева Кекева тожъ
# Земскова**, «крестьянская дѣвица» (л. 261).
#
# ⚠⚠ **«Анна Николаева Кекева тожъ ЗЕМСКОВА» разводит двух тёзок.** Корпус знал
# «Анну Николаеву Кекеву» дѣвицей (1902) и «Анну Николаеву Кекеву тожъ
# КУЗИНУ» — женкой (1900), и звания не сходились. Теперь видно, что двойная
# фамилия при этом имени бывает РАЗНАЯ: Земскова (двор 4) и Кузина (двор 6).
# По отчеству земсковская — дочь Николая Феодоровича, который в этом же году
# хоронит дочь Параскеву. ⇒ Анн Николаевых Кекевых, скорее всего, ДВЕ.
#
# ⚠ Вставные посторонние листы части первой: **л. 264** (удостоверение
# Меленковского уездного ЗАГС № 311 от 1922 г. о рождении 26 марта 1898 г.
# Ивана Кирилловича Данилова; оборот чист и не снят) и **лл. 272–272об**
# (печатный приговор Земского Начальника 5-го участка Ардатовского уезда
# Нижегородской губернии; снят и оборот). Из-за них разворот л. 263об смотрит
# на л. 265, а л. 271об — на л. 273.
#
# Proofread in Verso on 2026-10-28.

