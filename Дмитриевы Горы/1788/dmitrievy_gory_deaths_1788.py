# Метрическая тетрадь Покровской церкви с. Димитріевы Горы за 1788 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 86, л. 44об** (кадр 0050).
#
# ⚠⚠ **РАЗДЕЛ ПРИХОДА РАЗОРВАН НА ДВА КУСКА, И МЕЖДУ НИМИ ЧУЖОЙ ПРИХОД.** Часть первая
# стоит на **лл. 38об–39об** (16 записей), а части вторая и третья с табелем — на
# **л. 44об**, то есть **через четыре листа**, за вклинившимся разделом **с. Санчура**
# (Николаевская церковь, священникъ Василій Ѳедоровъ, лл. 40 и 43об–44). ⇒ границу
# читать **по подписи причта**, а не по нумерации листов.
#
# ⚠ **Это краткий реестр, а не метрическая книга**: одна строка на запись; в части первой
# названы отец, ребёнок и **два** воспріемника, в части третьей — только имя, причина и
# возраст. Год закрывается **табелем**, а не ведомостью.
#
# ✅✅ **ТАБЕЛЬ (л. 44об) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** — **тридцать девятый такой год
# подряд**. «Крестьяне: родившихся мужеска **9**, женска **7**, обоего **16**;
# браковавшихся лицъ **16**, супружествъ **8**; умершихъ мужеска **6**, женска **4**,
# обоего **10**». Подписи: священникъ **Василій Андреевъ**, діаконъ **Стефанъ Ивановъ**,
# дьячекъ **Лаврентій Ивановъ**, пономарь **Симеонъ Ѳедоровъ**.
#
# 🏆🏆 **№ 6 — ФИЛИПЪ ХАРИТОНОВЪ, И ЭТО ПЯТЫЙ МУЖЧИНА РОДА ЗА ЭТИМ ОТЧЕСТВОМ.**
# ⇒ род. ок. **1740 г.**, то есть ровесник **Никифора Харитонова** († 1806, 65 лѣтъ ⇒
# ок. 1741) и **на двадцать лет старше** Ѳедора (ок. 1760) и Василія (ок. 1767).
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.0× постранично, входящие сюда — при 7×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1788 = death_records(
    "ГАВО", "556", "106", "86", "Дмитриевы Горы", "Покровская",
    1788,
    *page("44об",
          *death_month(Month.AUGUST,
                       # 🏆🏆 **ФИЛИПЪ ХАРИТОНОВЪ — ПЯТЫЙ МУЖЧИНА ЗА ОТЧЕСТВОМ РОДА И ВТОРОЙ ИЗ «СТАРЫХ».**
                       # «Того села и вотчины **Филипъ Харитоновъ**, неизвѣстною болѣзнію», **48** лѣтъ, 18
                       # августа (сверено при 7×; возраст подтверждён строкой «48 — 1» в табелѣ л. 44об). ⇒
                       # **род. ок. 1740 г.** ⚠ Реестр этого года даёт в части третьей только имя, причину и
                       # возраст — **числа погребенія в нём нет**, как нет и родства. 🔴🔴 **И ОН ДЕЛИТ
                       # НОСИТЕЛЕЙ ОТЧЕСТВА НАДВОЕ ПО ВОЗРАСТУ.** Старшие: **Филипъ** (ок. 1740) и
                       # **Никифоръ** († 12 іюня 1806 г., 65 лѣтъ ⇒ ок. 1741). Младшие: **Ѳедоръ** († 10 мая
                       # 1810 г., 50 ⇒ ок. 1760) и **Василій** († 22 іюня 1812 г., 45 ⇒ ок. 1767). Между двумя
                       # парами — **двадцать лет**. ⚠⚠ **Что из этого следует и чего не следует.** Если все
                       # четверо — сыновья одного **Харитона**, то он род. ок. 1715–1720 и имел **два брака**:
                       # двадцатисемилетний разброс между старшим и младшим сыном иначе не выходит. Но
                       # венчаніе 1808 года доказало, что «Харитоновъ» в этом приходѣ — **дедичество**,
                       # семейное прозвание, которым зовут и внуков; ⇒ **пара 1740–41 гг. может быть
                       # поколением отцов, а пара 1760–67 гг. — их сыновьями**, и тогда «Харитонъ» — прадед. 📍
                       # Метрики этого не решают: **Харитона нет ни в одной из сорока прочитанных книг**
                       # (1786–1830) ⇒ он умеръ **до 1786 г.** Осталось четыре сдвоенных тетради 1778–1785 гг.
                       death(6, Gender.MALE, 18, None,
                             deceased=person("Филиппъ", "Харитоновъ"),
                             age=48,
                             cause_of_death="неизвестная болезнь"),
                       ),
          ),
    defaults=DEFAULTS,
)
