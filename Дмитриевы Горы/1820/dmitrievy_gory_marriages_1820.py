# 27 августа 1820 г., и она же впервые называет его родство прямым текстом:
# «…вотчины Г-на Баташева тогожъ села **крестьянской вдовы Ѳедоры Антоновой сынъ Ѳока**,
# оной же вотчины и Села съ **крестьянскою дѣвкою Марьею Семеновою**, по добровольному
# ихъ, родителей и Г-на ихъ согласію… **оба первымъ бракомъ**» (сверено при 10×).
#
# ⇒ Три вывода сразу:
# 1. **Ѳока — сын Ѳедоры Антоновой по документу, а не по выводу.** Прежде родство
#    держалось на том, что она трижды стояла кумой у его детей и детей его братьев
#    (1823, 1824, 1829); теперь оно записано в метрике.
# 2. **Ѳедора Антонова — вдова уже в августѣ 1820 г.** ⇒ **Ѳедоръ (Харитоновъ), отец
#    братьев, умер до 27 августа 1820 г.**, и его погребение надо искать в 1819 г. и
#    ✅✅ **НАЙДЕНО 14.09.2026: 10 мая 1810 г., 50 лѣтъ, горячкою** (1810 ч. 3 № 4). Эта
#    цель стояла в роадмапе десять прочитанных лет и трижды передатировалась.
#    глубже (либо в ревизиях).
# 3. **Оба первымъ бракомъ**, и Марья Семенова — из той же вотчины и того же села.
#
# ⚡ **И поручителем стоит человек, который вернётся через два года начальником.**
# «Поручители были **Московской Мѣщанинъ Тихонъ Наумовъ**, и той же вотчины и Села
# крестьяне: **Макаръ Аникинъ** и **Иванъ Тихоновъ**» (сверено при 9×). Тот же **Тихонъ
# Наумовъ** в 1822 г. назван «**Прикащикъ**» вотчины и держит у купели сына Игнатья
# (1822 ч. 1 № 18). ⇒ московский мещанин, ставший управляющим имением, — и он связан с
# обоими братьями.
#
# 🚫 **Игнатья Ѳедорова женихом здесь нет** (пять женихов разобраны поимённо) ⇒ его
# венчание — **1819 г. или раньше**, либо в приходе невесты.
# ⛔ **Уточнено 13.09.2026 по прочтении 1819 года:** женихом его нет и там, зато 1 генваря
# 1819 г. он уже кумъ и «крестьянинъ» (1819 ч. 1 № 1) ⇒ **1818 г. или раньше**. Антона нет тем более: он
# женат уже к 1816 г. по ревизии.
#
# ⓘ Прочие четыре венчанія: № 2 (3 октября) — Ѳедоръ, сынъ Никиты Алексѣева; № 3
# (3 октября) — Ѳедоръ, сынъ Игнатія Васильева; № 4 (4 октября) — Ѳедоръ, сынъ **вдовы
# Ѳеклы Харитоновой**; № 5 (4 октября) — Прокофій, сынъ Емельяна Власова. Все пять пар —
# «оба первымъ бракомъ»; поручителей от двух до четырёх.
# ⚠ **Ѳекла Харитонова** (№ 4) носит то же отчество, что отец братьев (**Ѳедоръ
# Харитоновъ** по ревизиям) ⇒ она может быть его сестрой. Доказательством это не
# является: проверять по ревизии, которая детей Харитона называет поимённо.
