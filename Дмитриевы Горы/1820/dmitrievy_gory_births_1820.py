#
# 🔴🔴 **АНТОНЪ ѲЕДОРОВЪ КУМОМЪ ШЕСТЬ РАЗ ЗА ГОД, И ЧЕТЫРЕ ИЗ НИХ — ПОДРЯД НА ОДНОМ
# ЛИСТЕ** (№№ 3, 5, 6, 7 на л. 420об, 7–18 генваря и 1 февраля). Столько кумовств за год
