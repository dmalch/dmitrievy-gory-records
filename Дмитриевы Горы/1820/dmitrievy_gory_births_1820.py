# подряд первой записи о роде.
# ⛔ **ОТОЗВАНО 13.09.2026 ПО ПРОЧТЕНИИ 1819 ГОДА** («самая ранняя запись о роде во всём
# корпусе»): **1 генваря 1819 г.** Игнатій — кумъ в первой же записи того года
# (1819 ч. 1 № 1), и это одиннадцатый перенос.
# ⚠ **И на том же листе сидит ловушка.** № 1 (той же страницы разворота, л. 420) называет
# кумомъ «**Антона Ѳилипова**» — сверено при 10×, «Ѳилиповъ» написано ясно. Однофамильцев
# по имени в приходе двое, и различает их только отчество.
#
# 🚫 **Ни Ѳоки, ни Игнатья в части первой 1820 года нет ни разу.** Для Ѳоки это ожидаемо:
# он женится только 27 августа (ч. 2 № 1), а до свадьбы корпус не видит его нигде — его
# первые кумовство и поручительство приходятся уже на 1821 год. ⇒ **в этом приходе холостой
# крестьянский сын у купели не стоит**, и отсутствие человека в части первой само по себе
# датирует его холостым.
# ⛔ **Уточнено 13.09.2026 по прочтении 1819 года:** Игнатій там **есть** — кумомъ
# 1 генваря и уже «крестьяниномъ» ⇒ по тому же правилу он женат к началу 1819 г.
# ⛔⛔ **И САМО ПРАВИЛО ОТОЗВАНО 13.09.2026 ПО ПРОЧТЕНИИ 1817 И 1818 ГОДОВ.** Ѳока стоит
# **поручителем** в 1818 г. (1818 ч. 2 № 12) и **кумомъ дважды в 1817-м** (1817 ч. 1
# №№ 28 и 56) — и там он назван «**крестьянскимъ сыномъ**», то есть холост: венчается он
# только 27 августа 1820 г. ⇒ **роль не маркирует ничего.**
# ✅ **Маркирует ТИТУЛ.** Книга различает «крестьянинъ» (свой двор, женат) и
# «крестьянскій сынъ» (в отцовском дворе): Ѳока — «крестьянскій сынъ» в 1817-м,
# «крестьянинъ» с 1821-го; Игнатій — «сынъ вдовы» женихом в генварѣ 1817 г. и
# «крестьянинъ» кумомъ в ноябрѣ того же года. А отсутствие Ѳоки в 1819 и 1820 гг. — просто
# совпадение, а не закон.
#
