# «О родившихся». **ГАВО ф. 556 оп. 106 д. 405, лл. 420–427об** (кадры альбома 428–436).
#
# ⚠ **Консисторская копия уездного дела**; тетрадь прихода — **лл. 420–437**, и книга сама
# это заверяет: на л. 437об «Въ сей Метрической тетради **восемнадцать листовъ**, а у
# шнура Муромскаго Духовнаго Правленія печать» (сургучная печать, подпись «Губернскій
# Секретарь Вознесенскій»). Альбом — 19 кадров, 428–446, лл. 419об–438; **кадры 441–445
# сняты поодиночке** — это лл. 433–437, и все пять **чисты** (тетрадь сшита на 18 листов,
# приход исписал 13). Титул и ч. 1 стоят на **одном листе 420**; ч. 2 — лл. 428–429,
# ч. 3 — лл. 429об–431об, **ведомость — л. 432**.
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ВЕДОМОСТЬ (л. 432) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** —
# **десятый такой год подряд**. «Родившихся мужеска **39**, женска **33**, обоего пола
# **72**»; «бракосочетавшихся лицъ 10, супружествъ **5**»; «умершихъ мужеска **4**,
# женска **16**, обоего **20**». Возрастная разбивка мужчин («ниже году 1, 24 — 1,
# 45 — 1, 64 — 1») сошлась построчно — и **поправила два моих возраста и один пол**
# (Кирило Ефремовъ 64, а не 61; Лазарь Евѳимовъ 24, а не 94; «младенецъ Евѳиміи» —
# девочка). ⇒ ведомость стоит читать **до** разбора части третьей, а не после.
# ⓘ «Ненатуральною смертію никого быть неслучилось».
#
# 🔴 **ВОТЧИНА — ИВАНА РОДІОНОВИЧА БАТАШЕВА** (титул: «вотчины Г-на Коллежскаго Ассессора
# **Ивана Родіоновича Баташева**», дальше сокращается до «вотчины Г-на Баташева»), как и
# в 1821 г.; к Шепелевымъ она перейдёт только к книге 1822 года. См. § «1821» в ARCHIVES.
# ⓘ Священникъ весь год — **Стефанъ Ивановъ**; **Тихонъ Экземплярскій** ещё семинарист и
# в книге не назван, зато дважды названа кумой его будущая жена — «**Священникова дочь
