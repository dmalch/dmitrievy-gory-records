from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Month, RecordDefaults, Relationship, marriage, marriage_month,
                          marriage_records, page, person, relative)
from verso.ru.dsl.statuses import PEASANT_SON

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1808 г., часть вторая
# «О бракосочетавшихся». **ГАВО ф. 556 оп. 106 д. 229, лл. 612–617об** (кадры 0634–0640).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 18 венчаній**, и ведомость (л. 625об) пишет ровно
# «бракосочетавшихся лицъ **36**, супружествъ **18**».
#
# 🏆🏆🏆🏆🏆 **№ 10 — И ЭТО ЧЕТВЁРТЫЙ РЕБЁНОКЪ ѲЕДОРА ХАРИТОНОВА. У ТРЁХ БРАТЬЕВЪ ЕСТЬ
# СЕСТРА.** 29 апрѣля 1808 г. «крестьянина **Василья Михайлова сынъ Максимъ**» венчается
# «оной же вотчины и Села **крестьянина ѲЕДОРА ХАРИТОНОВА съ дочерью дѣвкою АВДОТЬЕЮ**»,
# оба первымъ бракомъ (сверено при 8×). До сегодня корпус знал у Ѳедора **только сыновей** —
# Антона, Игнатія и Ѳоку, всех троих из ревизии 1816 г.
#
# ⚡ **№ 12 (4 октября) — поручителемъ стоит ѲОТІЙ ѲЕДОРОВЪ**, и имя написано именно так,
# «Ѳотій» (сверено при 8×) — за два года до книги 1810-го, где тот же человек подписан
# «Ѳоки Ѳедоровъ». ⇒ два написания одного имени, и это **самая ранняя** его запись.
#
# ⓘ № 1 венчает сына **бурмистра Ефима Григорьева** — управляющий вотчиной назван за
# четырнадцать лет до «прикащика Тихона». ⓘ № 14 и № 16 ставят поручителемъ **Тихона
# Дорофеева** — третьего Тихона прихода после Тихона Ѳедорова (1810) и московскаго
# мѣщанина Тихона Харитонова/Наумова (1812).
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 8×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_marriages_1808 = marriage_records(
    "ГАВО", "556", "106", "229", "Дмитриевы Горы", "Покровская",
    1808,
    *page("615",
          *marriage_month(Month.APRIL,
                          # 🏆🏆🏆🏆🏆 **У ТРЁХ БРАТЬЕВЪ ЕСТЬ СЕСТРА, И ВОТ ЕЁ СВАДЬБА.** «Приходу означеннаго Села
                          # вотчины Господина Коллежскаго Ассессора **Ивана Родіоновича Баташева** крестьянина
                          # **Василья Михайлова сынъ Максимъ**, оной же вотчины и Села **крестьянина ѲЕДОРА
                          # ХАРИТОНОВА съ дочерью дѣвкою АВДОТЬЕЮ**, по добровольному ихъ и родителей ихъ
                          # согласію… **оба первымъ бракомъ**» (обе половины сверены при 8×). 🔴🔴🔴 **ЭТО
                          # ЧЕТВЁРТЫЙ РЕБЁНОКЪ ѲЕДОРА ХАРИТОНОВА.** Корпус знал у него только сыновей —
                          # **Антона** (ок. 1796), **Игната** (ок. 1798) и **Ѳоку** (ок. 1802), всех троих из
                          # одной строки ревизии 1816 года. Авдотья старше всех: венчается в 1808-м, значит
                          # род. не позже **1793 г.** ⇒ **она первый ребёнокъ Ѳедора и Ѳедоры Антоновой,
                          # какого корпус знает**, и брак родителей уходит к 1792 г. или раньше. 🔗🔗 **И ОНА
                          # ОБЪЯСНЯЕТ ДВА ПРЕЖНИХ КУМОВСТВА, КОТОРЫЕ ВЫГЛЯДЕЛИ СЛУЧАЙНЫМИ.** (1) 13 декабря
                          # **1812** г. кумой у первенца Антона, **Анны**, стоит «крестьянская жена **Авдотья
                          # Ѳедорова**» (1812 ч. 1 № 70) — то есть **родная тётка у купели племянницы**. (2)
                          # 26 декабря **1813** г. сам **Антонъ** стоит кумомъ у сына **Максима Васильева**
                          # (1813 ч. 1 № 64) — то есть **у родного племянника**, а не «в чужом дворѣ», как
                          # предполагало прочтение 1813 года. ⛔ **ОТОЗВАНА 14.09.2026 оговорка 1813 года**
                          # «дворъ чужой: Максимъ Васильевъ в корпусе больше нигде не встречается».
                          # Встречается, и он зять рода. ⚠ **И это решает отчество Авдотьи.** 1810 ч. 1 № 73
                          # зовёт жену того же Максима Васильева «Авдотья **Харитонова**», а 1813-й — «Авдотья
                          # **Ѳедорова**». По венчанію верно второе: она дочь **Ѳедора**. «Харитонова» —
                          # **дедичество**, семейное прозвание по дѣду **Харитону**, и приход употребляет его
                          # как фамилию уже в 1807–1810 гг. ⇒ всякая «Харитонова» в этих книгах может быть и
                          # дочерью Харитона, и его внучкой; метрики двух поколений не разделяют
                          marriage(10, 29,
                                   groom=person("Максимъ", status=PEASANT_SON),
                                   bride=person("Овдотья", status="крестьянская дочь девка вотчины г-на Баташева"),
                                   groom_marriage_num=1, bride_marriage_num=1,
                                   witness1=person("Евсевій", "Абакумовъ"),
                                   witness2=person("Іуда", "Иродіоновъ"),
                                   witness3=person("Александръ", "Тарасовъ"),
                                   relatives=[relative(person("Ѳедоръ", "Харитоновъ"), Relationship.FATHER, "невеста"),
                                              relative(person("Василій", "Михайловъ"), Relationship.FATHER, "жених")]),
                          ),
          ),
    defaults=DEFAULTS,
)
