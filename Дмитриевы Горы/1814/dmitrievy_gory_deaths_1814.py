from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE, BATASHEV_PEASANT_GIRL
from verso.ru.dsl import (Gender, Month, RecordDefaults, death, death_month, death_records, page,
                          person)
from verso.ru.dsl.causes_of_death import FEVER

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1814 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 321, лл. 531–535** (альбом «Дмитриевы Горы
# 1814 (ГАВО 556-106-321)», кадр 0559 — разворот 530об–531).
#
# ⓘ Часть третья — **29 записей**; прочитана целиком 05.10.2026 на поиск Варвары Семеновой
# (вопрос 69). ⚠ Альбом года неполон (нет кадров 0551–0553 и 0565–0566), но часть третья
# в нём вся — см. `ARCHIVES.md` § «1814».
# ⓘ Колонка «какою болѣзнію» на л. 531 написана одним словом «горячкою» сверху вниз через
# все четыре записи страницы.
#
# ✅ Вычитано по сканам в Verso 05.10.2026.
# Первое чтение: найдено агентом при ~1.5×, запись перечитана кропом при 4×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1814 = death_records(
    "ГАВО", "556", "106", "321", "Дмитриевы Горы", "Покровская",
    1814,
    *page("531",
          *death_month(Month.MARCH,
                       # 🔴 **ПОГРЕБЕНІЕ ВАРВАРЫ СЕМЕНОВОЙ — ВОПРОС 69.** «Приходу означеннаго села вотчины
                       # г-на Баташева крестьянская дѣвка **Варвара Семенова** по исповѣди и святыхъ таинъ
                       # причастіи скончалась» 11 марта, 16 лѣтъ, горячкою; погребена 14 марта.
                       # 🔗 Это почти наверное дочь Семена Васильева, род. 4 декабря 1797 г. (1797 ч. 1 № 32):
                       # 16 лѣтъ 3 мѣсяца на день смерти, а в книгах 1796 и 1797 гг. Варвара одна — эта. ⚠ Части
                       # первые 1798–1799 гг. на Варвару «Семенову» не просматривались (там читали только
                       # детей Семена Васильева). ⇒ **Объяснено, почему её нет в ревизии 1816 г.**: умерла за два
                       # года до неё, дѣвкою. ⚠ Отца запись не называет — которому из двух Семёновъ
                       # Васильевыхъ она дочь (нашему, двор 38, или тёзке, † 1803), это не решает
                       death(3, Gender.FEMALE, 11, 14,
                             deceased=person("Варвара", "Семенова", status=BATASHEV_PEASANT_GIRL),
                             age=16,
                             cause_of_death=FEVER),
                       ),
          ),
    defaults=DEFAULTS,
)
