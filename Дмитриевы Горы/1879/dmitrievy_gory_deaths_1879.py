# Метрическая книга Покровской церкви с. Димитріевы Горы за 1879 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**195**, л. 283 (титул),
# записи лл. 283об–293об. **44 мужских и 43 женских — 87 погребений.**
# **ОДНА запись.**
#
# ⚠ **ФОРМА: ВСЁ НА ОБОРОТЕ, включая «ОТЪ ЧЕГО УМЕРЪ».** Оборот несёт счётъ (раздельно
# мужеска/женска), день смерти, день погребенія, званіе-имя-отчество-фамилію умершаго,
# лѣта (тоже раздельно м/ж) и причину; recto — только «Кто исповѣдывалъ и пріобщалъ» и
# «Кто совершалъ погребеніе и гдѣ погребены», имён там нет вовсе. Ч. 3 читается по одним
# оборотам.
#
# 🔴 **ВОЗРАСТ В 1879 г. ПИШЕТСЯ С ЕДИНИЦЕЙ, И ЭТО ПРОВЕРЕНО САМОЙ КНИГОЙ.** Почти каждая
# детская запись несёт «мѣс.», «недѣль» или «дней»; **голое число означает ГОДЫ**. Правило
# 3 regional-rules требует проверять это для каждого дела и года — здесь проверка сошлась
# семь раз подряд по парам «метрика ↔ погребение» внутри одного года:
#   • Филиппъ, сынъ Михаила Андреева Кандрюшина: род. 27 июня (ч. 1 № м31) — † 23 августа,
#     «2 мѣс.» ✓
#   • Илья, сынъ Ѳедора Петрова Кандрюшина: род. 4 июля (№ м33) — † 12 октября, «3½ мѣс.» ✓
#   • Василій, сынъ Николая Павлова Кочеткова: род. 26 июля (№ м39) — † 8 августа,
#     «2 недѣли» ✓
#   • Филиппъ и Екатерина, двойня Максима Онисимова: род. 8 ноября (№ м68/ж56) — † 9 и
#     8 ноября, «день» и «полдня» ✓
#   • Филиппъ, сынъ Павла Иванова: род. 7 ноября (№ м67) — † 28 ноября, «3½ недѣль» ✓
#   • Ульяна, дочь солдатки Матроны Павловой: род. 11 декабря (№ ж67) — † 12 декабря,
#     «1 день» ✓
#   • Ѳекла, дочь Якова Семенова: род. 16 сентября (№ ж51) — † 21 декабря, «3 мѣс.» ✓
#   • Мавра, дочь Акима Варѳоломеева: род. 22 апреля (№ ж20) — † 23 ноября, «7 мѣс.» ✓
#     (и эта пара исправляет чтение ч. 1: отец там прочитан «Якимъ Вересноеровъ», а здесь
#     он «**Акимъ Варѳоломеевъ**»).
#
# ⓘ **Год эпидемический, и болезни идут волнами**: январь–март — **коклюшъ и колтунъ**
# (младенцы), май–сентябрь — **поносъ** (летняя детская смертность), август–декабрь —
# **скарлатина**. Из 87 погребений заметно больше половины — младенцы до года.
#
# ⚠ **НЕ ЗАВЕДЕНЫ — голое отчество без фамилии либо чужая фамилия** (правила 1/5
# regional-rules); каждое, однако, что-то решает:
#   • **л. 283об № м2: «Михаила Антонова МИРОШКИНА сынъ младенецъ Иванъ», 4½ мѣс.**
#     († 6 января). 🔴 **Эта запись ДАТИРУЕТ и ИМЕНУЕТ отца.** 1878 год (ч. 1 № м57) даёт
#     «**Михаилъ Антоновъ** и жена его **Ксенія Димитріева**», сынъ **Іоаннъ**, род.
#     1 сентября 1878 г. ⇒ на 6 января 1879 г. ребёнку 4 мѣс. 5 дн., то есть «4½ мѣс.»
#     сходится, и Мирошкинъ ч. 1 № ж60 этого года — **тот же Михаилъ**, а не Максимъ, как
#     было прочитано при первом проходе (имя стоит в переносе; исправлено 14.09.2026).
#     ⇒ **вывод «двор 5 не Кекевы по мужской линии» СНЯТ**; см. ч. 1 1879 г.
#   • **л. 292об № м41: «Ивана Андреева сынъ младенецъ Стефанъ», 6 мѣс.** († 19 ноября)
#     ⇒ род. ок. мая 1879 г. — а ч. 1 № м14 даёт «Ивану Андрееву» сына **Георгія**,
#     род. 14 апреля 1879 г. Одна мать двух сыновей в апреле и в мае родить не может ⇒
#     **«Иванъ Андреевъ» в этом году — ДВА человека**, и наводка на Георгія Іоанновича
#     Кекева (д. 198–199, 1910–1914) этим ослаблена, а не подтверждена.
#   • **л. 291об № м39: «Михаила Максимова сынъ младенецъ Тимофей», 3½ мѣс.** Корпус знает
#     **Михаила Максимовича Кекева** (двор 5; МК 1892 л. 48об, брат Марѳы Максимовой
#     Горбачевой) и держал его в открытых вопросах 1880 г. с женой Анисіей Васильевой.
#     Здесь он на год раньше и уже отец. Фамилии в записи нет.
#   • **л. 291об № м37: «Евграфа Максимова сынъ младенецъ Козма», 1 г.** — Евграфа
#     Максимовича корпус не знает вовсе (та же заметка есть в МК 1884).
#   • **л. 290об № м35: «Емельяна Сильвестрова сынъ младенецъ Ѳедоръ», 1½ мѣс.** ⚠ Важно
#     для ч. 2 этого года: Емельянъ Сильвестровъ уже отец в 1879 г., то есть **в приходе
#     есть СТАРШИЙ Сильвестръ**, помимо Сильвестра Антонова, венчавшегося 3 октября
#     (брак № 18). ⇒ вывод «Іаковъ Сильвестровъ Кекевъ — сын того Сильвестра» остаётся
#     догадкой, и в ч. 2 он записан как догадка.
#   • Прочие отчества прохода среди хоронящих: **Иванъ Антоновъ** (л. 287об № ж24),
#     дѣвка **Варвара Антонова** (л. 288об № ж27), **Іосифъ Данилинъ** (л. 286об № ж16),
#     **Иванъ Максимовъ** (л. 284об № м6), солдатка **Прасковья Максимова** (№ м8),
#     солдатка **Татьяна Максимова** (л. 287об № м16).
#
# 🔴 **И ЕЩЁ ДВЕ ФАМИЛИИ ИЗ СПИСКА «ВПЕРВЫЕ В 1880 г.» СТОЯТ ЗДЕСЬ**: **Пушковъ**
# (л. 283об № м3 — «Анисимъ Михайловъ Пушковъ» деревни Кононовой, 79 л.) и **Бочкаревъ**
# (л. 292об № м42 — «Ефимъ Ефремовъ Бочкарь» той же деревни, 57 л.).
#
# Вычитан в Verso 16.10.2026: одна запись года, заведённая в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1879 = death_records(
    "ГАВО", "590", "12", "195", "Дмитриевы Горы", "Покровская",
    1879,
    *page("288об",
          *death_month(Month.MAY,
                       # 🔴🔴 **СТАРШИЙ ИЗВЕСТНЫЙ РЕБЁНОК МАКСИМА КАРПОВА.** ⚠ Первенство снято проходом
                       # вглубь: «самая ранняя запись о нём самом» уже не эта — МК 1871 (№ ж3), 1872 (№ м29) и
                       # 1874 (№ м91, † № 52) дают его с той же Анной Васильевой, и детей пары теперь шестеро:
                       # Ѳедоръ (ок. 1868), Татіана (1871), Петръ (1872), Спиридонъ (1874, † 5 дней),
                       # Агафья (1878, † 1880), Пелагея (1880). Ниже сохранён текст, каким он был написан.
                       # Отец сведён 16.10.2026 (maksim_karpovich); метрики Ѳедора в корпусе нет, и в дереве он
                       # стоит в союзе четы. «Того же села крестьянина **Максима Карпова** сынъ **Ѳедоръ**», **11** (сверено при
                       # 10× и 22×: две единицы, не «6»; в мужской графе лѣтъ, женская — прочерк) ⇒ род. ок.
                       # **1868 г.** **Возраст без единицы = годы**, и это не догадка: тот же писец в том же
                       # году пишет «мѣс.», «недѣль» и «дней» всюду, где имеет их в виду (см. шапку файла —
                       # восемь сверок «метрика ↔ погребение»). Здесь и «младенецъ» не сказано — просто
                       # «сынъ», как и у соседнего восьмилетнего Андрея Антона Филатова (№ м21). 🔴 **Корпус
                       # знает Максима Карпова по трём записям, и все они позже этой:** МК **1880** ч. 3 № ж8
                       # — дочь **Агафья**, 2 г. († 3 апреля); МК 1880 ч. 1 № ж28 — дочь **Пелагея** (3 мая)
                       # при жене **Аннѣ Васильевой**; МК **1882** ч. 3 № м37 — его собственное погребение,
                       # «крестьянинъ **Максимъ Карповъ КИКЕВЪ**», 58 л. ⇒ здесь он за три года до смерти
                       # хоронит одиннадцатилетнего сына, и у пары известны теперь **трое детей**: Ѳедоръ (ок.
                       # 1868), Агафья (ок. 1878), Пелагея (1880). ⚠ Фамилии при отце здесь нет — тождество
                       # опирается на редкое отчество «Карповъ», которого в приходе больше не встречается, и
                       # на запись 1882 г., где фамилия проставлена. ⚠ **Не сводить Максима Карпова с
                       # Максимомъ Антоновичемъ двора 5** — отчество разъединяет их надёжно (правило regional-
                       # rules). ⚠ Ранее здесь стояло, что 1879 год даёт «Максима Антонова» с фамилией
                       # Мирошкинъ (ч. 1 № ж60) — **имя прочитано неверно, там Михаилъ** (исправлено
                       # 14.09.2026 по 1878 г.); о Максимѣ Антоновичѣ двора 5 год не говорит ничего
                       death(20, Gender.MALE, 26, 28,
                             deceased=person("Ѳедоръ"), age=11,
                             relatives=[relative(person("Максимъ", "Карповъ"), Relationship.FATHER)],
                             cause_of_death=SCARLATINA),
                       ),
          ),
    defaults=DEFAULTS,
)
