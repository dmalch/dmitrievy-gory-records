# Никифоровой. Причт считает их всех.
#
# 🔴 **1 ГЕНВАРЯ 1819 г.** (№ 1 ниже) — **первая же запись года** и одиннадцатый перенос
# подряд: 1830 → … → 1821 → 1820 → **1819**. ⛔ **ОТОЗВАНО 13.09.2026 ПО ПРОЧТЕНИИ
# 1818 ГОДА** («самая ранняя запись о роде во всём корпусе»): **5 мая 1818 г.** Игнатій —
# кумъ (1818 ч. 1 № 33), и это двенадцатый перенос.
