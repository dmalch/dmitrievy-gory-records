from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import COUGH

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1819 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 390, лл. 242–244** (кадры альбома 0253–0255).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 12 м / 15 ж = 27 погребений**, и ведомость (л. 244об)
# пишет ровно «умершихъ мужеска **12**, женска **15**, обоего пола **27**»; её возрастная
# разбивка мужчин («3 — 2, 4 — 1, 9 — 1, 15 — 1, 33 — 1, 38 — 1, 42 — 1, 45 — 1, 50 — 1,
# 70 — 2») даёт «итого 12» и сошлась **построчно**.
# ⓘ Возрастная конвенция 1819 года: **голое число = ГОДЫ**, младенческий срок пишется
# словом («по году»). Столбцы «Лѣта мужеска» и «Лѣта женска» раздельные, как в 1820–1822 гг.
# ⓘ «Ненатуральною смертію въ семъ 1819-мъ году умершихъ никого быть неслучилось».
#
# 🔴🔴🔴 **ГОД ДАЁТ РОДУ РЕБЁНКА, О КОТОРОМ КОРПУС НЕ ЗНАЛ, И ЭТО САМЫЙ СТАРШИЙ ИЗ НИХ.**
# ж. № 3 — **Ксенія, дочь Антона Ѳедорова, пяти лет**, † 28 февраля. ⇒ **род. ок.
# 1813–1814 г.**, то есть **старше всех известных детей рода**, и женитьба Антона
# отодвигается к **1813 г. или раньше** (прежде корпус знал его женатым по ревизии 1816 г.).
#
# 🔴🔴 **И ГОД ОБЪЯСНЯЕТ, ПОЧЕМУ ЧЕРЕЗ ДВА ГОДА СМЕНИТСЯ ПРИЧТ.** ж. № 1 (27 генваря):
# «Приходу означеннаго Села **Священника Стефана Иванова жена Марья Иванова**», 54, «водянкою»,
# погребена 29 генваря — хоронил её священникъ **села Кудрина Василій Тецкій**, потому что
# вдовцу хоронить жену не положено. ⇒ **Стефанъ Ивановъ овдовел в начале 1819 года**, а
# 6 февраля 1821 г. выдаст дочь **Анну** за семинариста Тихона Экземплярскаго и уступит
# ему место (1821 ч. 2 № 5). Вдовый священникъ без сына — ровно та ситуация, в которой
# место передают зятю; 1819 год показывает её начало.
#
# ⓘ Прочее: 20 октября погребены разом крестьянинъ **Яковъ Родіоновъ** (33) и **отрокъ
# Дмитрій Петровъ** (15), 25 октября — двое детей (3 и 9 лет), 12 мая — две женщины
# (30 и 40) «горячкою». Двое старших — по 70 лет.
#
# ✅ Вычитано по сканам в Verso 02.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящая сюда — при 9×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1819 = death_records(
    "ГАВО", "556", "106", "390", "Дмитриевы Горы", "Покровская",
    1819,
    *page("242об",
          *death_month(Month.FEBRUARY,
                       # 🔴🔴🔴 **ДОЧЬ АНТОНА ѲЕДОРОВА, О КОТОРОЙ КОРПУС НЕ ЗНАЛ, И САМЫЙ СТАРШИЙ ИЗ ИЗВЕСТНЫХ
                       # ДЕТЕЙ РОДА.** «Въ МАРТѢ. Приходу означеннаго Села вотчины Г-на Баташева крестьянина
                       # **Антона Ѳедорова младенецъ Ксенія** по причастіи Святыхъ таинъ скончалась», **5**
                       # лѣтъ, кашлемъ; умерла 28 февраля, погребена 1 марта (сверено при 9×). 🔴🔴 **⇒ РОД. ОК.
                       # 1813–1814 г.**, то есть на семь лет раньше любого прежде известного ребёнка рода
                       # (Дарья Игнатова, ок. 1820, по ревизии 1834 г.). ⇒ **женитьба Антона — 1813 г. или
                       # раньше**; прежде корпус знал его женатым только по ревизии 1816 г. 🔗 **И она —
                       # ребёнок ПЕРВОЙ жены, которую корпус знает по имени.** РС-7 1816 г. пишет у Антона
                       # жену **Анну, 20 лет**; Ксенія зачата ок. 1813 г. ⇒ её мать — **Анна** (при 20 годах в
                       # 1816-м ей было семнадцать-восемнадцать, что тесно, но возможно). ⛔ **Уточнено
                       # 13.09.2026 по прочтении 1818 года:** окно смены жены — **1816 — ноябрь 1818**, а не
                       # «1816 — октябрь 1823»: 2 ноября 1818 г. у Антона рождается сынъ **Осипъ** уже **отъ
                       # Елены Васильевой** (1818 ч. 1 № 72). 🔗 **И Ксенія не одна.** 14 августа 1818 г.
                       # Антонъ похоронил **Стефаниду, двухъ лет** (1818 ч. 3 ж. № 13) ⇒ род. ок. 1816. ⇒ за
                       # полгода он хоронит двух дочерей от первой жены и крестит сына от второй. Метрики
                       # обеих девочек искать в **1813–1814 и 1816 гг.** (556-106-309, 321, 359 — все
                       # оцифрованы). ⓘ «Младенцемъ» книга зовёт и пятилетнюю: слово означает ребёнка, а не
                       # грудного. ⇒ возрастную конвенцию нельзя выводить из него
                       death(3, Gender.FEMALE, 28, 1,
                             b_month=Month.MARCH,
                             deceased=person("Ксенія"),
                             age=5,
                             relatives=[relative(person("Антонъ", "Ѳедоровъ"), Relationship.FATHER)],
                             cause_of_death=COUGH),
                       ),
          ),
    defaults=DEFAULTS,
)
