from corpus.statuses import SHEPELEV_PEASANT, SHEPELEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import COUGH
from verso.ru.dsl.statuses import ECON_PEASANT_MALE, MESHCHANIN

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1830 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 524, лл. 250–258об** (кадры альбома 13–22).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 42 м / 51 ж = 93 погребения** — и это **сходится с
# итоговой ведомостью до единицы** (л. 259: «умершихъ мужеска 42, женска 51, обоего
# пола 93»). Ведомость там же расписывает мужчин по возрастам, и её собственная сумма
# даёт «итого 42» ⇒ в 1830 г. она согласна и с чтением, и сама с собой (в 1833 г. не
# была ни тем, ни другим).
#
# ⚠ **1830-й — ГОД КОКЛЮША.** «Коклюшемъ» и «кашлемъ» помечено больше половины
# погребений, и почти все они младенческие: ведомость считает **17 умерших мужчин
# до году** из 42. Смертность вдвое выше рождаемости (93 против 75–77). Читая
# 1829-й и 1831-й, ждать той же волны — и не принимать её за пробел в книге.
#
# ⓘ **Форма даёт ДВЕ даты**: числовая колонка — **день смерти**, а «погребенъ N-го дня»
# в тексте — день погребения, обычно на второй день. В DSL стоит день смерти;
# погребение — в комментарии. (В 1833 г. форма писала одну дату.)
#
# ⓘ **Возраст пишется словами и без двусмысленности**: «полугоду», «1½», «4 недѣль»,
# «8 мѣсяцевъ», «90». Здесь нет ловушки дела 196, где голое число у младенца в 1886 г.
# значит месяцы: единица измерения названа всегда, кроме целых лет.
#
# 🔴 **Погребений рода в году нет.** Ни Ѳедоровыхъ братьев, ни Харитоновыхъ, ни жены
# и детей Флора Антонова, венчанного 13 октября (ч. 2 № 17).
# ⚠ Единственный **Антоновъ** части — «крестьянинъ **Ермилъ Антоновъ**, 55, отъ
# простуды» († 17 іюля, № 23 м). По возрасту он ровесник предполагаемого **Антона
# Ѳедорова**, а не его сын ⇒ отец у них разный, и к Флору он отношения не имеет.
#
# Имена сверены кропом при 3× в сером.
# Вычитано в Verso 06.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1830 = death_records(
    "ГАВО", "556", "106", "524", "Дмитриевы Горы", "Покровская",
    1830,
    *page("251",
          *death_month(Month.FEBRUARY,
                       # 🆕 **ЕДИНСТВЕННАЯ НЕНАТУРАЛЬНАЯ СМЕРТЬ ГОДА — И ВЕДОМОСТЬ ЕЁ ЗАВЕРЯЕТ ПОИМЁННО.**
                       # «Экономическаго вѣдомства деревни Кононова крестьянина **Гаврила Васильева** сынъ
                       # **Ѳедоръ**, 23, **въ казенномъ Рожновомъ бору отъ убіенія дерева скончался**, и **по
                       # вѣдѣнію Земскаго Суда** погребенъ февраля 17-го дня». Внизу ведомости (л. 259) причт
                       # пишет отдельной строкой: «въ семъ 1830-мъ году ненатуральною смертію умершихъ,
                       # **кромѣ убитаго деревомъ** деревни Кононова крестьянскаго сына **Ѳедора**, никого не
                       # имѣлось» ⇒ одна и та же смерть названа дважды, и это **редкий случай, когда ведомость
                       # даёт имя**, а не только число. 🆕 **Рожновъ боръ** — первое название лесного урочища
                       # за весь проход, и оно **казённое**, хотя крестьянин экономический, а село помещичье.
                       # Углежжение, которым живут дворы переписи 1897 г., начинается вот здесь: лес — место
                       # работы, и он убивает. ⓘ **Земскій судъ** ведёт дознание и разрешает погребение — на
                       # три дня позже обычного (смерть 14-го, погребение 17-го, при обычных двух днях)
                       death(6, Gender.MALE, 14,
                             17,
                             deceased=person("Ѳедоръ", status=ECON_PEASANT_MALE),
                             age=23,
                             relatives=[relative(person("Гаврилъ", "Васильевъ", residence="Кононово", status=ECON_PEASANT_MALE), Relationship.FATHER)],
                             cause_of_death="убит деревом",
                             comment="в казенном рожновом бору от убиения дерева скончался"),
                       ),
          ),
    *page("257об",
          *death_month(Month.SEPTEMBER,
                       # ✅ **ГОД ЗАМЫКАЕТСЯ САМ НА СЕБЯ — И ЭТИМ ПРОВЕРЯЕТ ВОЗРАСТНУЮ КОНВЕНЦИЮ.** «Того жъ
                       # села и вотчины крестьянина **Максима Савельева** дочь **Василиса**, **9 мѣсяцевъ**,
                       # кашлемъ», погребена сентября 14-го. Это ребёнок **первой записи книги**: ч. 1 № 1 —
                       # «у крестьянина **Максима Савельева** отъ жены его **Марьи Никитиной** родилась дочь
                       # **Василиса**», род. 7 генваря, крещ. 12-го. ⇒ 7 генваря → 12 сентября = **8 мѣс. 5
                       # дней**, писец пишет «9 мѣсяцевъ». Клерк округляет ВВЕРХ к ближайшему месяцу, не
                       # усекает ⇒ возраст в этой книге читать как интервал, а не как точку. ⚡ **И имя отца
                       # пишется двумя способами в одной книге**: здесь «**Савельевъ**», а 14 декабря тот же
                       # человек стоит воспріемникомъ как «**Максимъ Саввинъ**» (ч. 1 № 71). Это ровно та
                       # пара, из-за которой проход 1881 г. отложил вопрос «Саввина → Савельева» до перечитки
                       # 1887/1888: **вопрос снят — это варианты одного отчества у одного писца**, а не два
                       # человека
                       death(47, Gender.FEMALE, 12,
                             14,
                             deceased=person("Василиса"),
                             age="9 мес",
                             relatives=[relative(person("Максимъ", "Савельевъ", status=SHEPELEV_PEASANT), Relationship.FATHER)],
                             cause_of_death=COUGH),
                       ),
          ),
    *page("258об",
          *death_month(Month.DECEMBER,
                       # 🆕 **ЕДИНСТВЕННЫЙ ЧУЖОЙ, ПОГРЕБЁННЫЙ В ПРИХОДЕ ЗА ВЕСЬ ГОД.** «**Тамбовской губерніи
                       # города Елатьмы мѣщанинъ Аѳанасій Константиновъ**, 33, отъ чахотки», погребенъ декабря
                       # 24-го. Последняя запись части и книги. Все остальные 92 погребения — свои: село,
                       # деревня Кононово, солдатки прихода. Здесь же чужой уезд, чужая губерния и городское
                       # сословие. ⓘ Елатьма стоит на Оке километрах в сорока ниже по течению; мещанин умирает
                       # зимой, от чахотки, вдали от дома — похоже на торговый или промысловый заход, а не на
                       # родство. Ни поручителей, ни родных запись не называет
                       death(42, Gender.MALE, 23,
                             24,
                             deceased=person("Аѳанасій", "Константиновъ", status=MESHCHANIN, residence="Елатьма"),
                             age=33,
                             cause_of_death="чахоткою"),
                       ),
          ),
    defaults=DEFAULTS,
)
