# Метрическая книга Покровской церкви с. Димитріевы Горы за 1830 г., часть первая
# «О рождающихся». **ГАВО ф. 556 оп. 106 д. 524, лл. 238–246об** (кадры альбома 1–10).
#
# ⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 238–259**, приходъ
# **№ 9** (в 1833 г. тот же приход шёл под № 49 — нумерация приходов в деле своя для
# каждого года, на неё не опираться). Титул и первая запись — на одном листе 238, как
# в 1833, 1834, 1836 и 1837 гг.
#
# ⓘ **Вотчина названа иначе, чем в 1833 г.**: здесь сплошь «вотчины **дѣтей** Г. Г.
# Шепелевыхъ», в 1833-м — «вотчины Г. Г. Шепелевыхъ». Та же формула стоит в РС-8
# 1834 г. («Шепелевы, дети и наследники Баташевых») ⇒ в 1830 г. имение ещё числится
# за наследниками, и писец это держит.
#
# ✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ.** Часть первая пронумерована **сквозной** нумерацией
# (не раздельной по полу, как часть третья) и кончается на **№ 77**; по чтению это
# **36 м / 41 ж**.
# ⚠ **ИТОГОВАЯ ВЕДОМОСТЬ (л. 259) ДАЁТ 35 м / 40 ж = 75** — на одну запись меньше в
# каждой колонке. **Но списывать это на ведомость нельзя, как в 1833 г.**: здесь она
# сходится с чтением ТОЧНО по двум частям из трёх — «браковъ 17 случаевъ» = 17 венчаний
# части второй, «умершихъ мужеска 42, женска 51, обоего 93» = последние номера части
# третьей, — и **сама с собой согласна** (её возрастная разбивка умерших мужчин даёт
# «итого 42»). ⇒ расхождение локализовано в счёте рождений и составляет ровно две
# записи; чтение под ведомость НЕ подгонялось.
#
# 🔴🔴 **ГЛАВНОЕ, ЧТО ЭТА ЧАСТЬ ДАЁТ РОДУ, — ЭТО ОТСУТСТВИЕ ЗАПИСИ.** РС-8 1834 г.
# (двор 49) пишет у **Игната Ѳедорова** сына **Фрола, 4** ⇒ род. между апрелем 1829 и
# апрелем 1834 минус четыре, то есть **ок. 1830 г.** Часть первая 1830 года прочитана
# сплошь, и **рождения у Игната Ѳедорова в ней нет ни одного** — как нет его самого
# нигде в книге. ⇒ **Фролъ Игнатовъ род. между апрелем и декабрём 1829 г.**, и его
# метрику надо искать в **1829 г. (556-106-511, лл. 673–692, оцифровано)**.
# ✅✅ **НАЙДЕНА (10.09.2026): 13 августа 1829 г.** «У крестьянина **Игнатья Ѳедорова**
# отъ жены его **Евдокіи Ивановой** родился **сынъ Флоръ**», крещ. 18 августа
# (1829 ч. 1 № 42), воспріемницей — родная бабка, **вдова Ѳеодора Антонова**. Дата
# внутри выведенного окна, и возраст в РС-8 сходится (4 г. 7 мѣс. ⇒ «4»). ⇒ **вывод из
# отсутствия записи подтверждён прямой записью**; см. `../1829/`.
#
# 🆕 **В 1830 г. приход УЖЕ ПИШЕТ ФАМИЛИИ — за шесть лет до «Игната Ѳедорова КЕКЕВА»
# (1836).** В части первой их три: **Гудинъ / Гудина** (№ 42), **Ившинъ / Ившина**
# (№ 62), **Зонинъ** (№ 76); в части второй — **Ившинъ**, в части третьей — **Ившинъ**,
# **Зонинъ**, **Аникинъ**, **Силинъ**. ⇒ отсутствие фамилии у нашего рода в этом году —
# не свойство книги, а свойство рода: писец фамилию бы записал, если бы она была в ходу.
#
# ⚠ Сканы **синеватые и бледные**, как в 1833 г. — резать в сером (`crops --grey`),
# без `--enhance`.
#
# Имена сверены кропом при 3× в сером, ключевые — при 5–8×.
