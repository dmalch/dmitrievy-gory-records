# «О раждающихся». **ГАВО ф. 556 оп. 106 д. 599, лл. 307–314об** (кадры альбома 1–9).
#
# ⚠⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 307–322**. Титул на
# л. 307: «Подана Генваря 9-го дня 1837-го года. Книга, данная изъ Муромскаго Духовнаго
# Правленія Меленковской округи села Димитріевыхъ горъ въ **одноприходную Покровскую
# церковь** причту… на 1836 годъ. **Часть первая о раждающихся**» — и первые записи стоят
# **на том же листе, под титулом**, как и в 1837 г.
#
# ✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ: 106 записей о рождении (65 м / 41 ж).** Проверка — **итоговая
# ведомость причта** на л. 322: «родившихся мужеска 65, женска 41, обоего пола 106».
# Сошлась точно, как и по двум другим частям (25 венчаний, 71 погребение). Ведомость же
# добавляет: «**Незаконнорожденныхъ** 5 м / 1 ж», «Изъ Дворянской фамиліи не имѣется»,
# «Раскольниковъ нѣтъ». Ниже вынесены **восемь записей из 106**.
#
# ⓘ **Форма та же, что в 1837 г.**: четыре графы, дата прописью внутри текста, месяц
# строкой-заголовком, **записи по ОБЕИМ сторонам листа**. Причт тот же и named полностью:
# священники **Тихонъ Ивановъ** и **Михаилъ Ивановъ Экземплярскіе**, діаконъ **Яковъ
# Димитріевъ Звѣревъ**, дьячекъ **Василій Лаврентьевъ Горскій** (отчество названо здесь
# впервые — «Горскій» это фамилия, а не отчество), пономарь **Михаилъ Егоровъ**.
#
# 🔴 **РОД В ЭТОМ ГОДУ ЕСТЬ, но не отцами.** **Осипъ Антоновъ** — воспріемникъ 6 мая
# (№ 26 м ниже), сын Антона Ѳедорова, будущий рекрутъ 1840 г.; ему тут около семнадцати.
# А главная находка года лежит в части второй: «**земской Игнатъ Ѳедоровъ Кекевъ**» —
# фамилия рода за 22 года до ревизии 1858 г. (см. `..._marriages_1836.py`).
# ⚠ **Павла Ѳокина в году НЕТ**: по РС-9 1850 г. ему 14 (⇒ ок. 1836), но Ѳока Ѳедоровъ ни
# разу не назван отцом, а его дочь **Анна** родится 30 генваря 1837 г. ⇒ Павелъ родился
# в **1835 г.**, которого ф. 556 в ЭЧЗ не держит.
#
# Имена сверены кропом при 2.1×, ключевые — при 5–6×.
# Вычитано в Verso 09.10.2026.

