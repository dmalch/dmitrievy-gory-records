from corpus.statuses import (SHEPELEV_PEASANT, SHEPELEV_PEASANT_DAUGHTER_GIRL,
                             SHEPELEV_PEASANT_FEMALE, SHEPELEV_PEASANT_SON, SHEPELEV_ZEMSKOY)
from verso.ru.dsl import (Month, RecordDefaults, Relationship, Side, marriage, marriage_month,
                          marriage_records, page, person, relative)
from verso.ru.dsl.statuses import SOLDIER_WIFE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1836 г., часть вторая
# «О брачившихся». **ГАВО ф. 556 оп. 106 д. 599, лл. 315–318об** (кадры альбома 9–13).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 25 венчаний.** Проверка — итоговая ведомость причта на
# л. 322: «бракосочетавшихся лицъ 50, супружествъ 25». **ТРИ записи из 25** вынесены сюда,
# и одна из них — самая важная находка всего прохода вглубь.
#
# 🔴🔴🔴 **ФАМИЛИЯ РОДА НАЙДЕНА, И ОНА НА ДВАДЦАТЬ ДВА ГОДА СТАРШЕ, ЧЕМ СЧИТАЛ КОРПУС.**
# Запись № 1 (11 генваря, л. 315) называет поручителя по невесте: «Тогожъ села и вотчины
# **земской Игнатъ Ѳедоровъ КЕКЕВЪ**» — читается начисто при 6×. Это наш **Игнатъ
# Ѳедоровъ**, средний из трёх братьев двора 49 (ок. 1798 г. р.), родной брат Ѳоки.
# До сих пор самой ранней фамилией рода была ревизия **1858** г. (на строке Антона
# Ѳедорова, чтение владельца корпуса), а самой ранней метрической — «Павелъ Ѳокинъ
# Кекевъ» **1880** г. ⇒ **1836**.
# 🆕 И запись даёт ему **должность**: «**земской**» — выборный от мира при вотчинной
# конторе Шепелевых. Это объясняет, почему в 1842 г. он четырежды воспріемникъ: не просто
# сосед, а человек, которого зовут в свидетели.
#
# 🔴 **И год отзывает догадку 1839 года.** Запись № 20 (26 октября): «крестьянской сынъ
# **Карпъ Павловъ, ХОЛОСТОЙ**» (сверено при 5×). ⇒ у него не могло быть сына в 1824 г.,
# а значит **Максимъ Карповъ** (венчан в 1842 г. восемнадцати лет) — **не его сын**;
# предположение, записанное в комментарии к ч. 1 1839 г., снимается.
#
# ⓘ Форма та же, что в 1837 г.: возрастов нет, зато назван **отец невесты** и указано
# «холостой» / «вдовствующій», а поручители стоят в той же строке и читаются.
# Помесячно: генварь 9 · май 2 · іюль 1 · октябрь 8 · ноябрь 5. Февраля–апрѣля, іюня,
# августа, сентября и декабря венчаний нет.
#
# 🆕 **Две невесты из Нижней Вереи** (№ 4 и № 5, обе 17 и 22 генваря) — прямая связка с
# другим селом проекта: «прихода села Степанькова Экономическаго вѣдомства деревни
# **Нижней Вереи**».
#
# Имена сверены кропом при 2.1×, ключевые — при 5–6×.
# Вычитано в Verso 09.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE,
                          status_bride=SHEPELEV_PEASANT_DAUGHTER_GIRL,
                          status_groom=SHEPELEV_PEASANT_SON)

dmitrievy_gory_marriages_1836 = marriage_records(
    "ГАВО", "556", "106", "599", "Дмитриевы Горы", "Покровская",
    1836,
    *page("315",
          *marriage_month(Month.JANUARY,
                          # 🔴🔴🔴 **ФАМИЛИЯ РОДА, И САМАЯ РАННЯЯ В КОРПУСЕ: «ЗЕМСКОЙ ИГНАТЪ ѲЕДОРОВЪ КЕКЕВЪ».**
                          # Сама женитьба тут ни при чём — важен третий поручитель: «По невѣстѣ: Тогожъ села и
                          # вотчины **земской Игнатъ Ѳедоровъ Кекевъ**» (сверено при 6×, буквы чистые). Это
                          # средний из трёх братьев двора 49 РС-8 1834 г. (ок. 1798 г. р.), родной брат **Ѳоки
                          # Ѳедорова** — седьмого колена линии Анны. 🔴 **Датировка фамилии сдвигается на 22
                          # года**: прежде самое раннее «Кекевъ» давала ревизия 1858 г. (на строке Антона
                          # Ѳедорова, и то по чтению владельца корпуса), а первую метрическую — 1880 г.
                          # («Павелъ Ѳокинъ Кекевъ»). ⇒ род носит фамилию уже при крепостном праве, и писец её
                          # знает. 🆕 **И должность названа: «земской»** — выборный от мира человек при
                          # вотчинной конторе Шепелевых. Отсюда понятно, почему в 1842 г. Игнатій воспріемникъ
                          # четырежды: его зовут как свидетеля по должности, а не только по соседству. ⓘ Жених
                          # и невеста к роду отношения не имеют: **Епифанъ Максимовъ** ⚭ **Домника**,
                          # незаконнорожденная дочь солдатки Стефаниды Никифоровой из деревни Мостикова, «по
                          # отцу крестному Иванова»
                          marriage(1, 12,
                                   groom=person("Епифанъ", "Максимовъ"),
                                   bride=person("Домника", "Иванова", residence="Воютино", comment="незаконнорожденная, отчество по крестному отцу"),
                                   groom_marriage_num=1,
                                   witness1=person("Левъ", "Васильевъ", side=Side.GROOM),
                                   witness2=person("Иванъ", "Никифоровъ", side=Side.GROOM),
                                   witness3=person("Игнатъ", "Ѳедоровъ", "Кекевъ", status=SHEPELEV_ZEMSKOY, side=Side.BRIDE),
                                   relatives=[relative(person("Стефанида", "Никифорова", residence="Воютино", status=SOLDIER_WIFE), Relationship.MOTHER, "невеста")]),
                          ),
          ),
    *page("318",
          *marriage_month(Month.OCTOBER,
                          # 🔴 **ЗАПИСЬ, КОТОРАЯ ОТЗЫВАЕТ ДОГАДКУ 1839 ГОДА.** «Села Димитріевыхъ горъ вотчины
                          # Г. Г. Шепелевыхъ крестьянской сынъ **Карпъ Павловъ, холостой**, тогожъ села и
                          # вотчины **послѣ умершаго крестьянина Петра Васильева** съ дочерью, дѣвкою
                          # **Анисьею Петровой**» (слово «холостой» сверено при 5×). Комментарий к ч. 1 1839
                          # г. предполагал, что Карпъ — отец **Максима Карпова**, венчанного в 1842 г.
                          # восемнадцати лет (⇒ род. ок. 1824). **Это невозможно**: в октябре 1836 г. Карпъ
                          # вступает в ПЕРВЫЙ брак. ⇒ либо Карповъ в селе двое, либо отец Максима — другой
                          # человек; предположение снято. ✅ Зато пара опознаётся насквозь: в 1839 г. у «Карпа
                          # Павлова и Анисьи Петровой» рождается дочь **Матрена**, и восприемником стоит
                          # **Василей Власьевъ** — тот же, кто здесь поручитель по невесте. 🆕 Назван и тесть:
                          # **Петръ Васильевъ**, умерший до октября 1836 г.
                          marriage(20, 26,
                                   groom=person("Карпъ", "Павловъ"),
                                   bride=person("Анисья", "Петрова"),
                                   groom_marriage_num=1,
                                   witness1=person("Елисей", "Абрамовъ", side=Side.GROOM),
                                   witness2=person("Никита", "Еѳимовъ", side=Side.GROOM),
                                   witness3=person("Василей", "Власьевъ", side=Side.BRIDE),
                                   relatives=[relative(person("Петръ", "Васильевъ", comment="умерший"), Relationship.FATHER, "невеста")]),
                          ),
          ),
    *page("318об",
          *marriage_month(Month.NOVEMBER,
                          # 🔴 **ПЕРВОЕ ЗВЕНО САМОЙ КОРОТКОЙ ЖИЗНИ, КАКУЮ КОРПУС ПРОСЛЕЖИВАЕТ ЦЕЛИКОМ.**
                          # «Крестьянской сынъ **Егоръ Макаровъ**, холостой, съ дѣвкой **Агриппиной
                          # Михайловой**». Дальше его ведёт 1837 год: 25 іюля он тонет **восемнадцати лет**
                          # (ч. 3 1837 № 33 м, «отъ утону»), а 7 декабря у вдовы рождается сын **Антонъ** — и
                          # запись о рождении сама называет день и причину смерти отца (ч. 1 1837 № 46 м). ⇒
                          # **женился в семнадцать, умер в восемнадцать**, и все три записи теперь в корпусе.
                          # ⓘ Поручитель по невесте — **Флоръ Михайловъ**, по отчеству, вероятно, её брат; он
                          # же в генварѣ этого года венчается вдовцом (№ 9), а в 1839 г. кумит у Ѳеодора
                          # Антонова
                          marriage(23, 6,
                                   groom=person("Егоръ", "Макаровъ"),
                                   bride=person("Агрипина", "Михайлова"),
                                   groom_marriage_num=1, bride_marriage_num=1,
                                   witness1=person("Аѳанасій", "Васильевъ", side=Side.GROOM),
                                   witness2=person("Харитонъ", "Васильевъ", side=Side.GROOM),
                                   witness3=person("Флоръ", "Михайловъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
