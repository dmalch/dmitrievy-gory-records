from corpus.statuses import SHEPELEV_PEASANT, SHEPELEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import FEVER, PLEURISY

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1836 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 599, лл. 319–321об** (кадры альбома 13–16).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 71 погребение (41 м / 30 ж).** Проверка — итоговая
# ведомость причта на л. 322: «умершихъ мужеска 41, женска 30, обоего пола 71». Сошлась
# точно. **ЧЕТЫРЕ записи из 71** вынесены сюда.
#
# 🔴 **ВЕДОМОСТЬ РАСПИСЫВАЕТ УМЕРШИХ ПО ВОЗРАСТАМ, и первая её строка — «ниже году: 23»**
# из 41 мужского. Дальше поштучно: 2 г. — 1, 3 г. — 2, 4 — 1, 9 — 1, 16 — 1, 29 — 1,
# 33 — 1, 36 — 1, 40 — 1, 52 — 2, 54 — 3, 58 — 1, 62 — 1. ⇒ год, как и 1837-й, уносит
# прежде всего младенцев, «отъ поноса» и «отъ колотья», гуще всего в іюнѣ–августѣ.
#
# 🔴 **ВОЗРАСТ ПИШЕТСЯ ПРОПИСЬЮ И В НЕДЕЛЯХ, как в 1837 г., и год сам себя проверяет.**
# Больше двадцати младенцев этого года и родились, и умерли внутри книги, и всякий раз
# возраст сходится с датой крещения: Агафья Мартынова (крещ. 2 февраля — † 2 іюня, «пяти
# мѣсяцевъ»), Ѳедоръ Никифоровъ (крещ. 19 апрѣля — † 19 іюня, «двухъ мѣсяцевъ», день в
# день), Настасья Гаврилова (крещ. 12 апрѣля — † 28 іюня, «трехъ мѣсяцевъ»), Карпъ Саввинъ
# (крещ. 21 мая — † 28 іюня, «мѣсяца»), Гавріилъ Димитріевъ (крещ. 25 марта — † 8 августа,
# «четырехъ мѣсяцевъ»), Агафья Степанова (крещ. 10 февраля — † 15 ноября, «девяти
# мѣсяцевъ»). ⇒ **дробное этот писец называет словом, голое число значит годы.**
#
# 🔴🔴 **ПОГРЕБЕНИЙ РОДА В ГОДУ НЕТ** — ни братьев Ѳедоровыхъ, ни их жён и детей, ни
# вдовы **Ѳедоры Антоновой** (она доживёт до мая 1839 г.).
#
# ⚠ Дат погребения эта форма не пишет: одна дата на запись, и это **дата смерти**.
#
# Имена сверены кропом при 2.1×.
# Вычитано в Verso 09.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1836 = death_records(
    "ГАВО", "556", "106", "599", "Дмитриевы Горы", "Покровская",
    1836,
    *page("319об",
          *death_month(Month.MAY,
                       # ✅ Вычитка 2026-10-09: «Тогожъ села и вотчины крестьянина **Петра Іонина** сынъ,
                       # младенецъ **Тимоѳей**, мѣсяца, отъ колотья» — «Іонинъ» здесь отчество (Петръ Іоны
                       # сынъ), а не фамилия «Юкинъ», как читалось сначала. ⛔ Вывод, будто это ранняя запись
                       # рода Юкаевыхъ (CLAUDE.md села: «Юкаевъ — НЕ Кекевъ», МК 1913 г., л. 83об) и два рода
                       # жили рядом уже при крепостном праве, снят: опоры у него больше нет. ⓘ В том же году,
                       # 20 декабря, хоронят сына «**Варсонофья Юшкина**» (№ 40 м) — к Юкаевымъ его относить
                       # только по второй записи
                       death(11, Gender.MALE, 27,
                             deceased=person("Тимоѳей"),
                             age="1 месяц",
                             relatives=[relative(person("Петръ", "Іонинъ", status=SHEPELEV_PEASANT), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("320",
          *death_month(Month.JULY,
                       # ✅ Вычитка 2026-10-09: «Тогожъ села и вотчины крестьянина **Аѳанасья Іудина** сынъ,
                       # младенецъ **Иванъ**, 1½, отъ колотья» ⇒ мальчик род. ок. начала 1835 г. «Іудинъ» здесь
                       # отчество (Аѳанасій Іуды сынъ), а не фамилия «Гудинъ», как читалось сначала, — та же
                       # ошибка, что «Анна Іудина» 1824 г. (ч. 2 № 13). ⛔ Вывод «фамилия Гудинъ бытует в
                       # приходе минимум с 1835 г.» снят. ⓘ «Аѳанасій Іудинъ» с женой **Лукерьей Ивановой** —
                       # отец Максима, 1837 ч. 1 № 34 м (тоже вычитан: Іудинъ, не Гудинъ); «Аѳанасій и Анна
                       # Гудины» 1842 г. (ч. 1, зап. 48) со сканом ещё не сверены. Одна ли это семья — записи не
                       # говорят; не сведены
                       death(20, Gender.MALE, 9,
                             deceased=person("Иванъ"),
                             age=1.5,
                             relatives=[relative(person("Аѳанасій", "Іудинъ", status=SHEPELEV_PEASANT), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("321",
          *death_month(Month.SEPTEMBER,
                       # 🔴 **ЗАПИСЬ, КОТОРУЮ СЛЕДУЮЩИЙ ГОД ЦИТИРУЕТ ПО ПАМЯТИ — И НЕ ОШИБАЕТСЯ НИ НА ДЕНЬ.**
                       # «Шестаго числа, тогожъ села и вотчины крестьянинъ **Михей Васильевъ**, 36, отъ
                       # горячки». ✅ Часть первая 1837 г. записывает его посмертного сына: «у **вдовы Ефимьи
                       # Тихоновой**, оставшейся беременною послѣ умершаго **1836 года Сентября 6-го дня**
                       # мужа ея крестьянина **Михея Васильева**, родился сынъ **Ѳедоръ**» (13 апрѣля 1837 г.)
                       # — дата сходится буквально, и **теперь у Михея есть возраст**: 36 ⇒ род. ок. 1800 г.
                       # Младенец Ѳедоръ умрёт 17 іюня 1837 г. «двухъ мѣсяцевъ». 🔗 А в февралѣ 1837 г. его
                       # дочь **Агафья Михеева** выходит замуж за Семена Иванова (ч. 2 1837 № 7) — «съ дочерью
                       # умершаго крестьянина». ⇒ четыре записи одной семьи в двух делах, и все четыре
                       # согласны между собой. ⓘ За полгода до смерти, 10 февраля, он ещё кум у Михайла
                       # Андреева (ч. 1 № 5 м)
                       death(31, Gender.MALE, 6,
                             deceased=person("Михей", "Васильевъ"),
                             age=36,
                             cause_of_death=FEVER),
                       ),
          ),
    *page("321об",
          *death_month(Month.DECEMBER,
                       # 🔗 **ТРИ ЗАПИСИ ОБ ОДНОЙ СЕМЬЕ ВНУТРИ ОДНОЙ КНИГИ, И ВСЕ ТРИ ЗА ОДИН ГОД.** 12 генваря
                       # **Антонъ Григорьевъ** венчается холостым на **Натальѣ**, незаконнорожденной дочери
                       # солдатки Натальи Григорьевой (ч. 2 № 2); 7 декабря у них родится сын **Антонъ** (ч. 1
                       # № 61 м, крещ. 13-го); 23 декабря он умирает. ⇒ **свадьба, рождение и погребение
                       # уместились в одиннадцать с половиной месяцев** — самый короткий полный цикл, какой
                       # дал проход. ⓘ Возраст в источнике не назван цифрой; «10 дней» выведено из даты
                       # крещения (13 декабря) и даты смерти. ⓘ Тот же Антонъ Григорьевъ дважды кум в апрѣлѣ
                       # этого года (№ 10 ж, № 19 м)
                       death(41, Gender.MALE, 23,
                             deceased=person("Антонъ"),
                             age="2 недель",
                             relatives=[relative(person("Антонъ", "Григорьевъ", status=SHEPELEV_PEASANT), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    defaults=DEFAULTS,
)
