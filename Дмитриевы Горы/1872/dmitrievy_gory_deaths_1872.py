from verso.ru.dsl import (Gender, Month, RecordDefaults, death, death_month, death_records, page,
                          person)
from verso.ru.dsl.causes_of_death import NATURAL
from verso.ru.dsl.statuses import KAZENNYJ_PEASANT_MALE, PEASANT_FEMALE, PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1872 г., часть третья
# «О умершихъ». **ГАВО ф. 590 оп. 5 д. 45**, титул — л. 852 (чистый recto), записи
# лл. 852об–864об (закрывающий recto — л. 865). **ОДНА запись.**
#
# ⚠⚠ **Консисторская копия, а не приходский подлинник** — см. шапку файла о рождениях.
#
# ⚠ **Форма ч. 3 копии**: оборот несёт счётъ, мѣсяцъ смерти и погребенія, «Званіе, имя,
# отчество и фамилія умершаго», возраст в ДВУХ колонках (мужеска / женска) **и «Отъ чего
# умеръ»** ⇒ ч. 3 читается по одним оборотам; recto несёт «Кто исповѣдывалъ и пріобщалъ»
# и «Кто совершалъ погребеніе» и имён не даёт. Как в 1880–1888 гг.
#
# ⚠ **Единица возраста названа словом**: «3 недѣли», «8 мѣсяцевъ», «1 годъ», а голое
# число всегда значит ГОДЫ. Год сам себя проверяет — младенцы, крещённые в ч. 1 этого
# же года, хоронятся в ч. 3 с сроком, сходящимся до недели. Ср. предупреждение
# `../ARCHIVES.md` о д. 197, где конвенция меняется от года к году.
#
# ⚠⚠ **ЧАСТЬ ТРЕТЬЯ ОБРЫВАЕТСЯ НА НОЯБРЕ — ДЕКАБРЯ В НЕЙ НЕТ.** После ноябрьского итога
# («умершихъ мужескаго пола шесть») сразу стоит «Свидѣтельствовалъ Благочинный,
# Протоіерей», и раздел кончается на л. 864об. **Тот же дефект, что в 1880 г.** — и
# здесь он тем заметнее, что это КОПИЯ: значит, декабрьские погребения не попали уже в
# то, что причт отослал в консисторию. Искать их в приходском подлиннике, д. 195.
#
# 🔴🔴🔴 **ѲОКА МИТРОФАНОВЪ — РОДОНАЧАЛЬНИК НАЗВАН ЛИЧНО, С ОТЧЕСТВОМ И ДАТОЙ СМЕРТИ.**
# До сих пор Фока существовал в корпусе только как отчество своих сыновей; ни один год
# д. 196 (1880–1890) не называет его самого. Здесь он погребён — 70 лет, деревня
# Кононово ⇒ **это родоначальник КОНОНОВСКОЙ ветви**, той, что дала Василія (ч. 1 № м3
# этого года — воспріемникъ) и Филиппа (венчание 1880 г.). Сельскіе Ѳокины — Павелъ,
# Аникита, Алексей — идут от другого Фоки, и его смерти в этом году нет.
#
# Сверено кропом при 5×; запись вычитана в Verso 13.10.2026. Год не перечитан вторым
# сплошным проходом.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1872 = death_records(
    "ГАВО", "590", "5", "45", "Дмитриевы Горы", "Покровская",
    1872,
    *page("854об",
          *death_month(Month.MARCH,
                       # 🔴🔴🔴 **ЭТО САМ ФОКА — РОДОНАЧАЛЬНИК, КОТОРОГО КОРПУС ЗНАЛ ТОЛЬКО ПО ОТЧЕСТВУ
                       # СЫНОВЕЙ.** «Казенной деревни Кононовой крестьянинъ **Ѳока Митрофановъ**», 70 л., «отъ
                       # натуральной», † 15 марта, погребенъ 17 марта 1872 г. (сверено при 5–6×: Ѳ-о-к-а,
                       # затем М-и-т-р-о-ф-а-н-о-в-ъ; номер м14). ⇒ род. **ок. 1802 г.**, и у Фоки впервые
                       # появляется собственное отчество — **Митрофановичъ**. 🔴 **Ветвь — КОНОНОВСКАЯ, не
                       # сельская.** Деревня названа прямо, а десятью неделями раньше в той же деревне стоит
                       # воспріемникомъ «Василій Ѳокинъ» (ч. 1 № м3). ⇒ этот Фока — по всей вероятности отец
                       # кононовских **Василія** и, по венчанию 11 февраля 1880 г., **Филиппа**. ⚠ **Отцовство
                       # не сказано источником**: связывает их отчество «Ѳокинъ» при одной и той же деревне, и
                       # это сильная, но не прямая улика. (Второго сигнала год не даёт: «Василій Ѳокинъ и жена
                       # его Наталья Ѳедорова» с воспріемницей «Дарьей Ѳоковой» в № м5 — оба чтения сняты,
                       # там Василій **Іоновъ** и Дарья **Іонова**, вычитка 13.10.2026.) ⚠⚠⚠ **ОН НЕ
                       # ОТЕЦ СЕЛЬСКИХ ПАВЛА, АНИКИТЫ И АЛЕКСЕЯ** Фокичей (дворы 6 и 3 переписи 1897 г.), и
                       # решает это не цепочка «того же села / той же деревни», а **СОСЛОВИЕ**. Кононово в
                       # книге названо **казенной** деревней, то есть государственные крестьяне; Дмитриевы
                       # Горы — **помещичье** село (Глебовъ по 4-й ревизии, Баташевы по 8-й, Шепелевы по 9-й),
                       # и МК 1880 г. всё ещё пишет сельских **«временно-обязанными»**, то есть бывшими
                       # крепостными. Отец-казённый крестьянин 1802 г. р. при сыновьях-крепостных — сочетание,
                       # которого закон почти не допускает: государственных крестьян помещикам не продавали, и
                       # сословие сын наследовал от отца. ✅✅ **И ЭТО ПОДТВЕРЖДЕНО ИСТОЧНИКОМ ПРЯМО** (сверено
                       # 08.09.2026 по МК **1859** г., ф. 590 оп. 5 д. 4): дореформенная книга называет
                       # владельца поимённо и различает два населённых пункта в КАЖДОЙ записи — село идёт как
                       # «**отчины Гг. Шепелевыхъ**» (и далее «того же села и отчины»), Кононово — как
                       # «**казенной деревни Кононовой**» (далее «той же деревни»). До 1859 г. довод держался
                       # на ревизиях и на слове «временно-обязанный» 1880 года; теперь он сказан писцом.
                       # Дополнительно: regional-rules уже доказали в приходе **два рода Ѳокиныхъ** (два
                       # Василія — 1881 и 1882 гг., два Филиппа — 1880 г.), и различает их именно селение;
                       # наши носят уличные фамилии села (Кекевъ, Кузинъ), кононовскіе Ѳокины фамилий при себе
                       # не имеют вовсе. **Сельского Фоку этот год не хоронит и не называет ни разу.** ⚠
                       # Возраст «70» — голое число ⇒ годы (конвенция года, см. шапку файла); он и по нему
                       # годится в отцы сорокалетнему Василію, но точность возраста погребения в этих книгах
                       # невелика. 🔎 **Как это проверить, а не рассуждать.** Ревизии лежат по сословиям, и это
                       # и есть тест: **сельского Фоку искать в ПОМЕЩИЧЬИХ сказках** Дмитриевых Гор (8-я —
                       # ГАВО 301-5-485, 9-я — 301-5-629, обе оцифрованы), **а Ѳоку Митрофанова — в КАЗЁННОЙ
                       # описи по деревне Кононовой**, которой в наших холдингах пока нет. Если оба найдутся
                       # порознь — вопрос закрыт. Плюс ИР, которые расписаны по селениям. Сельскому Фоке к
                       # 1872 г. было бы около 65–70 ⇒ он должен быть жив в 1869 и 1859 гг. (ф. 590 оп. 5 дд.
                       # 34 и 4)
                       death(14, Gender.MALE, 15, 17,
                             deceased=person("Ѳока", "Митрофановъ", residence="Кононово", status=KAZENNYJ_PEASANT_MALE),
                             age=70,
                             cause_of_death=NATURAL),
                       ),
          ),
    defaults=DEFAULTS,
)
