                       # десять месяцев и пять дней, то есть возраст сходится с рождением
                       # Марьи почти день в день. Это НЕ два ребёнка (роды разошлись бы на
                       # пять дней) и НЕ два отца: перепись 1897 г. знает в приходе одного
                       # Михаила Ѳедорова (двор 4, № 4, 35 л., жена Марья Савельева).
                       # Остаётся расхождение ИМЕНИ одного младенца — «Марья» при рождении
