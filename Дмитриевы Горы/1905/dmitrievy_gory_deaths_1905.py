                       death(33, Gender.MALE, 1, 2,
                             deceased=person("Николай"), age=4,
                             relatives=[relative(person("Георгий", "Иоаннов", last_name_orig="Кекев"), Relationship.FATHER)],
                             cause_of_death=SCARLATINA,
                             comment="СЫН, о котором корпус не знал: четырёх лет, то есть рождён около 1901 г. "
                                     "Пара Георгий Иоаннов + Анна Иоаннова прослеживалась с 1907 г. (л. 337об), "
                                     "и это на шесть лет отодвигает её назад. На следующий день отец хоронит и "
                                     "дочь (запись № ж44)"),
                       # дочь того же Георгия Кекева (отчества писец на этот раз не поставил), рождённая **17
                       # января 1904 г.** (запись о рождении № ж5, л. 214об 1904 г.); «полтора года» источника
                       # округлены — ей был год и восемь месяцев. Умерла на другой день после брата, от той же
