from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import (PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON,
                                   RETIRED_SOLDIER)

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1905 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**,
# лл. 270–275об (титул — л. 270, записи — на лл. 270об–275об). 30 браков,
# из них ДВАДЦАТЬ ЧЕТЫРЕ обвенчаны 2 октября — рекорд прочитанных лет.
#
# **ТРИ кекевских брака** — больше, чем в любом другом прочитанном году
# (в 1907 и 1908 гг. было по два и по одному); Земсковых нет. Сверх того
# **Григорий Андреев Кекев и Флор Михайлов Кекев** стоят поручителями при
# браке № 7 (л. 271) — Флор Михайлов в корпусе больше не встречается нигде.
# Записи для поручителей не заводятся: правило прохода требует Кекева
# участником брака, а не свидетелем.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1905 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1905,
    *page("271об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # НОВОЕ лицо — **Александра Иоаннова Кекева**, 18 лет (род. ок. 1887 г.), и брак
                          # этот связывает её с уже известной ветвью: год спустя её муж **Пётр Георгиев
                          # Шимарянов** крестит дочь **Андрея Иоаннова Кекева** (запись о рождении № ж46 1906
                          # г., л. 306об). Андрей Иоаннович по отчеству её брат, и восприемничество зятя у
                          # шурина — обычное дело. Прямо родство не сказано нигде
                          marriage(8, 2,
                                   groom=person("Петр", "Георгиев", last_name_orig="Шимарянов", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=19,
                                   bride=person("Александра", "Иоаннова", last_name_orig="Кекева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=18,
                                   witness1=person("Петр", "Максимов", last_name_orig="Сухарев"),
                                   witness2=person("Тихон", "Симеонов", last_name_orig="Залетнин", status=RETIRED_SOLDIER),
                                   witness3=person("Феодор", "Космин", last_name_orig="Ерминский"),
                                   witness4=person("Димитрий", "Спиридонов", last_name_orig="Малынин")),
                          ),
          ),
    *page("273об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ЭТО ВЕНЧАНИЕ ЗАКРЫВАЕТ СПОР ОБ ИМЕНИ. В 1908 г. (л. 386об) отец записи № ж14 писан
                          # «**Ермилій** Георгіевъ Кекевъ» при жене Анне Климентьевой, в 1912 г. (л. 52об
                          # д.199) та же пара — «**Евфимій** Георгіевъ» и «Анна Климентіева», и вопрос был
                          # оставлен открытым. Здесь, за три года до первой из них, жених — **Евфимій
                          # Георгіевъ Кекевъ**, 22 лет (род. ок. 1883 г., перепись 1897 г. даёт Ефиму
                          # Егоровичу двора 5 тринадцать лет — сходится), первым браком. Значит «Ермилій» 1908
                          # года и есть описка. Заодно названа ДЕВИЧЬЯ фамилия жены — **Шишкина**, и это
                          # объясняет восприемника 1912 г. Симеона Климентова Шишкова, «брата матери». ⚠ На
                          # поле л. 274 против этой записи позднейшая приписка красными чернилами: «Согласно
                          # постановленія Народ. Судьи 3 участ. отъ 27 декабря 1921 г. бракъ расторгнутъ» —
                          # советский развод, отмеченный в церковной книге шестнадцать лет спустя
                          marriage(18, 2,
                                   groom=person("Евфимий", "Георгиев", last_name_orig="Кекев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=22,
                                   bride=person("Анна", "Климентьева", last_name_orig="Шишкина", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=17,
                                   witness1=person("Андрей", "Филиппов", last_name_orig="Ромашкин", status="запасный солдат"),
                                   witness2=person("Феодор", "Филиппов", last_name_orig="Шуянов"),
                                   witness3=person("Василий", "Петров", last_name_orig="Орлов", status=RETIRED_SOLDIER),
                                   witness4=person("Максим", "Филиппов", last_name_orig="Гаврилов")),
                          # **Анна Игнатиева Кекева**, 19 лет (род. ок. 1886 г.), — та самая «крестьянская
                          # дѣвица», что в феврале того же года крестит сына у Феодора Игнатиева (запись о
                          # рождении № м10, л. 253). По отчеству она сестра Феодора и Андрея Игнатиевых
                          # Кекевых, то есть дочь того Игнатия, чьё имя корпус знает только по отчествам
                          # детей. ⚠ Жених — **Юкачев**, род того же села, который в 1913 г. однажды был
                          # спутан с Кекевыми; «Ю» у этого писца ни с чем не спутать
                          marriage(23, 2,
                                   groom=person("Михаил", "Гаврилов", last_name_orig="Юкачев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age="20 лет 6 мес",
                                   bride=person("Анна", "Игнатиева", last_name_orig="Кекева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=19,
                                   witness1=person("Петр", "Иоаннов", last_name_orig="Сухарев"),
                                   witness2=person("Феодор", "Филиппов", last_name_orig="Шуянов"),
                                   witness3=person("Петр", "Иоаннов", last_name_orig="Щикин"),
                                   witness4=person("Михаил", "Филиппов", last_name_orig="Гаврилов")),
                          ),
          ),
    defaults=DEFAULTS,
)
