from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MAIDEN, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1906 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**, лл. 313–319об
# (титул — л. 313, записи — на лл. 313об–319об). 27 браков за год, из них
# пятнадцать 2 октября — та же осенняя картина, что в 1907 и 1908 гг.
#
# Кекев жених в одном браке из двадцати семи; Земсковых нет. Кроме того, Кекевы
# дважды стоят поручителями — **Григорий Андреев** при браке № 4 (3 февраля,
# л. 314) и **Георгий Иоаннов** при браке № 16 (2 октября, л. 316), — но записи
# для них не заводятся: правило прохода требует Кекева участником, а не
# свидетелем.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1906 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1906,
    *page("313об", reviewed=False,
          *marriage_month(Month.APRIL,
                          # ЭТОТ БРАК ЗАКРЫВАЕТ ОДИН ИЗ СТАРЫХ ВОПРОСОВ КОРПУСА. В 1911 г. (л. 5об д.199)
                          # Александра крестит пара «**Иоаннъ Филипповъ** Кекевъ и Марѳа Матвѣева» —
                          # единственная во всём корпусе строка с отчеством Филиппович, из-за которой в дереве
                          # завёлся дед Филипп, не подтверждённый больше ничем; и уже тогда было замечено, что
                          # восприемники той записи — **Андрей и Екатерина Димитриевы**, то есть двор 5.
                          # Здесь, за пять лет до неё, венчается «**Іоаннъ Димитріевъ Кекевъ**», 22 лет,
                          # первым браком, с **Марѳой Матѳіевой**: то же имя жениха, та же жена по имени и
                          # отчеству, первый брак у обоих. Значит «Филипповъ» 1911 года — описка, человек этот
                          # — **Иван Дмитриевич**, сын Дмитрия Максимовича (двор 5, в переписи 1897 г. ему 11
                          # лет — сходится с 22 в 1906 г.), а восприемниками у него стояли родные брат и
                          # сестра. Деда Филиппа в роду нет. ⚠ Возраст невесты писец не проставил — графа
                          # пуста. Фамилию её он выводит «Мерошкина» через «е»; в селе род пишется «Мирошкинъ»
                          marriage(5, 9,
                                   groom=person("Иоанн", "Димитриев", last_name_orig="Кекев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=22,
                                   bride=person("Марфа", "Матфиева", last_name_orig="Мерошкина", status=PEASANT_MAIDEN),
                                   bride_marriage_num=1,
                                   witness1=person("Стефан", "Иоаннов", last_name_orig="Шиков"),
                                   witness2=person("Василий", "Михайлов", last_name_orig="Кочетков"),
                                   witness3=person("Иаков", "Меркуриев", last_name_orig="Городничев"),
                                   witness4=person("Димитрий", "Спиридонов", last_name_orig="Малынин")),
                          ),
          ),
    defaults=DEFAULTS,
)
