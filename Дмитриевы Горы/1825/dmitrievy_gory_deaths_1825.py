from corpus.statuses import SHEPELEV_PEASANT, SHEPELEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import CONSUMPTION, DIARRHEA
from verso.ru.dsl.statuses import KAZENNYJ_PEASANT_FEMALE, KAZENNYJ_PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1825 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 466, лл. 632–635** (кадры альбома 14–18);
# л. 635об разлинован, но **пустой**.
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 21 м / 22 ж = 43 погребения**, и ведомость (л. 636) пишет
# ровно «умершихъ мужеска **21**, женска **22**, обоего пола **43**»; её возрастная
# разбивка мужчин («ниже году 9, году 4, 2 — 1, 6 — 1, 30 — 1, 35 — 1, 40 — 1, 56 — 1,
# 67 — 1, 87 — 1») даёт «итого 21».
#
# ⓘ **Графа «Какою болѣзнію» в 1825 году ЕСТЬ и заполнена сплошь** (натуральною,
# родимцемъ, чахоткою, водяною, кашлемъ, коклюшемъ, поносомъ, горячкою, колотьемъ,
# родами). ⛔ **ОТОЗВАНО 06.10.2026:** вывод «столбец пропадает в 1827-м — форма скачет через
# год» неверен: графа есть и в 1827 г. (вычитка по скану, 1827/…_deaths_1827.py).
# ⚠ **Оспы в году нет ни разу**, как и в 1826-м; 1828-й будет размечен ею весь.
#
# ✅ **ВОЗРАСТНАЯ КОНВЕНЦИЯ ПИНУЕТСЯ ДВУМЯ ПАРАМИ ВНУТРИ ГОДА, И ОНА ИНАЯ, ЧЕМ В 1826-м.**
# **Иродіонъ Макаровъ** род. 4 апрѣля (ч. 1 № 19) — погребенъ 10 сентября «5 мѣсяцевъ»
# при прожитых 5 мѣс. 4 дн.; **Соломонія Алексѣева** род. 1 августа (ч. 1 № 42) —
# погребена 12 сентября «5 недѣль» при прожитых 5 нед. 4 дн. ⇒ писец 1825 г. называет
# **истекший полный срок (округляет ВНИЗ)**, тогда как в 1826 г. мѣсяцы округлялись
# **вверх**. **Конвенцию между годами не переносить** — даже внутри одного дела.
#
# 🔴 **Погребений рода в году нет** — ни Ѳоки, ни Игната, ни Антона, ни их детей.
# ⚠ **Ловушка: ж. № 5 — «крестьянская вдова ѲЕОДОСІЯ Антонова, 52, чахоткою»** (26 февраля).
# Это **НЕ** Ѳеодора Антонова, 8-е колено рода: имя другое (Ѳеодосія), возраст даёт
# рождение ок. 1773 г. вместо ок. 1766-го, а **наша Ѳеодора погребена 28 мая 1839 г.**
# (556-106-634). Совпадение отчества и близкий возраст — ровно тот случай, ради которого
# в этом приходе нельзя отождествлять людей по имени с отчеством.
#
# ✅ Вычитано по сканам в Verso 03.10.2026.
# Первое чтение: имена сверены кропом при 2.6× в сером, ключевые — при 8–10× с
# `--enhance 1.4`.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1825 = death_records(
    "ГАВО", "556", "106", "466", "Дмитриевы Горы", "Покровская",
    1825,
    *page("632",
          *death_month(Month.JANUARY,
                       # 🔗 **ЗАПИСЬ, КОТОРУЮ ОБЪЯСНЯЕТ СЛЕДУЮЩИЙ ГОД.** «Приходу означеннаго Села казеннаго
                       # вѣдомства деревни Кононова крестьянина **Захара Петрова** жена **Аѳанасія
                       # Владимірова**, 26, чахотною», погребена 18 генваря. 🔗 Ровно через год, **17 генваря
                       # 1826 г.**, «того же села вѣдомства и деревни **вдовствующій крестьянинъ Захаръ
                       # Петровъ**» венчается на вдове **Ефимьѣ Сергеевой** (1826 ч. 2 № 2), а 18 марта у них
                       # рождается сынъ Яковъ (1826 ч. 1 № 10) — зачатый до брака. ⓘ Такой же двухлетний
                       # мостик даёт **Степанъ Никифоровъ**: жена **Офимья Леонтьева** погребена 25 декабря
                       # 1825 г. (ж. № 22), венчан вдовцом 19 февраля 1826 г. (1826 ч. 2 № 10). ⇒ **вдовец с
                       # двором женится в первый же мясоѣдъ** — правило, а не случай
                       death(3, Gender.FEMALE, 16, 18,
                             deceased=person("Аѳанасія", "Владимірова", residence="Кононово", status=KAZENNYJ_PEASANT_FEMALE),
                             age=26,
                             relatives=[relative(person("Захаръ", "Петровъ", status=KAZENNYJ_PEASANT_MALE), Relationship.HUSBAND)],
                             cause_of_death=CONSUMPTION),
                       ),
          ),
    *page("634",
          *death_month(Month.SEPTEMBER,
                       # ✅ **ПИН ВОЗРАСТНОЙ КОНВЕНЦИИ 1825 ГОДА.** «Села Дмитріевыхъ горъ вотчины малолѣтныхъ
                       # Г.Г. Шепелевыхъ крестьянина **Макара Ѳедорова** сынъ **Иродіонъ**, **5 мѣсяцевъ**,
                       # поносомъ», погребенъ 10 сентября. 🔗 Он родился внутри этой же книги: **4 апрѣля**,
                       # крещ. 5-го (ч. 1 № 19) ⇒ прожил **5 мѣсяцевъ и 4 дня**. Вторая пара года —
                       # **Соломонія Алексѣева** (1 августа → 12 сентября, «5 недѣль» при 5 нед. 4 дн., ж. №
                       # 15). ⇒ писец 1825 года называет **истекший полный срок**, то есть округляет **ВНИЗ**.
                       # ⚠ **А писец 1826 года округлял ВВЕРХ** (три пары из четырёх). ⇒ **возрастную
                       # конвенцию нельзя переносить даже между соседними годами одного дела** — её надо
                       # выводить из самого года, как это и сделано здесь. ⓘ Отец — **Макаръ Ѳедоровъ**, ещё
                       # один носитель самого частого в приходе отчества; к роду он отношения не имеет (обе
                       # ревизии называют сыновей Ѳедора Харитонова поимённо, и их трое)
                       death(17, Gender.MALE, 8, 10,
                             deceased=person("Иродіонъ"),
                             age="5 мес",
                             relatives=[relative(person("Макаръ", "Ѳедоровъ", status=SHEPELEV_PEASANT), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    *page("635",
          *death_month(Month.DECEMBER,
                       # 🔗 **ВТОРОЙ ВДОВЕЦ, ЖЕНИВШИЙСЯ В СЛЕДУЮЩЕМ ГОДУ.** «Казеннаго вѣдомства деревни
                       # Кононова крестьянина **Степана Никифорова** жена **Офимья Леонтьева**, 25, чахоткою».
                       # 🔗 **19 февраля 1826 г.** «вдовствующій крестьянинъ Стефанъ Никифоровъ» венчается
                       # снова (1826 ч. 2 № 10) — через восемь недель. ⓘ Чахотка — самая частая причина смерти
                       # взрослых в этом году: ею помечены шесть из двадцати двух женских погребений, и все
                       # умершие моложе сорока
                       death(22, Gender.FEMALE, 25, 27,
                             deceased=person("Офимья", "Леонтьева", residence="Кононово", status=KAZENNYJ_PEASANT_FEMALE),
                             age=25,
                             relatives=[relative(person("Степанъ", "Никифоровъ", status=KAZENNYJ_PEASANT_MALE), Relationship.HUSBAND)],
                             cause_of_death=CONSUMPTION),
                       ),
          ),
    defaults=DEFAULTS,
)
