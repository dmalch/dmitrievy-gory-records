# «О раждающихся». **ГАВО ф. 556 оп. 106 д. 466, лл. 619–625об** (кадры альбома 1–8).
#
# ⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 619–636**. Альбом —
# **развороты**, 19 кадров (`626_(618об-619).jpg` … `644_(636об-637).jpg`), лл. 618об–637.
# ⓘ **Кадр 634 снят ПОРТРЕТНО и в одиночку** — это л. 627, титульный лист части второй;
