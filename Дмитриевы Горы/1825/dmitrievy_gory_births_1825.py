# № 67 на л. 625об).
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ВЕДОМОСТЬ (л. 636) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** —
# **пятый такой год подряд** после 1829, 1828, 1827 и 1826. «Родившихся мужеска 33,
# женска 34, обоего пола **67**»; «бракосочетавшихся лицъ 24, супружествъ **12**»;
# «умершихъ мужеска **21**, женска **22**, обоего **43**», и возрастная разбивка мужчин
# («ниже году 9, году 4, 2 — 1, 6 — 1, 30 — 1, 35 — 1, 40 — 1, 56 — 1, 67 — 1, 87 — 1»)
# даёт «итого 21». Приписки: «**Изъ дворянской фамиліи никого не имѣется**»,
# «**Незаконнорожденныхъ не имѣется**», «**Солдатскихъ новорожденныхъ — 2**».
# ⓘ Год без единого незаконнорожденного — единственный такой за проход (1826 дал троих,
# включая двойню, 1827 — двоих).
#
# 🆕 **ВОТЧИНА НАЗВАНА ДВУМЯ ФОРМУЛАМИ, И ОНИ ДОПОЛНЯЮТ ДРУГ ДРУГА.** Часть первая пишет
# «вотчины **Г.Г. наслѣдниковъ Шепелевыхъ**» (сверено при 9×), часть вторая — «вотчины
# **малолѣтныхъ дѣтей** Господъ Шепелевыхъ». ⇒ имение — **наследство, и наследники
# малолетние**; 1827 год держит вторую формулу сплошь, 1828–1830 сокращают её до
# «вотчины дѣтей Г.Г. Шепелевыхъ».
#
# 🔴 **ЗЕМСКОЙ 1825 ГОДА — ТОТ ЖЕ, ЧТО В 1826 И 1828 гг.** (№ 48 ниже): жена **Пелагея
# Яковлева** названа во всех трёх годах. ⇒ **Николай держит должность по меньшей мере
# 1825–1828 гг.**
#
# ⓘ Причт тот же: священникъ **Тихонъ Экземплярскій**, діаконъ **Егоръ Драчевскій**,
# дьячекъ **Василій Лаврентьевъ**, пономарь **Михайло Егоровъ**. У дьячка 7 марта родился
# сынъ **Алексѣй** (№ 16). Соседний причт крестит здесь постоянно: **священникъ села
# Воютина Алексѣй Яковлевъ** (№№ 27, 33, 52, 61 — третий год подряд) и **заштатный
# священникъ села Казнева Василій Ивановъ** (№№ 26, 60).
#
# 🆕 **ПРИХОД ВИДИТ ЛЮДЕЙ ИЗДАЛЕКА.** № 6 — воспріемникъ «**10-го Егерскаго полка
# 2-го баталіона 2-й карабинерной роты рядовой Митрофанъ Васильевъ**»; № 7 — родился сын
# у **муромскаго мѣщанина Ивана Заворыкина**, кумъ — мѣщанинъ **города Касимова**;
# № 47 — «**Рязанской губерніи, Зарайскаго уѣзда села Лопецъ** крестьянина проѣзжающаго
# Ивана Емельянова» сын. Часть третья добавляет 87-летнего крестьянина из **Спасскаго
# уѣзда** (вотчины помѣщика Неронова, деревни Погарки), умершего здесь в пути.
#
# ⛔ **УТОЧНЕНО 11.09.2026 ПО ПРОЧТЕНИИ 1824 ГОДА:** фамилия, прочитанная здесь как
# «**Гонинъ**» (№ 54, Никифоръ), — это **Гудинъ**: 1824 год венчает «дѣвку **Анну
# Гудину**» (ч. 2 № 13, сверено при 11×). Та же поправка касается «Гунина» 1826 года.
