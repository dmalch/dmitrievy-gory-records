from verso.ru.dsl import (Month, RecordDefaults, Side, marriage, marriage_month, marriage_records,
                          page, person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1901 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**,
# лл. 100–104об (титул — л. 100, записи на лл. 100об–104об). **20 браков**,
# из них четырнадцать 3 октября — обычный осенний мясоед; год по числу браков
# вдвое меньше 1902-го (30) и 1905-го (30).
#
# **ОДИН кекевский брак** — № 15, и он закрывает сразу три вопроса о семье
# Космы Романовича (см. комментарий). Земсковых среди женихов и невест нет.
#
# ⚠ **Поручители здесь ВЫВЕРЕНЫ**: листы части второй лежат подряд, блоки
# recto (л. 104) ложатся на записи verso (л. 103об) один в один, поэтому
# свидетели брака № 15 в запись заводятся.
#
# ⚠ Кузины в части второй тоже есть, и снова не наши: 3 октября венчается
# **Пётр Васильев Кузин**, 18 л. 11 мес., с Евгенией Емельяновой Артамоновой,
# 17 л. 11 мес. (№ 9, л. 101об). Через десять дней она уже крестит ребёнка
# «крестьянской дѣвицей Евгенiей Емеліановой **Кузиной**» (л. 141) — писец
# по инерции оставил ей девичье звание при новой фамилии.
#
# Вычитано владельцем на сервере 16.11.2026: № 15.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1901 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1901,
    *page("103об",
          *marriage_month(Month.OCTOBER,
                          # **ВЕНЧАНИЕ Космы Романовича**, и оно даёт три вещи разом. (1) Пара **Косма Романов +
                          # Параскева** была известна корпусу с 1904 г. (по смерти сына в 1905 г.) — теперь у
                          # неё есть дата начала, **3 октября 1901 г.**, и она отодвигает семью на три года. (2)
                          # У жены появляется **девичья фамилия — МАРКИНА**; до сих пор она шла по корпусу одним
                          # именем-отчеством. (3) ⚠ **Отчество жены: «Антоніева» здесь, «Антипина» в 1908 г.,
                          # «Антониева» в 1913 г.** — а поручителем ПО НЕВЕСТЕ стоит **Игнатий АНТИППОВ
                          # Маркин**, то есть однофамилец с отчеством от Антиппа, почти наверняка её брат.
                          # Значит верна форма **Антиппова**, а «Антониева» обеих метрик — сглаживание редкого
                          # имени в привычное. В записи держится написание страницы. ⚠ Жениху 20 лет ⇒ род.
                          # около 1881 г.; отчество **Романов** в роду больше ни у кого, отец Роман корпусу
                          # неизвестен. ✅ Вычитано владельцем 16.11.2026: поручители по жениху — Іоаннъ
                          # Филипповъ Гринкинъ (читалось «Простяков») и Ѳеодоръ Григорьевъ Юдинъ (читалось
                          # «Юдев»), по невесте — **Іоаннъ Михайловъ Кекевъ** и Игнатій Антипповъ Маркинъ. ⛔ До
                          # вычитки первый поручитель по невесте читался «Иоанн МАКСИМОВ Кекев» и считался новым
                          # лицом — третьим сыном Максима Антоновича (двор 5), не попавшим в перепись; вычитка
                          # читает «Михайловъ», и этот вывод снят. С Иваном Михайловичем двора 2 запись пока не
                          # сведена
                          marriage(15, 3,
                                   groom=person("Косма", "Романовъ", last_name_orig="Кекевъ", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=20,
                                   bride=person("Параскева", "Антоніева", last_name_orig="Маркина", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=20,
                                   witness1=person("Іоаннъ", "Филипповъ", last_name_orig="Гринкинъ", side=Side.GROOM),
                                   witness2=person("Ѳеодоръ", "Григорьевъ", last_name_orig="Юдинъ", side=Side.GROOM),
                                   witness3=person("Іоаннъ", "Михайловъ", last_name_orig="Кекевъ", side=Side.BRIDE),
                                   witness4=person("Игнатій", "Антипповъ", last_name_orig="Маркинъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
