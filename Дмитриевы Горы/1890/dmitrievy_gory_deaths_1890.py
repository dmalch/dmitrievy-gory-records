from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DIARRHEA
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, SOLDIER

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1890 г.,
# часть третья «О умерших». ГАВО ф.590 оп.12 д.**196**, лл. 543–561об
# (титул — л. 543, записи на лл. 543об–561об).
#
# **ДВЕ записи, обе в июле, обе — младенцы.**
#
# ⚠ Часть третью читают по **оборотам**: правые половины разворотов несут «отъ чего
# умеръ», «кто исповѣдывалъ» и «кто совершалъ погребеніе», имён там нет. Это то же,
# что в 1891 и 1892 гг.; отличается от них только часть первая, где восприемники
# стоят на recto.
#
# ⚠ **Причины смерти этого года не выверялись** и в записи не заведены — кроме Феодора Мирошкина (№ м29, понос:
# вычитка владельца 11.11.2026).
#
# ✅ **ПАВЕЛЪ МИХАЙЛОВИЧЪ РОДИЛСЯ И ПОХОРОНЕН ВНУТРИ ОДНОЙ КНИГИ**: крещён 22 июня
# (ч. 1, № м33), погребён 23 июля одного месяца. Две записи сверяют друг друга.
#
# 🔴 **ВАСИЛІЙ АНДРЕЕВИЧЪ ВЕДЁТ В 1889 ГОД**: шести с половиной месяцев на 9 июля
# 1890 г. ⇒ родился около 24 декабря 1889 г., то есть его метрика — в книге
# **1889 года**, следующего года прохода (то же д. 196).
#
# Вычитан в Verso 25.10.2026: 2 записи года, заведённые в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1890 = death_records(
    "ГАВО", "590", "12", "196", "Дмитриевы Горы", "Покровская",
    1890,
    *page("551об",
          *death_month(Month.JULY,
                       # 🔴 **СЫН АНДРЕЯ ИОАННОВИЧА, КОРПУСУ НЕИЗВЕСТНЫЙ, И ОН ВЕДЁТ В 1889 ГОД.** «Того же
                       # села крестьянина **Андрея Иванова Кекса** сынъ **Василій**», 6½ мѣс. (сверено при
                       # 8×). Шести с половиной месяцев на 9 июля 1890 г. ⇒ род. около 24 декабря 1889 г., а
                       # часть первая 1890 г. кекевских рождений в январе не знает ⇒ **его метрика в книге
                       # 1889 года**, в том же д. 196. ⚠⚠ **В этом году в приходе ДВА Андрея Кекева, и оба
                       # корпусу известны.** Здесь отчество **Ивановъ**, а на л. 511 восприемник — «Андрей
                       # **Ѳедоровъ** Кекевъ» (ч. 1, № м9); оба чтения сверены при 8–9×. Андрей Иоанновичъ —
                       # это муж Стефаниды Георгиевой и отец Екатерины (1891); Андрей Феодоровичъ известен по
                       # 1912 г. Различать их можно только по отчеству, и обе записи его дают. ⚠ Мать метрика
                       # не называет — правило прихода. Жена Андрея Иоанновича в 1891–1894 гг. — **Стефанида
                       # Егорова (Георгиева)**, и по времени Василий её сын, но запись этого не говорит
                       death(39, Gender.MALE, 9, 11,
                             deceased=person("Василій"), age="6 мес 2 нед",
                             relatives=[relative(person("Андрей", "Ивановъ", last_name_orig="Кекевъ"), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       # ✅ **РОДИЛСЯ И ПОХОРОНЕН ВНУТРИ ОДНОЙ КНИГИ.** «Того же села запасно-отпускный солдатъ
                       # **Михаилъ Ѳедоровъ Кекевъ** сынъ **Павелъ**», 1 мѣс. (сверено при 8×). Он крещён 22
                       # июня того же года (ч. 1, № м33) — ровно месяц. Две записи сверяют друг друга день в
                       # день, как Агапия в 1893-м (Андрей Игнатьевич 1894 г. снят вычиткой 26.10.2026). 🔴 **Михаил Феодорович теряет
                       # младенцев три года подряд**: Павелъ (1890), затем дочь, погребённая 3 ноября 1892 г.
                       # десяти месяцев, — и между ними Марья, рождённая 29 декабря 1891 г. Именно в этой
                       # обстановке стоит нерешённый вопрос, одна ли это девочка под двумя именами (см. 1891
                       # г., № ж87). ⚠ Мать метрика не называет; жена его во всех записях — **Мария Саввина**
                       death(45, Gender.MALE, 22, 23,
                             deceased=person("Павелъ"), age="1 мес",
                             relatives=[relative(person("Михаилъ", "Ѳедоровъ", last_name_orig="Кекевъ", status=SOLDIER, comment="запасно-отпускной солдат"), Relationship.FATHER)],
                             cause_of_death=DIARRHEA,
                             page="552об"),
                       ),
          ),
    # Вторая волна (09.11.2026): дети замужних дочерей Кекевых, найденные по имени мужа.
    # Вычитано владельцем 11.11.2026: № м29 (прежде читалось «№ м20»; причина смерти — понос, прежде не заведена).
    *page("549об",
          *death_month(Month.JUNE,
                       # Феодор — сын Николая Максимовича Мирошкина и Дарьи Ивановны Кекевой, род. 1.04.1890 (ч. 1, л. 513об,
                       # № м16)
                       death(29, Gender.MALE, 27, 29,
                             deceased=person("Ѳеодоръ"), age="3 мес",
                             relatives=[relative(person("Николай", "Максимовъ", last_name_orig="Мирошкинъ"), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    defaults=DEFAULTS,
)
