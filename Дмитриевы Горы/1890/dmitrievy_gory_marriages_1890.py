# Метрическая книга Покровской церкви с. Димитриевы Горы за 1890 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**196**, лл. 534–542об.
# **37 браков**, из них 25 — 3 октября. ⚠ Л. 534об — лист формы «КОПІЯ СЪ
# МЕТРИЧЕСКОЙ КНИГИ», вшитый внутрь печатного прогона.
#
# **ДВЕ ЗАПИСИ**: одно кекевское венчание и одно поручительство у чужой пары.
#
# ✅✅ **ВЕНЧАНИЕ ѲЕОДОРА ИВАНОВИЧА (№ 20, 3 октября) ОБЪЯСНЯЕТ 1891 ГОД.** Его сын
# **Іоаннъ** крещён 11/13 октября 1891 г. — ровно через двенадцать месяцев, то есть
# первенец. Та же картина, что у обоих венчаний 1891 г. (Сильвестр +12 мес., Иоанн
# Михайлович +14 мес.): в этом приходе первый ребёнок приходит на первую годовщину.
#
# 🔴🔴 **ПОРУЧИТЕЛИ ПО ЖЕНИХЕ — ДВА ѲЕОДОРОВИЧА, И ФАМИЛИЯ НАПИСАНА ОДИН РАЗ НА
# ДВОИХ**: «крестьянинъ **Николай Ѳедоровъ** и запасно-отпускный **Алексій Ѳедоровъ
# Кекевъ**». Правило перечня (см. `../CLAUDE.md`) в чистом виде — по фамилии виден
# один из двух. ⇒ **Николай Феодоровичъ отодвинут на 1890 г.** (прежде 1894, потом
# 1893). И это довод структурный: Феодоровичи стоят поручителями у Ивановича, то
# есть две ветви держатся друг друга, а не просто делят фамилию.
#
# 🔴 **№ 16 — ЕГОРЪ МАКСИМОВЪ КЕКЕВЪ ПОРУЧИТЕЛЬ У ЧУЖОЙ ПАРЫ.** Найдено только со
# второго захода: сперва из поручительских recto был прочитан лишь л. 539 (против
# кекевского брака), и Егор Максимович на л. 538 остался бы не увиденным.
# ⚠⚠ **Урок: в год, где второй участник записан на RECTO, поручительские листы
# части второй надо читать СПЛОШЬ, как и восприемников части первой.**
# ⇒ Георгий Максимович отодвинут с 1891 на 1890 г.; цепочка его самых ранних
# записей 1894 → 1893 → 1891 → **1890**, и каждая — поручительство или купель в
# общий свадебный день села (2–3 октября).
#
# ⚠ Кекевских невест в году нет.
# ⚠ Поручители брака № 37 (9 ноября) утрачены: они стояли бы на л. 543, а там
# печатный титул части третьей — граница частей рвёт разворот, как всегда.
# ⚠ Не заведены: «деревни Кононовой … **Трофимъ Павловъ Кузинъ**» и прочие Кузины
# не двора 6; «вдовый крестьянинъ **Иванъ Васильевъ Кузинъ**», 26, венчается
# 1 июля вторым браком с вдовой **Еленой Діонисіевой** — ⚠ в 1891 г. (л. 15об) та
# же Елена Діонисіева записана женой «Ивана **Данилина** Кузина»; одно из двух
# чтений отчества неверно.
#
# Вычитан в Verso 25.10.2026: 2 записи года, заведённые в DSL.

