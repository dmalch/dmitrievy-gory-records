                          # Собственная его дочь Анна родится в августе 1891 г.; здесь он ещё просто
                          # «крестьянинъ». ⚠⚠ **Запись найдена со второго захода.** Сперва из поручительских
                          # recto был прочитан только л. 539 — тот, что против кекевского брака № 20, — и этот
                          # лист (538) остался бы непрочитанным. В год с формой «второй участник на recto»
                          # поручительские листы надо читать сплошь. ⚠ Разметка проверяет себя: по невесте
                          # поручаются **Зонины**, а невеста — **Зонина**. ✅ Фамилия жениха — «**Горбачевъ**»
                          # (вычитка 25.10.2026; прежде неуверенное «Ерицынъ»): «Ѳедоръ Васильевъ», того же
                          # отчества и фамилии, что поручитель Николай Васильевъ Горбачевъ
