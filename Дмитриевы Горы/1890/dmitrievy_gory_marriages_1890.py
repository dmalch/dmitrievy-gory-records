                          # Ивановъ Кекевъ**», 18, первымъ бракомъ, и «того же села крестьянская дочь
                          # **Пелагія Ѳедорова**», 18, первымъ бракомъ. Их сын **Іоаннъ** крещён 11/13 октября
                          # 1891 г. — ровно через двенадцать месяцев, то есть первенец, а не случайно
                          # найденный ребёнок. Оба по восемнадцати ⇒ оба род. около 1872 г. 🔴🔴 **Поручители по
                          # женихе — Николай и Алексий Феодоровичи, и фамилия написана ОДИН раз на двоих**
                          # («крестьянинъ Николай Ѳедоровъ и запасно-отпускный Алексій Ѳедоровъ Кекевъ»,
