                          # Дмитріевскихъ Горъ крестьяне **Николай Васильевъ Горбачевъ** и **Егоръ Максимовъ
                          # Кекевъ**» (сверено при 10×). ⇒ **Георгий Максимович отодвинут с 1891 на 1890 г.**
