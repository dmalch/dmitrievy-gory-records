# іерей **Николай Спекторскій**» — 483 − 452 + 1 = 32. ⇒ раздел полон, дыр в альбоме нет.
#
# ✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ: 86 записей о рождении (50 м / 36 ж).** Проверка — арифметика
# самого причта: помесячные итоги за его подписью сошлись **во всех двенадцати месяцах**
# (генварь 2 · февраль 7 · мартъ 4 · апрѣль 2 · май 11 · іюнь 11 · іюль 4 · августъ 7 ·
# сентябрь 3 · октябрь 15 · ноябрь 8 · декабрь 12). Ниже вынесены **восемь записей из 86**.
#
# ⓘ **Причт года — ПЯТЬ человек, и священников ДВА**: приходскій священникъ **Тихонъ
# Экземплярскій** и Григорьевскій священникъ **Михаилъ Экземплярскій**, который крестит
# в этом приходе весь год наравне с приходским; діаконъ **Яковъ Звѣревъ**, дьячекъ
# **Василій Горскій**, пономарь **Михайло Егоровъ**. Благочинный — протоіерей **Ѳедоръ**.
#
# 🔴 **СОСЛОВНАЯ ФОРМУЛА 1839 г. — ДВЕ РАЗНЫЕ ВЕЩИ, И ТОЛЬКО ОДНА ИЗ НИХ ДАТИРУЕТ.**
# 1. Село здесь — просто «крестьянинъ», **БЕЗ владельца**, тогда как и в 1842 г., и в
#    1837 г. в каждой записи стоит «вотчины Г. Г. **Шепелевыхъ**». ⇒ это **не ступень, а
#    исключение**: писец 1839 года владельца просто не пишет. (Прочтение 1837 года,
#    10.09.2026, отозвало прежнюю формулировку о «датирующем признаке».) Поэтому здесь НЕ
#    ставится SHEPELEV_PEASANT: источник владельца не называет — но владелец тот же.
# 2. Кононово — «**Экономической** деревни Кононовой», как и в 1837 г., а в 1842 г. —
#    «**Государственныхъ имуществъ** деревни Кононовой». ⇒ **вот эта** перемена реальна и
#    приходится на 1840–1842 гг., то есть на реформу Киселёва.
#
# 🔴🔴🔴 **НИ ОДНОГО РОЖДЕНИЯ В РОДУ (двор 49 РС-8 / 45 РС-9).** Ни Ѳока Ѳедоровъ, ни
# Игнатъ Ѳедоровъ, ни Антонъ Ѳедоровъ не стоят отцом ни в одной из 86 записей. А ждали
# ДВОИХ: **Иванъ Ѳокинъ** и **Василій Игнатьевъ** — обоим по РС-9 1850 г. одиннадцать лет,
# то есть ок. 1839 г. ⇒ оба родились в **1838 или 1840 г.**, а этих лет ф. 556 в ЭЧЗ НЕТ
# (1840 — оп. 111 д. 399, 1841 — оп. 106 д. 668, оба без электронной копии).
# Отрицательный результат стоит своего места: год закрыт, переискивать его не нужно.
#
# 🆕 **ЕДИНСТВЕННАЯ ФАМИЛИЯ ГОДА — и она не наша.** Л. 468об, № 46: «Того жъ села
# крестьянинъ **Ѳеодотъ Кичижинъ**» (чтение при 9×; «Кичигинъ» столь же возможно). Имя
# младенца в этой строке не далось даже при 11×, поэтому записи здесь нет. В корпусе
# Дмитриевых Гор ни Кичижиныхъ, ни Кичигиныхъ нет; на Кикевыхъ/Кикеевыхъ не похоже.
#
