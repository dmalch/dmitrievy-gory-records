from verso.ru.dsl import (Month, RecordDefaults, Side, marriage, marriage_month, marriage_records,
                          page, person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER_MAIDEN, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1839 г., часть вторая
# «О бракосочетавшихся». **ГАВО ф. 556 оп. 106 д. 634, лл. 470об–476** (кадры альбома 20–25).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 28 венчаний.** Помесячные итоги за подписью причта сошлись:
# генварь 6 · апрѣль 10 · май 2 · сентябрь 1 · октябрь 7 · ноябрь 2. Февраля, марта, іюня,
# іюля, августа и декабря венчаний нет — посты. **ДВЕ записи из 28** вынесены сюда.
#
# ⚠ **Поручители на RECTO и не читаны** — как в 1842, 1859, 1869 и 1872 гг. Обороты дают
# счёт, день, жениха с невестой, их лета и который брак; больше на них ничего нет.
#
# ⓘ **Венчальные дни года плотные**: 2 апрѣля — семь браков подряд (№ 7–13), 2 октября —
# пять (№ 20–24). Возраст женихов почти без разброса: восемнадцать лет у четырнадцати из
# двадцати восьми.
#
# 🔴🔴🔴 **НИ ОДНОГО ВЕНЧАНИЯ В РОДУ.** Ни жених, ни невеста ни в одной из 28 записей не
# принадлежат двору 49 РС-8 / 45 РС-9. Искали прежде всего **Осипа Антонова**: по РС-9
# 1850 г. он «отданъ въ рекруты въ 1840», а сын его Макаръ родился ок. 1840 г. ⇒ венчание
# должно приходиться примерно на 1838–1839 гг. В 1839 г. его НЕТ ⇒ остаётся 1838-й,
# которого ф. 556 в ЭЧЗ не держит.
#
# 🆕 **Год виден как единая ткань — ч. 2 читается только вместе с ч. 3.** Все четыре
# «вторых брака» этого года — вдовцы, чьих жён книга сама же и хоронит:
# **Антонъ Исаевъ** (жена Ефимья Тимоѳеева † 6 февраля 28 лѣтъ «отъ чахотки» — венчание
# 2 апрѣля, № 12, на вдовѣ Параскевѣ Семеновой 39 лѣтъ), **Михайло Ивановъ** (2 апрѣля,
# № 9), **Ѳеодоръ Семеновъ** (9 апрѣля, № 15, на вдовѣ Екатеринѣ Мокіевой), и
# **Адріанъ Климовъ** из Кононова — у него в один год уместились все три части: дочь
# **Татіана** род. 8 генваря (ч. 1 № 1), жена **Васса Михайлова** † 30 генваря 18 лѣтъ
# «**отъ родовъ**» (ч. 3 № 2), венчание вторымъ бракомъ 5 мая (№ 17) на **Вассѣ Петровой**
# из деревни Большаго Приклона, тоже 21 году. Три записи одной семьи в одной книге.
#
# Имена сверены кропом при 2.15×, поручители не читаны.
# Вычитано в Verso 09.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_SON,
                          status_female=PEASANT_DAUGHTER_MAIDEN)

dmitrievy_gory_marriages_1839 = marriage_records(
    "ГАВО", "556", "106", "634", "Дмитриевы Горы", "Покровская",
    1839,
    *page("470об",
          *marriage_month(Month.JANUARY,
                          # 🔴🔴 **ЭТО ВЕНЧАНИЕ ЗАКРЫВАЕТ ЗАПИСЬ, ПРОЧИТАННУЮ ТРЕМЯ ГОДАМИ ПОЗЖЕ.** «Того жъ
                          # села крестьянскій сынъ **Димитрій Леонтьевъ**, 19, первымъ бракомъ» ⚭ «того жъ
                          # села крестьянская дочь дѣвица **Настасья Петрова**, 17, первымъ бракомъ». Часть
                          # третья 1842 г. открывается ею же: «**Настасья Петрова, жена Димитрія Леонтьева, 20
                          # лѣтъ, отъ чахотки**» (кадр 0202 — один из восьми кадров, дозакачанных 09.09.2026).
                          # ✅ Арифметика сходится точно: 17 лет в генварѣ 1839 г. ⇒ род. ок. 1821/22 г. ⇒ 20
                          # лѣтъ в 1842 г. ⇒ **брак продлился три года**, и оба конца дуги лежат в разных
                          # делах одного фонда. ⓘ Ради этой сходимости запись и заведена: она показывает, что
                          # возрасты этого писца можно складывать между годами
                          marriage(2, 22,
                                   groom=person("Димитрій", "Леонтьевъ"),
                                   bride=person("Настасья", "Петрова"),
                                   groom_age=19, bride_age=17,
                                   groom_marriage_num=1, bride_marriage_num=1, witness1=person("Филипъ", "Васильевъ", side=Side.GROOM), witness2=person("Иларіонъ", "Леонтьевъ", side=Side.GROOM), witness3=person("Порфирій", "Аникіевъ", side=Side.BRIDE), witness4=person("Василей", "Власьевъ", side=Side.BRIDE)),
                          ),
          ),
    *page("471об",
          *marriage_month(Month.APRIL,
                          # ⚠⚠ **ЛОВУШКА ОТЧЕСТВА, ЗАВЕДЁННАЯ НАРОЧНО.** «Того жъ села крестьянскій сынъ
                          # **Никита Ѳеодоровъ**, 20, первымъ бракомъ» ⚭ «того жъ села крестьянская дочь
                          # дѣвица **Ефимья Максимова**, 18». ⇒ род. ок. 1819 г. У Ѳедора Харитонова сыновей
                          # ТРОЕ и все названы поимённо (Антонъ ок. 1796, Игнатъ ок. 1798, Ѳока ок. 1802 —
                          # РС-8 1834 дворъ 49, РС-9 1850 дворъ 45); Никиты среди них нет, да и по возрасту он
                          # им во внуки. ⇒ **второй род Ѳеодоровичей села**, о котором предупреждает
                          # CLAUDE.md. Год даёт этот род трижды: Никита здесь, **Василій Ѳеодоровъ** отцом в
                          # ч. 1 (№ 41) и **Семенъ Ѳедоровъ**, 17 л., в ч. 3 (№ 1). Ни одного из них не
                          # сводить с нашим двором по отчеству. ⚠ Невеста-тёзка: **Ефимья Максимова**
                          # венчается и 4 октября того же года (№ 25, 19 лѣтъ, за Михайла Матвѣева) — то есть
                          # в селе их две
                          marriage(8, 2,
                                   groom=person("Никита", "Ѳеодоровъ"),
                                   bride=person("Офимья", "Максимова"),
                                   groom_age=20, bride_age=18,
                                   groom_marriage_num=1, bride_marriage_num=1, witness1=person("Василей", "Никифоровъ", side=Side.GROOM), witness2=person("Михайло", "Андреевъ", side=Side.GROOM), witness3=person("Тихонъ", "Максимовъ", side=Side.BRIDE), witness4=person("Василей", "Филиповъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
