# Метрическая тетрадь Покровской церкви с. Димитріевы Горы за 1799 г., часть первая
# «О родившихся». **ГАВО ф. 556 оп. 106 д. 145, лл. 223–223об** (кадры 0265–0266).
#
# ⚠⚠ **ЭТО НЕ МЕТРИЧЕСКАЯ КНИГА, А КРАТКИЙ РЕЕСТР.** Одна строка на запись:
# «[отецъ] сынъ/дочь [имя], воспріемникъ былъ [имя]». **Матери не названы вовсе, и
# воспріемникъ только ОДИН.** Так же устроены тетради 1798 и 1802 гг. ⇒ то, что корпус
# умеет извлекать из полной книги (имя жены, вторая кума, титул, вотчина по записи),
# здесь **физически отсутствует**, и отрицательные выводы по этим годам слабее обычного.
# ⓘ Тетрадь **№ 12**, дана изъ **Муромскаго Духовнаго Правленія**; священникъ **Стефанъ
# Ивановъ** (в конце года болен — табель подписан за него), діаконъ **Егоръ Алексѣевъ**,
# дьячекъ **Лаврентій Ивановъ**, пономарь **Варсонофій Степановъ**.
# ⓘ Вотчина — **Господина Ивана Родіоновича Баташева**, с приписанной «казеннаго
# вѣдомства деревней Конновкой».
#
# **Состав:** л. 223 — титул и тут же ч. 1; ч. 1 — лл. 223–223об (**35 записей**);
# ч. 2 — л. 224 (**10 венчаній**); ч. 3 — л. 224 (**7 м / 1 ж = 8**); **табель — л. 224об**.
# ⚠ Раздел прихода в дѣлѣ **не один**: лл. 61–62об того же дѣла — это **1798 год**
# (см. `1798/`), а л. 222об несёт табель **чужого прихода** (діаконъ Григорій Дмитревъ,
# пономарь Алексѣй Яковлевъ).
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ТАБЕЛЬ (л. 224об) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** —
# **тридцатый такой год подряд**. «Крестьяне: родившихся мужеска **28**, женска **7**,
# обоего **35**; браковавшихся лицъ **20**, супружествъ **10**; умершихъ мужеска **7**,
# женска **1**, обоего **8**». Возрастная разбивка (7, 39, 40, 42, 58, 67, 80 — по одному)
# даёт 7 и сошлась построчно.
#
# 🏆🏆🏆 **САМАЯ РАННЯЯ ЗАПИСЬ О РОДЕ ВО ВСЁМ КОРПУСЕ — 19 ФЕВРАЛЯ 1799 г.** (№ 15 ниже),
# и это **кумовство самого Ѳедора Харитонова**. **Двадцать третій перенос подряд.**
# ⛔ **ОТОЗВАНО 14.09.2026 ПО ПРОЧТЕНИИ ТЕТРАДИ 1780 г.** (556-106-34, л. 22об, ч. 1 № 6):
#    17/19 марта 1780 г. крещёнъ **Алексѣй, сынъ Ѳедора Харитонова** — на **девятнадцать
#    лет** глубже, и это **метрика собственнаго ребёнка**, а не кумовство.
# 🏆 **И № 30 даёт Василію Харитонову ещё одного сына — Емеліана** (8/10 августа), а кумомъ
# у него стоит **Иванъ Петровъ** — тот самый, у чьего сына Ѳедоръ Харитоновъ был кумомъ
# шесть месяцев назад. **Взаимное кумовство внутри одного года.**
#
# 🚫🚫 **И ГОД ДАЁТ ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ О ДЕТЯХ ѲЕДОРА.** Ни в 1799, ни в 1798, ни в
# 1802 году **у Ѳедора Харитонова не рождается ни одного ребёнка** (35 + 50 + 61 записей
# разобраны). А ревизия 1816 г. ставит **Антону ок. 1796, Игнату ок. 1798, Ѳокѣ ок. 1802**.
# ⇒ либо возрасты сказки приблизительны, либо дети родились в **1797, 1800 и 1801 гг.**,
# и из них оцифрован только 1797-й (д. 132, «1796-1797»). 📍 Это и есть следующая цель.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 7×.

