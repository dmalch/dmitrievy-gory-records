                          # ученія Владимірской Духовной Семинаріи ученикъ **Павелъ Дмитріевъ Орловъ**, 23» ⚭
                          # «села Дмитріевыхъ горъ **священническая дочь дѣвица Елена Тихонова
                          # Экземплярская**, 16». ⇒ он женится на дочери **Тихона Ивановича Экземплярскаго** —
                          # того самого священника, которого сменяет: Экземплярскій подписывает книгу с июня
