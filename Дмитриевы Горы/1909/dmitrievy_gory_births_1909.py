# 1909–1914 гг.) по отчеству — его дети.
#
# ⚠ **ЧАСТЬ ПЕРВАЯ ПОДШИТА НЕ ПО ПОРЯДКУ.** Титул части — на л. **213** (recto),
# и за ним идёт январь: лл. 213об → 212об → 211об (1 января — 7 марта), а уже
# потом л. 190об, с которого читается 8 марта — 31 декабря. То есть три первых
# листа года лежат В КОНЦЕ прогона и в обратном порядке. Отсюда и сдвиг листов
# с восприемниками: правая страница разворота — recto СЛЕДУЮЩЕГО по оригиналу
# листа, поэтому восприемники л. 213об стоят на л. 212, л. 212об — на л. 211,
# л. 211об — на л. **190**, а дальше как обычно (л. 190об → л. 191 и т.д.).
#
# ⚠ **Восприемники декабрьских рождений (л. 209об, в том числе № м92) в деле
# отсутствуют**: на месте правой страницы подшит л. 210 — свидетельство о
# рождении, выданное Кулебакским волисполкомом в 1928 г. (Кузин Алексей
# Николаевич, р. 21 марта 1909). Прочие посторонние листы внутри части первой —
# лл. 196–196об (выпись 1927 г. из МК с. Архангел Муромского у.) и 197 (справка
# Кулебакского ЗАГС 1966 г.); из-за них разворот л. 195об смотрит на л. 198.
#
# ⚠ **Части третьей «Об умерших» за 1909 г. в альбоме нет**, поэтому файла со
# смертями за этот год не заведено. Внутренняя опись дела расписывает ч.3 для
# 1900–1907 и 1910 гг. и не даёт её ни для 1908, ни для 1909 г. — НО ПО 1908 ГОДУ
# ОПИСЬ ОШИБАЕТСЯ: часть третья 1908 г. в деле есть, лл. 407–415об, и найдена
# 02.09.2026 (см. `../1908/dmitrievy_gory_deaths_1908.py`). Значит молчание описи
# про 1909 г. отсутствия части НЕ доказывает — надо пересмотреть неснятые листы
# д.198, а если их нет, идти в консисторскую копию ф.590 оп.5 д.238 (лл. 189–235).
#
# ⚠ **Написание фамилии в этом году гуляет сильнее обычного**: «Кекевъ» (лл. 191об,
# 208об), «Кикевъ» (лл. 199об, 200об) и «Кикеевъ» (лл. 193об, 209об) — последняя
