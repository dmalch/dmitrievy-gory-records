from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import (PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON,
                                   PEASANT_WIDOW, SOLDIER_DAUGHTER, SOLDIER_SON, UNTER_OFFICER)

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1909 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198** — часть
# разорвана на ЧЕТЫРЕ куска и разбросана по всему делу:
#
#   | Листы        | Что                                   |
#   |--------------|---------------------------------------|
#   | **24, 24об** | титул части и браки № 1–5             |
#   | 189–189об    | № 6–10 (поручители на л. 159)         |
#   | 159об        | № 11–16                               |
#   | **28об–29об**| № 17–24 (поручители на лл. 29 и 30)   |
#
# ✅✅ **Лл. 24, 24об и 28об–30 найдены 03.09.2026** — они лежали в начале дела,
# среди листов, которым внутренняя опись не даёт года («ч. 2 б/г»), и попали в
# альбом Apple Photos «Дмитриевы Горы 1901»; кадры перенесены в альбом 1909 г.
# До этого дня у года не хватало **больше половины браков**: № 1–5 считались
# утраченными, а № 17–24 — несуществующими (вывод «год кончается № 16» снят).
# Итог писца на л. 29об: «въ Октябрѣ браковъ совершено восемнадцать»; всего
# в году **24 брака**. Что эти листы не 1910-го года, видно из того, что у
# 1910 г. браки № 17–24 уже есть, на лл. 156–157об.
#
# ⚠ **Поручителей браков № 1–5 в альбоме нет** — это л. 25, не снятый; и
# поручителей № 11–16 в деле нет вовсе (следующий по оригиналу лист — л. 160,
# титул части первой 1910 г.).
#
# **Кекевы в ТРЁХ браках из двадцати четырёх** — в одном жених, в двух невеста;
# Земсковых нет.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1909 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1909,
    *page("24об", reviewed=False,
          *marriage_month(Month.JANUARY,
                          # **ВЕНЧАНИЕ Иоанна Андреевича**, и оно даёт ему сразу возраст, звание и жену.
                          # Корпус знал пару «Иоанн Андреев + Татиана Онисимова» только по рождениям 1912 и
                          # 1917 гг. (лл. 53об, 238об д.199) — теперь у неё есть дата начала, **30 января 1909
                          # г.** ⚠ Жениху **18 лет 3 месяца** ⇒ род. около октября 1890 г., и он **«солдатскій
                          # сынъ»**: отец Андрей служил. ⚠⚠ Невеста — **вдова, 19 лет, вторым браком**, с
                          # фамилией **НИКИТОВА**, какой корпус за ней не знал: до сих пор она проходила одним
                          # именем-отчеством. То есть к девятнадцати годам она успела овдоветь, а Никитовы (в
                          # селе пишутся и «Никитины») — семья её первого мужа, не девичья. ⚠ Поручителей нет:
                          # л. 25, правая страница этого разворота, в альбом не попал
                          marriage(3, 30,
                                   groom=person("Иоанн", "Андреев", last_name_orig="Кекев", status=SOLDIER_SON),
                                   groom_marriage_num=1, groom_age="18 лет 3 мес",
                                   bride=person("Татиана", "Онисимова", last_name_orig="Никитова", status=PEASANT_WIDOW),
                                   bride_marriage_num=2, bride_age=19),
                          ),
          ),
    *page("159об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ЭТО та «Екатерина Димитриева Шапаринова, солдатка», что в 1911 г. восприемница у
                          # Иоанна Филиппова Кекева (запись о рождении № м16, л. 5об д.199) вместе с запасным
                          # солдатом Андреем Димитриевым Кекевым: венчание 1909 г. и объясняет её замужнюю
                          # фамилию, и показывает, что мужа за те два года успели призвать. Невеста
                          # «солдатская дочь» и по отчеству — из Димитриевых (Андрей, Александр, Петр, Феодор
                          # и Елена Димитриевы Кекевы), отцом которых по всему выходит отставной солдат
                          # Димитрий Максимов Кекев, поручитель 1911 г. и хозяин двора 5 переписи 1897 г. ⚠
                          # Возраст, однако, не сходится: Катерина Дмитриева двора 5 в 1897 г. — 6 лет, то
                          # есть в октябре 1909 г. ей 18, а не 22. Либо венчальный возраст завышен на четыре
                          # года (обычное дело), либо невеста — другая Екатерина Димитриева; отчество и звание
                          # сходятся, и только. Поручителей нет: правая страница разворота в деле отсутствует
                          # (см. заголовок файла). Фамилия жениха на этой странице выведена «Шамарынъ» — род
                          # пишется в корпусе ещё и «Шимаринъ» (л. 198об того же года), «Шимаринова» (1914) и
                          # «Шапаринова» (1911, по этому самому мужу). На поле пометка о выдаче свидетельства
                          marriage(12, 2,
                                   groom=person("Александр", "Георгиев", last_name_orig="Шамарын", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=20,
                                   bride=person("Екатерина", "Димитриева", last_name_orig="Кекева", status=SOLDIER_DAUGHTER),
                                   bride_marriage_num=1, bride_age=22),
                          ),
          ),
    *page("28об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ✅ **ЗАМЫКАЕТ ПЕРЕПИСЬ НА МЕТРИКУ.** Невеста — **Матрона Георгиева Кекева**,
                          # «крестьянская дочь», двадцати лет ⇒ род. около 1889 г.; в переписи 1897 г. в дворе
                          # 5 записана **Матрона Егоровна, 7 лет** (~1890), дочь Егора (Георгия) Максимовича.
                          # Возраст сходится с точностью до года, отчество и село — точно. У двора 5 это
                          # очередной человек, прослеженный от переписи до метрики. ⚠ Жених вдовец и унтер-
                          # офицер, на восемь лет старше. ⚠ Поручители: по женихе Николай Максимов Мирошкин и
                          # Пётр Иванов Пашин, по невесте — тот же **Николай Максимов Мирошкин** и Иаков
                          # Стефанов Мирошкин. Мирошкин стоит на обеих сторонах и вообще во всех пяти браках
                          # л. 29 — это село венчает осенним мясоедом одним и тем же кругом поручителей; в
                          # запись он заводится один раз
                          marriage(21, 2,
                                   groom=person("Максим", "Феодоров", last_name_orig="Костин", status=UNTER_OFFICER, comment="запасный старший унтер-офицер"),
                                   groom_marriage_num=2, groom_age=28,
                                   bride=person("Матрона", "Георгиева", last_name_orig="Кекева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=20,
                                   witness1=person("Николай", "Максимов", last_name_orig="Мирошкин"),
                                   witness2=person("Петр", "Иванов", last_name_orig="Пашин"),
                                   witness3=person("Иаков", "Стефанов", last_name_orig="Мирошкин")),
                          ),
          ),
    defaults=DEFAULTS,
)
