# всё это время лежала **в начале дела, среди листов без года («б/г»)**, и попала
# в альбом Apple Photos «Дмитриевы Горы 1901». Кадры перенесены в альбом 1909 г.
#
# Опознание — тремя независимыми доводами:
#   1. **Якорь по записи.** Л. 114об хоронит 21 мая «крестьянина Михаила Симеонова
#      Кекева дочь Марію, 10 дней», а часть первая 1909 г. даёт её рождение
#      **13 мая 1909 г.** (№ ж26, л. 193об): отец, имя, месяц и возраст сходятся.
#   2. **Клир.** Здесь служит **протоіерей Орловъ** при и.д. псаломщика **Ѳеодорѣ
#      Покровскомъ**; в 1901 г. тот же Орлов ещё «священникъ», а псаломщик —
#      Евгений Фигуровский. 18 февраля хоронят **жену протоиерея Елену Тихонову
#      Орлову**, 65 л.
#   3. **Исключением.** Незанятых лет для ч. 3 в деле больше не остаётся.
#
# ⚠⚠ **Лл. 111–113 в альбом НЕ попали** — это записи с 18 февраля по 24 марта
# 1909 г. (между № ж4/м4 и № ж8). Год в этой части неполон, и «Кекевых нет» про
# конец февраля и март утверждать нельзя.
#
# ⚠ **Графа «отъ чего умеръ» заведена ВЫБОРОЧНО.** Соответствие блоков recto
# записям verso проверялось полосным кропом по обеим страницам разворота и вышло
# однозначным не везде: причины стоят там, где чередование «причина → подпись
# псаломщика» читается один в один (№ ж13, ж15, ж54, ж61, м49). У № ж30 разметка
# recto не сошлась, у № ж2 правой страницы (л. 111) в альбоме нет — там причина
# не заводится.
#
# **СЕМЬ кекевских погребений**, и одно из них — самое весомое за весь проход:
# **«крестьянинъ Ѳеодоръ Игнатіевъ Кекевъ, 76 лѣтъ»** (№ м49), лицо поколения
# дедов, см. комментарий к записи.
#
# ⚠ Не заводится **«Стефана Павлова МОИСЕВА сынъ Михаилъ»** (№ м12, л. 114об,
# 1 г 5 мес): имя и отчество те же, что у Степана Павловича двора 6, но фамилия
# на странице читается «Моисевъ», а не «Кузинъ»/«Кекевъ», и Моисевы — отдельный
# род села. Свою запись двор 6 в этом году имеет отдельно (№ ж54).
#
