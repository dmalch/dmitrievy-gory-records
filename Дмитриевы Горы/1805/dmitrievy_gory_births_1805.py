from corpus.statuses import (BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE, BATASHEV_PEASANT_SPOUSE,
                             BATASHEV_PEASANT_WIFE)
from verso.ru.dsl import (Gender, Month, RecordDefaults, birth, birth_month, birth_records, page,
                          person)

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1805 г., часть первая
# «О раждающихся». **ГАВО ф. 556 оп. 106 д. 197, лл. 508–514** (кадры 0513–0520).
#
# ⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 508–520об**; альбом
# захватывает чистый л. 507об и л. 521. Кадры .tif. ⓘ **Сплошная проза без бланка**,
# нумерация раздельная по полу — как в 1803 и 1806 гг.
#
# **Состав:** л. 508 — титул и тут же ч. 1; ч. 1 — лл. 508–514 (**32 м / 37 ж = 69**);
# ч. 2 — лл. 514об–517 (**17 венчаній**); ч. 3 — лл. 517об–520 (**16 м / 14 ж = 30**);
# **ведомость — л. 520об**.
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ВЕДОМОСТЬ СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** — **двадцать
# четвёртый такой год подряд**. «Родившихся мужеска **32**, женска **37**, обоего **69**»;
# «браковавшихся лицъ **34**, супружествъ **17**»; «умершихъ мужеска **16**, женска
# **14**, обоего **30**».
# ⓘ Ненатуральная смерть названа отдельно и подробно: крестьянинъ **Кипріанъ Андреевъ**,
# 35 лѣтъ, «въ мукомольной мельницѣ **шестернею измятъ**», по свидѣтельству Нижняго
# Земскаго Суда (ч. 3 м. № 5, 13 марта).
# ⚠ **Поручителей год не записывает** — как 1803 и 1806 гг.
#
# 🔴 Род в году назван трижды: **Офимья Харитонова** родит сына (№ 20 ниже), **Василій
# Харитоновъ** будет кумомъ 7 мая (м. № 13, у Игнатія Иванова и Анны Прокофьевой, сынъ
# Иванъ), а **Саломея Петрова** — жена Ѳоки/Ѳотія Ѳедорова — кумой 9 іюля (ж. № 14).
# ⓘ 🆕 Фамилия в книге: м. № 3 называет мать «**Анна Гудина**».
# ⓘ Причт: священникъ **Стефанъ Ивановъ**, діаконъ **Егоръ Драчевскій**, дьячекъ
# **Лаврентій Ивановъ**, пономарь **Варсонофій Степановъ Валединскій** (ведомость
# подписана «Варсонофій Валединскій»). Бурмистръ — **Ефимъ Григорьевъ** (кумъ у сына
# діакона, м. № 12).
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 6×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE, status_mother=BATASHEV_PEASANT_WIFE)

dmitrievy_gory_births_1805 = birth_records(
    "ГАВО", "556", "106", "197", "Дмитриевы Горы", "Покровская",
    1805,
    *page("511",
          *birth_month(Month.JULY,
                       # 🔴🔴 **ВТОРОЙ СЫНЪ ОФИМЬИ ХАРИТОНОВОЙ — И ПОСЛЕДНІЙ ПРИ ЖИВОМ ОТЦѢ.** «…у крестьянина
                       # **Трофима Родіонова** отъ жены его **Офимьи Харитоновой** родился сынъ **Антонъ**,
                       # іюля 5 числа, молитвованъ и крещенъ въ церкви тогожъ іюля 9 числа… воспріемники были
                       # **Артемъ Григорьевъ** и крестьянская жена **Татьяна Ѳедорова**» (сверено при 6×). ⓘ
                       # **Та же пара кумовьёв, что у брата Ѳедора в 1803-м** (1803 ч. 1 м. № 9) — Артемъ
                       # Григорьевъ и Татьяна Ѳедорова, только там она «дѣвка», здесь «жена»: между двумя
                       # крещеніями она вышла замуж. 🔗 **Через восемь месяцев её муж умрёт**: 13 марта 1806 г.
                       # хоронят «крестьянина **Трофима Родіонова**, 36 лѣтъ, горячкою» (1806 ч. 3 м. № 5) ⇒
                       # он род. ок. 1770, и Офимья остаётся вдовой с двумя сыновьями, трёх лет и восьми
                       # месяцев. В 1810 г. книга так её и зовёт — **«вдова Афимья Харитонова»** (1810 ч. 1 №
                       # 53)
                       birth(20, Gender.MALE, 5, 9,
                             child=person("Антонъ"),
                             father=person("Трофимъ", "Родіоновъ"),
                             mother=person("Офимья", "Харитонова"),
                             god_parent1=person("Артемъ", "Григорьевъ"),
                             god_parent2=person("Татьяна", "Ѳедорова", status=BATASHEV_PEASANT_SPOUSE)),
                       ),
          ),
    defaults=DEFAULTS,
)
