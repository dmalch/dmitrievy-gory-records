from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (CONFESSION_LIST, CensusRole, RecordDefaults, census_records, household,
                          member, page, person)

# Исповедная роспись 1805 г., с. Дмитриевы Горы, церковь Покрова Пресвятыя Богородицы.
# **ГАВО ф. 556 оп. 111 д. 214, лл. 702–715об** (заказ № 5003, получен 28.10.2026; Photos
# «Дмитриевы Горы 1805 ИР (ГАВО 556-111-214)», pk 3757). Раздел целый, от заголовка до итога.
#
# Взят двор 60 (л. 706об) — оба сына Харитона Петрова одним хозяйством
# (`../families/Кикеевы.md`, линия Анны): «Федоръ Харитоновъ 48, жена его Федора Антонова 47,
# дѣти ихъ Антонъ 11, Игнатій 8, Фотій 4, Авдотья 17; Василій Харитоновъ 39, жена его Авдотья
# Арефьева 27, дѣти ихъ Григорій 4, Татьяна 12 и Татьяна 1». Василій уже женат на Авдотьѣ Арефьевой
# (венчание 17.04.1803, 1803 ч. 2 № 4); Григорій — сын от первой жены (†09.10.1806, 6 лѣтъ).
# 🆕 Авдотья Ѳедорова 17 ⇒ род. ок. 1788 — та, что вышла за Максима Васильева 29.04.1808.
#
# Не взяты, но стоят рядом: двор 55 на л. 706 — Семенъ, Иванъ, Петръ Васильевы с женами
# (вопрос 69, Марья Семенова), возрасты не прочитаны; двор 61 — Родіонъ Кондратьевъ с сыномъ
# Трофимомъ, мужемъ Офимьи Харитоновой.
#
# ⚠ Цифры стоят на полстроки ВЫШЕ своей строки; разложены по этому правилу (оно даёт
# Родіону Кондратьеву 51, ИР 1810 — 61, ИР 1815 — 66).
# ⚠ После Татьяны (женский № 309) стоит ещё строка «310 Татьяна» с цифрой «1» — вычиткой
# внесена в двор № 11 (дочь Василия, «Татьяна же», 1 год): две Татьяны одного отца, 12 и 1.
# Нумерация граф в ИР — по полу отдельно, поэтому номера членов двора здесь — сквозной счёт,
# а не номера граф (`rules/extraction-confessions.md`).
#
# Вычитано в Verso 29.10.2026 (прочитано 28.10.2026 по кадру 1820 при ~1.6–2×).

census = census_records(
    "ГАВО", "556", "111", "214", "Дмитриевы Горы", 1805,
    *page("706об",
          household("60",
                    member(1, person("Федоръ", "Харитоновъ"), CensusRole.HEAD, age=48),
                    member(2, person("Федора", "Антонова"), CensusRole.WIFE, ref_member=1, age=47),
                    member(3, person("Антонъ"), CensusRole.SON, ref_member=1, age=11),
                    member(4, person("Игнатій"), CensusRole.SON, ref_member=1, age=8),
                    member(5, person("Фотій"), CensusRole.SON, ref_member=1, age=4,
                           comment="в метриках — Ѳока Ѳедоровъ"),
                    member(6, person("Авдотья"), CensusRole.DAUGHTER, ref_member=1, age=17),
                    member(7, person("Василій", "Харитоновъ"), CensusRole.BROTHER, ref_member=1, age=39),
                    member(8, person("Авдотья", "Арефьева"), CensusRole.WIFE, ref_member=7, age=27),
                    # Григорій (†1806, 6 лѣтъ ⇒ род. 1800) и старшая Татьяна (ок. 1793) родились до венчания
                    # Василия с Авдотьей Арефьевой (17.04.1803) — это дети его первой жены, Аксиньи Никифоровой
                    # (12). Роспись пишет «дѣти ихъ» одной строкой; в союз они входят через parent_member=12, а
                    # secondary_* закрывает им союз с Авдотьей (m8) — иначе у ребёнка две матери
                    member(9, person("Григорій"), CensusRole.SON, ref_member=7, parent_member=12, age=4,
                           secondary_role=CensusRole.SON, secondary_ref_member=12),
                    member(10, person("Татьяна"), CensusRole.DAUGHTER, ref_member=7, parent_member=12, age=12,
                           secondary_role=CensusRole.DAUGHTER, secondary_ref_member=12),
                    # Младшая — дочь Авдотьи: род. 5.01.1804 (1804 № 1), ей 1 год
                    member(11, person("Татьяна"), CensusRole.DAUGHTER, ref_member=7, age=1, comment="Татьяна же"),
                    # В росписи её нет — умерла до 1803 г.; восстановлена по ревизии 1782 г. («Аксинья
                    # Никиѳорова», жена Василія) и по венчанію 1803 г. Василия «вторымъ бракомъ»
                    member(12, person("Аксинья", "Никиѳорова"), None, ref_member=7, spouse_member=7, hidden=True),
                    ),
          ),
    defaults=RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                            status_female=BATASHEV_PEASANT_FEMALE),
    **CONFESSION_LIST,
)
