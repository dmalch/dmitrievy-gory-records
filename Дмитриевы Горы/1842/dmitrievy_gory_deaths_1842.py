from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DIARRHEA, PLEURISY
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1842 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 689, лл. 181об–196** (кадры 0198–0213).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: около 99 погребений** (46 м / 53 ж по помесячным итогам
# причта). **ЧЕТЫРЕ записи из 99** вынесены сюда.
#
# ⚠⚠ **ЛИСТЫ 185об И 186 ВЕРНУЛИСЬ В КОРПУС ТОЛЬКО 09.09.2026.** Выгрузка ЭЧЗ, из которой
# собран альбом, брала лишь развороты и пропускала кадры, снятые ПООДИНОЧКЕ; их дозакачали
# отдельно. Без них апрѣльские погребения (и декабрьские рождения ч. 1) отсутствовали бы
# молча. См. ARCHIVES.md § «1842».
#
# 🔴🔴 **ВОЗРАСТНАЯ КОНВЕНЦИЯ ГОДА ПИНУЕТСЯ САМОЙ КНИГОЙ.** Три младенца этого года и
# родились, и умерли внутри него, и в каждом случае возраст сходится с датой рождения:
# Петръ Иродіоновъ (р. 17 мая — † 12 августа, «3 мѣсяца»), Ѳедосья Васильева (р. 25 мая —
# † 23 сентября, «4 мѣсяца»), Акилина Иларіонова (р. 6 іюня — † 6 декабря, «полу году»).
# ⇒ **дробь и «мѣсяца» при младенце означают месяцы, а голое число — ГОДЫ.** Правило
# выведено из года, а не перенесено из соседнего дела (ср. Дмитриевы Горы д. 197, где
# конвенция меняется между 1894 и 1898 гг.).
#
# ✅ Вычитано по скану в Verso 09.10.2026. Номера ч. 1 — книжные, по полу (см. файл рождений).

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1842 = death_records(
    "ГАВО", "556", "106", "689", "Дмитриевы Горы", "Покровская",
    1842,
    *page("192об",
          *death_month(Month.SEPTEMBER,
                       # 🔴 **СРЕДНЕЕ ЗВЕНО АРКИ 1842 ГОДА.** «Тогожъ села крестьянинъ **Иларіонъ Яковлевъ**,
                       # 27, отъ опухоли». ⇒ род. ок. **1815 г.** За три месяца до смерти, 6 іюня, у него
                       # родилась дочь **Акилина** (ч. 1 № 10 ж); вдова **Марья Степанова**, 21, венчается
                       # вторымъ бракомъ 13 ноября (ч. 2 № 23), а сама Акилина умирает 6 декабря (ниже).
                       # Четыре записи одной семьи в одной книге
                       death(34, Gender.MALE, 5, 7,
                             deceased=person("Иларіонъ", "Яковлевъ"),
                             age=27,
                             cause_of_death="от опухоли",
                             page="191об"),
                       # 🔴🔴 **ПЕРВЫЙ ИЗ ДВУХ СЫНОВЕЙ ИГНАТІЯ ѲЕДОРОВА, УМЕРШИХЪ ЗА ТРИ ДНЯ.** «Тогожъ села
                       # крестьянина **Игнатія Ѳедорова** сынъ, младенецъ **Михаилъ**» (имя отца сверено при
                       # 6×). Игнатъ — родной брат Ѳоки Ѳедорова и сын Ѳедора Харитонова, то есть боковая
                       # линия Анны. 🆕 **Ревизия 1850 г. этого ребёнка знать не может**: она перечисляет
                       # только живых (Фролъ, Ѳедоръ, Василій), а Михаилъ умер за восемь лет до неё. Метрика
                       # показывает то, чего ревизия показать не в состоянии. ✅ **Возраст прочитан при
                       # вычитке 09.10.2026 — 1 год 10 месяцев** (первый проход его не разобрал) ⇒ род. между
                       # 10 октября и 10 ноября 1840 г. Потому **в ч. 1 этого года рождения Михаила и нет**;
                       # книги 1840 г. в ряду ф. 556 нет
                       death(36, Gender.MALE, 10, 12,
                             deceased=person("Михаилъ"),
                             age="1 год 10 мес",
                             relatives=[relative(person("Игнатій", "Ѳедоровъ", status=PEASANT_MALE), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       # 🔴🔴 **ВТОРОЙ СЫН ИГНАТІЯ ѲЕДОРОВА, ЧЕРЕЗ ТРИ ДНЯ ПОСЛЕ БРАТА.** «Тогожъ села
                       # крестьянина **Игнатья Ѳедорова** сынъ, младенецъ **Степанъ**, 6, отъ поноса». Голое
                       # число по конвенции этого года — ГОДЫ ⇒ род. ок. **1836 г.** 🆕 Как и Михаилъ, ревизии
                       # 1850 г. неизвестен. ⇒ у Игнатія Ѳедорова корпус теперь знает **пятерых сыновей**:
                       # Фролъ (ок. 1830), Степанъ (ок. 1836, † 1842), Михаилъ (1840, † 1842), Ѳедоръ (ок.
                       # 1833½) и Василій (ок. 1839) — и дочь Екатерину (восприемница, ч. 1 № 2 м). ⚠ Сентябрь
                       # 1842 г. в приходе тяжёлый: девять погребений мужеска пола, почти все младенцы «отъ
                       # поноса» и «отъ колотья»
                       death(38, Gender.MALE, 13, 15,
                             deceased=person("Степанъ"),
                             age=6,
                             relatives=[relative(person("Игнатій", "Ѳедоровъ", status=PEASANT_MALE), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    *page("195об",
          *death_month(Month.DECEMBER,
                       # 🔴 **ЗАМОК АРКИ — И ПРОВЕРКА ВОЗРАСТНОЙ КОНВЕНЦИИ.** «Села Димитріевыхъ горъ **послѣ
                       # умершаго** крестьянина **Иларіона Яковлева** дочь, младенецъ **Акилина**, полу году,
                       # отъ колотья». Родилась 6 іюня (ч. 1 № 10 ж) — ровно полгода день в день. ✅ Писец сам
                       # пометил отца умершимъ, и это согласуется с ч. 3 (Иларіонъ † 5 сентября) и с ч. 2
                       # (вдова венчается 13 ноября)
                       death(52, Gender.FEMALE, 6, 8,
                             deceased=person("Акилина"),
                             age="полгода",
                             relatives=[relative(person("Иларіонъ", "Яковлевъ", status=PEASANT_MALE), Relationship.FATHER)],
                             cause_of_death=PLEURISY,
                             page="194об"),
                       ),
          ),
    defaults=DEFAULTS,
)
