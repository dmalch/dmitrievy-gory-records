from verso.ru.dsl.statuses import (PEASANT_DAUGHTER_MAIDEN, PEASANT_FEMALE, PEASANT_MALE,
                                   PEASANT_SON, PEASANT_WIDOW)

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1842 г., часть вторая
# «О бракосочетавшихся». **ГАВО ф. 556 оп. 106 д. 689, лл. 175–181** (кадры 0191–0197).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 23 венчания.** Помесячные итоги за подписью причта сошлись:
# январь 1 · февраль 4 · апрѣль 1 · май 1 · іюль 1 · октябрь 9 · ноябрь 6. Марта, іюня,
# августа, сентября и декабря венчаний нет — посты. **ДВЕ записи из 23** вынесены сюда.
#
# ⚠ **Поручители — на RECTO**, как в 1859, 1869 и 1872 гг. Первый проход читал только
# обороты (счёт, день, жених с невестой, их лета и который брак); поручителей обеих
# вынесенных записей прочитала вычитка 09.10.2026.
#
# ⓘ **Венчальный день октября — 2-е** (девять браков в один день), ноября — 6-е и 8-е.
#
# 🆕 **Год виден как единая ткань.** Пять из шести «вторых браков» этого года — вдовцы,
# чьих жён книга сама же и хоронит в ч. 3: Евимъ Павловъ (жена † 13 января, венчание
# 26 апрѣля), Василей Михайловъ (жена † 20 апрѣля/мая, венчание 15 іюля), Никифоръ
# Захаровъ (жена † апрѣль, венчание 26 октября), Василей Исаевъ (жена † 24 марта, венчание
# 26 октября), Власъ Александровъ (жена † 22 іюля, венчание 26 октября). ⇒ **ч. 2 и ч. 3
# одного года читаются только вместе.**
#
# ✅ Вычитано по скану в Verso 09.10.2026, с поручителями. Номера ч. 1 — книжные, по полу
# (см. файл рождений).

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1842 = marriage_records(
    "ГАВО", "556", "106", "689", "Дмитриевы Горы", "Покровская",
    1842,
    *page("178об",
          *marriage_month(Month.OCTOBER,
                          # 🔴🔴 **ВЕНЧАНИЕ МАКСИМА КАРПОВА — САМАЯ РАННЯЯ ЕГО ЗАПИСЬ, И ОНА ДАЁТ ЕМУ ГОД
                          # РОЖДЕНИЯ.** «Села Димитріевыхъ горъ крестьянскій сынъ **Максимъ Карповъ**, 18,
                          # первымъ бракомъ» ⚭ «тогожъ села крестьянина **Андрея Денисова** дочь дѣвица
                          # **Софья**, 18». ⇒ род. ок. **1824 г.** ⓘ Карпъ — одно из имён «поколения дедов»
                          # корпуса (Фока, Карпъ, Антонъ, Иоаннъ, Флоръ), и до сих пор Максимъ Карповъ был
                          # известен только по погребению дочери Агафьи в 1880 г. (МК 1880, ч. 3). ⚠
                          # **Тождество двух Максимовъ Карповыхъ не доказано**: 38 лет между венчанием и той
                          # метрикой возможны, но в селе имя не уникально — проверяется ревизиями 1850 и 1858
                          # гг. 🆕 Мать невесты **Акилина Терентьева** умерла 19 февраля того же года (ч. 3), а
                          # вторая дочь Андрея Денисова, **Марія**, венчается 6 ноября (№ 18) — обе выданы в
                          # первую осень после смерти матери
                          marriage(12, 2,
                                   groom=person("Максимъ", "Карповъ", status=PEASANT_SON),
                                   bride=person("Софья", status=PEASANT_DAUGHTER_MAIDEN),
                                   groom_age=18, bride_age=18,
                                   groom_marriage_num=1, bride_marriage_num=1, witness1=person("Николай", "Денисовъ", side=Side.GROOM), witness2=person("Максимъ", "Фотіевъ", side=Side.GROOM), witness3=person("Павелъ", "Андреевъ", side=Side.BRIDE), witness4=person("Василей", "Федотовъ", side=Side.BRIDE), relatives=[relative(person("Андрей", "Денисовъ"), Relationship.FATHER, "невеста")]),
                          ),
          ),
    *page("180об",
          *marriage_month(Month.NOVEMBER,
                          # 🔴 **ПОСЛЕДНЕЕ ВЕНЧАНИЕ ГОДА ЗАМЫКАЕТ АРКУ, НАЧАТУЮ В ІЮНѢ.** «Тогожъ села
                          # крестьянинъ **Филипъ Мокіевъ**, 32, вторымъ бракомъ» ⚭ «тогожъ села крестьянская
                          # **вдова Марья Степанова**, 21, вторымъ бракомъ». Невеста — вдова **Иларіона
                          # Яковлева**, умершаго 5 сентября 27 лѣтъ (ч. 3), у которого 6 іюня родилась дочь
                          # **Акилина** (ч. 1 № 10 ж). Через три недели после этого венчания, 6 декабря, Акилина
                          # умерла «полу году» — и записана уже дочерью «послѣ умершаго» отца. ⇒ рождение,
                          # вдовство, новый брак и смерть младенца — **четыре записи одной семьи в одной
                          # книге**. ⚠ У жениха своя утрата: жена **Устинья Яковлева**, 53, умерла 12 февраля
                          # (ч. 3). Разница в возрасте (32 и 53) велика — либо возраст Устиньи прочитан
                          # неверно, либо Филипъ Мокіевъ в селе не один; **в род не заводится**
                          marriage(23, 13,
                                   groom=person("Филипъ", "Мокіевъ"),
                                   bride=person("Марья", "Степанова", status=PEASANT_WIDOW),
                                   groom_age=32, bride_age=21,
                                   groom_marriage_num=2, bride_marriage_num=2, witness1=person("Павелъ", "Мокіевъ", side=Side.GROOM), witness2=person("Александръ", "Яковлевъ", side=Side.GROOM), witness3=person("Ѳедоръ", "Семеновъ", side=Side.BRIDE), witness4=person("Іларіонъ", "Даниловъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
