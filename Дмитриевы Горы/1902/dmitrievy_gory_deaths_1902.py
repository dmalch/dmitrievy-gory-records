                       # ж27 читается «Іоанновъ» (владелец, 17.09 и 15.11.2026). У этой пары теперь известны
                       # шестеро подряд — Елена (1901), Татиана (1902), Мария (1905), Анна (1907), вторая
                       # Мария (1908) и Александра (1910), — и из первых четырёх не выжила ни одна. ⚠ В
                       # декабре того же 1902 года у них родится Татиана (запись о рождении № ж70, л. 80об) ⚠
