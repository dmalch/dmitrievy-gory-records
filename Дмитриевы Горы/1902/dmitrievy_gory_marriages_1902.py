from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1902 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**,
# лл. 82–87об (титул — л. 82, записи — на лл. 82об–87об). **30 браков**, и из
# них **двадцать четыре обвенчаны 2 октября** — рекорд прочитанных лет
# (в 1905 г. было двадцать четыре из тридцати, в 1908 и 1907 — по шестнадцать).
#
# ⚠ **Поручители по строкам НЕ выверены.** Листы части второй лежат подряд, но
# соответствие блоков recto записям verso в этом году до конца не доведено, и
# свидетели в запись не заводятся — лучше пусто, чем неверно. Кекевых среди
# прочитанных поручителей обоих кекевских браков нет.
#
# **ДВА кекевских брака**, и оба 2 октября. Второй из них — **главная находка
# всего прохода за 1902 год**: он окончательно разводит двух Андреев
# Иоанновичей, которых разбор 1903 года только развёл по жёнам.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1902 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1902,
    *page("84об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ВЕНЧАНИЕ **Феодора Игнатиевича**, и оно закрывает два вопроса. Первое: у его жены
                          # есть **девичья фамилия — ФИЛАТКИНА**; до сих пор она проходила по корпусу одним
                          # именем-отчеством. Второе: отчество **Никитина ПОДТВЕРЖДЕНО** венчальной записью, и
                          # «Параскева **Никифорова**» 1905 года (л. 252об) окончательно опознана как описка
                          # того писца. ⚠ Обоим по 18 лет, то есть жених род. около 1884 г. — а его отец
                          # **Игнатий Феодорович** венчается вторым браком в 1904 г. сорока пяти лет, то есть
                          # род. около 1859 г. Отцу при рождении сына было двадцать пять: сходится, и это
                          # первая проверка возраста Игнатия по независимой записи
                          marriage(14, 2,
                                   groom=person("Феодор", "Игнатиев", last_name_orig="Кекев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=18,
                                   bride=person("Параскева", "Никитина", last_name_orig="Филаткина", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=18),
                          ),
          ),
    *page("86об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ⚠⚠⚠ **ЭТА ЗАПИСЬ ОКОНЧАТЕЛЬНО РАЗВОДИТ ДВУХ АНДРЕЕВ ИОАННОВИЧЕЙ.** Разбор 1903
                          # года показал, что это имя стоит в одном году с двумя разными жёнами, и вывел двух
                          # человек косвенно — из того, что вдова Наталия Евфимиева пережила мужа. Здесь то же
                          # сказано ПРЯМО: **Андрей Іоанновъ Кекевъ венчается ПЕРВЫМ браком 2 октября 1902 г.,
                          # семнадцати лет и одиннадцати с половиной месяцев**, то есть род. около октября
                          # 1884 г., и жена его — **Евфросиния Афанасиева**, та самая, с которой он крестит
                          # детей в 1903, 1904 и 1906 гг. А «Андрей Іоанновъ Кекевъ», погребённый 7 марта 1904
                          # г. **сорока одного года**, род. около 1863 г. и к 1902 г. давно женат на Наталии
                          # Евфимиевой. Между ними двадцать один год: это ДВА человека, и догадка про
                          # посмертного ребёнка окончательно не нужна. ⚠ Отсюда же следует, что **Анна, дочь
                          # Андрея Иоаннова, погребённая 24 июня 1902 г. года и полумесяца** (запись о смерти
                          # № ж18), — дочь СТАРШЕГО Андрея: младший к её рождению (около июня 1901 г.) ещё не
                          # был женат. ⚠ Девичья фамилия невесты читается неуверенно — «Апрятинова» либо
                          # «Апришнова»; в других записях корпуса она всегда просто «Евфросинія Аѳанасіева»
                          marriage(23, 2,
                                   groom=person("Андрей", "Иоаннов", last_name_orig="Кекев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age="17 лет 11 мес",
                                   bride=person("Евфросиния", "Афанасиева", last_name_orig="Апрятинова", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=20),
                          ),
          ),
    defaults=DEFAULTS,
)
