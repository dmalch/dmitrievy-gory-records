from verso.ru.dsl import (Month, RecordDefaults, Side, marriage, marriage_month, marriage_records,
                          page, person)
from verso.ru.dsl.statuses import (PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON,
                                   SOLDIER)

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1902 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**,
# лл. 82–87об (титул — л. 82, записи — на лл. 82об–87об). **30 браков**, и из
# них **двадцать четыре обвенчаны 2 октября** — рекорд прочитанных лет
# (в 1905 г. было двадцать четыре из тридцати, в 1908 и 1907 — по шестнадцать).
#
# ✅ **Поручители обоих кекевских браков вписаны вычиткой владельца 18.11.2026**,
# со сторонами (до неё соответствие блоков recto записям verso не было доведено,
# и свидетели не заводились). Кекевых среди них нет; при Феодоре Игнатьевиче
# поручитель по жениху — запасный солдат Пётр Иоаннович Шиков, муж Ксении Иоанновны Кекевой; Стефан Тимофеев Скрулетов и Пётр Васильев
# Кузин стоят поручителями в обоих браках.
#
# **ДВА кекевских брака**, и оба 2 октября. Второй из них — **главная находка
# всего прохода за 1902 год**: он окончательно разводит двух Андреев
# Иоанновичей, которых разбор 1903 года только развёл по жёнам.
#
# Вычитано владельцем на сервере 18.11.2026: № 14, № 23.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1902 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1902,
    *page("84об",
          *marriage_month(Month.OCTOBER,
                          # ВЕНЧАНИЕ **Феодора Игнатиевича**, и оно закрывает два вопроса. Первое: у его жены
                          # есть **девичья фамилия — ФИЛАТКИНА**; до сих пор она проходила по корпусу одним
                          # именем-отчеством. Второе: отчество **Никитина ПОДТВЕРЖДЕНО** венчальной записью, и
                          # «Параскева **Никифорова**» 1905 года (л. 252об) окончательно опознана как описка
                          # того писца. ⚠ Обоим по 18 лет, то есть жених род. около 1884 г. — а его отец
                          # **Игнатий Феодорович** венчается вторым браком в 1904 г. сорока пяти лет, то есть
                          # род. около 1859 г. Отцу при рождении сына было двадцать пять: сходится, и это
                          # первая проверка возраста Игнатия по независимой записи
                          marriage(14, 2,
                                   groom=person("Ѳеодоръ", "Игнатіевъ", last_name_orig="Кекевъ", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=18,
                                   bride=person("Параскева", "Никитина", last_name_orig="Филаткина", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=18, witness1=person("Петръ", "Тимофѣевъ", last_name_orig="Никитавъ", side=Side.GROOM), witness2=person("Петръ", "Іоанновъ", last_name_orig="Шиковъ", status=SOLDIER, side=Side.GROOM, comment="запасный солдат"), witness3=person("Стефанъ", "Тимофѣевъ", last_name_orig="Скрулетовъ", side=Side.BRIDE), witness4=person("Петръ", "Василіевъ", last_name_orig="Кузинъ", side=Side.BRIDE)),
                          ),
          ),
    *page("86об",
          *marriage_month(Month.OCTOBER,
                          # ⚠⚠⚠ **ЭТА ЗАПИСЬ ОКОНЧАТЕЛЬНО РАЗВОДИТ ДВУХ АНДРЕЕВ ИОАННОВИЧЕЙ.** Разбор 1903 года
                          # показал, что это имя стоит в одном году с двумя разными жёнами, и вывел двух человек
                          # косвенно — из того, что вдова Наталия Евфимиева пережила мужа. Здесь то же сказано
                          # ПРЯМО: **Андрей Іоанновъ Кекевъ венчается ПЕРВЫМ браком 2 октября 1902 г., семнадцати
                          # лет и одиннадцати с половиной месяцев**, то есть род. около октября 1884 г., и жена
                          # его — **Евфросиния Афанасиева**, та самая, с которой он крестит детей в 1903, 1904 и
                          # 1906 гг. А «Андрей Іоанновъ Кекевъ», погребённый 7 марта 1904 г. **сорока одного
                          # года**, род. около 1863 г. и к 1902 г. давно женат на Наталии Евфимиевой. Между ними
                          # двадцать один год: это ДВА человека, и догадка про посмертного ребёнка окончательно
                          # не нужна. ⚠ Отсюда же следует, что **Анна, дочь Андрея Иоаннова, погребённая 24 июня
                          # 1902 г.** (запись о смерти № ж18; возраст по вычитке — «1 год 6 мес»), — дочь
                          # СТАРШЕГО Андрея: младший к её рождению (около июня 1901 г.) ещё не был женат. ✅
                          # Вычитано владельцем 18.11.2026: девичья фамилия невесты — **Секрѣтова** (до вычитки
                          # читалась неуверенно, «Апрятинова» либо «Апришнова»); жениху «17 лет 11 мес 2 нед»;
                          # поручители по жениху Стефан Тимофеев Скрулетов и Максим Петров Захаров, по невесте
                          # Пётр Васильев Кузин и Иоанн Иосифов Авданин. В других записях корпуса она просто
                          # «Евфросинія Аѳанасіева»
                          marriage(23, 2,
                                   groom=person("Андрей", "Іоанновъ", last_name_orig="Кекевъ", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age="17 лет 11 мес 2 нед",
                                   bride=person("Евфросинія", "Афанасіева", last_name_orig="Секрѣтова", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=20, witness1=person("Стефанъ", "Тимофѣевъ", last_name_orig="Скрулетовъ", side=Side.GROOM), witness2=person("Максимъ", "Петровъ", last_name_orig="Захаровъ", side=Side.GROOM), witness3=person("Петръ", "Василіевъ", last_name_orig="Кузинъ", side=Side.BRIDE), witness4=person("Іоаннъ", "Іосифовъ", last_name_orig="Авданинъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
