from corpus.statuses import (SHEPELEV_PEASANT, SHEPELEV_PEASANT_DAUGHTER, SHEPELEV_PEASANT_FEMALE,
                             SHEPELEV_PEASANT_SON, SHEPELEV_PEASANT_WIFE)
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import COUGH, FEVER, PLEURISY

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1826 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 476, лл. 708–713об** (кадры альбома 12–18).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 25 м / 39 ж = 64 погребения**, и ведомость (л. 714) пишет
# ровно «умершихъ мужеска **25**, женска **39**, обоего пола **64**»; её возрастная
# разбивка мужчин («ниже году 10, 1¼ — 2, 1½ — 2, 3 — 2, 5 — 2, 12 — 1, 13 — 1, 19 — 1,
# 20 — 1, 60 — 1, 63 — 1, 77 — 1») даёт «итого 25». Приписка: «въ семъ 1826-мъ году
# **ненатуральною смертію умершихъ никого не имѣлось**».
#
# ⓘ **Графа причины смерти в 1826 году ЕСТЬ.** Заголовок читается «**Какою болѣзнію**», и
# заполнена она сплошь: горячкою, поносомъ, кашлемъ, коклюшемъ, чахоткою, водяною,
# колотьемъ, лихорадкою, родами, натуральною. (⚠ «родами» — возможно, только ж. № 34,
# которую вычитка 04.10.2026 читает «горячкою»; остальные строки графы не перечитывались.)
# ⛔ **ОТОЗВАНО 06.10.2026:** вывод «в 1827-м её нет — форма скачет через год» неверен.
# Графа есть и в 1827 г. («Какою болѣзнію померъ», 1827/…_deaths_1827.py); первое
# прочтение 1827-го её не увидело. Она стоит во всех прочитанных годах 1825–1828.
#
# ⓘ **Что убивало в 1826-м**: десять из двадцати пяти мужчин — «ниже году», и держат их
# поносъ, кашель и коклюшъ; у взрослых — чахотка (четверо) и «натуральная» (шестеро,
# все за шестьдесят). **Оспы в году нет ни разу** — при том, что 1828-й весь ею размечен.
#
# 🔴 **Погребений рода в году нет** — ни Ѳоки, ни Игната, ни Антона, ни их детей. Сын
# Антона **Андрей**, родившийся 7 августа (ч. 1 № 50), этот год переживает; сын Игната
# **Семенъ** (ок. 1824) тоже — его похоронят 11 іюля 1828 г. «4 лѣтъ».
#
# ✅ **ВОЗРАСТНАЯ КОНВЕНЦИЯ ВЫВЕДЕНА ИЗ САМОГО ГОДА И ПИНУЕТСЯ ЧЕТЫРЬМЯ ПАРАМИ.** Единицы
# писец называет прямо («10 ти мѣсяцевъ», «6 ти недѣль», «5 ти лѣтъ»), держит идиому
# «полугоду» и пишет дроби («1½»). Четверо родились и умерли внутри книги, и каждый раз
# возраст сходится с **округлением ВВЕРХ**: Ефросинія Иванова (20 мая → 28 іюня, «1 мѣс»),
# Елисей Михеевъ (10 іюня → 2 августа, «2 мѣс»), Павелъ Ѳедоровъ (27 іюня → 12 августа,
# «6 недѣль», № 19 ниже), Платонъ Ѳокинъ (9 ноября → 18 декабря, «6 недѣль»). ⇒ та же
# конвенция, что 1829 год пинует восемью парами. **Голое число здесь означает ГОДЫ**.
#
# ✅ Вычитано по сканам в Verso 04.10.2026.
# Первое чтение: имена сверены кропом при 2.6× в сером, ключевые — при 5–8×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1826 = death_records(
    "ГАВО", "556", "106", "476", "Дмитриевы Горы", "Покровская",
    1826,
    *page("710об",
          *death_month(Month.MAY,
                       # 🆕🆕 **ВОТЧИНА ШЕПЕЛЕВЫХЪ ДЕРЖИТ ЗАВОД, И ЕГО ХОРОНЯТ ЗДЕСЬ.** «**Сноведскаго Завода,
                       # вотчины дѣтей Г-дъ Шепелевыхъ** женки **Варвары Петровой** дочь **Стефанида**,
                       # полугоду, кашлемъ… погребена на отведенномъ кладбищѣ по церковному чиноположенію села
                       # Димитріевыхъ горъ священникомъ Экземплярскимъ съ пономаремъ Егоровымъ» 30 мая. 🔗
                       # Книга называет заводъ трижды: здесь, в ч. 1 № 1 («Сноведскаго завода дѣвка Прасковья
                       # Семенова» кумою) и в ч. 1 № 88 («тойже вотчины **Сноведскаго Завода прикащикъ Ефимъ
                       # Капустинъ**»). ⇒ Сноведской чугуноплавильный заводъ — **часть той же вотчины**, что и
                       # село, а Шепелевы, стало быть, наследники Баташевыхъ по выксунскому кусту. Ту же
                       # вторую половину наследства ч. 1 № 85 называет прямо: «вотчины **наслѣдниковъ
                       # Баташова**». 🔗 1828 год дал четвёртым нижегородским селением вотчины **Введенскій
                       # заводъ / Виловку**; Сноведь — пятое, и первое, чьи люди тут погребены. ⚠ Отца записи
                       # нет: ребёнок назван по матери, и «женка» — её сословный статус, а не имя мужа
                       death(19, Gender.FEMALE, 28, 30,
                             deceased=person("Стефанида", residence="Сноведской завод", status=SHEPELEV_PEASANT_DAUGHTER),
                             age="полгода",
                             relatives=[relative(person("Варвара", "Петрова", status="крестьянская женка вотчины гг. Шепелевых"), Relationship.MOTHER)],
                             cause_of_death=COUGH),
                       ),
          ),
    *page("712",
          *death_month(Month.AUGUST,
                       # ✅ **ПИН ВОЗРАСТНОЙ КОНВЕНЦИИ 1826 ГОДА.** «Означеннаго села и вотчины крестьянина
                       # **Ѳедора Семенова** сынъ **Павелъ**, **6 ти недѣль**, колотьемъ», погребенъ 14
                       # августа. 🔗 Он же родился внутри этой книги: 27 іюня, крещ. 29-го (ч. 1 № 37) ⇒ прожил
                       # **6 недѣль и 4 дня**. Писец округлил вниз до полной недели — или, что то же самое,
                       # назвал истекший срок. Три другие пары года (Ефросинія Иванова, Елисей Михеевъ,
                       # Платонъ Ѳокинъ) дают округление **вверх** до полного месяца. ⇒ шкала у него не одна:
                       # недѣли он считает точно, мѣсяцы округляет. ⚠ Практический вывод для всего прохода:
                       # **единицу здесь всегда называют словом**, и голое число в этой книге означает ГОДЫ —
                       # в отличие от дела 196, где то же голое число у младенца в 1886 г. значило месяцы
                       death(19, Gender.MALE, 12, 14,
                             deceased=person("Павелъ", status=SHEPELEV_PEASANT_SON),
                             age="6 недель",
                             relatives=[relative(person("Ѳедоръ", "Семеновъ"), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("713",
          *death_month(Month.OCTOBER,
                       # 🔗 **ЗАПИСЬ, КОТОРАЯ ОБЪЯСНЯЕТ ВЕНЧАНИЕ 8 НОЯБРЯ.** «Означеннаго села и вотчины
                       # крестьянина **Василья Тимоѳеева** жена **Ульянія Денисова**, 20», умерла 7 октября,
                       # погребена 9-го; причина — **горячка** (⛔ прежде читалось «родами» — исправлено
                       # вычиткой по скану 04.10.2026). 🔗 Через **месяц**, 8 ноября (⛔ не 13-го — та же
                       # вычитка), тот же Василій Тимоѳеевъ венчается «вдовствующимъ крестьяниномъ» на дѣвкѣ
                       # Праскевѣ Ивановой — и поручителем у него
                       # стоит **Антонъ Ѳедоровъ** (ч. 2 № 18). ⇒ обе записи рода в этой части года сходятся в
                       # одну историю. ⓘ Второй такой же случай в книге: **Кондратій Тимоѳеевъ** (по отчеству,
                       # вероятно, брат) хоронит жену Евдокію Иванову 14 февраля (ж. № 6, двадцати четырёх
                       # лет) и венчается 3 октября (ч. 2 № 14). ⛔ **ОТОЗВАНО 04.10.2026 вместе с «родами»**
                       # рассуждение о мертворождённом ребёнке: умерла она горячкою, и о ребёнке запись не
                       # говорит ничего
                       death(34, Gender.FEMALE, 7, 9,
                             deceased=person("Ульянія", "Денисова", status=SHEPELEV_PEASANT_WIFE),
                             age=20,
                             relatives=[relative(person("Василій", "Тимоѳеевъ"), Relationship.HUSBAND)],
                             cause_of_death=FEVER),
                       ),
          ),
    defaults=DEFAULTS,
)
