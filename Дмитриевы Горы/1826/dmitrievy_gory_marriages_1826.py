# раньше**, и окно сужается с «1822–1826» до **1822–1825**: 1825 (556-106-466),
# 1824 (453), 1823 (437), 1822 (428) — все четыре оцифрованы. Следующий шаг — 1825-й.
#
# ⚠ **Имя «Ѳока» в приходе носят как минимум двое.** Кроме нашего Ѳоки Ѳедорова книга
# 1826 г. держит кононовского **Ѳоку Митрофанова** (ч. 1 № 72, ч. 3 м. № 25). ⛔ Третий,
# «Ѳока Антоновъ» (поручитель, № 7 ниже), снят вычиткой по скану 04.10.2026: это **Іона
# Антоновъ** — тот же, что поручитель 1824 г. (ч. 2 № 27; свод `iona_antonovich_1824`). 🔗 Тот же урок, что дал 1830 год «Филиппомъ
# Ѳокіевымъ», и что стоил проходу 1880-х двух Филипповъ и двух Василіевъ Ѳокиныхъ:
# **отчество «Ѳокинъ» само по себе не доказывает ничего.**
# ⚠ 1825 год добавляет к ним **нерасшифрованного «[Ѳо…ій] Ѳедорова»** — поручителя
# 2 октября (1825 ч. 2 № 8), который может быть и нашим Ѳокой, и отцом Филиппа Ѳотіева.
#
# ⓘ Год хорошо сшивается сам с собой: **Кондратій Тимоѳеевъ** хоронит жену 12 февраля
# (ч. 3 ж. № 6) и венчается вдовцом 3 октября (№ 14); **Василій Тимоѳеевъ** хоронит жену
# 7 октября (ч. 3 ж. № 34) и венчается 8 ноября (№ 18 ниже) — **через месяц**;
# **Захаръ Петровъ** венчан 17 генваря (№ 2), а 18 марта у него уже родился сынъ (ч. 1
