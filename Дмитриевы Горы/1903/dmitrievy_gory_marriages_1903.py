from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1903 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**. 19 браков.
#
# ⚠ **ЧАСТЬ ВТОРАЯ ПОДШИТА ВРАЗБРОС, И ПОРЯДОК ЛИСТОВ НЕ СОВПАДАЕТ С ПОРЯДКОМ
# ЗАПИСЕЙ.** Читать её надо так: **л. 25об** (браки № 1–5, февраль–октябрь) →
# **л. 30об** (№ 6–11, 1 и 3 октября) → **л. 22об** (№ 12–16, октябрь–ноябрь) →
# **л. 23об** (№ 17–19, ноябрь). Внутренняя опись дела даёт эти листы тремя
# строками (22–23об, 25, 30) и ещё три листа помечает «ч.2 **б/г**» (24, 28–29об):
# это правые половины разворотов, на которых года не печатают.
#
# ⚠ **Поручители обоих кекевских браков УТРАЧЕНЫ.** Оба стоят на л. 30об, а
# правой половины этого разворота в деле нет: соседний л. 31 — печатный титул
# части первой, то есть разворот разорван переплётом. Свидетели в записи не
# заводятся — лучше пусто, чем неверно.
#
# 🆕 **04.09.2026 сверка альбомов переставила два листа и закрыла вопрос.**
# (1) **Л. 30 (recto)** лежал по ошибке в альбоме 1909 г. — это лист 1903 г. и
# он несёт поручителей браков **№ 1–5**: во втором блоке «по женихѣ Григорій
# **Артамошкинъ**, по невѣстѣ Косма **Афонинъ**» при браке № 2 Димитрия
# Потапова Артамошкина с Иулианией Петровой Афониной, в четвёртом Горячевы при
# невесте № 4 Пелагии Стефановой Горячевой. (2) ❌ **Л. 28, прежний кандидат в
# поручители № 6–11, оказался листом 1909 года** (клир «протоіерей Орловъ съ
# Покровскимъ», на обороте — браки 1909 г. № 17–21) и перенесён в альбом
# 1909 г. Свободных листов поручителей у года больше нет: № 6–11 и № 17–19
# просто отсутствуют в деле.
#
# **ДВА кекевских брака**, и оба 3 октября; Земсковых нет. Год выдаёт замуж
# **Марию Георгиевну** двора 5 и женит **Григория Андреевича** двора 7, попутно
# называя девичью фамилию его жены.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1903 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1903,
    *page("30об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ЭТО **Марья Егоровна** двора 5 переписи 1897 г. — дочь Георгия (Егора) Максимовича
                          # и Надежды Дмитриевой, сестра Евфимия Георгиевича. В переписи ей 10 лет, здесь 17,
                          # то есть род. ок. 1886–1887 гг.: сходится. Корпус знал её только восприемницей 1914
                          # г.; теперь у неё есть венчание и фамилия по мужу — **Шимарянова**. ⚠ Шимаряновы
                          # роднятся с Кекевыми не впервые: через два года, 2 октября 1905 г., Пётр Георгиев
                          # Шимарянов возьмёт Александру Иоанновну Кекеву (брак № 8, л. 271об)
                          marriage(7, 3,
                                   groom=person("Феодор", "Филиппов", last_name_orig="Шимарянов", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=18,
                                   bride=person("Мария", "Георгиева", last_name_orig="Кекева", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=17),
                          # ВЕНЧАНИЕ **Григория Андреевича** двора 7 (сын Андрея Ивановича Кикева), и оно
                          # решает два вопроса разом. Первое: у его жены наконец есть **девичья фамилия —
                          # ЗАЛЕПИНА**, до сих пор она проходила по корпусу одним именем-отчеством. Второе:
                          # отчество **Васильева ПОДТВЕРЖДЕНО** венчальной записью, и «Екатерина
                          # **Филиппова**» 1913 г. окончательно опознана как описка — против неё теперь пять
                          # записей (1903, 1904, 1906, 1909, 1911). ⚠ Возраст жениха «19 лѣтъ 2 мѣс.» даёт
                          # рождение около **августа 1884 г.**; перепись 1897 г. пишет ему 12 лет, то есть ок.
                          # 1885 г. — расхождение в год. Невеста на полтора года старше. ⚠⚠ **Фамилия невесты
                          # и «Загетнина» 1909 года — ✅ **разрешено 16.09.2026: одна фамилия, и она
                          # ЗАЛЕПИНА**; чтение двух чтениях.** Комментарий к записи 1909 г. (№ ж51, л. 199об)
                          # заметил рядом с этой семьёй «Антония Васильева» и «Наталию Васильеву
                          # **Залепиных**» — по отчеству брата и сестру жены — и предположил, что жена
                          # Григория из Залепиных. Здесь та же женщина записана **Залепиной**, и в этом же
                          # году фамилия «Залепинъ» встречается ещё трижды (лл. 28, 38, 48). Какое из двух
                          # чтений верно, не решено; DSL держит написание своей страницы. ⚠ Залепины стоят
                          # рядом с Кекевыми и в части первой: Евфимий Алексиев Залепин крестит сына Андрея
                          # Иоанновича (запись о рождении № м42, л. 48)
                          marriage(11, 3,
                                   groom=person("Григорий", "Андреев", last_name_orig="Кекев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age="19 лет 2 мес",
                                   bride=person("Екатерина", "Васильева", last_name_orig="Залепина", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=21),
                          ),
          ),
    defaults=DEFAULTS,
)
