# Метрическая книга Покровской церкви с. Димитріевы Горы за 1833 г., часть вторая
# «О бракосочетавшихся». **ГАВО ф. 556 оп. 106 д. 557, лл. 94–96** (кадры альбома 13–15).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 13 венчаний** — и это **единственная часть 1833 года,
# которая сошлась с итоговой ведомостью** («бракосочетавшихся лицъ 26, случаевъ 13»,
# л. 101). Части первая и третья с той же ведомостью НЕ сходятся (см. `..._births_1833.py`).
# **ТРИ записи из 13** ниже.
#
# ⓘ Год скупой на свадьбы: 13 против 22–29 в 1834–1839 гг. Помесячно: генварь 2, февраль 0,
# апрѣль 2, май 1, октябрь 7, ноябрь 1. Венчальный день — **2 октября** (шесть браков).
# Форма как в 1834–1837 гг.: возрастов нет, назван отец невесты, поручители читаются.
#
# 🆕 **«По отцу крестному» работает и для ЖЕНИХА.** № 4 (9 апрѣля): «крестьянской дѣвки
# Ирины Лаврентьевой незаконнорожденный сынъ **Игнатій, по отцу крестному Власовъ**,
# холостой». ⇒ правило прихода, найденное в 1836 г. на младенцах, действует и когда
# незаконнорожденный вырастает и женится: отчество ему так и остаётся по восприемнику.
#
# Имена сверены кропом при 2.1× в сером.
# Вычитано в Verso 06.10.2026.

