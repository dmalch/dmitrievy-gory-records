# ⚠⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 82–101**, приходъ
# **№ 49**. Титул на л. 82: «Подана Генваря 10-го дня 1834 года. Книга, данная изъ
# Муромскаго Духовнаго Правленія… въ церковь **Покрова Пресвятыя Богородицы** причту…
# на 1833 годъ. **Часть первая о раждающихся**» — и первые записи на том же листе, как
# в 1834, 1836 и 1837 гг. Форма та же.
#
# ✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ.** Последние номера части первой — **41 м / 33 ж = 74 записи**.
# ⚠⚠ **НО ИТОГОВАЯ ВЕДОМОСТЬ (л. 101) ДАЁТ 37 м / 32 ж = 69 — И ОНА ПРОТИВОРЕЧИТ САМА
# СЕБЕ.** По части третьей то же: последний номер 42 м, а ведомость пишет «умершихъ
# мужеска 40» — при том, что **её собственная возрастная разбивка тут же даёт «итого 42»**.
# ⇒ **в 1833 г. ведомость как проверка НЕ РАБОТАЕТ.** В 1834, 1836 и 1837 гг. она сходилась
# с чтением до единицы; здесь причт считал небрежно. Года по ней не проверять — и, что
# важнее, **не подгонять чтение под её цифры**.
#
# ⓘ Причт тот же: священники **Тихонъ** и **Михаилъ Экземплярскіе**, діаконъ **Яковъ
# Звѣревъ**, дьячекъ **Василій Горскій**, пономарь **Михаилъ Егоровъ**. Ведомость
# добавляет: «незаконнорожденныхъ 4 м / 1 ж, изъ нихъ умерло 2», «изъ Дворянской фамиліи
# не имѣется», «раскольниковъ нѣтъ», «въ семъ 1833-мъ году ненатуральною смертію умершихъ
# никого не имѣлось».
#
# 🆕 **В приходе стоят войска.** Воспріемниками идут «**Казанскаго пѣхотнаго полка** 3-й
# мушкатерской роты фельдфебель Мардарій Барановъ», «**Казанскаго егерскаго полка** 8-й
# роты рядовой Емельянъ Уваровъ», «**Московскаго пѣхотнаго полка** 4-го баталіона 4-й
# гранадерской роты рядовой Панфилъ Гавриловъ»; в ч. 3 хоронят сына рядового
# **Меленковской инвалидной команды**. Ни в одном другом прочитанном году такого нет.
#
