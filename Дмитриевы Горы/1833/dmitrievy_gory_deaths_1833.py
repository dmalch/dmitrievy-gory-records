from corpus.statuses import SHEPELEV_PEASANT, SHEPELEV_PEASANT_FEMALE, SHEPELEV_PEASANT_WIFE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import CONSUMPTION, DIARRHEA, PLEURISY
from verso.ru.dsl.statuses import ECON_PEASANT_MALE, ECON_PEASANT_SON

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1833 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 557, лл. 96об–100об** (кадры альбома 16–20).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ.** Последние номера — **42 м / 36 ж = 78 погребений**.
# ⚠⚠ **Итоговая ведомость (л. 101) пишет «умершихъ мужеска 40, женска 36, обоего пола 76»
# — и тут же противоречит себе**: её собственная возрастная разбивка умерших мужеска пола
# («ниже году 18 · 1 году 7 · 2 — 3 · 3 — 1 · 6 — 2 · 12 · 17 · 28 · 41 · 50 · 51 · 57 ·
# 63 · 70 · 73») даёт **«итого 42»**. ⇒ **ведомость 1833 года как проверка НЕ РАБОТАЕТ.**
# В 1834, 1836 и 1837 гг. она сходилась с чтением до единицы; здесь причт считал небрежно.
# **ТРИ записи из 78** ниже.
#
# 🩺 Год тяжёлый для младенцев: «ниже году» — 18 из 42 мужских, и почти все «отъ поноса»
# в маѣ–августѣ. Взрослые уходят «отъ чахотки» и «отъ горячки»; старше семидесяти — двое.
# Ведомость подписывает: «въ семъ 1833-мъ году ненатуральною смертію умершихъ никого не
# имѣлось» — та же формула, что в 1834 г., и здесь она чтению не противоречит.
#
# 🔴 **Погребений рода в году нет.** Ни братьев Ѳедоровыхъ, ни их жён и детей: сын Игната
# **Ѳеодоръ**, родившийся 1 іюня (ч. 1 № 17 м), год пережил и доживёт до 1909-го.
#
# ⚠ Дат погребения эта форма не пишет: одна дата на запись, и это **дата смерти**.
#
# Имена сверены кропом при 2.1× в сером.
# Вычитано в Verso 06.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1833 = death_records(
    "ГАВО", "556", "106", "557", "Дмитриевы Горы", "Покровская",
    1833,
    *page("96об",
          *death_month(Month.JANUARY,
                       # 🔗 **ПЕРВАЯ ЗАПИСЬ ЧАСТИ — И ПЕРВОЕ ЗВЕНО ТРЁХЗАПИСНОЙ ДУГИ ВНУТРИ ОДНОГО ГОДА.**
                       # «Села Димитріевыхъ горъ вотчины Г. Г. Шепелевыхъ крестьянина **Конона Васильева**
                       # жена **Лукерья Андреева**, 55, отъ чахотки». 2 октября Кононъ венчается вторымъ
                       # бракомъ на **Ксеніи Тимоѳеевой** (ч. 2 № 9 — там же поручителем стоит **Флоръ
                       # Антоновъ**), а 24 ноября новая жена рожает сына **Егора**, которого писец записывает
                       # **незаконнорожденнымъ**, потому что зачат он до венчания (ч. 1 № 34 м). ⇒ вдовство,
                       # новый брак и добрачное дитя — **три записи одной семьи в одной книге**, и приход не
                       # смягчает формулировок
                       death(1, Gender.FEMALE, 4,
                             deceased=person("Лукерья", "Андреева", status=SHEPELEV_PEASANT_WIFE),
                             age=53,
                             relatives=[relative(person("Кононъ", "Васильевъ"), Relationship.HUSBAND)],
                             cause_of_death=CONSUMPTION),
                       ),
          ),
    *page("98",
          *death_month(Month.MAY,
                       # 🆕 **КОНЕЦ ЕДИНСТВЕННОЙ ЗА ПРОХОД ИСТОРИИ ПОДКИДЫША.** «Экономическаго вѣдомства
                       # деревни Кононовой крестьянина **Ивана Григорьева подкинутый младенецъ Яковъ**, отъ
                       # колотья». 24 апрѣля этот младенец «**найденъ подкинутый**» у того же двора и наречён
                       # при крещении Яковомъ (ч. 1 № 11 м); через месяц с небольшим его хоронят. ⇒ **вся его
                       # жизнь и весь его след в мире — две строки одной книги**, без имени родителей и без
                       # возраста. ⓘ Иванъ Григорьевъ записан здесь `FOSTER_FATHER`: источник называет его
                       # дворовладельцем, у которого ребёнка нашли, а не отцом
                       death(17, Gender.MALE, 26,
                             deceased=person("Яковъ", status=ECON_PEASANT_SON),
                             age="1 мес",
                             relatives=[relative(person("Иванъ", "Григорьевъ", residence="Кононово", status=ECON_PEASANT_MALE), Relationship.FOSTER_FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("99",
          *death_month(Month.JULY,
                       # 🔗 **СЕМЬЯ, КОТОРУЮ КОРПУС ТЕПЕРЬ ВИДИТ ЧЕТЫРЕ ГОДА ПОДРЯД, И ТРЕТИЙ ЕЁ МЛАДЕНЕЦ В
                       # МОГИЛЕ.** «**Степана Кузьмина** сынъ, младенецъ **Яковъ**, трехъ мѣсяцевъ, отъ
                       # поноса». Родился 28 апрѣля того же года (ч. 1 № 12 м) — ровно три месяца без девяти
                       # дней. Со Стефанидой… то есть с **Екатериной Спиридоновой** у него за девять лет
                       # пятеро известных детей: Яковъ (1833, † 1833), **Онисимъ** (1837, † 1837),
                       # **Настасья** (1839), **Тимоѳей** († 1839 «9½ мѣс») и **Андрей** (1842). ⇒ трое из
                       # пяти не пережили первого года — и это ровно та доля, какую даёт ведомость года («ниже
                       # году 18» из 42)
                       death(30, Gender.MALE, 19,
                             deceased=person("Яковъ"),
                             age="3 месяца",
                             relatives=[relative(person("Степанъ", "Кузминъ", status=SHEPELEV_PEASANT), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    defaults=DEFAULTS,
)
