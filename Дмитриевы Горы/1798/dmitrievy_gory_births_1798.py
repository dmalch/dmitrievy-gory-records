from corpus.statuses import BATASHEV_PEASANT, BATASHEV_PEASANT_FEMALE
from verso.ru.dsl import (Gender, Month, RecordDefaults, birth, birth_month, birth_records, page,
                          person)

# Метрическая тетрадь Покровской церкви с. Димитріевы Горы за 1798 г., часть первая
# «О родившихся». **ГАВО ф. 556 оп. 106 д. 145, лл. 61–61об** (кадры 0075–0076).
#
# ⚠⚠ **КРАТКИЙ РЕЕСТР, а не метрическая книга** — одна строка на запись, **матери не
# названы**, воспріемникъ **только один**. То же в 1799 и 1802 гг.
# ⚠ **Два прихода в одном дѣлѣ:** лл. 61–62об — **1798 год** нашего прихода,
# лл. 222об–224об — **1799-й** (см. `1799/`). Тетрадь **№ 13**.
#
# **Состав:** л. 61 — титул и тут же ч. 1; ч. 1 — лл. 61–61об (**50 записей**);
# ч. 2 — л. 62 (**9 венчаній**); ч. 3 — л. 62 (**8 м / 6 ж = 14**); **табель — л. 62об**.
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ТАБЕЛЬ (л. 62об) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** —
# **двадцать девятый такой год подряд**. «Крестьяне: родившихся мужеска **36**, женска
# **14**, обоего **50**; браковавшихся лицъ **18**, супружествъ **9**; умершихъ мужеска
# **8**, женска **6**, обоего **14**». Возрастная разбивка (40, 45, 48, 55, 60, 67 — по
# одному, 70 — двое) даёт 8 и сошлась построчно.
# ⚠ Перекос рождений (36 мальчиков против 14 девочек) — обратный 1806 году и такой же
# резкий; в кратком реестре пол виден только по слову «сынъ/дочь», и списывать это на
# чтение нельзя: так считает сам табель.
#
# 🔴 **ВАСИЛІЙ ХАРИТОНОВЪ КУМОМЪ ТРИЖДЫ ЗА ГОД**: № 22 (25/27 іюня, у **Тимоѳея
# Ѳедорова** сынъ Иванъ), № 30 (6/8 сентября, у **Семена Ефримова** сынъ Гавріилъ — ниже)
# и № 45 (7/10 декабря, у **Игната Иванова** сынъ Антонъ).
#
# 🚫🚫 **И ГЛАВНЫЙ ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ: ИГНАТЪ ѲЕДОРОВЪ В 1798 ГОДУ НЕ РОЖДАЛСЯ.**
# Ревизия 1816 г. даёт ему 18 лѣтъ ⇒ род. ок. 1798, но среди пятидесяти записей года
# **нет ни одного ребёнка Ѳедора Харитонова**. То же в 1799 (35 записей) и 1802 (61).
# ⇒ трое братьев родились в **1797, 1800 и 1801 гг.** — из них оцифрован только 1797-й
# (д. 132, «1796-1797»). 📍 Это следующая цель прохода.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
# Первое чтение: имена сверены кропом при 2.2× постранично, входящие сюда — при 7×.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=BATASHEV_PEASANT,
                          status_female=BATASHEV_PEASANT_FEMALE)

dmitrievy_gory_births_1798 = birth_records(
    "ГАВО", "556", "106", "145", "Дмитриевы Горы", "Покровская",
    1798,
    *page("61об",
          *birth_month(Month.SEPTEMBER,
                       # 🔴🔴 **ПЯТЫЙ РАЗ У ОДНОГО И ТОГО ЖЕ ДВОРА — И ЭТО САМЫЙ ДЛИННЫЙ УЗОР КУМОВСТВА ЗА ВЕСЬ
                       # ПРОХОД.** «Тогожъ села **Семена Ефримова** сынъ **Гавріилъ**, былъ воспріемникъ
                       # **Василей Харитоновъ**» (сверено при 7×). 🔗 **Василій Харитоновъ крестит детей Семена
                       # Ефимова пять раз за одиннадцать лет**: 1798 (Гавріилъ, здесь), **1802** (Макаръ, 1802
                       # ч. 1 № 23), **1803** (Параскева, 1803 ч. 1 ж. № 32), **1806** (Иванъ, 1806 ч. 1 м. №
                       # 33) и **1809** (Гавріилъ, 1809 ч. 1 № 28). ⇒ и с 1803 года полные книги называют жену
                       # Семена — **Евдокія Харитонова** ⇒ **он крестит у сестры**, а «Семенъ Ефимовъ» в 1803
                       # и 1806 гг. назван **земскимъ**, выборным начальником села. ⚠ **Здесь имени жены
                       # нет**: краткий реестр 1798 года матерей не пишет. Родство выводится из полных книг
                       # 1803–1809 гг., а не из этой записи. ⓘ Тот же Василій кумуетъ в 1798 году ещё дважды —
                       # у **Тимоѳея Ѳедорова** (№ 22) и у **Игната Иванова** (№ 45)
                       birth(30, Gender.MALE, 6, 8,
                             child=person("Вавилъ"),
                             father=person("Семенъ", "Ефимовъ"),
                             god_parent1=person("Василей", "Харитоновъ")),
                       ),
          ),
    defaults=DEFAULTS,
)
