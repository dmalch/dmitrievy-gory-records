from verso.ru.dsl import (Month, RecordDefaults, Side, marriage, marriage_month, marriage_records,
                          page, person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, SOLDIER_SON

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1900 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**, титул —
# **л. 18**, записи на лл. **18об–19об и 21**, а продолжение — на лл.
# **107–109об и 111–111об**, в девяноста листах оттуда. **34 брака**, из них
# тридцать 2 октября.
#
# ⚠ **Части второй в описи отведены только лл. 19–19об** — она не знает ни
# титула на л. 18, ни записей л. 18об, ни поручителей л. 21. Состав проверен
# по листам.
#
# ⚠ **Лист 21 — поручители октябрьских браков л. 19об**, хотя между ними
# подшит л. 20 (конец части первой). А у **л. 111 стороны переставлены**
# относительно остальных листов части: запись (ноябрьский брак № 34) стоит на
# recto, поручители браков № 30–33 — на verso. Между л. 109об и л. 111об
# вклинены лл. 110–110об — титул и январь части третьей **1909 года**.
#
# **ОДИН кекевский брак** — № 26, и он венчает человека, известного по
# переписи 1897 г. Земсковых среди женихов и невест нет; «Григорій Земсковъ»
# стоит поручителем по невесте в браке № 5 (л. 21) — единственная земсковская
# строка части второй.
#
# ⚠ Кузины в части второй есть и снова не наши: Васильевичи.
#
# Вычитано владельцем на пилоте 13.11.2026: № 26.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1900 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1900,
    *page("108об",
          *marriage_month(Month.OCTOBER,
                          # ⚠⚠ **ВЕНЧАНИЕ ЧЕЛОВЕКА ИЗ ПЕРЕПИСИ, и возраст сходится в год.** Двор 5 (Кикев Максим
                          # Антонов) держит внука **Андрея Дмитриева**, 15 лет в 1897 г., живущего с отцом
                          # Дмитрием Максимовичем в Ардатовском уезде; жениху здесь 19 ⇒ род. около 1881 г. — то
                          # же лицо. Значит Андрей вернулся в село венчаться. Корпус знал его с 1902 г.
                          # («поступившій въ военную службу»); теперь у семьи есть начало — **2 октября 1900
                          # г.**, и жена: **Елена Иродіонова МАСЛИХИНА**, девичья фамилия, до сих пор
                          # неизвестная. ✅ **Поручитель по жениху — Георгій Максимовъ Кекевъ**, то есть Егор
                          # Максимович, № 4 того же двора 5 и РОДНОЙ ДЯДЯ жениха (брат его отца Дмитрия). В тот
                          # же год он крестит собственного сына Илию (часть первая, № м30). Это делает привязку
                          # Димитриевичей к двору 5 не догадкой по отчеству, а сцепкой двух записей одного года.
                          # ⚠ Жених — «солдатскій сынъ», то есть отец его Дмитрий Максимович отслужил; перепись
                          # 1897 г. зовёт того «сторожем частного леса». ⚠⚠ **Отчество невесты — Иродіонова, и
                          # это вторая Иродионова за два года**: в 1901 г. так названа жена Гавриила Иоаннова
                          # Залетина (№ м42; до вычитки 16.11.2026 он читался «Земсков», а «Иродионовой» читали
                          # и жену Георгия Иоаннова Кекева в № м54 — там «Александра Іоаннова»). Теперь видно,
                          # что Иродионы в селе — Маслихины (её отец — Иродіонъ Филипповъ Маслихинъ, метрика
                          # 1882 г.), и «Иродіонова» не редкость. Поручители: по жениху Георгій Максимовъ Кекевъ
                          # и Григорій Антоніевъ Артамошкинъ, по невесте Гавріилъ Іоанновъ Залетинъ и Григорій
                          # Никитинъ Юкачевъ. ✅ Вычитано владельцем 13.11.2026; до вычитки читались
                          # «Мазилихина», «Меркурий … Артамонщиков», «Гавриил Максимов Заплатин» и «Григорий
                          # Аникичев»
                          marriage(26, 2,
                                   groom=person("Андрей", "Дмитріевъ", last_name_orig="Кекевъ", status=SOLDIER_SON),
                                   groom_marriage_num=1, groom_age=19,
                                   bride=person("Елена", "Иродіонова", last_name_orig="Маслихина", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age="18 лет 6 мес",
                                   witness1=person("Георгій", "Максимовъ", last_name_orig="Кекевъ", side=Side.GROOM),
                                   witness2=person("Григорій", "Антоніевъ", last_name_orig="Артамошкинъ", side=Side.GROOM),
                                   witness3=person("Гавріилъ", "Іоанновъ", last_name_orig="Залетинъ", side=Side.BRIDE),
                                   witness4=person("Григорій", "Никитинъ", last_name_orig="Юкачевъ", side=Side.BRIDE)),
                          ),
          ),
    defaults=DEFAULTS,
)
