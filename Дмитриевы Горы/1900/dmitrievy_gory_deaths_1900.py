from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DIARRHEA, PLEURISY
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, SOLDIER

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1900 г.,
# часть третья «О умерших». ГАВО ф.590 оп.12 д.**198**, лл. 112–113об
# **и 125–129об** (титул — л. 112).
#
# ⚠⚠ **Часть третья 1900 г. разорвана надвое, и между половинами лежит чужой
# год.** Лл. 112–113об дают январь — апрель, а продолжение — на л. 125об и
# далее; лл. **114–124об, вклинившиеся между ними, — это часть третья
# 1909 года** (найдена 03.09.2026, кадры перенесены в альбом 1909 г.).
#
# ✅ **Отсюда решается и старая загадка 1909 года.** У его части третьей
# считался пропуск «лл. 111–113 в альбоме нет» — конец февраля и март. На деле
# эти листы в деле ЕСТЬ и все три заняты 1900 годом (л. 111 — часть вторая,
# лл. 112–113об — часть третья), а их нет только в альбоме 1909 г. Значит у
# 1909 г. не «не найдены листы», а **лакуна в самом деле**: его часть третья
# подшита как 110–110об + 114–124об, и записей за конец февраля — март 1909 г.
# в деле нет вовсе.
#
# ⚠ Разворот [**л. 113об | л. 125**] — то есть графа «отъ чего умеръ» для
# записей марта — апреля стоит через одиннадцать листов. Соответствие
# **ВЫВЕРЕНО**: строка месячного итога («Итого въ Мартѣ…») стоит на обеих
# страницах на одной и той же высоте, а по краям прогона держат два якоря —
# «отъ чахотки» против 42-летней женщины и «отъ старости» против 78-летней
# вдовы. Поэтому причина смерти в запись заводится.
#
# **ОДНО кекевское погребение** — младенческое, и это самый пустой по нашему
# роду год из прочитанных (в 1901 г. было десять). Земсковых и Кузиных
# (двора 6) в части третьей нет: «Іоанна Ва[сильева] Кузина сынъ Пётръ,
# 7 мѣс.» (л. 126об) — снова Васильевичи Кузины, отдельная семья.
#
# ⚠ В ноябре запись «умершихъ не было» (л. 127об) — месяц без похорон.
#
# Вычитано владельцем на пилоте 13.11.2026: № ж9 и № м22.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1900 = death_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1900,
    *page("113об",
          *death_month(Month.MARCH,
                       # **Дочь Михаила Феодоровича** — та, что род. 6.03.1899 (1899 ч. 1 № ж10; сведены 13.11.2026).
                       # Когда год читался впервые, 1899 ещё не был прочитан: года от роду ⇒ род. около начала 1899 г. До сих пор самой
                       # ранней его записью было рождение сына Александра 11 марта 1901 г. (тот прожил три
                       # месяца), теперь у пары есть ребёнок и до него — и тоже умерший. ⚠⚠ **Звание отца —
                       # «запасный солдатъ», и оно смыкает метрику с переписью**: двор 4 (Земсков Фёдор
                       # Игнатьев) держит сына **Михаила**, 35 лет, «грамотный (в военной службе)», при жене
                       # **Марье Савельевой**, 35 лет, — а метрика 1901 и 1906 гг. зовёт жену Михаила
                       # Феодоровича **Марией Саввиной**. Отчество, звание, возраст и жена сходятся; вместе с
                       # «Алексіемъ Ѳеодоровымъ Кекевымъ тоже Земсковымъ» части первой (№ м53) это второй
                       # довод, что Феодоровы Кекевы и есть Земсковы двора 4. Дочерей у Михаила перепись знает
                       # двух — Орину (3 г.) и Татьяну (1 г.); Матрона — третья, рождённая уже после переписи.
                       # ⚠ Похоронена **31 марта — на следующий день после того, как крестили Марию, дочь
                       # Николая Феодоровича** (часть первая, № ж20). ⚠ Умерла **от плеврита** (вычитка владельца
                       # 13.11.2026; прежде читалось «от коклюша» — и сюда относили вспышку коклюша, что в эти же
                       # дни забирает ещё трёх младенцев прихода, л. 113об, апрель; Матрона в неё не входит) ⚠ **Первенство
                       # снято 05.09.2026**: Михаил Федорович Кекев назван раньше — рождение 1893 № 10,
                       # 1893-04-08.
                       # ✅ Вычитано владельцем 13.11.2026: отец — «запасный солдатъ Михаилъ Ѳеодоровъ Кекевъ»
                       death(9, Gender.FEMALE, 30, 31,
                             deceased=person("Матрона"), age=1,
                             relatives=[relative(person("Михаилъ", "Ѳеодоровъ", last_name_orig="Кекевъ", status=SOLDIER, comment="запасный солдат"), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    # Вторая волна (08.11.2026): дети замужних дочерей Кекевых, найденные по имени мужа.
    *page("127об",
          *death_month(Month.AUGUST,
                       # Андрей — сын Алексея Наумовича Иванова и Елены Игнатьевны Кекевой, род. 1.07.1899 (1899 ч. 1, № м41)
                       # ✅ Вычитано владельцем 13.11.2026: причина — «отъ поноса»; сведён со своим рождением (1899 № м41)
                       death(22, Gender.MALE, 17, 18,
                             deceased=person("Андрей"), age=1,
                             relatives=[relative(person("Алексій", "Наумовъ", last_name_orig="Ивановъ"), Relationship.FATHER)],
                             cause_of_death=DIARRHEA),
                       ),
          ),
    defaults=DEFAULTS,
)
