from verso.ru.dsl import (CensusRole, Month, RecordDefaults, census_records, household, member,
                          person)
from verso.ru.dsl.statuses import SOLDIER_DAUGHTER, SOLDIER_SON

# Ревизские сказки 10-й ревизии 1858 г. по **нижним воинским чинам** с. Дмитриевы Горы.
# **ГАВО ф. 301 оп. 5 д. 796** (лл. 499–553); тот же материал лежит вторым экземпляром
# в **д. 795** (лл. 648–722) — см. ниже.
#
# ⚠⚠ **ЭТО НЕ ОДНА СКАЗКА НА СЕЛО, А 26 ОДНОДВОРНЫХ.** У каждой солдатской семьи своя
# сказка: лист «Мужескій полъ» (оборот) и «Женскій полъ» (следующий recto), своя дата
# подачи и свой «№ семьи 9/10 ревизіи» — почти всегда **«1»**, потому что семья в сказке
# одна. ⇒ **номера дворов здесь редакционные** (1, 2 — по порядку листов), как и у
# переписи 1897 г. по двум делам; номер источника указан в comment= каждого двора.
# С л. 533об мужская сторона пуста: те семьи состоят из одной солдатки с дочерьми.
# Есть вставной лист **525а**.
#
# ⚠⚠ **Д. 795 И Д. 796 — ОДИН МАТЕРИАЛ В ДВУХ ЭКЗЕМПЛЯРАХ**, а не два дела: те же 26
# семей, те же возрасты (сверено построчно на «Филиппъ Ивановъ Кузьминъ, 13» и «Иванъ
# Леонтьевъ, 5»). Различаются номер и дата подачи — 796 «№ 477, подана 29 апрѣля 1858»,
# 795 «№ 418, подана 22 апрѣля 1858». Читан д. 796; д. 795 сверен выборочно.
#
# ⚠ Титул л. 499 читается «Владимірской губерніи Меленковскаго Уѣзда **села Дмитріевыхъ
# Горъ**» (село подчёркнуто писцом) — прежняя пометка холдингов «город Меленки, НЕ село»
# **снята**.
#
# 🔴 **ЗАВЕДЕНЫ ТОЛЬКО ДВА ДВОРА ИЗ ДВАДЦАТИ ШЕСТИ** — те, что дают мать корпусному
# человеку. Рода (Ѳокиныхъ, Порфирьевыхъ, Кекевыхъ, Земсковыхъ, Акиллиныхъ) в сказках
# **нет вовсе**, и это закономерность: они числят семьи, чьи мужчины к 1858 г. уже были
# в военном ведомстве, а солдаты рода взяты в рекруты позже и в 1858 г. стоят крестьянами
# в основной сказке 301-5-784. Полный состав 26 семей и разбор — в `ARCHIVES.md`
# § «нижние воинские чины».
#
# 🎯 **ОТЧЕСТВО НЕЗАКОННОРОЖДЕННОГО — ПО КРЁСТНОМУ ОТЦУ, И СКАЗКА ПИШЕТ ЭТО ФОРМУЛОЙ**:
# «сынъ Ксенофонтъ, **по крестному отцу Ксенофонтовъ**», и так же «Самойловъ»,
# «Макаровъ», «Емельяновъ», «Дмитріевъ»; у дочерей — «Яковлева», «Максимова», «Иванова».
# ⇒ такое отчество указывает на **кума, а не на отца**, и родство по нему строить нельзя.
# Комментарий к МК 1873 (ч. 2 № 12) выводил это из одного случая — теперь это цитата.
#
# reviewed=True на обоих дворах: имена и возрасты сверены при 3.4–8×, и оба сходятся с
# метрическими книгами (см. комментарии). Вычитка в Verso 12.10.2026 поправила три первых
# чтения: Варваре Родіоновой — «22» (первое чтение колебалось между «22» и «42»), Прасковья
# Игнатьева — «4 мѣсяцевъ», а не «Умерла въ 18..», мать двора 2 — Екатерина **Игнатьева**, а
# не «Никитьева». Все три сверены по скану.

SOLDIER_WIFE_F = "солдатка"

census = census_records(
    "ГАВО", "301", "5", "796", "Дмитриевы Горы", 1858,

    # Л. 524об (мужескій полъ) — 525 (женскій полъ). Источник: «№ семьи 10 ревизіи — 1».
    # Однодворная сказка, подана 29 апрѣля 1858 г. (№ 477).
    household("1",
              # «Солдатка **Варвара Родіонова**» — **22** (сверено при 3.4×) ⇒ род. ок. **1836 г.** Первое
              # чтение не решало между «22» и «42» и оставляло графу пустой; вычитка 12.10.2026 прочла «22»,
              # и сын четырёх лет и дочь четырёх месяцев с ним сходятся. ⇒ Второй экземпляр (д. 795,
              # л. 715об–716) всё ещё годится для сверки этой цифры. ⓘ Муж не назван нигде в сказке; по
              # отчеству детей он был солдатомъ по имени **Игнатій**
              member(1, person("Варвара", "Родіонова"), CensusRole.HEAD, age=22),
              # 🎯 **ЭТО КОРПУСНЫЙ ЧЕЛОВѢКЪ, И ЗДЕСЬ ОН ПОЛУЧАЕТ МАТЬ.** «Солдатки Варвары Родіоновой
              # **законный сынъ Максимъ Игнатьевъ**» — 4 (сверено при 3.6×) ⇒ род. ок. **1854 г.** 🔗 МК
              # **1871** ч. 2 № 6 венчает «крестьянскаго сына Максима Игнатьева, 18 л. 11 мѣс.» с **Мариной
              # Абрамовой** 3 октября 1871 г. ⇒ род. ок. ноября 1852 г.; расхождение полтора года — для
              # ревизского возраста обычное, и оба чтения независимы. 🔗 Он же **воспріемникъ у Ѳеодосьи
              # Ѳокиной** 20 ноября 1871 г. (МК 1871 ч. 1 № м73) и отец в августе 1871 г. (дочь Васса). ⓘ
              # «Законный», а не «незаконнорожденный» ⇒ мать была замужем за солдатомъ, и отчество —
              # настоящее, отцовское
              member(2, person("Максимъ", "Игнатьевъ", status=SOLDIER_SON), CensusRole.SON, age=4),
              # «Ея законная дочь **Прасковья Игнатьева**» — **4 мѣсяцевъ** ⇒ род. ок. **декабря 1857 г.**,
              # сестра Максима Игнатьева. Первое чтение приняло возраст в графе «Лѣта» за «Умерла въ 18..» и
              # числило её выбывшей; вычитка 12.10.2026 прочла «4 мѣсяцевъ», скан это подтверждает
              member(3, person("Прасковья", "Игнатьева", status=SOLDIER_DAUGHTER), CensusRole.DAUGHTER,
                     age="4 мес"),
              page="524об-525", reviewed=True,
              comment="Номер двора редакционный: источник нумерует единственную семью сказки «1»"),

    # Л. 525а об (мужескій полъ) — 526 (женскій полъ). Однодворная сказка на вставном листѣ 525а.
    household("2",
              # «Солдатка **Екатерина Игнатьева**» — **28** (сверено при 3.4×; цифры «2» и «8» различимы) ⇒
              # род. ок. **1830 г.** Сына родила около двадцати трёх лет. Первое чтение — «Никитьева»;
              # вычитка 12.10.2026 прочла «Игнатьева», и обе страницы пишут так («Игнатьевой» на мужской,
              # «Игнатьевы» на женской: прописная И без перекладины, за ней «г» с хвостом). ⓘ Муж не назван;
              # сын записан незаконнорожденным, то есть отца сказка не знает вовсе
              member(1, person("Екатерина", "Игнатьева"), CensusRole.HEAD, age=28),
              # 🎯🎯 **ЭТО ОН — И ЗАПИСЬ ОБЪЯСНЯЕТ ЕГО ОТЧЕСТВО ПО САМОМУ СЕБѢ.** «Солдатки Екатерины Игнатьевой
              # **незаконнорожденный сынъ Ксенофонтъ, по крестному отцу Ксенофонтовъ**» — **5** (сверено при
              # 4×) ⇒ род. ок. **1853 г.** 🔗 МК **1873** ч. 2 № 12 венчает «того же села **солдатскій
              # незаконнорожденный сынъ Ксенофонтъ Ксенофонтовъ**, 19 л. 8 мѣс., первымъ бракомъ» с **Домникой
              # Тимофѣевой** 3 октября 1873 г. ⇒ род. ок. февраля 1854 г. — сходится с ревизией в пределах
              # года. 🔗 21 декабря **1874** г. у них родится дочь **Евгенія**, и воспріемникомъ станет
              # **Василій Ѳлоровъ** (МК 1874 ч. 1 № ж67). 🎯 **Комментарий к тому венчанию выводил правило из
              # одного случая** («имя крёстного становится и отчеством»). Здесь источник пишет его формулой, и
              # не только у него: в тех же сказках «по крестному отцу Самойловъ», «Макаровъ», «Емельяновъ»,
              # «Дмитріевъ», а у дочерей «Яковлева», «Максимова», «Иванова». ⇒ **отчество указывает на кума, а
              # не на отца**, и родство по нему строить нельзя. ⚠ Отца не называет ни ревизия, ни метрика
              member(2, person("Ксенофонтъ", "Ксенофонтовъ", comment="незаконнорожденный, отчество по крестному отцу"), CensusRole.SON, age=5),
              page="525аоб", reviewed=True,
              comment="Номер двора редакционный: источник нумерует единственную семью сказки «1»"),

    record_day=29, record_month=Month.APRIL,
    archive_suffix="301-5-796", suffix_in_res_names=True,
    prev_revision_year=1850,
    reviewed=False,
    defaults=RecordDefaults(residence="Дмитриевы Горы", status_female=SOLDIER_WIFE_F),
)
