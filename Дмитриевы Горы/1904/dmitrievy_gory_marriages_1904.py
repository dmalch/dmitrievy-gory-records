from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import (PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON,
                                   PEASANT_WIDOW)

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1904 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**198**,
# лл. 237–241об (титул — л. 237, записи — на лл. 237об–241об). 24 брака,
# из них шестнадцать 3 октября.
#
# **ЧЕТЫРЕ кекевских брака** — рекорд прохода (в 1905 г. было три); Земсковых
# нет. Год ставит в книгу троих людей, которых корпус знал только по отчествам
# чужих записей или не знал вовсе: **Игнатия Феодоровича** (деда Игнатиевичей),
# **Петра Алексиевича** (двор 3, до сих пор без единой записи) и вдову
# **Наталию Евфимиеву**.
#
# ⚠ **Поручители в этом году НЕ расписаны по строкам.** Столбец прочитан, но
# соответствие строк recto записям verso не выверено, поэтому свидетели в
# записи не заводятся — лучше пусто, чем неверно.
#
# reviewed=False: read once from the scans, not yet checked back against them.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_marriages_1904 = marriage_records(
    "ГАВО", "590", "12", "198", "Дмитриевы Горы", "Покровская",
    1904,
    *page("237об", reviewed=False,
          *marriage_month(Month.APRIL,
                          # НОВОЕ лицо — **Наталия Евфимиева Кекева**, крестьянская вдова 35 лет (род. ок.
                          # 1869 г.), выходящая вторым браком. «Кекева» у вдовы — по покойному мужу. ✅
                          # **РАЗБОР 1903 ГОДА НАЗВАЛ ЕГО: Андрей Иоаннов Кекев**, погребённый 7 марта 1904 г.
                          # сорока одного года (запись о смерти № м9, л. 243об) — она венчается через пять
                          # недель после его похорон. В апреле 1903 г. эта пара крестила дочь Александру
                          # (запись о рождении № ж18, л. 34об), и это единственное место, где жена Андрея
                          # Иоанновича названа по имени. ⚠ Жених **Алексий Николаев ПРОШИН** — не Кекев, но
                          # имя-отчество у него то же, что у Алексия Николаевича Кекева, и это прямо бьёт по
                          # открытому вопросу 1907 года: «крестьянина Алексія Николаева дочь Анна», умершая 20
                          # августа 1907 г. без фамилии (л. 376об), может быть дочерью любого из двоих
                          marriage(6, 12,
                                   groom=person("Алексий", "Николаев", last_name_orig="Прошин", status="вдовый крестьянин"),
                                   groom_marriage_num=2, groom_age=42,
                                   bride=person("Наталия", "Евфимиева", last_name_orig="Кекева", status=PEASANT_WIDOW),
                                   bride_marriage_num=2, bride_age=35),
                          ),
          ),
    *page("239об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # ПЕРВЫЙ БРАК Алексия Николаевича, и он замыкает цепочку, которую проход собирал три
                          # года: венчание 3 октября 1904 г. → дочь Анна 5 ноября 1905 г. при жене **Матроне
                          # Симеоновой** (л. 265об) → вдовство и второй брак 3 октября 1908 г. (л. 405об).
                          # Невеста здесь названа полностью — Матрона Симеонова, — и это подтверждает чтение
                          # 1905 года. Возраст жениха «18 и 7 мѣсяцевъ» даёт рождение около марта 1886 г.; в
                          # 1908 г. ему записано 23, что сходится с точностью до полугода. ⚠ Графа лет невесты
                          # не заполнена
                          marriage(12, 3,
                                   groom=person("Алексий", "Николаев", last_name_orig="Кекев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age="18 лет 7 мес",
                                   bride=person("Матрона", "Симеонова", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1),
                          # ПЕРВАЯ И ЕДИНСТВЕННАЯ запись **Петра Алексиевича** (двор 3 переписи 1897 г., 11
                          # лет): до сих пор он существовал в корпусе только строкой переписи. Здесь ему 19, и
                          # он женится на **Екатерине Михайловой Елискиной**. ⚠ Это, по-видимому, и есть
                          # разгадка «**Екатерины Михайловой Кекевой**», которая с февраля 1905 г. ходит по
                          # книгам восприемницей: в 1905 г. она «крестьянская жёнка» (л. 252), в 1907 и 1910
                          # гг. «солдатская жёнка» (лл. 345, 356) — то есть мужа между тем призвали, — а
                          # «крестьянская дѣвица Екатерина Михайлова Кекева» 1909 года (л. 192) тогда ДРУГАЯ
                          # женщина, урождённая Кекева. Прямо этого ни одна запись не говорит
                          marriage(13, 3,
                                   groom=person("Петр", "Алексиев", last_name_orig="Кекев", status=PEASANT_SON),
                                   groom_marriage_num=1, groom_age=19,
                                   bride=person("Екатерина", "Михайлова", last_name_orig="Елискина", status=PEASANT_DAUGHTER),
                                   bride_marriage_num=1, bride_age=18),
                          ),
          ),
    *page("241об", reviewed=False,
          *marriage_month(Month.OCTOBER,
                          # **ИГНАТИЙ ФЕОДОРОВИЧ САМ**, а не только отчеством своих детей. Корпус знал его по
                          # отчеству Феодора и Андрея Игнатиевичей и Анны Игнатиевны и по одному
                          # восприемничеству 1912 г.; здесь он венчается вторым браком **45 лет** — то есть
                          # родился около 1859 г., — и это первая дата в его жизни. Через него получает
                          # возраст и его отец **Феодор**, по отчеству общий с Николаем, Михаилом и Андреем
                          # Феодоровичами: если все четверо братья, Феодор родился в 1830-х. Невеста —
                          # крестьянская вдова Неонила Евдокимова Кучкина, 43 лет, тоже вторым браком
                          marriage(22, 27,
                                   groom=person("Игнатий", "Феодоров", last_name_orig="Кекев"),
                                   groom_marriage_num=2, groom_age=45,
                                   bride=person("Неонила", "Евдокимова", last_name_orig="Кучкина", status=PEASANT_WIDOW),
                                   bride_marriage_num=2, bride_age=43),
                          ),
          ),
    defaults=DEFAULTS,
)
