# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**196**, л. 312 (титул),
# записи лл. 312об–320об. **32 брака**: январь 3, февраль 2, май 3, июль 1,
# сентябрь 2, **октябрь 17** (№ 12–28), ноябрь 4.
#
# **ОДНА запись.** Прочитаны все обороты 312об–320об; recto снято `spread`-ом
# по нужной строке.
# ⚠ Форма как везде в ч. 2: оборот несёт счётъ, мѣсяцъ и день, жениха, невесту и
# лѣта обоих; **поручители — на RECTO**, вместе с «кто совершалъ таинство» и
# подписью свидѣтелей. (В ч. 1 этого года НАОБОРОТ — воспріемники на обороте.)
#
# 🔴🔴🔴 **ГОД ДАЁТ ВЕНЧАНИЕ СТЕФАНА ИВАНОВИЧА — И ЧЕРЕЗ НЕГО ЦЕЛЫЙ ДВОР.**
# Корпус знал Стефана Иоанновича по двум записям 1887–1888 гг. (рождение дочери
# Настасьи 18 дек. 1887 г. и её погребение 13 янв. 1888 г.), без возраста, без
# фамилии жены и без родни. Брак № 18 даёт всё сразу:
#   1. **возраст «19 л. 10 мѣс.» ⇒ род. ок. декабря 1866 г.** — метрику искать в
#      МК 1866/1867 гг. (д. 195);
#   2. **фамилию и происхождение невесты** — «солдатская дочь **Евфимія Игнатьева
#      КИРИЛЛИНА**», 20 л.; 1887 год зовёт жену Стефана «Евдокіей Игнатьевой» без
#      фамилии, но отчество то же, брак у обоих первый и единственный, а между
#      венчанием и рождением Настасьи четырнадцать месяцев ⇒ **это одна женщина**,
#      и «Евдокія» — обычная для этого писца вариация имени;
#   3. **брата** — поручитель по женихѣ «**Андрей Ивановъ Кекевъ**» (вычитка 20.10.2026;
#      прежде «Іоанновъ»), то же отчество ⇒ **Стефанъ Ивановичъ приписывается ко двору 7**,
#      где корпус держит старшего Андрея Иоанновича (~1862). Этого корпус не знал;
#   4. **шурина** — поручитель по невѣстѣ «**Максимъ Игнатьевъ Кириллинъ**», её
#      отчество и её фамилия. Именно это совпадение и **доказывает выравнивание
#      разворота** (правило 6 regional-rules — сверять фамилию поручителя с оборотом).
#
# 🔴🔴 **И ОПРОВЕРГАЕТ ПЕРВЕНСТВО 1887 ГОДА.** Второй поручитель по женихѣ —
# «**Алексѣй Ѳокинъ Кекевъ**». 1887 год объявил его (ч. 1, № м70) главным открытием:
# первым случаем, когда Ѳокеевича двора 6 называют Кекевымъ **прямо**, а не через
# уличную фамилию. Здесь он на год раньше, а 1885 год (д.196 л. 236об) даёт его
# **отцом**. ⇒ **кандидат `make claim-check`**: утверждения, написанные с 1887 годом,
# надо пересмотреть.
#
# ⓘ **Елеазаръ Арсеніевъ Гуненкинъ** (вычитка 20.10.2026; прежде «Гунякинъ»), рядовой
# солдатъ, второй поручитель по невѣстѣ, заведён — **свояк невесты**: МК 1885 ч. 1 № ж50
# (л. 251об, 7/8 ноября; в DSL не заведена) крестит у «уволеннаго въ запасъ арміи рядоваго
# солдата Ели|азара Арсеньева Гунен|кина и жены его Анны Игнатьевой» дочь Екатерину, а
# восприемница — «крестьянская дѣвица Евфимія Игнатьева», невеста этого брака (сверено по
# скану 20.10.2026). Прежнее «Лазарь Арсеньевъ Гунякинъ» — ошибка первого чтения; помета,
# что дочь Екатерину хоронят в ч. 3 1885 г., снята: в ноябре–декабре (жен. № 47–54) её нет.
# ⚠ Не заведены:
# «Никита Ивановъ **ЮКАЕВЪ**», 43 г., вторымъ бракомъ (№ 11) — Юкаевы отдельный род
# того же села (`../CLAUDE.md`), НЕ Кекевы; «Ѳедоръ Ѳокинъ **Денисовъ**» (№ 30,
# д. Кононово) — Ѳокинъ с чужой фамилией, брат «Василія Ѳокина Денисова» 1887 г.;
# «Евдокія Данилина **Филатова**» (№ 12) — см. ч. 1, «Данилинъ» не кузинское отчество.
#
# ⓘ № 29 (2 нояб.) венчает невесту «прихода **города Меленокъ, Покровскаго Собора**,
# деревни Волково» — тот самый приход, чья «выпись» подшита в книгу 1885 года на
# лл. 241–242.
#
# Вычитан в Verso 20.10.2026: одна запись года, заведённая в DSL.

