from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import SCARLATINA
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитриевы Горы за 1886 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**196**, л. 321 (титул),
# записи лл. 321об–340об. **ОДНА запись.** Год кончается на № м72 / № ж72.
#
# ⚠ Вся ч. 3 озаглавлена «**КОПІЯ** СЪ МЕТРИЧЕСКОЙ КНИГИ НА 1886» — только третья
# часть, как в 1888 г. (в 1887-м копией названа вся книга).
# ⚠ **Возраст стоит в ДВУХ колонках, «Мужеска» и «Женска»**: пол берётся из того, в
# какой колонке написано число, а не из имени умершего. Так же в 1885 и 1887 гг.
# ⚠ **«Отъ чего умеръ» — на ОБОРОТЕ** (в 1887 г. было на recto), поэтому ч. 3 читается
# по одним оборотам: recto несёт только «кто исповѣдывалъ» и «кто совершалъ
# погребеніе», имён там нет.
# ⚠ С л. 340 печатный бланк кончается и писец разлиновывает страницы от руки. То же
# было в 1885 г. с л. 276 и в 1887-м с л. 374 — конец печатной тетради приходится на
# декабрь.
#
# ✅✅✅ **ГОД ДОКАЗЫВАЕТ СОБСТВЕННУЮ ВОЗРАСТНУЮ КОНВЕНЦИЮ.** Единственная наша запись
# ч. 3 — ребёнок, чьё **рождение стоит в этой же книге** (ч. 1, № ж25, 15 апреля).
# В графе возраста написано **голое «3½», без единицы измерения**. Будь это годы,
# ребёнок родился бы в 1883 г.; на деле между записями три месяца десять дней. ⇒
# **в ч. 3 1886 г. голое число у младенца означает МѢСЯЦЫ.** Правило 3
# `../../regional-rules/dmitrievy-gory/README.md` предупреждает, что конвенцию нельзя
# переносить из соседнего года (в д.197 1898 г. — годы, а в 1894-м у младенца «4» —
# месяцы); здесь она установлена **изнутри года**, одной семьёй и одной книгой.
# У взрослых голое число по-прежнему годы: в том же году «Флоръ Антоновъ 72»,
# «Ѳома Максимовъ 18», «Максимъ Ѳокинъ Быловъ 62».
#
# 🔴🔴 **ЗАЦЕПКА, КОТОРУЮ ГОД ДАЁТ, НО НЕ ЗАКРЫВАЕТ: «ФЛОРЪ АНТОНОВЪ», 72 л.**
# (л. 321об, № м3, †8 января, «отъ натуральной», **фамилии нет**). 1885 год венчает
# «**Алексѣя Флорова КИКѢЕВА**», 23 л., зап. солдата Великолуцкаго полка (д.196
# л. 261об; до вычитки 19.10.2026 читалось «Аникиту Ѳлорова Кекева») — и «Флоровъ» стало
# **девятым отчеством поколения дедов**, корпусу до тех пор неизвестным. Через семь недель после той свадьбы хоронят Флора, 72 л. ⇒ род. ок.
# 1814 г.; отчество — «**Антоновъ**», то самое, каким корпус зовёт дедов **двора 5**
# (Максимъ ~1827 и Алексій ~1829 Антоновичи). Гипотеза: Флоръ Антоновичъ — отец
# Алексѣя (и Ивана, Николая Флоровичей) и брат Максима и Алексія. **НЕ ЗАВЕДЕНО**: фамилии в записи нет, второго
# сигнала нет, а «Антоновыхъ» в приходе несколько (Григорій Антоновъ **Хохловъ**,
# л. 302об; Михаилъ Антоновъ **Кочетковъ**, 1885 л. 237об). Проверять по восприемникамъ
# у детей Алексѣя (женат с ноября 1885; первенец — Алексѣй, 30 сентября 1887 г.).
#
# ⚠ Не заведены (правило 5): «**Ѳома Максимовъ**», крестьянскій сынъ, 18 л. († 15 февр.,
# л. 325об) — Максимовичъ без фамилии, а Максимовичей в приходе много (Шумановы,
# Ермилкины, Пушковы); при 10× имя читается «Ѳома», НЕ «Ѳока». «**Максимъ Ѳокинъ
# БЫЛОВЪ**», 62 († 3 мая, л. 331об) — Ѳокеевичъ с чужой фамилией. «Козьма Ѳедоровъ»
# без фамилии (л. 324об) — он же «Абашинъ» по правке 1889 г.
#
# ⓘ **1886 год — год двух эпидемий.** Январь–апрель **оспа**: в марте умерло 15 муж.
# пола против обычных 3–6, в феврале 8; «отъ оспы» стоит почти в каждой детской
# записи, больше всего в д. Кононовой. Лето — скарлатина и понос. Смертность 1886 г.
# самая высокая из прочитанных лет дела 196.
#
# Вычитан в Verso 20.10.2026: одна запись года, заведённая в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1886 = death_records(
    "ГАВО", "590", "12", "196", "Дмитриевы Горы", "Покровская",
    1886,
    *page("333об",
          *death_month(Month.JULY,
                       # ✅✅✅ **РОДИЛАСЬ И УМЕРЛА ВНУТРИ ОДНОЙ КНИГИ — И ЭТИМ ДОКАЗАЛА ВОЗРАСТНУЮ КОНВЕНЦИЮ
                       # ГОДА.** «Села Дмитріевыхъ горъ крестьянина **Василья Авксентіева Кузина** дочь
                       # **Александра**», возраст **3½**, «отъ скарлатины» (сверено при 6×). Её рождение — ч.
                       # 1, **№ ж25, 15 апреля 1886 г.** ⇒ 15 апр. → 25 июля = **3 мѣс. 10 дн.** 🔴 В графе
                       # стоит **голое «3½», без единицы измерения**. Будь это годы, ребёнок родился бы в 1883
                       # г. — но метрика о рождении лежит четырьмя месяцами раньше в этой же книге. ⇒ **голое
                       # число у младенца в ч. 3 1886 г. означает МѢСЯЦЫ.** Правило 3 regional-rules запрещает
                       # переносить конвенцию из соседнего года; здесь она установлена изнутри — одной семьёй
                       # и одной книгой, самым сильным способом, каким это вообще возможно. 🔴 **Семья Василія
                       # Авксентіевича теряет первенца, названного этим же годом.** Корпус до 1886 г. не знал
                       # ни жены его (Акилина Николаева), ни детей. Годом позже он потеряет и вторую дочь —
                       # **Евдокію**, 6 мѣс., † 20 июля 1887 г. (ч. 3, № ж26, «отъ кори»): **два ребёнка за
                       # две книги подряд**
                       death(51, Gender.FEMALE, 25, 27,
                             deceased=person("Александра"), age="3 мес 2 нед",
                             relatives=[relative(person("Василій", "Авксентіевъ", last_name_orig="Кузинъ"), Relationship.FATHER)],
                             cause_of_death=SCARLATINA),
                       ),
          ),
    defaults=DEFAULTS,
)
