# Метрическая книга Покровской церкви с. Димитриевы Горы за 1886 г.,
# часть первая «О родившихся». ГАВО ф.590 оп.12 д.**196**, лл. 277об–311об
# (титул — л. 277).
#
# **Пятый год, читанный в деле 196** (1880–1890), после 1890, 1889, 1888 и 1887 гг.
# Читано на четыре фамилии — Кикев/Кекев, Земсков, Кузин, Акиллин — **и на голое
# отчество** (см. `../CLAUDE.md`). **ШЕСТЬ записей**: четыре рождения и два
# восприемничества.
#
# ⚠⚠ **ФОРМА 1886 г. — КАК В 1888-м, НЕ КАК В 1887-м: ВОСПРІЕМНИКИ НА ОБОРОТЕ.**
# Оборот несёт счётъ (раздельный м/ж), мѣсяцъ и день рожденія/крещенія, имя,
# родителей И воспріемниковъ; recto — «Кто совершалъ таинство крещенія» и
# рукоприкладство, имён там нет. ⇒ **часть первая читается по одним оборотам**,
# и год стоит вдвое дешевле 1887-го. Печатный колонтитул читается через разворот:
# на обороте «МЕТРИЧЕСКОЙ КНИГИ НА 1886», на recto «ГОДЪ, ЧАСТЬ ПЕРВАЯ О РОДИВШИХСЯ».
# **Форма меняется между соседними годами одного дела — проверять заново каждый год.**
#
# 🔴🔴 **АНДРЕЙ ѲЕОДОРОВИЧЪ — ВОСПРИЕМНИКЪ ДВАЖДЫ ЗА ГОД.** В феврале — у Николая
# Флорова (№ м6; это Флоровичъ, не брат — см. запись), в декабре — у брата Игнатія
# (№ ж86), и оба раза он «крестьянскій сынъ», то есть ещё не женат. Это сходится с 1887
# годом, где он венчается (ч. 2, № 10) с **Ульяной Ивановой Пупковой** — а она в 1886 г.
# дважды названа «крестьянской дѣвицей» (лл. 294об, 295об). Две стороны одной свадьбы,
# каждая со своей стороны, за год до неё.
#
# 🔴🔴 **ГОД ОТОДВИГАЕТ ДВУХ ОТЦОВ НА ВОСЕМЬ ЛЕТ.** Корпус знал Николая Флоровича отцом
# с 1894 г. (теперь — с 1884-го, № ж27), Игнатія Ѳеодоровича — с 1893/1894 гг.; здесь
# оба отцы уже в 1886-м. **Жена Игнатія названа — Евдокія Николаева** (описка, см.
# запись). Жена Николая — **Ѳомаида Петрова** (вычитка 20.10.2026; прежде «Соломонида»),
# как в 1882 и 1884 гг.; книги 1888–1908 гг., ещё не вычитанные, пишут «Соломонида».
#
# 🔴🔴 **ДВОР 5 В ОДНОЙ СТРОКЕ** (№ ж43; до вычитки 20.10.2026 — «№ ж15»): Егоръ
# Максимовъ крестит дочь **Марью** (прежде «Марѳа»), а восприемники — его племянник
# **Иванъ Михайловъ Кекевъ**, сын брата Михаила («крестьянскій сынъ» ⇒ не женат; прежде
# читался «Иванъ Максимовъ», брат отца), и **Екатерина Максимова**, «крестьянская жена»
# (прежде «Евфимія»), — по всей видимости сестра отца, кума у Егора и в 1896 г. Фамилия
# «Кекевъ» стоит один раз, при первом имени, и покрывает обоих — правило 2
# `../../regional-rules/dmitrievy-gory/README.md`.
#
# 🔴 **ТРИ НАПИСАНИЯ ФАМИЛИИ В ОДНОМ ГОДУ**: Кекевъ (лл. 279об, 290об, 309об),
# Кекева (л. 309об) и **Кикевъ** (л. 299об). ⛔ Четвёртое, «Кекъ» (л. 305об),
# ОТОЗВАНО 16.09.2026 — см. комментарий к записи. **Иванъ Михайловъ стоит в этой же книге
# и «Кекевымъ» (л. 290об), и «Кикевымъ» (л. 299об)**, а 1885 год пишет его «Кекевымъ» —
# **оба написания на одном человеке в одном году**, и это лучшее доказательство тождества
# Кикевъ = Кекевъ, какое даёт проход.
#
# ⚠⚠ **«ДАНИЛИНЪ» В ЭТОМ СЕЛЕ — НЕ ПРИЗНАК КУЗИНЫХЪ.** 1887 год свёл Даниловичей
# Кузиных отчасти по форме отчества; 1886-й эту опору выбивает. На л. 308об стоят
# «**Николай Данилинъ ФИЛАТОВЪ**» и «**Евдокія Данилина ШИШКОВА**», а ч. 2 венчает
# «крестьянскую дочь **Евдокію Данилину ФИЛАТОВУ**» (брак № 12). Всего «Данилиныхъ»
# в книге пятеро, и ни один не назван Кузиным. ⇒ **отчество само по себе не решает
# ничего** (правило 5). 1885 год подтверждает это с другой стороны: там «Николай
# Данилинъ **Кузинъ**» крестит дочь 24 октября, а «Николай Даниловъ **Филатовъ**»
# венчается 2 октября первым браком — два разных человека в одной книге.
#
# ⚠⚠ **«КУСИНЪ» ≠ «КУЗИНЪ», и это видно только при 11×.** В д. Кононовой свой род
# **Кусиныхъ** (л. 297об, Иродіонъ Михайловъ Кусинъ с сыном Филиппомъ); при 2,4× он
# читается как «Кузинъ» и попадает в проход ложно. У «з» петля НИЖЕ строки, у «с» —
# открытая дуга. Оба кропа сняты при 11× и сверены между собой.
#
# ⚠ Не заведены (нет второго сигнала, правило 5): «Михаилъ Ѳедоровъ **Дурановъ**»
# (л. 290об) — не Михаилъ Ѳеодоровичъ Кекевъ, тот женат на Марьѣ Саввиной; «Андрей
# Максимовъ **Власовъ**» (л. 290об); «Григорій Антоновъ **Хохловъ**» (л. 302об);
# «Стефанъ и Яковъ Максимовы **Шумановы**» (л. 293об); «Иванъ Максимовъ **Пушковъ**»
# (л. 292об; Ивана Максимова **Кекева** в этой книге нет — на л. 290об вычитка 20.10.2026
# читает «Иванъ **Михайловъ**»); «Егоръ Ѳедоровъ безъ фамиліи» (л. 287об) — из
# д. Кононовой, не из села.
#
