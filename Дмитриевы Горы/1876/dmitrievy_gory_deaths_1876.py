from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import DEBILITY, PLEURISY
from verso.ru.dsl.statuses import PEASANT_FEMALE, PEASANT_MALE, TEMP_OBLIGED_PEASANT_MALE

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1876 г.,
# часть третья «О умершихъ». ГАВО ф.590 оп.12 д.**195**, л. 160 (титул),
# записи лл. 160об–172об. **51 мужское и 61 женское — 112 погребений**
# (в 1877 г. было 101, в 1878 г. — 84, в 1879 г. — 87). **ДВЕ записи.**
#
# ⚠ Форма как в 1877–1879 гг.: **всё на обороте, включая «ОТЪ ЧЕГО УМЕРЪ»**; recto несёт
# только «кто исповѣдывалъ» и «кто совершалъ погребеніе». Ч. 3 читается по оборотам.
# Счётъ, как и в ч. 1, **сквозной по году и в двух колонках** (мужская/женская).
#
# 🔴 **ВОЗРАСТНАЯ ЕДИНИЦА ГОДА ЗАКРЕПЛЕНА ИСТОЧНИКОМ, А НЕ ДОГАДКОЙ.** Писец 1876 г.
# **подписывает единицу словом** везде, где она не годы: «недѣля», «6½ мѣсяцевъ», «12 дней»,
# «7 недѣль». ⇒ **голое число = годы.** («9 сутокъ» № м16 вычитка 15.10.2026 прочла
# «9 мѣс.» — примером суток он больше не служит.) Проверено полутора десятками пар
# «метрика ↔ погребение» внутри года: Марія Максима Тарасова (род. 16 янв. — † 23 янв.,
# «недѣля»), Матрона Степана Васильева (24 марта — 6 апр., «12 дней»), Яковъ Ефима
# Тимофѣева (24 апр. — 16 июня, «7 недѣль»), Ѳедотъ Василія Павлова (1 июня — 18 июля,
# «7 недѣль»), близнецы вдовы Ульяны Ивановой (21 апр. — 21 апр. и 13 авг.). Оговорка
# metric-book-scans («единица — конвенция ДѢЛА и может меняться между годами») здесь
# проверена и для 1876 г. держится.
#
# ⓘ **Самый смертный год из четырёх прочитанных** (112 против 101, 87 и 84), и волны те же:
# **коклюшъ** январь–апрель, **поносъ** июнь–август (в июле девять мужских смертей из
# девяти, почти все — от поноса), **коклюшъ** снова сентябрь–октябрь. Взрослые умирают
# «отъ натуральной» (77, 78, 80, 87 и 91 года) и «отъ чахотки».
#
# ⚠ **НЕ ЗАВЕДЕНЫ:**
#   • **Тѣло неизвѣстнаго человѣка мужескаго пола, вынутое изъ воды** (22 мая) — без имени,
#     без возраста, без причины.
#   • «Отъ излишняго употребленія вина», 24 мая, Андрей Иларіоновъ д. Кононовой, 28 л.
#   • **Димитрій Тарасовъ, 91 годъ** (19 авг.) — старейший умерший четырёх прочитанных лет.
#   • **Пять записей, где мать и её младенец уходят подряд**: Маріамна Димитріева († 28 апр.)
#     и её дочь Евдокія († 10 мая); Ксенія Ефимова († 24 июня) и её дочь Марія († 23 янв.);
#     Мавра Максимова († 18 апр.) и её дочь Марія († 27 мая).
#   • **Обе близнецовые пары года умирают целиком**: Симеонъ и Георгій вдовы Ульяны
#     Ивановой (д. Кононова) и Яковъ с Василіемъ Василія Герасимова (19 и 20 ноября,
#     «5 недѣль» оба).
#
# Вычитан в Verso 15.10.2026: две записи года, заведённые в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE)

dmitrievy_gory_deaths_1876 = death_records(
    "ГАВО", "590", "12", "195", "Дмитриевы Горы", "Покровская",
    1876,
    *page("162об",
          *death_month(Month.APRIL,
                       # 🔴🔴 **КОНОНОВСКІЙ МЛАДЕНЕЦЪ МАКСИМЪ ѲОКИНЪ — И ВОЗРАСТ ЧИТАЕТСЯ ИНАЧЕ.** «Казенной
                       # деревни Кононовой крестьянина **Максима Ѳокина** сынъ млад. **Максимъ**», **9 мѣс.**,
                       # «отъ плеврита». 🔄 **15.10.2026 (вычитка):** не «9 сутокъ» и не коклюшъ — прежний
                       # вывод «метрики в ч. 1 1876 г. нет, рождение ~7 апреля» снят. 9 мѣсяцевъ от 16
                       # апреля кладут рождение на ~июль 1875 г., а МК 1875 ч. 1 № м36 крестит 5 августа 1875
                       # г. **Максима, сына кононовскаго Василія Ѳокина** и Настасьи Андрѣевой — 8½ мѣс. до
                       # погребения. ⚠⚠ **Отец здесь назван Максимомъ**: либо это пятый кононовскій Ѳокинъ с
                       # сыномъ, чьей метрики корпус не держит, либо писец назвал отца именем сына. Не сведено
                       # — вопрос владельцу. ⚠ Родство Максима с Василіемъ, Филиппомъ, Григоріемъ и
                       # Харитономъ Ѳокиными «той же деревни» источником НЕ сказано и не приписано
                       death(16, Gender.MALE, 16, 18,
                             deceased=person("Максимъ", residence="Кононово"), age="9 мес",
                             relatives=[relative(person("Максимъ", "Ѳокинъ"), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("171об",
          *death_month(Month.DECEMBER,
                       # 🔴 **ОДИН ИЗ БЛИЗНЕЦОВЪ НАДЕЖДЫ ѲОКИНОЙ, И ГОД ЗАМКНУЛСЯ НА НЁМ** (сведено с № м73 ч. 1
                       # вычиткой 15.10.2026 — aleksej_ananievich_1876). «Села Димитріевыхъ
                       # горъ временно-обязаннаго крестьянина **Ананія Ефимова** сынъ младенецъ **Алексѣй**»,
                       # **2½ недѣли** (в DSL — «2 нед»: половины недели формат возраста не несёт, подлинник
                       # читается «2½ недѣли»). 🔴 Это ребёнок, крещённый **17 ноября** того же года (ч. 1 №
                       # м73, двойня Григорій и Алексѣй, мать — **Надежда Ѳокина**): от 17 ноября до 5 декабря
                       # — 18 дней, то есть 2 недѣли 4 дня. Писец округлил до «2½ недѣли» — сходится. ⓘ
                       # **Метрика и погребение сомкнулись внутри года**, и это ещё одна проверка возрастной
                       # единицы 1876 г. (см. шапку файла). Брат-близнецъ **Григорій** в ч. 3 не значится —
                       # пережил год
                       death(49, Gender.MALE, 5, 7,
                             deceased=person("Алексѣй"), age="2 нед",
                             relatives=[relative(person("Ананій", "Ефимовъ", status=TEMP_OBLIGED_PEASANT_MALE), Relationship.FATHER)],
                             cause_of_death=DEBILITY),
                       ),
          ),
    defaults=DEFAULTS,
)
