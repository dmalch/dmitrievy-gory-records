from verso.ru.dsl import (Month, RecordDefaults, marriage, marriage_month, marriage_records, page,
                          person)
from verso.ru.dsl.statuses import PEASANT_DAUGHTER, PEASANT_FEMALE, PEASANT_MALE, PEASANT_SON

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1876 г.,
# часть вторая «О бракосочетавшихся». ГАВО ф.590 оп.12 д.**195**, записи лл. 155об–159об
# (титул — л. 155). **26 браковъ**: январь 7 (№ 1–7), февраль 1 (№ 8), апрель 1 (№ 9),
# май 1 (№ 10), июнь 4 (№ 11–14), **октябрь 12** (№ 15–26). В марте, июле–сентябре, ноябре
# и декабре — **ни одного**. **ДВЕ записи.**
#
# ⓘ Браков больше, чем в 1877 г. (21), и распределение то же: два куста, зимний мясоед и
# октябрь после Успенского поста. Двенадцать октябрьских — почти половина года, из них
# **семь 3 октября** (№ 15–22).
#
# ⚠⚠ **ПОРУЧИТЕЛИ ПОСЛЕДНИХ ПЯТИ БРАКОВ (№ 22–26) В КНИГЕ НЕ СУЩЕСТВУЮТ.** Ч. 2 кончается
# на л. 159об, а столбец «Кто были поручители» стоит на ЛИЦЕВОЙ стороне разворота — то есть
# на л. 160, который занят **печатным титулом ч. 3 «О умершихъ»** (проверено кропом).
# Граница части рвёт разворот; это не пропуск в чтении и не утрата листа. Та же оговорка
# по 1877 г. и д. 196.
#
# ⛔ **«ФАМИЛИЯ «АКИММИНЪ» ОТОДВИНУТА НА 24 ГОДА» (№ 22) — СНЯТО ВЫЧИТКОЙ 15.10.2026.** Жених
# — «крестьянскій сынъ **Семенъ Акиллинъ**», невеста — «**Стефанида Епифанова**», не
# «Акимминъ» и не «Степанова». «Акиллинъ» — **отчество** (старая форма от имени Акила,
# «Акилла» в names.csv), а не фамилия. ✅ То же отчество — и «Акимминъ» МК **1900** г.: вычитка
# владельца 05.11.2026 прочла там «Михаилъ Симеоновъ **Акиллинъ**», отчество деда в роли фамилии
# внука. Фамилии «Акимминъ» ни одна вычитанная запись не даёт; «Семенъ Акимминъ» МК 1880 г.
# (л. 6об, открытый вопрос, не вычитан) — вероятно, этот же Семенъ Акиловичъ.
#
# ⚠ **НЕ ЗАВЕДЕНЫ:**
#   • Возрасты женихов в этом году стоят плотной группой 17–19 лет (только три вдовца
#     старше: 40, 48 и 29), невест — 16½–22. Это самый ранний брачный возраст из четырёх
#     прочитанных лет дела.
#   • № 4 (23 янв.) — «вдовый крестьянинъ **Андрей Семеновъ**, 48, вторымъ бракомъ» ×
#     «вдова **Марія Иванова**, 34, вторымъ». Та же пара крестит сына Василія 25 декабря
#     того же года (ч. 1 № м77, «жена его вторая Марья Иванова») — венчание и метрика
#     сомкнулись внутри года.
#   • № 8 (4 февр.) — **Пантелеймонъ Ермилковъ** × **Анна Павлова**; их сынъ Козьма род.
#     27 октября (ч. 1 № м66). Ещё одна пара, замкнувшаяся внутри года.
#   • Невесты со стороны: приход с. Санчуръ (д. Муратово — четырежды), с. Воютино,
#     с. Эммануиловка, **Нижегородская губ., Ардатовскій у., с. Сноведскій Заводъ**
#     («дочь умершаго мастероваго» — единственная не-крестьянка среди невест года).
#
# Вычитан в Verso 15.10.2026: две записи года, заведённые в DSL.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=PEASANT_MALE,
                          status_female=PEASANT_FEMALE,
                          status_bride=PEASANT_DAUGHTER,
                          status_groom=PEASANT_SON)

dmitrievy_gory_marriages_1876 = marriage_records(
    "ГАВО", "590", "12", "195", "Дмитриевы Горы", "Покровская",
    1876,
    *page("159об",
          *marriage_month(Month.OCTOBER,
                          # 🔴🔴 **СЕМЕНЪ АКИЛЛИНЪ, НЕ АКИММИНЪ — И ЭТО ОТЧЕСТВО.** «Села Димитріевыхъ горъ
                          # крестьянскій сынъ **Семенъ Акиллинъ**, 18½, первымъ бракомъ» × «прихода села Санчуръ,
                          # деревни Муратова крестьянская дочь **Стефанида Епифанова**, 22, первымъ бракомъ».
                          # 🔄 **15.10.2026 (вычитка):** до неё читалось «Акимминъ» («в фамилии две «м»», при 5×)
                          # и «Степанова», и запись считалась самой ранней для уличной фамилии Симеоновыхъ — ⛔
                          # это снято. «Акиллинъ» — старое отчество от **Акилы** (Семенъ Акиловичъ). ✅ Та же
                          # пара — родители Іосифа МК 1892 г. № м16: «Симеонъ Акиллинъ безъ фамиліи» ×
                          # «Стефанида Епифанова», вычитано в тот же день (semen__akimmin /
                          # stepanida_stepanovna_akimmina). ⚠ **Поручителей нет физически**: столбец стоял бы на
                          # л. 160, а там печатный титул ч. 3 (см. шапку файла)
                          marriage(22, 3,
                                   groom=person("Семенъ", "Акиллинъ"),
                                   bride=person("Стефанида", "Епифанова", residence="Муратово"),
                                   groom_marriage_num=1, bride_marriage_num=1,
                                   groom_age="18 лет 6 мес", bride_age=22),
                          # 🔴 **ВЕНЧАНИЕ, КОТОРОЕ ЗАМЫКАЕТ ЗВАНІЕ В Ч. 1 ТОГО ЖЕ ГОДА.** «Того же села
                          # крестьянскій сынъ **Григорій Антоновъ**, 19 л. 9 мѣс., первымъ бракомъ» × «казенной деревни
                          # Кононовой крестьянская дочь **Елизавета Иларіонова**, 18, первымъ бракомъ» ⇒ род.
                          # ок. **1857 г.** ⓘ 26 апреля 1876 г. он ещё «крестьянскій сынъ» и крестит сына
                          # Михаила Максимова (вычитка 15.10.2026; было «Мирона») **вместе с дѣвицей Анной
                          # Максимовой** двора 5, его сестрой (ч. 1 № м28) —
                          # полгода спустя женится. Правило 1877 г. («крестьянскій сынъ датирует холостого»)
                          # здесь проверяется на третьем человеке и держится. ⚠ Антоновыхъ в году не менее
                          # девяти разных (см. шапку файла ч. 1); связи с Максимомъ Антоновичемъ двора 5
                          # источник не даёт, и она **не приписана**. ⚠ Поручителей нет физически (см. шапку
                          # файла)
                          marriage(23, 6,
                                   groom=person("Григорій", "Антоновъ"),
                                   bride=person("Елизавета", "Иларіонова", residence="Кононово"),
                                   groom_marriage_num=1, bride_marriage_num=1,
                                   groom_age="19 л 9 мес", bride_age=18),
                          ),
          ),
    defaults=DEFAULTS,
)
