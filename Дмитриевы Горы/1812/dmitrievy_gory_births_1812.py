# Метрическая книга Покровской церкви с. Димитріевы Горы за 1812 г., часть первая
# «О родившихся». **ГАВО ф. 556 оп. 106 д. 297, лл. 420–429об** (кадры 0465–0475).
#
# ⚠ **Консисторская копия уездного дела**; раздел прихода — **лл. 420–443об**, и книга
# говорит это сама: заверка на л. 443об — «въ сей тетради нумерованныхъ **двадцать четыре
# листа**, а пришнуръ Муромскаго Духовнаго правленія печать. Протоіерей Гавріилъ»
# ⇒ 420–443 ровно. Тетрадь выдана **Муромскимъ Духовнымъ Правленіемъ** (в 1813 г. её
# выдаст уже Владимірская Консисторія).
#
# **Состав:** л. 420 — титул **и тут же ч. 1**; ч. 1 — лл. 420–429об (**77 записей**);
# ч. 2 — лл. 430–434 (**10 венчаній**); лл. 434об–435об — **чистые** (в альбоме сняты не
# все: 434об и 435об отсутствуют, л. 435 снят и пуст); ч. 3 — лл. 436–441об (**25 м /
# 26 ж = 51**); **ведомость — л. 442**; лл. 442об–443 чисты, заверка — л. 443об.
#
# ✅✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ, ВЕДОМОСТЬ (л. 442) СХОДИТСЯ ПО ВСЕМ ТРЁМ ЧАСТЯМ** —
# **восемнадцатый такой год подряд**. «Родившихся мужеска **37**, женска **40**, обоего
# пола **77**»; «бракосочетавшихся лицъ **20**, супружествъ **10**»; «умершихъ мужеска
# **25**, женска **26**, обоего **51**». ⇒ **непроснятый л. 434об венчаній не несёт** —
# их ровно десять, и все десять прочитаны. Возрастная разбивка мужчин сошлась построчно
# и **содержит строку «45 — 1»**: это Василій Харитоновъ (см. ч. 3).
# ⓘ Единственная ненатуральная смерть названа отдельно: «ненатуральною болѣзнію умерилъ
# никого кромѣ крестьянина **Якова Никитина**, которой **утонулъ**, коему отъ роду 25».
#
# 🏆🏆🏆🏆 **ГОД ДАЁТ ДВЕ ЗАПИСИ О РОДЕ, И ОБЕ — ПЕРВЫЕ В СВОЁМ РОДЕ ЗА ВЕСЬ ПРОХОД.**
# № 70 — **метрика Анны Антоновой, 13 декабря**, ровно там, где её предсказало прочтение
# 1813 года; ч. 3 м. № 8 — **погребеніе Василія Харитонова**, дяди трёх братьев и хозяина
# двора (см. `dmitrievy_gory_deaths_1812.py`). ⇒ **корпус впервые держит запись о
# ПОКОЛЕНИИ ХАРИТОНОВЫХЪ**, а не только о внуках.
# ⛔ **ОТОЗВАНО 14.09.2026 ПО ПРОЧТЕНИИ 1810 ГОДА**, что № 70 — самая ранняя запись о роде:
# **9 генваря 1810 г.** Василій Харитоновъ уже стоит кумомъ (1810 ч. 1 № 2), на два года и
# одиннадцать месяцев глубже, и там же — **погребеніе самого Ѳедора Харитонова**.
#
# 🚫🚫 **ВЕНЧАНІЯ АНТОНА В ГОДУ НЕТ** — десять венчаній разобраны поимённо, и первое из
# них 4 февраля (генварь пуст). А Анна род. 13 декабря ⇒ зачатие около марта ⇒ **брак
# заключён в 1811 г. или раньше**, когда Антону было пятнадцать-шестнадцать (род. ок.
# 1796). Канонический минимум до указа 1830 г. — **пятнадцать лет для мужчин**, так что
# это законно, но рано. 📍 **Альбома за 1811 год нет**; ближайшая доступная книга —
# **1810 (556-106-267, 34 кадра)**.
# ✅✅ **НАЙДЕНО 14.09.2026 ИМЕННО ТАМ: 9 ОКТЯБРЯ 1810 г.** (1810 ч. 2 № 9) — «крестьянина
# **Ѳедора Харитонова** сынъ **Антонъ**» × «крестьянская дочь дѣвка **Елена Васильева**»,
# оба первымъ бракомъ. Вывод «1811 или раньше» был верен и перелетел цель на год.
# 🚫 **Ни Ѳоки, ни Игнатья в 1812 году нет вовсе** — им десять и четырнадцать лет.
#
# ⓘ Вотчина — **Г-на Коллежскаго Ассессора Ивана Родіоновича Баташева**. Причт:
# священникъ **Стефанъ (Степанъ) Ивановъ**, діаконъ **Егоръ Драчевскій**, дьячекъ
# **Лаврентій Ивановъ** — все трое подписали ведомость.
# ⚠ Тёзки на месте: № 24 — «Антонъ Петровъ», № 30 — «Антонъ Степановъ» (его же хоронят
# 3 декабря), № 43 — «Антонъ Ѳилиповъ» съ женой **Василисой Терентьевой**; № 26 — «Петръ
# Ѳедоровъ», № 27 — «Никифоръ Ѳедоровъ» (д. Коннова); ч. 2 № 5 женит сына «Фоки
# Антонова», ч. 2 № 10 — сына «Ѳедора Антонова», ч. 2 № 3 — пріимыша «Ивана Ѳедорова».
# ⓘ **1812 год слышен глухо**: ополченскіе «ратниковы жёны» появятся только в книге
# 1813 года, а август этого года выкосил младенцев **поносомъ** — двенадцать погребеній
# подряд с 11 по 25 августа.
#
# ✅ Вычитано по сканам в Verso 01.10.2026.
