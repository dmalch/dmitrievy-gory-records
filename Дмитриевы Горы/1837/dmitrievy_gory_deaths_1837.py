from corpus.statuses import SHEPELEV_PEASANT, SHEPELEV_PEASANT_FEMALE, SHEPELEV_PEASANT_SPOUSE
from verso.ru.dsl import (Gender, Month, RecordDefaults, Relationship, death, death_month,
                          death_records, page, person, relative)
from verso.ru.dsl.causes_of_death import CONSUMPTION, FEVER, PLEURISY

# Метрическая книга Покровской церкви с. Димитріевы Горы за 1837 г., часть третья
# «О умершихъ». **ГАВО ф. 556 оп. 106 д. 611, лл. 353–355об** (кадры альбома 14–17).
#
# ✅ **ЧАСТЬ ПРОЧИТАНА ЦЕЛИКОМ: 74 погребения (39 м / 35 ж).** Проверка — итоговая
# ведомость причта на л. 356: «умершихъ мужеска 39, женска 35, обоего пола 74». Сошлась
# точно. **ПЯТЬ записей из 74** вынесены сюда.
#
# 🔴🔴 **ГОД МЛАДЕНЧЕСКОГО МОРА, И ЦИФРУ ДАЁТ САМ ПРИЧТ.** Ведомость на л. 356 расписывает
# умерших мужеска пола по возрастам, и первая строка — «**до 1 году — 24**» из 39. То есть
# почти две трети мужских погребений — младенцы, «отъ поноса» и «отъ колотья», гуще всего
# в маѣ–іюлѣ. Осенью приходит другая беда: «отъ горячки» умирают дети 5–15 лет (Никифоръ
# Михайловъ хоронит двух дочерей, 5 и 10 лѣтъ, за две недели).
#
# 🔴🔴 **ВОЗРАСТ В 1837 г. ПИШЕТСЯ ПРОПИСЬЮ И В НЕДЕЛЯХ — ЭТО ТОЧНЕЕ, ЧЕМ 1839 ГОД.**
# «пяти недѣль», «десяти дней», «трехъ недѣль», «полугоду», «двухъ мѣсяцевъ» — и всякий
# раз сходится с датой крещения из части первой, потому что почти все эти младенцы
# родились в этой же книге. Проверено на десятке дуг; самые точные: **Максимъ Никитинъ**
# (крещ. 19 генваря — † 15 марта, «двухъ мѣсяцевъ», день в день), **Марія Константинова**
# (род. 15 генваря — † 21 февраля, «пяти недѣль»), **Агаѳія Тимоѳеева** (крещ. 7 февраля —
# † 13 апрѣля, «двухъ мѣсяцевъ»), **Ирина Алексѣева** (крещ. 17 апрѣля — † 31 мая, «шести
# недѣль»), **Исай Саввинъ** (крещ. 9 мая — † 31 мая, «трехъ недѣль»). ⇒ голое число здесь
# значит **годы**, всё дробное писец называет словом.
#
# 🔴🔴🔴 **ПОГРЕБЕНИЙ РОДА В ГОДУ НЕТ.** Ни Ѳока, ни Игнатъ, ни Антонъ Ѳедоровы, ни их
# жёны и дети в части третьей не значатся — и дочь Ѳоки **Анна**, родившаяся 30 генваря
# (ч. 1 № 6 ж), тоже не похоронена в этом году. ⇒ она умерла позже, между 1838 и 1850 гг.
#
# ⚠ Дат погребения эта форма не пишет: одна дата на запись, и это **дата смерти**.
#
# Имена сверены кропом при 2.1×.
# Вычитано в Verso 09.10.2026.

DEFAULTS = RecordDefaults(residence="Дмитриевы Горы", status_male=SHEPELEV_PEASANT,
                          status_female=SHEPELEV_PEASANT_FEMALE)

dmitrievy_gory_deaths_1837 = death_records(
    "ГАВО", "556", "106", "611", "Дмитриевы Горы", "Покровская",
    1837,
    *page("353",
          *death_month(Month.JANUARY,
                       # 🔴 **ВТОРОЕ ЗВЕНО ЧЕТЫРЁХЗАПИСНОЙ АРКИ ГОДА.** «Тринадцатаго числа, села Димитріевыхъ
                       # горъ вотчины Г. Г. Шепелевыхъ крестьянинъ **Константинъ Кононовъ**, 20, отъ горячки».
                       # Через два дня, 15 генваря, у его вдовы **Марины Михайловой** рождается дочь **Марья**
                       # (ч. 1 № 4 ж); 21 февраля дочь умирает (ниже); 25 апрѣля вдова венчается вторымъ
                       # бракомъ за Егора Тимоѳеева (ч. 2 № 11). ⚠ Запись о рождении датирует его смерть
                       # **15-м** генваря, эта — **13-м**. Расхождение источника с самим собою; обе строки
                       # сверены, править нечего
                       death(2, Gender.MALE, 13,
                             deceased=person("Константинъ", "Кононовъ"),
                             age=20,
                             cause_of_death=FEVER),
                       ),
          *death_month(Month.FEBRUARY,
                       # 🔴 **ТРЕТЬЕ ЗВЕНО АРКИ — И ОНО ПИНУЕТ ВОЗРАСТНУЮ КОНВЕНЦИЮ ГОДА.** «Двадцать перваго
                       # числа, тогожъ села и вотчины **крестьянской вдовы Марины Михайловой** дочь, младенецъ
                       # **Марія**, пяти недѣль, отъ колотья». ✅ Родилась 15 генваря (ч. 1 № 4 ж) — 15 генваря
                       # + пять недель = 19 февраля, писец пишет 21-е. Сходится, и это **первая из десятка
                       # внутрикнижных проверок**, на которых стоит правило: дробное этот писец называет
                       # словом, а голое число значит годы. ⓘ Отец в записи не назван — он умер за пять недель
                       # до того (выше), и книга это уже сказала в части первой
                       death(5, Gender.FEMALE, 21,
                             deceased=person("Марія"),
                             age="5 недель",
                             relatives=[relative(person("Марина", "Михайлова", status="крестьянская вдова вотчины гг. Шепелевых"), Relationship.MOTHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("354об",
          *death_month(Month.JULY,
                       # 🔗 **СЕМЬЯ, КОТОРУЮ КОРПУС ТЕПЕРЬ ВИДИТ ТРИ ГОДА ПОДРЯД — И ВСЕ ТРИ РАЗА ЧЕРЕЗ ПОТЕРЮ
                       # ИЛИ ПРИБЫЛЬ.** «**Степана Кузьмина** сынъ, младенецъ **Онисимъ**, пяти мѣсяцевъ, отъ
                       # колотья». Родился 14 февраля того же года (ч. 1 № 6 м) — ровно пять месяцев без
                       # недели. У той же пары (жена **Екатерина Спиридонова**) в 1839 г. умирает сын
                       # **Тимоѳей** «9½ мѣсяцевъ» и рождается дочь **Настасья**, а в 1842 г. — сын **Андрей**
                       death(32, Gender.MALE, 8,
                             deceased=person("Онисимъ"),
                             age="5 месяцев",
                             relatives=[relative(person("Степанъ", "Кузминъ", status=SHEPELEV_PEASANT), Relationship.FATHER)],
                             cause_of_death=PLEURISY),
                       ),
          ),
    *page("355",
          *death_month(Month.JULY,
                       # 🆕 **ЕДИНСТВЕННОЕ УТОПЛЕНИЕ ГОДА, И ОНО ЗАМЫКАЕТ ВТОРУЮ ПОСМЕРТНУЮ ЗАПИСЬ.** «Двадцать
                       # пятаго числа… крестьянинъ **Егоръ Макаровъ**, 18, **отъ утону**». ✅ Часть первая
                       # назвала этот день сама, не зная о части третьей: 7 декабря у его вдовы **Агриппины
                       # Михайловой** родился сын **Антонъ** «послѣ мужа своего… **умершаго отъ утону Іюля
                       # 25-го дня**» (ч. 1 № 46 м). ⇒ две части книги сходятся на дате и причине без единой
                       # поправки. ⓘ Восемнадцати лет и уже женат — в этом приходе венчают именно в этом
                       # возрасте (1839 г.: восемнадцать лет у четырнадцати женихов из двадцати восьми)
                       death(33, Gender.MALE, 25,
                             deceased=person("Егоръ", "Макаровъ"),
                             age=18,
                             cause_of_death="утонул"),
                       ),
          *death_month(Month.AUGUST,
                       # 🔗 **ЧАСТЬ ВТОРАЯ БЕЗ ЧАСТИ ТРЕТЬЕЙ ОБМАНЫВАЕТ — И ВОТ ПРИМЕР.** «**Емельяна
                       # Алексѣева** жена **Мавра Гаврилова**, 22, отъ чахотки». Ровно через три месяца, 5
                       # ноября, «крестьянинъ **Емельянъ Алексѣевъ**, **вдовой**» венчается на **Марѳѣ
                       # Петровой** (ч. 2 № 21) — и невеста не из прихода, а из **деревни Осиповки Ардатовской
                       # округи Нижегородской губерніи, вотчины тѣхъ же Г. Г. Шепелевыхъ**. 🆕 ⇒ **владельцы
                       # держат сёла и за губернской границей, и невест берут оттуда**. Это объясняет
                       # ардатовский след, который корпус встречал восемьюдесятью годами позже: в 1911 г.
                       # вдовец Василій Ермолаевъ Кекевъ женится на вдове из того же Ардатовскаго уезда
                       death(23, Gender.FEMALE, 3,
                             deceased=person("Мавра", "Гаврилова", status=SHEPELEV_PEASANT_SPOUSE),
                             age=22,
                             relatives=[relative(person("Емельянъ", "Алексѣевъ"), Relationship.HUSBAND)],
                             cause_of_death=CONSUMPTION),
                       ),
          ),
    defaults=DEFAULTS,
)
