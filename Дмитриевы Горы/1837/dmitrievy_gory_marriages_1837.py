# («№ | Когда, и кто имянно вѣнчаны | Кто были поручители»); лета жениха и невесты, которые
# есть и в 1839, и в 1842 гг., здесь **не пишутся вовсе**, зато каждая запись называет
# невесту «съ дочерью такого-то крестьянина» и различает «холостой» / «вдовый». ⇒ год
# бесполезен для датировок по возрасту и **очень ценен для сцепки поколений**.
#
# ⓘ **Венчальный день года — 3 октября**: восемь браков подряд (№ 14–20). В генварѣ 4,
# в февралѣ 4, в апрѣлѣ 2, в маѣ 1, в октябрѣ 8, в ноябрѣ 2 (номера идут сплошь, помесячных
# итогов эта форма не пишет). Марта, іюня–сентября и декабря венчаний нет — посты.
#
# ⓘ **Поручители стоят в той же строке и ЧИТАЮТСЯ** — в отличие от 1839 и 1842 гг., где
# они на recto и не читаны.
#
