# «О родившихся». **ГАВО ф. 556 оп. 106 д. 611, лл. 341–348об** (кадры альбома 1–9).
#
# ⚠⚠ **Консисторская копия уездного дела**; раздел нашего прихода — **лл. 341–356**,
# приходъ **№ 42**. Титул на л. 341: «Подана Генваря 10-го дня 1838 года. Книга, данная
# изъ Муромскаго Духовнаго Правленія Меленковской округи села Димитріевыхъ горъ въ
# **одноприходную Покровскую церковь** причту, для записки родившихся, бракомъ
# сочетавшихся и умершихъ на 1837 годъ». **Часть первая начинается на том же листе, прямо
# под титулом** — первые четыре записи года стоят на л. 341, а не на обороте.
#
# ✅ **ГОД ПРОЧИТАН ЦЕЛИКОМ: 95 записей о рождении (48 м / 47 ж).** Проверка — **итоговая
# ведомость самого причта** на л. 356: «Итого въ показанной Метрической книгѣ родившихся
# мужеска 48, женска 47, обоего пола 95». Сошлась с чтением точно, как и по двум другим
# частям (22 венчания, 74 погребения). Ниже вынесены **восемь записей из 95**.
#
# 🔴🔴 **ФОРМА 1837 г. — НЕ ТА, ЧТО В 1839 И 1842 гг., И ЭТО МЕНЯЕТ ПОРЯДОК ЧТЕНИЯ.**
# Граф всего четыре («№ мужеска/женска | У кого кто родился | Число крещенія | Кто были
# воспріемники»), дата рождения написана **прописью внутри текста** («Пятнадцатаго
# числа»), месяц вынесен в строку-заголовок. Главное: **записи идут по ОБЕИМ сторонам
# листа**, так что правило «читать только версо» здесь не работает — пропустишь половину
# года. Возраст младенцев в ч. 3 писан прописью и **в неделях и днях** («пяти недѣль»,
# «десяти дней»), то есть точнее, чем в 1839 г.
#
# ⓘ **Причт тот же, что в 1839 г., и священников ДВА**: **Тихонъ Ивановъ Экземплярскій**
# (здесь названо и отчество) и **Михаилъ Ивановъ Экземплярскій**; діаконъ **Яковъ
# Звѣревъ**, дьячекъ **Василій Горскій**, пономарь **Михаилъ Егоровъ**.
#
# ⚠⚠ **СОСЛОВНАЯ ФОРМУЛА: 1837 г. ВЛАДЕЛЬЦА НАЗЫВАЕТ** — «села Димитріевыхъ горъ
# **вотчины Г. Г. Шепелевыхъ**», как и 1842 г. ⇒ **безвладельческий 1839 год — исключение,
# а не ступень**; вчерашняя формулировка о «датирующем признаке» в файлах 1839 г. отозвана
# и исправлена. Кононово в 1837 и 1839 гг. — «**Экономическаго вѣдомства**», в 1842 г. —
# «Государственныхъ имуществъ»: вот эта перемена как раз между 1839 и 1842 гг.
#
# 🆕 **ПЯТЬ ПОСМЕРТНЫХ И РЕКРУТСКИХ ЗАПИСЕЙ, и писец каждый раз называет дату и причину** —
# такой щедрости нет ни в 1839, ни в 1842 г.: вдова Марина Михайлова «послѣ умершаго
# 1837 года Генваря 15-го дня перваго мужа ея **Константина Кононова**» (№ 4 ж ниже);
# вдова Ефимья Тихонова «послѣ умершаго **1836 года Сентября 6-го дня** мужа **Михея
# Васильева**»; солдатка Марья Сидорова «послѣ мужа **Акима Данилова, отданнаго въ рекруты
# 1836-го года мѣсяца Декабря 10-го дня**»; вдова Агриппина Михайлова «послѣ мужа
# **Егора Макарова, умершаго отъ утону Іюля 25-го дня**» (№ 46 м ниже); солдатка Пелагія
# Кузьмина «прижитой законно съ мужемъ ея солдатомъ Самуиломъ Леонтьевымъ».
#
# ⛔ **«Фамилия ГУДИНЪ в 1837 г.» — СНЯТО вычиткой 2026-10-09.** Отец № 34 м ниже — «Аѳанасій
# **Іудинъ**»: это отчество, не фамилия (как он же в 1836 г., ч. 3 № 20 м, и «Анна Іудина»
# 1824 г., ч. 2 № 13). «Анна Гудина», жена Николая Денисова (№ 17 м), и «Никифоръ Гудинъ»,
# трижды кум и поручитель, в DSL не внесены и со сканом не сверены — прочитаны тем же первым
# проходом; прежде чем на них ссылаться, перечитать (вероятно, «Іудина» / «Іудинъ»).
#
